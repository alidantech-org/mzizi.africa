// Regenerates src/lib/review/data-catalog.ts from the API's list routes: bun scripts/data-catalog.ts
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));

const root = join(here, '../../api/src/modules');
const routes = new Set<string>();
const walk = (dir: string) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (name.endsWith('.controller.ts')) for (const m of readFileSync(path, 'utf8').matchAll(/@Get\("\/v1\/([a-z-]+)\/([a-z-]+)"\)/g)) if (m[1] !== 'pipeline') routes.add(`${m[1]}/${m[2]}`);
  }
};
walk(root);
const groups: Record<string, string[]> = {};
for (const route of [...routes].sort()) {
  const [group, name] = route.split('/');
  (groups[group!] ??= []).push(name!);
}
writeFileSync(join(here, '../src/lib/review/data-catalog.ts'), `// Generated by scripts/data-catalog.ts from the API's list routes; do not edit by hand.\nexport const DATA_CATALOG: Record<string, string[]> = ${JSON.stringify(groups, null, 2)};\n`);
console.log(`${routes.size} list routes in ${Object.keys(groups).length} groups`);
