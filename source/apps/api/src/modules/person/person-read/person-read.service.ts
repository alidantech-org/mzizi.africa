import type { PersonContactResponseDto } from "#/modules/person/dto/person-contact-response.dto.ts";
import type { PersonContactsListResponseDto } from "#/modules/person/dto/person-contacts-list-response.dto.ts";
import type { PersonHandleListQueryDto } from "#/modules/person/dto/person-handle-list-query.dto.ts";
import type { PersonHandleResponseDto } from "#/modules/person/dto/person-handle-response.dto.ts";
import type { PersonHandlesListResponseDto } from "#/modules/person/dto/person-handles-list-response.dto.ts";
import type { PersonListQueryDto } from "#/modules/person/dto/person-list-query.dto.ts";
import type { PersonNameListQueryDto } from "#/modules/person/dto/person-name-list-query.dto.ts";
import type { PersonNameResponseDto } from "#/modules/person/dto/person-name-response.dto.ts";
import type { PersonNamesListResponseDto } from "#/modules/person/dto/person-names-list-response.dto.ts";
import type { PersonProfileListQueryDto } from "#/modules/person/dto/person-profile-list-query.dto.ts";
import type { PersonProfileResponseDto } from "#/modules/person/dto/person-profile-response.dto.ts";
import type { PersonProfilesListResponseDto } from "#/modules/person/dto/person-profiles-list-response.dto.ts";
import type { PersonResponseDto } from "#/modules/person/dto/person-response.dto.ts";

/**
 * The Person Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class PersonPersonReadService {
  abstract findPeople(input: PersonListQueryDto): Promise<PeopleListResponseDto>;
  abstract findPersonContacts(input: PersonContactListQueryDto): Promise<PersonContactsListResponseDto>;
  abstract findPersonHandles(input: PersonHandleListQueryDto): Promise<PersonHandlesListResponseDto>;
  abstract findPersonNames(input: PersonNameListQueryDto): Promise<PersonNamesListResponseDto>;
  abstract findPersonProfiles(input: PersonProfileListQueryDto): Promise<PersonProfilesListResponseDto>;
  abstract getPersonById(input: { personId: string }): Promise<PersonResponseDto>;
  abstract getPersonContactById(input: { contactId: string }): Promise<PersonContactResponseDto>;
  abstract getPersonHandleById(input: { handleId: string }): Promise<PersonHandleResponseDto>;
  abstract getPersonNameById(input: { personNameId: string }): Promise<PersonNameResponseDto>;
  abstract getPersonProfileById(input: { profileId: string }): Promise<PersonProfileResponseDto>;
}