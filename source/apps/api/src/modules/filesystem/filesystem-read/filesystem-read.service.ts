/**
 * The Filesystem Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class FilesystemFilesystemReadService {
  abstract findFileAttachments(input: FileAttachmentListQueryDto): Promise<FileAttachmentsListResponseDto>;
  abstract findFileVersions(input: FileVersionListQueryDto): Promise<FileVersionsListResponseDto>;
  abstract findFiles(input: FileListQueryDto): Promise<FilesListResponseDto>;
  abstract findFolders(input: FolderListQueryDto): Promise<FoldersListResponseDto>;
  abstract findFormats(input: FormatListQueryDto): Promise<FormatsListResponseDto>;
  abstract getFileAttachmentById(input: { attachmentId: string }): Promise<FileAttachmentResponseDto>;
  abstract getFileById(input: { fileId: string }): Promise<FileResponseDto>;
  abstract getFileVersionById(input: { versionId: string }): Promise<FileVersionResponseDto>;
  abstract getFolderById(input: { folderId: string }): Promise<FolderResponseDto>;
  abstract getFormatById(input: { formatId: string }): Promise<FormatResponseDto>;
}