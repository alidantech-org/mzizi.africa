/**
 * The Finance Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class FinanceFinanceReadService {
  abstract findBudgetaryUnits(input: BudgetaryUnitListQueryDto): Promise<BudgetaryUnitsListResponseDto>;
  abstract findBudgets(input: BudgetListQueryDto): Promise<BudgetsListResponseDto>;
  abstract findExpenditures(input: ExpenditureListQueryDto): Promise<ExpendituresListResponseDto>;
  abstract findFiscalYears(input: FiscalYearListQueryDto): Promise<FiscalYearsListResponseDto>;
  abstract findLedgerEntries(input: LedgerEntryListQueryDto): Promise<LedgerEntriesListResponseDto>;
  abstract findRevenueRecords(input: RevenueRecordListQueryDto): Promise<RevenueRecordsListResponseDto>;
  abstract findTransfers(input: TransferListQueryDto): Promise<TransfersListResponseDto>;
  abstract getBudgetById(input: { budgetId: string }): Promise<BudgetResponseDto>;
  abstract getBudgetaryUnitById(input: { unitId: string }): Promise<BudgetaryUnitResponseDto>;
  abstract getExpenditureById(input: { expenditureId: string }): Promise<ExpenditureResponseDto>;
  abstract getFiscalYearById(input: { fiscalYearId: string }): Promise<FiscalYearResponseDto>;
  abstract getLedgerEntryById(input: { entryId: string }): Promise<LedgerEntryResponseDto>;
  abstract getRevenueRecordById(input: { revenueId: string }): Promise<RevenueRecordResponseDto>;
  abstract getTransferById(input: { transferId: string }): Promise<TransferResponseDto>;
}