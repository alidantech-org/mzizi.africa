
import type { AmenitiesListResponseDto } from "#/modules/services/dto/amenities-list-response.dto.ts";
import type { AmenityListQueryDto } from "#/modules/services/dto/amenity-list-query.dto.ts";
import type { AmenityOfficeListQueryDto } from "#/modules/services/dto/amenity-office-list-query.dto.ts";
import type { AmenityOfficeResponseDto } from "#/modules/services/dto/amenity-office-response.dto.ts";
import type { AmenityOfficesListResponseDto } from "#/modules/services/dto/amenity-offices-list-response.dto.ts";
import type { AmenityResponseDto } from "#/modules/services/dto/amenity-response.dto.ts";
import type { PublicServiceListQueryDto } from "#/modules/services/dto/public-service-list-query.dto.ts";
import type { PublicServiceResponseDto } from "#/modules/services/dto/public-service-response.dto.ts";
import type { PublicServicesListResponseDto } from "#/modules/services/dto/public-services-list-response.dto.ts";
import type { ServiceDeliveriesListResponseDto } from "#/modules/services/dto/service-deliveries-list-response.dto.ts";
import type { ServiceDeliveryListQueryDto } from "#/modules/services/dto/service-delivery-list-query.dto.ts";
import type { ServiceDeliveryResponseDto } from "#/modules/services/dto/service-delivery-response.dto.ts";

/**
 * The Services Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class ServicesServicesReadService {
  abstract findAmenities(input: AmenityListQueryDto): Promise<AmenitiesListResponseDto>;
  abstract findAmenityOffices(input: AmenityOfficeListQueryDto): Promise<AmenityOfficesListResponseDto>;
  abstract findPublicServices(input: PublicServiceListQueryDto): Promise<PublicServicesListResponseDto>;
  abstract findServiceDeliveries(input: ServiceDeliveryListQueryDto): Promise<ServiceDeliveriesListResponseDto>;
  abstract getAmenityById(input: { amenityId: string }): Promise<AmenityResponseDto>;
  abstract getAmenityOfficeById(input: { amenityOfficeId: string }): Promise<AmenityOfficeResponseDto>;
  abstract getPublicServiceById(input: { serviceId: string }): Promise<PublicServiceResponseDto>;
  abstract getServiceDeliveryById(input: { deliveryId: string }): Promise<ServiceDeliveryResponseDto>;
}