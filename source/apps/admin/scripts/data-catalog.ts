// Regenerates src/lib/review/data-catalog.ts from the API's generated catalog (Dryv: `bun run catalog`): bun scripts/data-catalog.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Operation = { method: string; path: string; role: string };

const here = fileURLToPath(new URL('.', import.meta.url));
const catalog = JSON.parse(
  readFileSync(join(here, '../../../backend/api/src/system/catalog/catalog.json'), 'utf8'),
) as { operations: Operation[] };

const routes = new Set<string>();
for (const operation of catalog.operations) {
  const match = operation.method === 'GET' && operation.role === 'list' ? /^\/v1\/([a-z-]+)\/([a-z-]+)$/.exec(operation.path) : null;
  if (match && match[1] !== 'pipeline') routes.add(`${match[1]}/${match[2]}`);
}
const groups: Record<string, string[]> = {};
for (const route of [...routes].sort()) {
  const [group, name] = route.split('/');
  (groups[group!] ??= []).push(name!);
}
writeFileSync(
  join(here, '../src/lib/review/data-catalog.ts'),
  `// Generated by scripts/data-catalog.ts from the API's generated catalog; do not edit by hand.\nexport const DATA_CATALOG: Record<string, string[]> = ${JSON.stringify(groups, null, 2)};\n`,
);
console.log(`${routes.size} list routes in ${Object.keys(groups).length} groups`);
