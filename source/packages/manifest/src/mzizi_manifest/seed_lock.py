"""Seed manifest lock: resolves every manifest entry to files with content identity and planned registry keys.

The keys are a plan, not a claim of publication.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import yaml

from .paths import SEED_ROOT
from .seed_folders import (
    _sha256,
    entry_pinned,
    entry_versioning,
    expand_entry,
    media_type_of,
    object_key,
    resolve_effective,
)
from .seed_vocabulary import MANIFEST_NAME


def resolve_files(manifest: dict, root: Path = SEED_ROOT) -> list[dict]:
    """Every uploadable file of the manifest with its identity, effective folder metadata, versioning and readable object key."""
    out = []
    for entry in manifest["entries"]:
        versioning, pinned, origin = (
            entry_versioning(entry, manifest),
            entry_pinned(entry, manifest),
            entry.get("origin"),
        )
        for file in expand_entry(entry, root):
            effective, _ = resolve_effective(file, root)
            out.append(
                {
                    "path": file,
                    "entry": entry["id"],
                    "loader": entry["loader"],
                    "sha256": _sha256(root / file),
                    "bytes": (root / file).stat().st_size,
                    "media_type": media_type_of(file, entry),
                    "effective": effective,
                    "versioning": versioning,
                    "pin": pinned,
                    "origin": origin if isinstance(origin, str) else (origin or {}).get(file),
                    "key": object_key(manifest, (effective or {})["access"], file),
                }
            )
    return sorted(out, key=lambda f: f["path"])


def manifest_sha256(root: Path = SEED_ROOT) -> str:
    return hashlib.sha256((root / MANIFEST_NAME).read_bytes()).hexdigest()


def build_lock(manifest: dict, root: Path = SEED_ROOT) -> dict:
    """The lock: one line of identity per file. It records no upload state; publication state lives in the filesystem registry."""
    return {
        "schema_version": 2,
        "release": manifest["release"],
        "manifest_sha256": manifest_sha256(root),
        "bucket": manifest["bucket"],
        "region": manifest["region"],
        "logical_root": manifest["logical_root"],
        "files": {
            f["path"]: {
                "entry": f["entry"],
                "sha256": f["sha256"],
                "bytes": f["bytes"],
                "media_type": f["media_type"],
                "access": f["effective"]["access"],
                "versioning": f["versioning"],
                "key": f["key"],
            }
            for f in resolve_files(manifest, root)
        },
    }


def dump_lock(lock: dict) -> str:
    """YAML with one flow-style line per file, so a changed file is a one-line diff."""
    head = {k: v for k, v in lock.items() if k != "files"}
    lines = [
        "# Generated by `uv run mzizi-manifest lock` from manifest.yaml, the _folder.yaml descriptors and the files. Do not edit.",
        "# It plans identities and readable object keys; it records no upload state (that lives in the filesystem registry).",
        yaml.safe_dump(head, sort_keys=False, default_flow_style=False).rstrip(),
        "files:",
    ]
    lines += [
        f"  {json.dumps(path, ensure_ascii=False)}: {json.dumps(value, ensure_ascii=False)}"
        for path, value in lock["files"].items()
    ]
    return "\n".join(lines) + "\n"
