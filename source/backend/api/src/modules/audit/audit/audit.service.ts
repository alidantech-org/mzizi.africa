
import type { CommentListQueryDto } from "#/modules/audit/dto/comment-list-query.dto.ts";
import type { CommentResponseDto } from "#/modules/audit/dto/comment-response.dto.ts";
import type { CommentsListResponseDto } from "#/modules/audit/dto/comments-list-response.dto.ts";
import type { CreateCommentBodyDto } from "#/modules/audit/dto/create-comment-body.dto.ts";
import type { CreateEvidenceReferenceBodyDto } from "#/modules/audit/dto/create-evidence-reference-body.dto.ts";
import type { CreateReviewDecisionBodyDto } from "#/modules/audit/dto/create-review-decision-body.dto.ts";
import type { EvidenceReferenceListQueryDto } from "#/modules/audit/dto/evidence-reference-list-query.dto.ts";
import type { EvidenceReferenceResponseDto } from "#/modules/audit/dto/evidence-reference-response.dto.ts";
import type { EvidenceReferencesListResponseDto } from "#/modules/audit/dto/evidence-references-list-response.dto.ts";
import type { ReviewDecisionListQueryDto } from "#/modules/audit/dto/review-decision-list-query.dto.ts";
import type { ReviewDecisionResponseDto } from "#/modules/audit/dto/review-decision-response.dto.ts";
import type { ReviewDecisionsListResponseDto } from "#/modules/audit/dto/review-decisions-list-response.dto.ts";

/**
 * The Audit contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class AuditAuditService {
  abstract createComment(input: CreateCommentBodyDto): Promise<CommentResponseDto>;
  abstract createEvidenceReference(input: CreateEvidenceReferenceBodyDto): Promise<EvidenceReferenceResponseDto>;
  abstract createReviewDecision(input: CreateReviewDecisionBodyDto): Promise<ReviewDecisionResponseDto>;
  abstract findComments(input: CommentListQueryDto): Promise<CommentsListResponseDto>;
  abstract findEvidenceReferences(input: EvidenceReferenceListQueryDto): Promise<EvidenceReferencesListResponseDto>;
  abstract findReviewDecisions(input: ReviewDecisionListQueryDto): Promise<ReviewDecisionsListResponseDto>;
  abstract getCommentById(input: { commentId: string }): Promise<CommentResponseDto>;
  abstract getEvidenceReferenceById(input: { evidenceId: string }): Promise<EvidenceReferenceResponseDto>;
  abstract getReviewDecisionById(input: { decisionId: string }): Promise<ReviewDecisionResponseDto>;
}