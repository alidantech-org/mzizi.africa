import { Injectable } from "@nestjs/common";
import type { AppropriationCollectionDto } from "#/modules/finance/schema/dto/appropriation-collection.dto.ts";
import type { BudgetCollectionDto } from "#/modules/finance/schema/dto/budget-collection.dto.ts";
import type { FindingCollectionDto } from "#/modules/finance/schema/dto/finding-collection.dto.ts";
import type { GovernmentBudgetsDto } from "#/modules/finance/schema/dto/government-budgets.dto.ts";
import type { InstitutionFindingsDto } from "#/modules/finance/schema/dto/institution-findings.dto.ts";
import type { RevisionLinesDto } from "#/modules/finance/schema/dto/revision-lines.dto.ts";
import { ListAppropriationsUseCase } from "#/modules/finance/features/budgets/use-cases/list-appropriations.repository.ts";
import { ListBudgetsUseCase } from "#/modules/finance/features/budgets/use-cases/list-budgets.repository.ts";
import { ListFindingsUseCase } from "#/modules/finance/features/budgets/use-cases/list-findings.repository.ts";

/**
 * The Budgets contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class FinanceBudgetsService {
  abstract listAppropriations(input: RevisionLinesDto): Promise<AppropriationCollectionDto>;
  abstract listBudgets(input: GovernmentBudgetsDto): Promise<BudgetCollectionDto>;
  abstract listFindings(input: InstitutionFindingsDto): Promise<FindingCollectionDto>;
}

@Injectable()
export class FinanceBudgetsServiceImpl extends FinanceBudgetsService {
  constructor(
    private readonly listAppropriationsUseCase: ListAppropriationsUseCase,
    private readonly listBudgetsUseCase: ListBudgetsUseCase,
    private readonly listFindingsUseCase: ListFindingsUseCase,
  ) {
    super();
  }

  listAppropriations(input: RevisionLinesDto): Promise<AppropriationCollectionDto> {
    return this.listAppropriationsUseCase.execute(input);
  }

  listBudgets(input: GovernmentBudgetsDto): Promise<BudgetCollectionDto> {
    return this.listBudgetsUseCase.execute(input);
  }

  listFindings(input: InstitutionFindingsDto): Promise<FindingCollectionDto> {
    return this.listFindingsUseCase.execute(input);
  }
}
