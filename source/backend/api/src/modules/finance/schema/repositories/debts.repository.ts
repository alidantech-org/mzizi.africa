import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { DebtsEntity } from "#/modules/finance/schema/entities/debts.entity.ts";
import * as Debts from "#/modules/finance/schema/types/debts/index.ts";

/**
 * Repository of Debts: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class DebtsRepository
  extends EntityRepository<
    DebtsEntity,
    Debts.Types.DebtsSortableField,
    Debts.Types.DebtsEditableField,
    Debts.Types.DebtsSelectableField,
    Debts.Types.IDebtsCreatable
  >
  implements IUpdatableRepository<DebtsEntity, Debts.Types.IDebtsUpdatable>
{
  constructor(
    @InjectRepository(DebtsEntity)
    repository: Repository<DebtsEntity>,
  ) {
    super(repository, Debts.Config.DEBTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Debts.Types.IDebtsUpdatable): Promise<DebtsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find debts by borrower entity id, paged by the shared query. */
  async findByBorrowerEntity(
    query: BaseQueryDto<DebtsEntity>,
    borrowerEntityId: NonNullable<DebtsEntity["borrowerEntityId"]>,
  ): Promise<IFindAllResponse<DebtsEntity>> {
    return await this.findByQuery(query, { borrowerEntityId, deletedAt: IsNull() });
  }

  /** Find debts by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<DebtsEntity>,
    countryId: NonNullable<DebtsEntity["countryId"]>,
  ): Promise<IFindAllResponse<DebtsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find debts by currency id, paged by the shared query. */
  async findByCurrency(
    query: BaseQueryDto<DebtsEntity>,
    currencyId: NonNullable<DebtsEntity["currencyId"]>,
  ): Promise<IFindAllResponse<DebtsEntity>> {
    return await this.findByQuery(query, { currencyId, deletedAt: IsNull() });
  }

  /** Find debts by debt kind id, paged by the shared query. */
  async findByDebtKind(
    query: BaseQueryDto<DebtsEntity>,
    debtKindId: NonNullable<DebtsEntity["debtKindId"]>,
  ): Promise<IFindAllResponse<DebtsEntity>> {
    return await this.findByQuery(query, { debtKindId, deletedAt: IsNull() });
  }

  /** Find debts by lender entity id, paged by the shared query. */
  async findByLenderEntity(
    query: BaseQueryDto<DebtsEntity>,
    lenderEntityId: NonNullable<DebtsEntity["lenderEntityId"]>,
  ): Promise<IFindAllResponse<DebtsEntity>> {
    return await this.findByQuery(query, { lenderEntityId, deletedAt: IsNull() });
  }

  /** Find debts by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<DebtsEntity>,
    sourceCitationId: NonNullable<DebtsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<DebtsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the debts with this code (unique). */
  async findByCode(code: NonNullable<DebtsEntity["code"]>): Promise<DebtsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
