import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { BudgetsEntity } from "#/modules/finance/schema/entities/budgets.entity.ts";
import * as Budgets from "#/modules/finance/schema/types/budgets/index.ts";

/**
 * Repository of Budgets: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class BudgetsRepository
  extends EntityRepository<
    BudgetsEntity,
    Budgets.Types.BudgetsSortableField,
    Budgets.Types.BudgetsEditableField,
    Budgets.Types.BudgetsSelectableField,
    Budgets.Types.IBudgetsCreatable
  >
  implements IUpdatableRepository<BudgetsEntity, Budgets.Types.IBudgetsUpdatable>
{
  constructor(
    @InjectRepository(BudgetsEntity)
    repository: Repository<BudgetsEntity>,
  ) {
    super(repository, Budgets.Config.BUDGETS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Budgets.Types.IBudgetsUpdatable,
  ): Promise<BudgetsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find budgets by budget kind id, paged by the shared query. */
  async findByBudgetKind(
    query: BaseQueryDto<BudgetsEntity>,
    budgetKindId: NonNullable<BudgetsEntity["budgetKindId"]>,
  ): Promise<IFindAllResponse<BudgetsEntity>> {
    return await this.findByQuery(query, { budgetKindId, deletedAt: IsNull() });
  }

  /** Find budgets by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<BudgetsEntity>,
    countryId: NonNullable<BudgetsEntity["countryId"]>,
  ): Promise<IFindAllResponse<BudgetsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find budgets by fiscal period id, paged by the shared query. */
  async findByFiscalPeriod(
    query: BaseQueryDto<BudgetsEntity>,
    fiscalPeriodId: NonNullable<BudgetsEntity["fiscalPeriodId"]>,
  ): Promise<IFindAllResponse<BudgetsEntity>> {
    return await this.findByQuery(query, { fiscalPeriodId, deletedAt: IsNull() });
  }

  /** Find budgets by government entity id, paged by the shared query. */
  async findByGovernmentEntity(
    query: BaseQueryDto<BudgetsEntity>,
    governmentEntityId: NonNullable<BudgetsEntity["governmentEntityId"]>,
  ): Promise<IFindAllResponse<BudgetsEntity>> {
    return await this.findByQuery(query, { governmentEntityId, deletedAt: IsNull() });
  }

  /** Find budgets by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<BudgetsEntity>,
    sourceCitationId: NonNullable<BudgetsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<BudgetsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the budgets with this code (unique). */
  async findByCode(code: NonNullable<BudgetsEntity["code"]>): Promise<BudgetsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
