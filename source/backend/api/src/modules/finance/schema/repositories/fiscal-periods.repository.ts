import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { FiscalPeriodsEntity } from "#/modules/finance/schema/entities/fiscal-periods.entity.ts";
import * as FiscalPeriods from "#/modules/finance/schema/types/fiscal-periods/index.ts";

/**
 * Repository of Fiscal Periods: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class FiscalPeriodsRepository
  extends EntityRepository<
    FiscalPeriodsEntity,
    FiscalPeriods.Types.FiscalPeriodsSortableField,
    FiscalPeriods.Types.FiscalPeriodsEditableField,
    FiscalPeriods.Types.FiscalPeriodsSelectableField,
    FiscalPeriods.Types.IFiscalPeriodsCreatable
  >
  implements IUpdatableRepository<FiscalPeriodsEntity, FiscalPeriods.Types.IFiscalPeriodsUpdatable>
{
  constructor(
    @InjectRepository(FiscalPeriodsEntity)
    repository: Repository<FiscalPeriodsEntity>,
  ) {
    super(repository, FiscalPeriods.Config.FISCAL_PERIODS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: FiscalPeriods.Types.IFiscalPeriodsUpdatable,
  ): Promise<FiscalPeriodsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find fiscal periods by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<FiscalPeriodsEntity>,
    countryId: NonNullable<FiscalPeriodsEntity["countryId"]>,
  ): Promise<IFindAllResponse<FiscalPeriodsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find fiscal periods by period kind id, paged by the shared query. */
  async findByPeriodKind(
    query: BaseQueryDto<FiscalPeriodsEntity>,
    periodKindId: NonNullable<FiscalPeriodsEntity["periodKindId"]>,
  ): Promise<IFindAllResponse<FiscalPeriodsEntity>> {
    return await this.findByQuery(query, { periodKindId, deletedAt: IsNull() });
  }

  /** Find fiscal periods by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<FiscalPeriodsEntity>,
    sourceCitationId: NonNullable<FiscalPeriodsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<FiscalPeriodsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the fiscal periods with this code (unique). */
  async findByCode(
    code: NonNullable<FiscalPeriodsEntity["code"]>,
  ): Promise<FiscalPeriodsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
