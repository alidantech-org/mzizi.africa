import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { BudgetVersionsEntity } from "#/modules/finance/schema/entities/budget-versions.entity.ts";
import * as BudgetVersions from "#/modules/finance/schema/types/budget-versions/index.ts";

/**
 * Repository of Budget Versions: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class BudgetVersionsRepository
  extends EntityRepository<
    BudgetVersionsEntity,
    BudgetVersions.Types.BudgetVersionsSortableField,
    BudgetVersions.Types.BudgetVersionsEditableField,
    BudgetVersions.Types.BudgetVersionsSelectableField,
    BudgetVersions.Types.IBudgetVersionsCreatable
  >
  implements
    IUpdatableRepository<BudgetVersionsEntity, BudgetVersions.Types.IBudgetVersionsUpdatable>
{
  constructor(
    @InjectRepository(BudgetVersionsEntity)
    repository: Repository<BudgetVersionsEntity>,
  ) {
    super(repository, BudgetVersions.Config.BUDGET_VERSIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: BudgetVersions.Types.IBudgetVersionsUpdatable,
  ): Promise<BudgetVersionsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find budget versions by budget id, paged by the shared query. */
  async findByBudget(
    query: BaseQueryDto<BudgetVersionsEntity>,
    budgetId: NonNullable<BudgetVersionsEntity["budgetId"]>,
  ): Promise<IFindAllResponse<BudgetVersionsEntity>> {
    return await this.findByQuery(query, { budgetId, deletedAt: IsNull() });
  }

  /** Find budget versions by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<BudgetVersionsEntity>,
    sourceCitationId: NonNullable<BudgetVersionsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<BudgetVersionsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find budget versions by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<BudgetVersionsEntity>,
    statusId: NonNullable<BudgetVersionsEntity["statusId"]>,
  ): Promise<IFindAllResponse<BudgetVersionsEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }
}
