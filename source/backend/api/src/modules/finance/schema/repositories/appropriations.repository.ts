import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { AppropriationsEntity } from "#/modules/finance/schema/entities/appropriations.entity.ts";
import * as Appropriations from "#/modules/finance/schema/types/appropriations/index.ts";

/**
 * Repository of Appropriations: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class AppropriationsRepository
  extends EntityRepository<
    AppropriationsEntity,
    Appropriations.Types.AppropriationsSortableField,
    Appropriations.Types.AppropriationsEditableField,
    Appropriations.Types.AppropriationsSelectableField,
    Appropriations.Types.IAppropriationsCreatable
  >
  implements
    IUpdatableRepository<AppropriationsEntity, Appropriations.Types.IAppropriationsUpdatable>
{
  constructor(
    @InjectRepository(AppropriationsEntity)
    repository: Repository<AppropriationsEntity>,
  ) {
    super(repository, Appropriations.Config.APPROPRIATIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Appropriations.Types.IAppropriationsUpdatable,
  ): Promise<AppropriationsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find appropriations by budget version id, paged by the shared query. */
  async findByBudgetVersion(
    query: BaseQueryDto<AppropriationsEntity>,
    budgetVersionId: NonNullable<AppropriationsEntity["budgetVersionId"]>,
  ): Promise<IFindAllResponse<AppropriationsEntity>> {
    return await this.findByQuery(query, { budgetVersionId, deletedAt: IsNull() });
  }

  /** Find appropriations by classification id, paged by the shared query. */
  async findByClassification(
    query: BaseQueryDto<AppropriationsEntity>,
    classificationId: NonNullable<AppropriationsEntity["classificationId"]>,
  ): Promise<IFindAllResponse<AppropriationsEntity>> {
    return await this.findByQuery(query, { classificationId, deletedAt: IsNull() });
  }

  /** Find appropriations by currency id, paged by the shared query. */
  async findByCurrency(
    query: BaseQueryDto<AppropriationsEntity>,
    currencyId: NonNullable<AppropriationsEntity["currencyId"]>,
  ): Promise<IFindAllResponse<AppropriationsEntity>> {
    return await this.findByQuery(query, { currencyId, deletedAt: IsNull() });
  }

  /** Find appropriations by parent appropriation id, paged by the shared query. */
  async findByParentAppropriation(
    query: BaseQueryDto<AppropriationsEntity>,
    parentAppropriationId: NonNullable<AppropriationsEntity["parentAppropriationId"]>,
  ): Promise<IFindAllResponse<AppropriationsEntity>> {
    return await this.findByQuery(query, { parentAppropriationId, deletedAt: IsNull() });
  }

  /** Find appropriations by project id, paged by the shared query. */
  async findByProject(
    query: BaseQueryDto<AppropriationsEntity>,
    projectId: NonNullable<AppropriationsEntity["projectId"]>,
  ): Promise<IFindAllResponse<AppropriationsEntity>> {
    return await this.findByQuery(query, { projectId, deletedAt: IsNull() });
  }

  /** Find appropriations by recipient entity id, paged by the shared query. */
  async findByRecipientEntity(
    query: BaseQueryDto<AppropriationsEntity>,
    recipientEntityId: NonNullable<AppropriationsEntity["recipientEntityId"]>,
  ): Promise<IFindAllResponse<AppropriationsEntity>> {
    return await this.findByQuery(query, { recipientEntityId, deletedAt: IsNull() });
  }

  /** Find appropriations by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<AppropriationsEntity>,
    sourceCitationId: NonNullable<AppropriationsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<AppropriationsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find appropriations by unit feature id, paged by the shared query. */
  async findByUnitFeature(
    query: BaseQueryDto<AppropriationsEntity>,
    unitFeatureId: NonNullable<AppropriationsEntity["unitFeatureId"]>,
  ): Promise<IFindAllResponse<AppropriationsEntity>> {
    return await this.findByQuery(query, { unitFeatureId, deletedAt: IsNull() });
  }

  /** Find the appropriations with this code (unique). */
  async findByCode(
    code: NonNullable<AppropriationsEntity["code"]>,
  ): Promise<AppropriationsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
