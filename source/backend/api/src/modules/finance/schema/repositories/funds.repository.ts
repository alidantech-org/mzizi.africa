import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { FundsEntity } from "#/modules/finance/schema/entities/funds.entity.ts";
import * as Funds from "#/modules/finance/schema/types/funds/index.ts";

/**
 * Repository of Funds: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class FundsRepository
  extends EntityRepository<
    FundsEntity,
    Funds.Types.FundsSortableField,
    Funds.Types.FundsEditableField,
    Funds.Types.FundsSelectableField,
    Funds.Types.IFundsCreatable
  >
  implements IUpdatableRepository<FundsEntity, Funds.Types.IFundsUpdatable>
{
  constructor(
    @InjectRepository(FundsEntity)
    repository: Repository<FundsEntity>,
  ) {
    super(repository, Funds.Config.FUNDS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Funds.Types.IFundsUpdatable): Promise<FundsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find funds by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<FundsEntity>,
    countryId: NonNullable<FundsEntity["countryId"]>,
  ): Promise<IFindAllResponse<FundsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find funds by fund kind id, paged by the shared query. */
  async findByFundKind(
    query: BaseQueryDto<FundsEntity>,
    fundKindId: NonNullable<FundsEntity["fundKindId"]>,
  ): Promise<IFindAllResponse<FundsEntity>> {
    return await this.findByQuery(query, { fundKindId, deletedAt: IsNull() });
  }

  /** Find funds by funding source id, paged by the shared query. */
  async findByFundingSource(
    query: BaseQueryDto<FundsEntity>,
    fundingSourceId: NonNullable<FundsEntity["fundingSourceId"]>,
  ): Promise<IFindAllResponse<FundsEntity>> {
    return await this.findByQuery(query, { fundingSourceId, deletedAt: IsNull() });
  }

  /** Find funds by managing entity id, paged by the shared query. */
  async findByManagingEntity(
    query: BaseQueryDto<FundsEntity>,
    managingEntityId: NonNullable<FundsEntity["managingEntityId"]>,
  ): Promise<IFindAllResponse<FundsEntity>> {
    return await this.findByQuery(query, { managingEntityId, deletedAt: IsNull() });
  }

  /** Find funds by scope unit feature id, paged by the shared query. */
  async findByScopeUnitFeature(
    query: BaseQueryDto<FundsEntity>,
    scopeUnitFeatureId: NonNullable<FundsEntity["scopeUnitFeatureId"]>,
  ): Promise<IFindAllResponse<FundsEntity>> {
    return await this.findByQuery(query, { scopeUnitFeatureId, deletedAt: IsNull() });
  }

  /** Find funds by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<FundsEntity>,
    sourceCitationId: NonNullable<FundsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<FundsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the funds with this code (unique). */
  async findByCode(code: NonNullable<FundsEntity["code"]>): Promise<FundsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
