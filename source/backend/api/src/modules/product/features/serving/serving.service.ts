import { Injectable } from "@nestjs/common";
import type { ReleaseCollectionDto } from "#/modules/product/schema/dto/release-collection.dto.ts";
import type { ReleaseWindowDto } from "#/modules/product/schema/dto/release-window.dto.ts";
import type { SiteDetailDto } from "#/modules/product/schema/dto/site-detail.dto.ts";
import type { SiteKeyDto } from "#/modules/product/schema/dto/site-key.dto.ts";
import { GetSiteUseCase } from "#/modules/product/features/serving/use-cases/get-site.repository.ts";
import { ListReleasesUseCase } from "#/modules/product/features/serving/use-cases/list-releases.repository.ts";

/**
 * The Serving contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class ProductServingService {
  abstract getSite(input: SiteKeyDto): Promise<SiteDetailDto>;
  abstract listReleases(input: ReleaseWindowDto): Promise<ReleaseCollectionDto>;
}

@Injectable()
export class ProductServingServiceImpl extends ProductServingService {
  constructor(
    private readonly getSiteUseCase: GetSiteUseCase,
    private readonly listReleasesUseCase: ListReleasesUseCase,
  ) {
    super();
  }

  getSite(input: SiteKeyDto): Promise<SiteDetailDto> {
    return this.getSiteUseCase.execute(input);
  }

  listReleases(input: ReleaseWindowDto): Promise<ReleaseCollectionDto> {
    return this.listReleasesUseCase.execute(input);
  }
}
