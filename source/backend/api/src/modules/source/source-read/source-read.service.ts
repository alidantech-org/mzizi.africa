/**
 * The Source Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class SourceSourceReadService {
  abstract findAttributions(input: AttributionListQueryDto): Promise<AttributionsListResponseDto>;
  abstract findCaptures(input: CaptureListQueryDto): Promise<CapturesListResponseDto>;
  abstract findDocuments(input: DocumentListQueryDto): Promise<DocumentsListResponseDto>;
  abstract findMethods(input: MethodListQueryDto): Promise<MethodsListResponseDto>;
  abstract findPublishers(input: PublisherListQueryDto): Promise<PublishersListResponseDto>;
  abstract findVerifications(input: VerificationListQueryDto): Promise<VerificationsListResponseDto>;
  abstract getAttributionById(input: { attributionId: string }): Promise<AttributionResponseDto>;
  abstract getCaptureById(input: { captureId: string }): Promise<CaptureResponseDto>;
  abstract getDocumentById(input: { documentId: string }): Promise<DocumentResponseDto>;
  abstract getMethodById(input: { methodId: string }): Promise<MethodResponseDto>;
  abstract getPublisherById(input: { publisherId: string }): Promise<PublisherResponseDto>;
  abstract getVerificationById(input: { verificationId: string }): Promise<VerificationResponseDto>;
}