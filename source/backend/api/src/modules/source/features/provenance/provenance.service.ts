import { Injectable } from "@nestjs/common";
import type { EvidenceCollectionDto } from "#/modules/source/schema/dto/evidence-collection.dto.ts";
import type { RowEvidenceDto } from "#/modules/source/schema/dto/row-evidence.dto.ts";
import type { SourceCollectionDto } from "#/modules/source/schema/dto/source-collection.dto.ts";
import type { SourceWindowDto } from "#/modules/source/schema/dto/source-window.dto.ts";
import { ListEvidenceUseCase } from "#/modules/source/features/provenance/use-cases/list-evidence.repository.ts";
import { ListSourcesUseCase } from "#/modules/source/features/provenance/use-cases/list-sources.repository.ts";

/**
 * The Provenance contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class SourceProvenanceService {
  abstract listEvidence(input: RowEvidenceDto): Promise<EvidenceCollectionDto>;
  abstract listSources(input: SourceWindowDto): Promise<SourceCollectionDto>;
}

@Injectable()
export class SourceProvenanceServiceImpl extends SourceProvenanceService {
  constructor(
    private readonly listEvidenceUseCase: ListEvidenceUseCase,
    private readonly listSourcesUseCase: ListSourcesUseCase,
  ) {
    super();
  }

  listEvidence(input: RowEvidenceDto): Promise<EvidenceCollectionDto> {
    return this.listEvidenceUseCase.execute(input);
  }

  listSources(input: SourceWindowDto): Promise<SourceCollectionDto> {
    return this.listSourcesUseCase.execute(input);
  }
}
