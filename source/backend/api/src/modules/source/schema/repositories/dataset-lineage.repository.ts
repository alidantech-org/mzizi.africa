import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { DatasetLineageEntity } from "#/modules/source/schema/entities/dataset-lineage.entity.ts";
import * as DatasetLineage from "#/modules/source/schema/types/dataset-lineage/index.ts";

/**
 * Repository of Dataset Lineage: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class DatasetLineageRepository
  extends EntityRepository<
    DatasetLineageEntity,
    DatasetLineage.Types.DatasetLineageSortableField,
    DatasetLineage.Types.DatasetLineageEditableField,
    DatasetLineage.Types.DatasetLineageSelectableField,
    DatasetLineage.Types.IDatasetLineageCreatable
  >
  implements
    IUpdatableRepository<DatasetLineageEntity, DatasetLineage.Types.IDatasetLineageUpdatable>
{
  constructor(
    @InjectRepository(DatasetLineageEntity)
    repository: Repository<DatasetLineageEntity>,
  ) {
    super(repository, DatasetLineage.Config.DATASET_LINEAGE_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: DatasetLineage.Types.IDatasetLineageUpdatable,
  ): Promise<DatasetLineageEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find dataset lineage by dataset id, paged by the shared query. */
  async findByDataset(
    query: BaseQueryDto<DatasetLineageEntity>,
    datasetId: NonNullable<DatasetLineageEntity["datasetId"]>,
  ): Promise<IFindAllResponse<DatasetLineageEntity>> {
    return await this.findByQuery(query, { datasetId, deletedAt: IsNull() });
  }

  /** Find dataset lineage by input capture id, paged by the shared query. */
  async findByInputCapture(
    query: BaseQueryDto<DatasetLineageEntity>,
    inputCaptureId: NonNullable<DatasetLineageEntity["inputCaptureId"]>,
  ): Promise<IFindAllResponse<DatasetLineageEntity>> {
    return await this.findByQuery(query, { inputCaptureId, deletedAt: IsNull() });
  }

  /** Find dataset lineage by input dataset id, paged by the shared query. */
  async findByInputDataset(
    query: BaseQueryDto<DatasetLineageEntity>,
    inputDatasetId: NonNullable<DatasetLineageEntity["inputDatasetId"]>,
  ): Promise<IFindAllResponse<DatasetLineageEntity>> {
    return await this.findByQuery(query, { inputDatasetId, deletedAt: IsNull() });
  }

  /** Find dataset lineage by input document id, paged by the shared query. */
  async findByInputDocument(
    query: BaseQueryDto<DatasetLineageEntity>,
    inputDocumentId: NonNullable<DatasetLineageEntity["inputDocumentId"]>,
  ): Promise<IFindAllResponse<DatasetLineageEntity>> {
    return await this.findByQuery(query, { inputDocumentId, deletedAt: IsNull() });
  }

  /** Find dataset lineage by role, paged by the shared query. */
  async findByRole(
    query: BaseQueryDto<DatasetLineageEntity>,
    role: NonNullable<DatasetLineageEntity["role"]>,
  ): Promise<IFindAllResponse<DatasetLineageEntity>> {
    return await this.findByQuery(query, { role, deletedAt: IsNull() });
  }
}
