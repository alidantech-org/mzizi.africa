import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ManifestReleasesEntity } from "#/modules/source/schema/entities/manifest-releases.entity.ts";
import * as ManifestReleases from "#/modules/source/schema/types/manifest-releases/index.ts";

/**
 * Repository of Manifest Releases: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ManifestReleasesRepository
  extends EntityRepository<
    ManifestReleasesEntity,
    ManifestReleases.Types.ManifestReleasesSortableField,
    ManifestReleases.Types.ManifestReleasesEditableField,
    ManifestReleases.Types.ManifestReleasesSelectableField,
    ManifestReleases.Types.IManifestReleasesCreatable
  >
  implements
    IUpdatableRepository<ManifestReleasesEntity, ManifestReleases.Types.IManifestReleasesUpdatable>
{
  constructor(
    @InjectRepository(ManifestReleasesEntity)
    repository: Repository<ManifestReleasesEntity>,
  ) {
    super(repository, ManifestReleases.Config.MANIFEST_RELEASES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: ManifestReleases.Types.IManifestReleasesUpdatable,
  ): Promise<ManifestReleasesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find manifest releases by file version id, paged by the shared query. */
  async findByFileVersion(
    query: BaseQueryDto<ManifestReleasesEntity>,
    fileVersionId: NonNullable<ManifestReleasesEntity["fileVersionId"]>,
  ): Promise<IFindAllResponse<ManifestReleasesEntity>> {
    return await this.findByQuery(query, { fileVersionId, deletedAt: IsNull() });
  }

  /** Find manifest releases by manifest id, paged by the shared query. */
  async findByManifest(
    query: BaseQueryDto<ManifestReleasesEntity>,
    manifestId: NonNullable<ManifestReleasesEntity["manifestId"]>,
  ): Promise<IFindAllResponse<ManifestReleasesEntity>> {
    return await this.findByQuery(query, { manifestId, deletedAt: IsNull() });
  }

  /** Find manifest releases by status, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<ManifestReleasesEntity>,
    status: NonNullable<ManifestReleasesEntity["status"]>,
  ): Promise<IFindAllResponse<ManifestReleasesEntity>> {
    return await this.findByQuery(query, { status, deletedAt: IsNull() });
  }
}
