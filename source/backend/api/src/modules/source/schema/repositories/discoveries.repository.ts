import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { DiscoveriesEntity } from "#/modules/source/schema/entities/discoveries.entity.ts";
import * as Discoveries from "#/modules/source/schema/types/discoveries/index.ts";

/**
 * Repository of Discoveries: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class DiscoveriesRepository
  extends EntityRepository<
    DiscoveriesEntity,
    Discoveries.Types.DiscoveriesSortableField,
    Discoveries.Types.DiscoveriesEditableField,
    Discoveries.Types.DiscoveriesSelectableField,
    Discoveries.Types.IDiscoveriesCreatable
  >
  implements IUpdatableRepository<DiscoveriesEntity, Discoveries.Types.IDiscoveriesUpdatable>
{
  constructor(
    @InjectRepository(DiscoveriesEntity)
    repository: Repository<DiscoveriesEntity>,
  ) {
    super(repository, Discoveries.Config.DISCOVERIES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Discoveries.Types.IDiscoveriesUpdatable,
  ): Promise<DiscoveriesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find discoveries by address id, paged by the shared query. */
  async findByAddress(
    query: BaseQueryDto<DiscoveriesEntity>,
    addressId: NonNullable<DiscoveriesEntity["addressId"]>,
  ): Promise<IFindAllResponse<DiscoveriesEntity>> {
    return await this.findByQuery(query, { addressId, deletedAt: IsNull() });
  }

  /** Find discoveries by found on address id, paged by the shared query. */
  async findByFoundOnAddress(
    query: BaseQueryDto<DiscoveriesEntity>,
    foundOnAddressId: NonNullable<DiscoveriesEntity["foundOnAddressId"]>,
  ): Promise<IFindAllResponse<DiscoveriesEntity>> {
    return await this.findByQuery(query, { foundOnAddressId, deletedAt: IsNull() });
  }

  /** Find discoveries by source id, paged by the shared query. */
  async findBySource(
    query: BaseQueryDto<DiscoveriesEntity>,
    sourceId: NonNullable<DiscoveriesEntity["sourceId"]>,
  ): Promise<IFindAllResponse<DiscoveriesEntity>> {
    return await this.findByQuery(query, { sourceId, deletedAt: IsNull() });
  }
}
