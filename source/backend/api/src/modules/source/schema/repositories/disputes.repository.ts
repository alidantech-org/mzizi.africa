import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { DisputesEntity } from "#/modules/source/schema/entities/disputes.entity.ts";
import * as Disputes from "#/modules/source/schema/types/disputes/index.ts";

/**
 * Repository of Disputes: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class DisputesRepository
  extends EntityRepository<
    DisputesEntity,
    Disputes.Types.DisputesSortableField,
    Disputes.Types.DisputesEditableField,
    Disputes.Types.DisputesSelectableField,
    Disputes.Types.IDisputesCreatable
  >
  implements IUpdatableRepository<DisputesEntity, Disputes.Types.IDisputesUpdatable>
{
  constructor(
    @InjectRepository(DisputesEntity)
    repository: Repository<DisputesEntity>,
  ) {
    super(repository, Disputes.Config.DISPUTES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Disputes.Types.IDisputesUpdatable,
  ): Promise<DisputesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find disputes by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<DisputesEntity>,
    kindId: NonNullable<DisputesEntity["kindId"]>,
  ): Promise<IFindAllResponse<DisputesEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find disputes by resolution citation id, paged by the shared query. */
  async findByResolutionCitation(
    query: BaseQueryDto<DisputesEntity>,
    resolutionCitationId: NonNullable<DisputesEntity["resolutionCitationId"]>,
  ): Promise<IFindAllResponse<DisputesEntity>> {
    return await this.findByQuery(query, { resolutionCitationId, deletedAt: IsNull() });
  }

  /** Find disputes by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<DisputesEntity>,
    statusId: NonNullable<DisputesEntity["statusId"]>,
  ): Promise<IFindAllResponse<DisputesEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }

  /** Find disputes by subject table, paged by the shared query. */
  async findBySubjectTable(
    query: BaseQueryDto<DisputesEntity>,
    subjectTable: NonNullable<DisputesEntity["subjectTable"]>,
  ): Promise<IFindAllResponse<DisputesEntity>> {
    return await this.findByQuery(query, { subjectTable, deletedAt: IsNull() });
  }

  /** Find the disputes with this code (unique). */
  async findByCode(code: NonNullable<DisputesEntity["code"]>): Promise<DisputesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
