import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ContendersEntity } from "#/modules/source/schema/entities/contenders.entity.ts";
import * as Contenders from "#/modules/source/schema/types/contenders/index.ts";

/**
 * Repository of Contenders: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ContendersRepository
  extends EntityRepository<
    ContendersEntity,
    Contenders.Types.ContendersSortableField,
    Contenders.Types.ContendersEditableField,
    Contenders.Types.ContendersSelectableField,
    Contenders.Types.IContendersCreatable
  >
  implements IUpdatableRepository<ContendersEntity, Contenders.Types.IContendersUpdatable>
{
  constructor(
    @InjectRepository(ContendersEntity)
    repository: Repository<ContendersEntity>,
  ) {
    super(repository, Contenders.Config.CONTENDERS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Contenders.Types.IContendersUpdatable,
  ): Promise<ContendersEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find contenders by citation id, paged by the shared query. */
  async findByCitation(
    query: BaseQueryDto<ContendersEntity>,
    citationId: NonNullable<ContendersEntity["citationId"]>,
  ): Promise<IFindAllResponse<ContendersEntity>> {
    return await this.findByQuery(query, { citationId, deletedAt: IsNull() });
  }

  /** Find contenders by dispute id, paged by the shared query. */
  async findByDispute(
    query: BaseQueryDto<ContendersEntity>,
    disputeId: NonNullable<ContendersEntity["disputeId"]>,
  ): Promise<IFindAllResponse<ContendersEntity>> {
    return await this.findByQuery(query, { disputeId, deletedAt: IsNull() });
  }
}
