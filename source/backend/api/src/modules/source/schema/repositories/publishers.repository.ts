import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { PublishersEntity } from "#/modules/source/schema/entities/publishers.entity.ts";
import * as Publishers from "#/modules/source/schema/types/publishers/index.ts";

/**
 * Repository of Publishers: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class PublishersRepository
  extends EntityRepository<
    PublishersEntity,
    Publishers.Types.PublishersSortableField,
    Publishers.Types.PublishersEditableField,
    Publishers.Types.PublishersSelectableField,
    Publishers.Types.IPublishersCreatable
  >
  implements IUpdatableRepository<PublishersEntity, Publishers.Types.IPublishersUpdatable>
{
  constructor(
    @InjectRepository(PublishersEntity)
    repository: Repository<PublishersEntity>,
  ) {
    super(repository, Publishers.Config.PUBLISHERS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Publishers.Types.IPublishersUpdatable,
  ): Promise<PublishersEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find publishers by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<PublishersEntity>,
    countryId: NonNullable<PublishersEntity["countryId"]>,
  ): Promise<IFindAllResponse<PublishersEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find publishers by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<PublishersEntity>,
    kindId: NonNullable<PublishersEntity["kindId"]>,
  ): Promise<IFindAllResponse<PublishersEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find publishers by official entity id, paged by the shared query. */
  async findByOfficialEntity(
    query: BaseQueryDto<PublishersEntity>,
    officialEntityId: NonNullable<PublishersEntity["officialEntityId"]>,
  ): Promise<IFindAllResponse<PublishersEntity>> {
    return await this.findByQuery(query, { officialEntityId, deletedAt: IsNull() });
  }

  /** Find the publishers with this code (unique). */
  async findByCode(code: NonNullable<PublishersEntity["code"]>): Promise<PublishersEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
