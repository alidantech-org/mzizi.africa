import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ArtifactsEntity } from "#/modules/source/schema/entities/artifacts.entity.ts";
import * as Artifacts from "#/modules/source/schema/types/artifacts/index.ts";

/**
 * Repository of Artifacts: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ArtifactsRepository
  extends EntityRepository<
    ArtifactsEntity,
    Artifacts.Types.ArtifactsSortableField,
    Artifacts.Types.ArtifactsEditableField,
    Artifacts.Types.ArtifactsSelectableField,
    Artifacts.Types.IArtifactsCreatable
  >
  implements IUpdatableRepository<ArtifactsEntity, Artifacts.Types.IArtifactsUpdatable>
{
  constructor(
    @InjectRepository(ArtifactsEntity)
    repository: Repository<ArtifactsEntity>,
  ) {
    super(repository, Artifacts.Config.ARTIFACTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Artifacts.Types.IArtifactsUpdatable,
  ): Promise<ArtifactsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find artifacts by edition id, paged by the shared query. */
  async findByEdition(
    query: BaseQueryDto<ArtifactsEntity>,
    editionId: NonNullable<ArtifactsEntity["editionId"]>,
  ): Promise<IFindAllResponse<ArtifactsEntity>> {
    return await this.findByQuery(query, { editionId, deletedAt: IsNull() });
  }

  /** Find artifacts by file version id, paged by the shared query. */
  async findByFileVersion(
    query: BaseQueryDto<ArtifactsEntity>,
    fileVersionId: NonNullable<ArtifactsEntity["fileVersionId"]>,
  ): Promise<IFindAllResponse<ArtifactsEntity>> {
    return await this.findByQuery(query, { fileVersionId, deletedAt: IsNull() });
  }

  /** Find artifacts by parent id, paged by the shared query. */
  async findByParent(
    query: BaseQueryDto<ArtifactsEntity>,
    parentId: NonNullable<ArtifactsEntity["parentId"]>,
  ): Promise<IFindAllResponse<ArtifactsEntity>> {
    return await this.findByQuery(query, { parentId, deletedAt: IsNull() });
  }

  /** Find the artifacts with this code (unique). */
  async findByCode(code: NonNullable<ArtifactsEntity["code"]>): Promise<ArtifactsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
