import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { CoverageEntity } from "#/modules/source/schema/entities/coverage.entity.ts";
import * as Coverage from "#/modules/source/schema/types/coverage/index.ts";

/**
 * Repository of Coverage: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class CoverageRepository
  extends EntityRepository<
    CoverageEntity,
    Coverage.Types.CoverageSortableField,
    Coverage.Types.CoverageEditableField,
    Coverage.Types.CoverageSelectableField,
    Coverage.Types.ICoverageCreatable
  >
  implements IUpdatableRepository<CoverageEntity, Coverage.Types.ICoverageUpdatable>
{
  constructor(
    @InjectRepository(CoverageEntity)
    repository: Repository<CoverageEntity>,
  ) {
    super(repository, Coverage.Config.COVERAGE_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Coverage.Types.ICoverageUpdatable,
  ): Promise<CoverageEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find coverage by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<CoverageEntity>,
    countryId: NonNullable<CoverageEntity["countryId"]>,
  ): Promise<IFindAllResponse<CoverageEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find coverage by coverage subject id, paged by the shared query. */
  async findByCoverageSubject(
    query: BaseQueryDto<CoverageEntity>,
    coverageSubjectId: NonNullable<CoverageEntity["coverageSubjectId"]>,
  ): Promise<IFindAllResponse<CoverageEntity>> {
    return await this.findByQuery(query, { coverageSubjectId, deletedAt: IsNull() });
  }

  /** Find coverage by level id, paged by the shared query. */
  async findByLevel(
    query: BaseQueryDto<CoverageEntity>,
    levelId: NonNullable<CoverageEntity["levelId"]>,
  ): Promise<IFindAllResponse<CoverageEntity>> {
    return await this.findByQuery(query, { levelId, deletedAt: IsNull() });
  }

  /** Find coverage by product id, paged by the shared query. */
  async findByProduct(
    query: BaseQueryDto<CoverageEntity>,
    productId: NonNullable<CoverageEntity["productId"]>,
  ): Promise<IFindAllResponse<CoverageEntity>> {
    return await this.findByQuery(query, { productId, deletedAt: IsNull() });
  }

  /** Find coverage by publisher entity id, paged by the shared query. */
  async findByPublisherEntity(
    query: BaseQueryDto<CoverageEntity>,
    publisherEntityId: NonNullable<CoverageEntity["publisherEntityId"]>,
  ): Promise<IFindAllResponse<CoverageEntity>> {
    return await this.findByQuery(query, { publisherEntityId, deletedAt: IsNull() });
  }

  /** Find coverage by scope unit feature id, paged by the shared query. */
  async findByScopeUnitFeature(
    query: BaseQueryDto<CoverageEntity>,
    scopeUnitFeatureId: NonNullable<CoverageEntity["scopeUnitFeatureId"]>,
  ): Promise<IFindAllResponse<CoverageEntity>> {
    return await this.findByQuery(query, { scopeUnitFeatureId, deletedAt: IsNull() });
  }

  /** Find coverage by source id, paged by the shared query. */
  async findBySource(
    query: BaseQueryDto<CoverageEntity>,
    sourceId: NonNullable<CoverageEntity["sourceId"]>,
  ): Promise<IFindAllResponse<CoverageEntity>> {
    return await this.findByQuery(query, { sourceId, deletedAt: IsNull() });
  }

  /** Find the coverage with this code (unique). */
  async findByCode(code: NonNullable<CoverageEntity["code"]>): Promise<CoverageEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
