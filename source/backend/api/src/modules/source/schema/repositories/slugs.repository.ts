import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { SlugsEntity } from "#/modules/source/schema/entities/slugs.entity.ts";
import * as Slugs from "#/modules/source/schema/types/slugs/index.ts";

/**
 * Repository of Slugs: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class SlugsRepository
  extends EntityRepository<
    SlugsEntity,
    Slugs.Types.SlugsSortableField,
    Slugs.Types.SlugsEditableField,
    Slugs.Types.SlugsSelectableField,
    Slugs.Types.ISlugsCreatable
  >
  implements IUpdatableRepository<SlugsEntity, Slugs.Types.ISlugsUpdatable>
{
  constructor(
    @InjectRepository(SlugsEntity)
    repository: Repository<SlugsEntity>,
  ) {
    super(repository, Slugs.Config.SLUGS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Slugs.Types.ISlugsUpdatable): Promise<SlugsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find slugs by canonical slug id, paged by the shared query. */
  async findByCanonicalSlug(
    query: BaseQueryDto<SlugsEntity>,
    canonicalSlugId: NonNullable<SlugsEntity["canonicalSlugId"]>,
  ): Promise<IFindAllResponse<SlugsEntity>> {
    return await this.findByQuery(query, { canonicalSlugId, deletedAt: IsNull() });
  }

  /** Find slugs by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<SlugsEntity>,
    countryId: NonNullable<SlugsEntity["countryId"]>,
  ): Promise<IFindAllResponse<SlugsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find slugs by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<SlugsEntity>,
    fromToPrecision: NonNullable<SlugsEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<SlugsEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find slugs by language id, paged by the shared query. */
  async findByLanguage(
    query: BaseQueryDto<SlugsEntity>,
    languageId: NonNullable<SlugsEntity["languageId"]>,
  ): Promise<IFindAllResponse<SlugsEntity>> {
    return await this.findByQuery(query, { languageId, deletedAt: IsNull() });
  }

  /** Find slugs by namespace id, paged by the shared query. */
  async findByNamespace(
    query: BaseQueryDto<SlugsEntity>,
    namespaceId: NonNullable<SlugsEntity["namespaceId"]>,
  ): Promise<IFindAllResponse<SlugsEntity>> {
    return await this.findByQuery(query, { namespaceId, deletedAt: IsNull() });
  }

  /** Find slugs by parent slug id, paged by the shared query. */
  async findByParentSlug(
    query: BaseQueryDto<SlugsEntity>,
    parentSlugId: NonNullable<SlugsEntity["parentSlugId"]>,
  ): Promise<IFindAllResponse<SlugsEntity>> {
    return await this.findByQuery(query, { parentSlugId, deletedAt: IsNull() });
  }

  /** Find slugs by subject table, paged by the shared query. */
  async findBySubjectTable(
    query: BaseQueryDto<SlugsEntity>,
    subjectTable: NonNullable<SlugsEntity["subjectTable"]>,
  ): Promise<IFindAllResponse<SlugsEntity>> {
    return await this.findByQuery(query, { subjectTable, deletedAt: IsNull() });
  }

  /** Find the slugs with this code (unique). */
  async findByCode(code: NonNullable<SlugsEntity["code"]>): Promise<SlugsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
