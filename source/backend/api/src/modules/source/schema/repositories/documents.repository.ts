import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { DocumentsEntity } from "#/modules/source/schema/entities/documents.entity.ts";
import * as Documents from "#/modules/source/schema/types/documents/index.ts";

/**
 * Repository of Documents: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class DocumentsRepository
  extends EntityRepository<
    DocumentsEntity,
    Documents.Types.DocumentsSortableField,
    Documents.Types.DocumentsEditableField,
    Documents.Types.DocumentsSelectableField,
    Documents.Types.IDocumentsCreatable
  >
  implements IUpdatableRepository<DocumentsEntity, Documents.Types.IDocumentsUpdatable>
{
  constructor(
    @InjectRepository(DocumentsEntity)
    repository: Repository<DocumentsEntity>,
  ) {
    super(repository, Documents.Config.DOCUMENTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Documents.Types.IDocumentsUpdatable,
  ): Promise<DocumentsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find documents by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<DocumentsEntity>,
    kindId: NonNullable<DocumentsEntity["kindId"]>,
  ): Promise<IFindAllResponse<DocumentsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find documents by publisher id, paged by the shared query. */
  async findByPublisher(
    query: BaseQueryDto<DocumentsEntity>,
    publisherId: NonNullable<DocumentsEntity["publisherId"]>,
  ): Promise<IFindAllResponse<DocumentsEntity>> {
    return await this.findByQuery(query, { publisherId, deletedAt: IsNull() });
  }

  /** Find documents by source id, paged by the shared query. */
  async findBySource(
    query: BaseQueryDto<DocumentsEntity>,
    sourceId: NonNullable<DocumentsEntity["sourceId"]>,
  ): Promise<IFindAllResponse<DocumentsEntity>> {
    return await this.findByQuery(query, { sourceId, deletedAt: IsNull() });
  }

  /** Find the documents with this code (unique). */
  async findByCode(code: NonNullable<DocumentsEntity["code"]>): Promise<DocumentsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
