import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { SourcesEntity } from "#/modules/source/schema/entities/sources.entity.ts";
import * as Sources from "#/modules/source/schema/types/sources/index.ts";

/**
 * Repository of Sources: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class SourcesRepository
  extends EntityRepository<
    SourcesEntity,
    Sources.Types.SourcesSortableField,
    Sources.Types.SourcesEditableField,
    Sources.Types.SourcesSelectableField,
    Sources.Types.ISourcesCreatable
  >
  implements IUpdatableRepository<SourcesEntity, Sources.Types.ISourcesUpdatable>
{
  constructor(
    @InjectRepository(SourcesEntity)
    repository: Repository<SourcesEntity>,
  ) {
    super(repository, Sources.Config.SOURCES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Sources.Types.ISourcesUpdatable,
  ): Promise<SourcesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find sources by classification id, paged by the shared query. */
  async findByClassification(
    query: BaseQueryDto<SourcesEntity>,
    classificationId: NonNullable<SourcesEntity["classificationId"]>,
  ): Promise<IFindAllResponse<SourcesEntity>> {
    return await this.findByQuery(query, { classificationId, deletedAt: IsNull() });
  }

  /** Find sources by credibility id, paged by the shared query. */
  async findByCredibility(
    query: BaseQueryDto<SourcesEntity>,
    credibilityId: NonNullable<SourcesEntity["credibilityId"]>,
  ): Promise<IFindAllResponse<SourcesEntity>> {
    return await this.findByQuery(query, { credibilityId, deletedAt: IsNull() });
  }

  /** Find sources by kind, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<SourcesEntity>,
    kind: NonNullable<SourcesEntity["kind"]>,
  ): Promise<IFindAllResponse<SourcesEntity>> {
    return await this.findByQuery(query, { kind, deletedAt: IsNull() });
  }

  /** Find sources by licence id, paged by the shared query. */
  async findByLicence(
    query: BaseQueryDto<SourcesEntity>,
    licenceId: NonNullable<SourcesEntity["licenceId"]>,
  ): Promise<IFindAllResponse<SourcesEntity>> {
    return await this.findByQuery(query, { licenceId, deletedAt: IsNull() });
  }

  /** Find sources by official entity id, paged by the shared query. */
  async findByOfficialEntity(
    query: BaseQueryDto<SourcesEntity>,
    officialEntityId: NonNullable<SourcesEntity["officialEntityId"]>,
  ): Promise<IFindAllResponse<SourcesEntity>> {
    return await this.findByQuery(query, { officialEntityId, deletedAt: IsNull() });
  }

  /** Find sources by publisher id, paged by the shared query. */
  async findByPublisher(
    query: BaseQueryDto<SourcesEntity>,
    publisherId: NonNullable<SourcesEntity["publisherId"]>,
  ): Promise<IFindAllResponse<SourcesEntity>> {
    return await this.findByQuery(query, { publisherId, deletedAt: IsNull() });
  }

  /** Find the sources with this code (unique). */
  async findByCode(code: NonNullable<SourcesEntity["code"]>): Promise<SourcesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
