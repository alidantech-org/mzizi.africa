import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { VerificationsEntity } from "#/modules/source/schema/entities/verifications.entity.ts";
import * as Verifications from "#/modules/source/schema/types/verifications/index.ts";

/**
 * Repository of Verifications: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class VerificationsRepository
  extends EntityRepository<
    VerificationsEntity,
    Verifications.Types.VerificationsSortableField,
    Verifications.Types.VerificationsEditableField,
    Verifications.Types.VerificationsSelectableField,
    Verifications.Types.IVerificationsCreatable
  >
  implements IUpdatableRepository<VerificationsEntity, Verifications.Types.IVerificationsUpdatable>
{
  constructor(
    @InjectRepository(VerificationsEntity)
    repository: Repository<VerificationsEntity>,
  ) {
    super(repository, Verifications.Config.VERIFICATIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Verifications.Types.IVerificationsUpdatable,
  ): Promise<VerificationsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find verifications by evidence id, paged by the shared query. */
  async findByEvidence(
    query: BaseQueryDto<VerificationsEntity>,
    evidenceId: NonNullable<VerificationsEntity["evidenceId"]>,
  ): Promise<IFindAllResponse<VerificationsEntity>> {
    return await this.findByQuery(query, { evidenceId, deletedAt: IsNull() });
  }

  /** Find verifications by method id, paged by the shared query. */
  async findByMethod(
    query: BaseQueryDto<VerificationsEntity>,
    methodId: NonNullable<VerificationsEntity["methodId"]>,
  ): Promise<IFindAllResponse<VerificationsEntity>> {
    return await this.findByQuery(query, { methodId, deletedAt: IsNull() });
  }

  /** Find verifications by outcome, paged by the shared query. */
  async findByOutcome(
    query: BaseQueryDto<VerificationsEntity>,
    outcome: NonNullable<VerificationsEntity["outcome"]>,
  ): Promise<IFindAllResponse<VerificationsEntity>> {
    return await this.findByQuery(query, { outcome, deletedAt: IsNull() });
  }

  /** Find verifications by supersedes id, paged by the shared query. */
  async findBySupersedes(
    query: BaseQueryDto<VerificationsEntity>,
    supersedesId: NonNullable<VerificationsEntity["supersedesId"]>,
  ): Promise<IFindAllResponse<VerificationsEntity>> {
    return await this.findByQuery(query, { supersedesId, deletedAt: IsNull() });
  }

  /** Find the verifications with this code (unique). */
  async findByCode(
    code: NonNullable<VerificationsEntity["code"]>,
  ): Promise<VerificationsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
