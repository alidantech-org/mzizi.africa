import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { SourceDatasetsEntity } from "#/modules/source/schema/entities/datasets.entity.ts";
import * as Datasets from "#/modules/source/schema/types/datasets/index.ts";

/**
 * Repository of Datasets: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class DatasetsRepository
  extends EntityRepository<
    SourceDatasetsEntity,
    Datasets.Types.DatasetsSortableField,
    Datasets.Types.DatasetsEditableField,
    Datasets.Types.DatasetsSelectableField,
    Datasets.Types.IDatasetsCreatable
  >
  implements IUpdatableRepository<SourceDatasetsEntity, Datasets.Types.IDatasetsUpdatable>
{
  constructor(
    @InjectRepository(SourceDatasetsEntity)
    repository: Repository<SourceDatasetsEntity>,
  ) {
    super(repository, Datasets.Config.DATASETS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Datasets.Types.IDatasetsUpdatable,
  ): Promise<SourceDatasetsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find datasets by assembly, paged by the shared query. */
  async findByAssembly(
    query: BaseQueryDto<SourceDatasetsEntity>,
    assembly: NonNullable<SourceDatasetsEntity["assembly"]>,
  ): Promise<IFindAllResponse<SourceDatasetsEntity>> {
    return await this.findByQuery(query, { assembly, deletedAt: IsNull() });
  }

  /** Find datasets by category id, paged by the shared query. */
  async findByCategory(
    query: BaseQueryDto<SourceDatasetsEntity>,
    categoryId: NonNullable<SourceDatasetsEntity["categoryId"]>,
  ): Promise<IFindAllResponse<SourceDatasetsEntity>> {
    return await this.findByQuery(query, { categoryId, deletedAt: IsNull() });
  }

  /** Find datasets by file version id, paged by the shared query. */
  async findByFileVersion(
    query: BaseQueryDto<SourceDatasetsEntity>,
    fileVersionId: NonNullable<SourceDatasetsEntity["fileVersionId"]>,
  ): Promise<IFindAllResponse<SourceDatasetsEntity>> {
    return await this.findByQuery(query, { fileVersionId, deletedAt: IsNull() });
  }

  /** Find the datasets with this code (unique). */
  async findByCode(
    code: NonNullable<SourceDatasetsEntity["code"]>,
  ): Promise<SourceDatasetsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
