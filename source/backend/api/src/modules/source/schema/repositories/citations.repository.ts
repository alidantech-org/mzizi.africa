import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { CitationsEntity } from "#/modules/source/schema/entities/citations.entity.ts";
import * as Citations from "#/modules/source/schema/types/citations/index.ts";

/**
 * Repository of Citations: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class CitationsRepository
  extends EntityRepository<
    CitationsEntity,
    Citations.Types.CitationsSortableField,
    Citations.Types.CitationsEditableField,
    Citations.Types.CitationsSelectableField,
    Citations.Types.ICitationsCreatable
  >
  implements IUpdatableRepository<CitationsEntity, Citations.Types.ICitationsUpdatable>
{
  constructor(
    @InjectRepository(CitationsEntity)
    repository: Repository<CitationsEntity>,
  ) {
    super(repository, Citations.Config.CITATIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Citations.Types.ICitationsUpdatable,
  ): Promise<CitationsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find citations by address id, paged by the shared query. */
  async findByAddress(
    query: BaseQueryDto<CitationsEntity>,
    addressId: NonNullable<CitationsEntity["addressId"]>,
  ): Promise<IFindAllResponse<CitationsEntity>> {
    return await this.findByQuery(query, { addressId, deletedAt: IsNull() });
  }

  /** Find citations by artifact id, paged by the shared query. */
  async findByArtifact(
    query: BaseQueryDto<CitationsEntity>,
    artifactId: NonNullable<CitationsEntity["artifactId"]>,
  ): Promise<IFindAllResponse<CitationsEntity>> {
    return await this.findByQuery(query, { artifactId, deletedAt: IsNull() });
  }

  /** Find citations by capture id, paged by the shared query. */
  async findByCapture(
    query: BaseQueryDto<CitationsEntity>,
    captureId: NonNullable<CitationsEntity["captureId"]>,
  ): Promise<IFindAllResponse<CitationsEntity>> {
    return await this.findByQuery(query, { captureId, deletedAt: IsNull() });
  }

  /** Find citations by locator kind id, paged by the shared query. */
  async findByLocatorKind(
    query: BaseQueryDto<CitationsEntity>,
    locatorKindId: NonNullable<CitationsEntity["locatorKindId"]>,
  ): Promise<IFindAllResponse<CitationsEntity>> {
    return await this.findByQuery(query, { locatorKindId, deletedAt: IsNull() });
  }

  /** Find citations by subject table, paged by the shared query. */
  async findBySubjectTable(
    query: BaseQueryDto<CitationsEntity>,
    subjectTable: NonNullable<CitationsEntity["subjectTable"]>,
  ): Promise<IFindAllResponse<CitationsEntity>> {
    return await this.findByQuery(query, { subjectTable, deletedAt: IsNull() });
  }

  /** Find the citations with this code (unique). */
  async findByCode(code: NonNullable<CitationsEntity["code"]>): Promise<CitationsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
