import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ManifestBindingsEntity } from "#/modules/source/schema/entities/manifest-bindings.entity.ts";
import * as ManifestBindings from "#/modules/source/schema/types/manifest-bindings/index.ts";

/**
 * Repository of Manifest Bindings: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ManifestBindingsRepository
  extends EntityRepository<
    ManifestBindingsEntity,
    ManifestBindings.Types.ManifestBindingsSortableField,
    ManifestBindings.Types.ManifestBindingsEditableField,
    ManifestBindings.Types.ManifestBindingsSelectableField,
    ManifestBindings.Types.IManifestBindingsCreatable
  >
  implements
    IUpdatableRepository<ManifestBindingsEntity, ManifestBindings.Types.IManifestBindingsUpdatable>
{
  constructor(
    @InjectRepository(ManifestBindingsEntity)
    repository: Repository<ManifestBindingsEntity>,
  ) {
    super(repository, ManifestBindings.Config.MANIFEST_BINDINGS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: ManifestBindings.Types.IManifestBindingsUpdatable,
  ): Promise<ManifestBindingsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find manifest bindings by manifest release id, paged by the shared query. */
  async findByManifestRelease(
    query: BaseQueryDto<ManifestBindingsEntity>,
    manifestReleaseId: NonNullable<ManifestBindingsEntity["manifestReleaseId"]>,
  ): Promise<IFindAllResponse<ManifestBindingsEntity>> {
    return await this.findByQuery(query, { manifestReleaseId, deletedAt: IsNull() });
  }

  /** Find manifest bindings by source id, paged by the shared query. */
  async findBySource(
    query: BaseQueryDto<ManifestBindingsEntity>,
    sourceId: NonNullable<ManifestBindingsEntity["sourceId"]>,
  ): Promise<IFindAllResponse<ManifestBindingsEntity>> {
    return await this.findByQuery(query, { sourceId, deletedAt: IsNull() });
  }
}
