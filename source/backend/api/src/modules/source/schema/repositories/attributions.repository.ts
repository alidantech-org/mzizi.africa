import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { AttributionsEntity } from "#/modules/source/schema/entities/attributions.entity.ts";
import * as Attributions from "#/modules/source/schema/types/attributions/index.ts";

/**
 * Repository of Attributions: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class AttributionsRepository
  extends EntityRepository<
    AttributionsEntity,
    Attributions.Types.AttributionsSortableField,
    Attributions.Types.AttributionsEditableField,
    Attributions.Types.AttributionsSelectableField,
    Attributions.Types.IAttributionsCreatable
  >
  implements IUpdatableRepository<AttributionsEntity, Attributions.Types.IAttributionsUpdatable>
{
  constructor(
    @InjectRepository(AttributionsEntity)
    repository: Repository<AttributionsEntity>,
  ) {
    super(repository, Attributions.Config.ATTRIBUTIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Attributions.Types.IAttributionsUpdatable,
  ): Promise<AttributionsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find attributions by file version id, paged by the shared query. */
  async findByFileVersion(
    query: BaseQueryDto<AttributionsEntity>,
    fileVersionId: NonNullable<AttributionsEntity["fileVersionId"]>,
  ): Promise<IFindAllResponse<AttributionsEntity>> {
    return await this.findByQuery(query, { fileVersionId, deletedAt: IsNull() });
  }

  /** Find attributions by license value id, paged by the shared query. */
  async findByLicenseValue(
    query: BaseQueryDto<AttributionsEntity>,
    licenseValueId: NonNullable<AttributionsEntity["licenseValueId"]>,
  ): Promise<IFindAllResponse<AttributionsEntity>> {
    return await this.findByQuery(query, { licenseValueId, deletedAt: IsNull() });
  }

  /** Find attributions by publisher id, paged by the shared query. */
  async findByPublisher(
    query: BaseQueryDto<AttributionsEntity>,
    publisherId: NonNullable<AttributionsEntity["publisherId"]>,
  ): Promise<IFindAllResponse<AttributionsEntity>> {
    return await this.findByQuery(query, { publisherId, deletedAt: IsNull() });
  }

  /** Find the attributions with this code (unique). */
  async findByCode(
    code: NonNullable<AttributionsEntity["code"]>,
  ): Promise<AttributionsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
