import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { DomainsEntity } from "#/modules/source/schema/entities/domains.entity.ts";
import * as Domains from "#/modules/source/schema/types/domains/index.ts";

/**
 * Repository of Domains: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class DomainsRepository
  extends EntityRepository<
    DomainsEntity,
    Domains.Types.DomainsSortableField,
    Domains.Types.DomainsEditableField,
    Domains.Types.DomainsSelectableField,
    Domains.Types.IDomainsCreatable
  >
  implements IUpdatableRepository<DomainsEntity, Domains.Types.IDomainsUpdatable>
{
  constructor(
    @InjectRepository(DomainsEntity)
    repository: Repository<DomainsEntity>,
  ) {
    super(repository, Domains.Config.DOMAINS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Domains.Types.IDomainsUpdatable,
  ): Promise<DomainsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find domains by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<DomainsEntity>,
    fromToPrecision: NonNullable<DomainsEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<DomainsEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find domains by source id, paged by the shared query. */
  async findBySource(
    query: BaseQueryDto<DomainsEntity>,
    sourceId: NonNullable<DomainsEntity["sourceId"]>,
  ): Promise<IFindAllResponse<DomainsEntity>> {
    return await this.findByQuery(query, { sourceId, deletedAt: IsNull() });
  }

  /** Find the domains with this code (unique). */
  async findByCode(code: NonNullable<DomainsEntity["code"]>): Promise<DomainsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }

  /** Find the domains with this host (unique). */
  async findByHost(host: NonNullable<DomainsEntity["host"]>): Promise<DomainsEntity | null> {
    return await this.findOne({ host, deletedAt: IsNull() });
  }
}
