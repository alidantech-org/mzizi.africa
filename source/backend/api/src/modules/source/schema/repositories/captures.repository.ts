import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { CapturesEntity } from "#/modules/source/schema/entities/captures.entity.ts";
import * as Captures from "#/modules/source/schema/types/captures/index.ts";

/**
 * Repository of Captures: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class CapturesRepository
  extends EntityRepository<
    CapturesEntity,
    Captures.Types.CapturesSortableField,
    Captures.Types.CapturesEditableField,
    Captures.Types.CapturesSelectableField,
    Captures.Types.ICapturesCreatable
  >
  implements IUpdatableRepository<CapturesEntity, Captures.Types.ICapturesUpdatable>
{
  constructor(
    @InjectRepository(CapturesEntity)
    repository: Repository<CapturesEntity>,
  ) {
    super(repository, Captures.Config.CAPTURES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Captures.Types.ICapturesUpdatable,
  ): Promise<CapturesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find captures by document id, paged by the shared query. */
  async findByDocument(
    query: BaseQueryDto<CapturesEntity>,
    documentId: NonNullable<CapturesEntity["documentId"]>,
  ): Promise<IFindAllResponse<CapturesEntity>> {
    return await this.findByQuery(query, { documentId, deletedAt: IsNull() });
  }

  /** Find captures by manifest release id, paged by the shared query. */
  async findByManifestRelease(
    query: BaseQueryDto<CapturesEntity>,
    manifestReleaseId: NonNullable<CapturesEntity["manifestReleaseId"]>,
  ): Promise<IFindAllResponse<CapturesEntity>> {
    return await this.findByQuery(query, { manifestReleaseId, deletedAt: IsNull() });
  }

  /** Find captures by path id, paged by the shared query. */
  async findByPath(
    query: BaseQueryDto<CapturesEntity>,
    pathId: NonNullable<CapturesEntity["pathId"]>,
  ): Promise<IFindAllResponse<CapturesEntity>> {
    return await this.findByQuery(query, { pathId, deletedAt: IsNull() });
  }

  /** Find captures by source id, paged by the shared query. */
  async findBySource(
    query: BaseQueryDto<CapturesEntity>,
    sourceId: NonNullable<CapturesEntity["sourceId"]>,
  ): Promise<IFindAllResponse<CapturesEntity>> {
    return await this.findByQuery(query, { sourceId, deletedAt: IsNull() });
  }

  /** Find the captures with this code (unique). */
  async findByCode(code: NonNullable<CapturesEntity["code"]>): Promise<CapturesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
