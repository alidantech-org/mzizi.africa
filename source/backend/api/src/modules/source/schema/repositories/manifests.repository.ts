import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ManifestsEntity } from "#/modules/source/schema/entities/manifests.entity.ts";
import * as Manifests from "#/modules/source/schema/types/manifests/index.ts";

/**
 * Repository of Manifests: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ManifestsRepository
  extends EntityRepository<
    ManifestsEntity,
    Manifests.Types.ManifestsSortableField,
    Manifests.Types.ManifestsEditableField,
    Manifests.Types.ManifestsSelectableField,
    Manifests.Types.IManifestsCreatable
  >
  implements IUpdatableRepository<ManifestsEntity, Manifests.Types.IManifestsUpdatable>
{
  constructor(
    @InjectRepository(ManifestsEntity)
    repository: Repository<ManifestsEntity>,
  ) {
    super(repository, Manifests.Config.MANIFESTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Manifests.Types.IManifestsUpdatable,
  ): Promise<ManifestsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find manifests by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<ManifestsEntity>,
    kindId: NonNullable<ManifestsEntity["kindId"]>,
  ): Promise<IFindAllResponse<ManifestsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find the manifests with this code (unique). */
  async findByCode(code: NonNullable<ManifestsEntity["code"]>): Promise<ManifestsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
