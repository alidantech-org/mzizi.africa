import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ProductsEntity } from "#/modules/source/schema/entities/products.entity.ts";
import * as Products from "#/modules/source/schema/types/products/index.ts";

/**
 * Repository of Products: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ProductsRepository
  extends EntityRepository<
    ProductsEntity,
    Products.Types.ProductsSortableField,
    Products.Types.ProductsEditableField,
    Products.Types.ProductsSelectableField,
    Products.Types.IProductsCreatable
  >
  implements IUpdatableRepository<ProductsEntity, Products.Types.IProductsUpdatable>
{
  constructor(
    @InjectRepository(ProductsEntity)
    repository: Repository<ProductsEntity>,
  ) {
    super(repository, Products.Config.PRODUCTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Products.Types.IProductsUpdatable,
  ): Promise<ProductsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find products by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<ProductsEntity>,
    kindId: NonNullable<ProductsEntity["kindId"]>,
  ): Promise<IFindAllResponse<ProductsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find products by publisher id, paged by the shared query. */
  async findByPublisher(
    query: BaseQueryDto<ProductsEntity>,
    publisherId: NonNullable<ProductsEntity["publisherId"]>,
  ): Promise<IFindAllResponse<ProductsEntity>> {
    return await this.findByQuery(query, { publisherId, deletedAt: IsNull() });
  }

  /** Find the products with this code (unique). */
  async findByCode(code: NonNullable<ProductsEntity["code"]>): Promise<ProductsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
