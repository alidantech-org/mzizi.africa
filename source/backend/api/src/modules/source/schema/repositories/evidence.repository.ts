import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { EvidenceEntity } from "#/modules/source/schema/entities/evidence.entity.ts";
import * as Evidence from "#/modules/source/schema/types/evidence/index.ts";

/**
 * Repository of Evidence: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class EvidenceRepository
  extends EntityRepository<
    EvidenceEntity,
    Evidence.Types.EvidenceSortableField,
    Evidence.Types.EvidenceEditableField,
    Evidence.Types.EvidenceSelectableField,
    Evidence.Types.IEvidenceCreatable
  >
  implements IUpdatableRepository<EvidenceEntity, Evidence.Types.IEvidenceUpdatable>
{
  constructor(
    @InjectRepository(EvidenceEntity)
    repository: Repository<EvidenceEntity>,
  ) {
    super(repository, Evidence.Config.EVIDENCE_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Evidence.Types.IEvidenceUpdatable,
  ): Promise<EvidenceEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find evidence by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<EvidenceEntity>,
    kindId: NonNullable<EvidenceEntity["kindId"]>,
  ): Promise<IFindAllResponse<EvidenceEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find the evidence with this code (unique). */
  async findByCode(code: NonNullable<EvidenceEntity["code"]>): Promise<EvidenceEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
