import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { PathsEntity } from "#/modules/source/schema/entities/paths.entity.ts";
import * as Paths from "#/modules/source/schema/types/paths/index.ts";

/**
 * Repository of Paths: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class PathsRepository
  extends EntityRepository<
    PathsEntity,
    Paths.Types.PathsSortableField,
    Paths.Types.PathsEditableField,
    Paths.Types.PathsSelectableField,
    Paths.Types.IPathsCreatable
  >
  implements IUpdatableRepository<PathsEntity, Paths.Types.IPathsUpdatable>
{
  constructor(
    @InjectRepository(PathsEntity)
    repository: Repository<PathsEntity>,
  ) {
    super(repository, Paths.Config.PATHS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Paths.Types.IPathsUpdatable): Promise<PathsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find paths by domain id, paged by the shared query. */
  async findByDomain(
    query: BaseQueryDto<PathsEntity>,
    domainId: NonNullable<PathsEntity["domainId"]>,
  ): Promise<IFindAllResponse<PathsEntity>> {
    return await this.findByQuery(query, { domainId, deletedAt: IsNull() });
  }

  /** Find paths by kind, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<PathsEntity>,
    kind: NonNullable<PathsEntity["kind"]>,
  ): Promise<IFindAllResponse<PathsEntity>> {
    return await this.findByQuery(query, { kind, deletedAt: IsNull() });
  }

  /** Find paths by method, paged by the shared query. */
  async findByMethod(
    query: BaseQueryDto<PathsEntity>,
    method: NonNullable<PathsEntity["method"]>,
  ): Promise<IFindAllResponse<PathsEntity>> {
    return await this.findByQuery(query, { method, deletedAt: IsNull() });
  }

  /** Find the paths with this code (unique). */
  async findByCode(code: NonNullable<PathsEntity["code"]>): Promise<PathsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
