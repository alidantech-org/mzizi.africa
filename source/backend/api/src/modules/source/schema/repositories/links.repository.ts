import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { LinksEntity } from "#/modules/source/schema/entities/links.entity.ts";
import * as Links from "#/modules/source/schema/types/links/index.ts";

/**
 * Repository of Links: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class LinksRepository
  extends EntityRepository<
    LinksEntity,
    Links.Types.LinksSortableField,
    Links.Types.LinksEditableField,
    Links.Types.LinksSelectableField,
    Links.Types.ILinksCreatable
  >
  implements IUpdatableRepository<LinksEntity, Links.Types.ILinksUpdatable>
{
  constructor(
    @InjectRepository(LinksEntity)
    repository: Repository<LinksEntity>,
  ) {
    super(repository, Links.Config.LINKS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Links.Types.ILinksUpdatable): Promise<LinksEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find links by from slug id, paged by the shared query. */
  async findByFromSlug(
    query: BaseQueryDto<LinksEntity>,
    fromSlugId: NonNullable<LinksEntity["fromSlugId"]>,
  ): Promise<IFindAllResponse<LinksEntity>> {
    return await this.findByQuery(query, { fromSlugId, deletedAt: IsNull() });
  }

  /** Find links by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<LinksEntity>,
    fromToPrecision: NonNullable<LinksEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<LinksEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find links by relation kind id, paged by the shared query. */
  async findByRelationKind(
    query: BaseQueryDto<LinksEntity>,
    relationKindId: NonNullable<LinksEntity["relationKindId"]>,
  ): Promise<IFindAllResponse<LinksEntity>> {
    return await this.findByQuery(query, { relationKindId, deletedAt: IsNull() });
  }

  /** Find links by to slug id, paged by the shared query. */
  async findByToSlug(
    query: BaseQueryDto<LinksEntity>,
    toSlugId: NonNullable<LinksEntity["toSlugId"]>,
  ): Promise<IFindAllResponse<LinksEntity>> {
    return await this.findByQuery(query, { toSlugId, deletedAt: IsNull() });
  }
}
