import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ProvenanceEntity } from "#/modules/source/schema/entities/provenance.entity.ts";
import * as Provenance from "#/modules/source/schema/types/provenance/index.ts";

/**
 * Repository of Provenance: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ProvenanceRepository
  extends EntityRepository<
    ProvenanceEntity,
    Provenance.Types.ProvenanceSortableField,
    Provenance.Types.ProvenanceEditableField,
    Provenance.Types.ProvenanceSelectableField,
    Provenance.Types.IProvenanceCreatable
  >
  implements IUpdatableRepository<ProvenanceEntity, Provenance.Types.IProvenanceUpdatable>
{
  constructor(
    @InjectRepository(ProvenanceEntity)
    repository: Repository<ProvenanceEntity>,
  ) {
    super(repository, Provenance.Config.PROVENANCE_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Provenance.Types.IProvenanceUpdatable,
  ): Promise<ProvenanceEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find provenance by capture id, paged by the shared query. */
  async findByCapture(
    query: BaseQueryDto<ProvenanceEntity>,
    captureId: NonNullable<ProvenanceEntity["captureId"]>,
  ): Promise<IFindAllResponse<ProvenanceEntity>> {
    return await this.findByQuery(query, { captureId, deletedAt: IsNull() });
  }

  /** Find provenance by dataset id, paged by the shared query. */
  async findByDataset(
    query: BaseQueryDto<ProvenanceEntity>,
    datasetId: NonNullable<ProvenanceEntity["datasetId"]>,
  ): Promise<IFindAllResponse<ProvenanceEntity>> {
    return await this.findByQuery(query, { datasetId, deletedAt: IsNull() });
  }

  /** Find provenance by document id, paged by the shared query. */
  async findByDocument(
    query: BaseQueryDto<ProvenanceEntity>,
    documentId: NonNullable<ProvenanceEntity["documentId"]>,
  ): Promise<IFindAllResponse<ProvenanceEntity>> {
    return await this.findByQuery(query, { documentId, deletedAt: IsNull() });
  }
}
