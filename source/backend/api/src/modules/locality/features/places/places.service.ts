import { Injectable } from "@nestjs/common";
import type { CitationInputDto } from "#/modules/locality/schema/dto/citation-input.dto.ts";
import type { EvidenceDetailDto } from "#/modules/locality/schema/dto/evidence-detail.dto.ts";
import type { LanguageListDto } from "#/modules/locality/schema/dto/language-list.dto.ts";
import type { LocalityMatchesDto } from "#/modules/locality/schema/dto/locality-matches.dto.ts";
import type { LocalityProfileDto } from "#/modules/locality/schema/dto/locality-profile.dto.ts";
import type { PlaceInputDto } from "#/modules/locality/schema/dto/place-input.dto.ts";
import type { PositionInputDto } from "#/modules/locality/schema/dto/position-input.dto.ts";
import type { SearchInputDto } from "#/modules/locality/schema/dto/search-input.dto.ts";
import type { SourceCollectionDto } from "#/modules/locality/schema/dto/source-collection.dto.ts";
import type { SourceSearchInputDto } from "#/modules/locality/schema/dto/source-search-input.dto.ts";
import { BrowseSourcesUseCase } from "#/modules/locality/features/places/use-cases/browse-sources.usecase.ts";
import { GetEvidenceUseCase } from "#/modules/locality/features/places/use-cases/get-evidence.usecase.ts";
import { GetLocalityUseCase } from "#/modules/locality/features/places/use-cases/get-locality.usecase.ts";
import { ListLanguagesUseCase } from "#/modules/locality/features/places/use-cases/list-languages.usecase.ts";
import { ResolveLocalityUseCase } from "#/modules/locality/features/places/use-cases/resolve-locality.usecase.ts";
import { SearchLocalitiesUseCase } from "#/modules/locality/features/places/use-cases/search-localities.usecase.ts";

/**
 * The Places contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class LocalityPlacesService {
  abstract browseSources(input: SourceSearchInputDto): Promise<SourceCollectionDto>;
  abstract getEvidence(input: CitationInputDto): Promise<EvidenceDetailDto>;
  abstract getLocality(input: PlaceInputDto): Promise<LocalityProfileDto>;
  abstract listLanguages(): Promise<LanguageListDto>;
  abstract resolveLocality(input: PositionInputDto): Promise<LocalityProfileDto>;
  abstract searchLocalities(input: SearchInputDto): Promise<LocalityMatchesDto>;
}

@Injectable()
export class LocalityPlacesServiceImpl extends LocalityPlacesService {
  constructor(
    private readonly browseSourcesUseCase: BrowseSourcesUseCase,
    private readonly getEvidenceUseCase: GetEvidenceUseCase,
    private readonly getLocalityUseCase: GetLocalityUseCase,
    private readonly listLanguagesUseCase: ListLanguagesUseCase,
    private readonly resolveLocalityUseCase: ResolveLocalityUseCase,
    private readonly searchLocalitiesUseCase: SearchLocalitiesUseCase,
  ) {
    super();
  }

  browseSources(input: SourceSearchInputDto): Promise<SourceCollectionDto> {
    return this.browseSourcesUseCase.execute(input);
  }

  getEvidence(input: CitationInputDto): Promise<EvidenceDetailDto> {
    return this.getEvidenceUseCase.execute(input);
  }

  getLocality(input: PlaceInputDto): Promise<LocalityProfileDto> {
    return this.getLocalityUseCase.execute(input);
  }

  listLanguages(): Promise<LanguageListDto> {
    return this.listLanguagesUseCase.execute();
  }

  resolveLocality(input: PositionInputDto): Promise<LocalityProfileDto> {
    return this.resolveLocalityUseCase.execute(input);
  }

  searchLocalities(input: SearchInputDto): Promise<LocalityMatchesDto> {
    return this.searchLocalitiesUseCase.execute(input);
  }
}
