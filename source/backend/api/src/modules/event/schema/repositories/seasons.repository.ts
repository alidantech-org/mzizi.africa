import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { SeasonsEntity } from "#/modules/event/schema/entities/seasons.entity.ts";
import * as Seasons from "#/modules/event/schema/types/seasons/index.ts";

/**
 * Repository of Seasons: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class SeasonsRepository
  extends EntityRepository<
    SeasonsEntity,
    Seasons.Types.SeasonsSortableField,
    Seasons.Types.SeasonsEditableField,
    Seasons.Types.SeasonsSelectableField,
    Seasons.Types.ISeasonsCreatable
  >
  implements IUpdatableRepository<SeasonsEntity, Seasons.Types.ISeasonsUpdatable>
{
  constructor(
    @InjectRepository(SeasonsEntity)
    repository: Repository<SeasonsEntity>,
  ) {
    super(repository, Seasons.Config.SEASONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Seasons.Types.ISeasonsUpdatable,
  ): Promise<SeasonsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find seasons by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<SeasonsEntity>,
    countryId: NonNullable<SeasonsEntity["countryId"]>,
  ): Promise<IFindAllResponse<SeasonsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find seasons by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<SeasonsEntity>,
    fromToPrecision: NonNullable<SeasonsEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<SeasonsEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find seasons by scope feature id, paged by the shared query. */
  async findByScopeFeature(
    query: BaseQueryDto<SeasonsEntity>,
    scopeFeatureId: NonNullable<SeasonsEntity["scopeFeatureId"]>,
  ): Promise<IFindAllResponse<SeasonsEntity>> {
    return await this.findByQuery(query, { scopeFeatureId, deletedAt: IsNull() });
  }

  /** Find seasons by season kind id, paged by the shared query. */
  async findBySeasonKind(
    query: BaseQueryDto<SeasonsEntity>,
    seasonKindId: NonNullable<SeasonsEntity["seasonKindId"]>,
  ): Promise<IFindAllResponse<SeasonsEntity>> {
    return await this.findByQuery(query, { seasonKindId, deletedAt: IsNull() });
  }

  /** Find seasons by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<SeasonsEntity>,
    sourceCitationId: NonNullable<SeasonsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<SeasonsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the seasons with this code (unique). */
  async findByCode(code: NonNullable<SeasonsEntity["code"]>): Promise<SeasonsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
