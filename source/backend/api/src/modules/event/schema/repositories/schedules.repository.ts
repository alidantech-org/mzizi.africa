import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { SchedulesEntity } from "#/modules/event/schema/entities/schedules.entity.ts";
import * as Schedules from "#/modules/event/schema/types/schedules/index.ts";

/**
 * Repository of Schedules: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class SchedulesRepository
  extends EntityRepository<
    SchedulesEntity,
    Schedules.Types.SchedulesSortableField,
    Schedules.Types.SchedulesEditableField,
    Schedules.Types.SchedulesSelectableField,
    Schedules.Types.ISchedulesCreatable
  >
  implements IUpdatableRepository<SchedulesEntity, Schedules.Types.ISchedulesUpdatable>
{
  constructor(
    @InjectRepository(SchedulesEntity)
    repository: Repository<SchedulesEntity>,
  ) {
    super(repository, Schedules.Config.SCHEDULES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Schedules.Types.ISchedulesUpdatable,
  ): Promise<SchedulesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find schedules by anchor event id, paged by the shared query. */
  async findByAnchorEvent(
    query: BaseQueryDto<SchedulesEntity>,
    anchorEventId: NonNullable<SchedulesEntity["anchorEventId"]>,
  ): Promise<IFindAllResponse<SchedulesEntity>> {
    return await this.findByQuery(query, { anchorEventId, deletedAt: IsNull() });
  }

  /** Find schedules by basis provision id, paged by the shared query. */
  async findByBasisProvision(
    query: BaseQueryDto<SchedulesEntity>,
    basisProvisionId: NonNullable<SchedulesEntity["basisProvisionId"]>,
  ): Promise<IFindAllResponse<SchedulesEntity>> {
    return await this.findByQuery(query, { basisProvisionId, deletedAt: IsNull() });
  }

  /** Find schedules by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<SchedulesEntity>,
    countryId: NonNullable<SchedulesEntity["countryId"]>,
  ): Promise<IFindAllResponse<SchedulesEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find schedules by issuer entity id, paged by the shared query. */
  async findByIssuerEntity(
    query: BaseQueryDto<SchedulesEntity>,
    issuerEntityId: NonNullable<SchedulesEntity["issuerEntityId"]>,
  ): Promise<IFindAllResponse<SchedulesEntity>> {
    return await this.findByQuery(query, { issuerEntityId, deletedAt: IsNull() });
  }

  /** Find schedules by schedule kind id, paged by the shared query. */
  async findByScheduleKind(
    query: BaseQueryDto<SchedulesEntity>,
    scheduleKindId: NonNullable<SchedulesEntity["scheduleKindId"]>,
  ): Promise<IFindAllResponse<SchedulesEntity>> {
    return await this.findByQuery(query, { scheduleKindId, deletedAt: IsNull() });
  }

  /** Find schedules by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<SchedulesEntity>,
    sourceCitationId: NonNullable<SchedulesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<SchedulesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find schedules by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<SchedulesEntity>,
    statusId: NonNullable<SchedulesEntity["statusId"]>,
  ): Promise<IFindAllResponse<SchedulesEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }

  /** Find schedules by supersedes schedule id, paged by the shared query. */
  async findBySupersedesSchedule(
    query: BaseQueryDto<SchedulesEntity>,
    supersedesScheduleId: NonNullable<SchedulesEntity["supersedesScheduleId"]>,
  ): Promise<IFindAllResponse<SchedulesEntity>> {
    return await this.findByQuery(query, { supersedesScheduleId, deletedAt: IsNull() });
  }

  /** Find the schedules with this code (unique). */
  async findByCode(code: NonNullable<SchedulesEntity["code"]>): Promise<SchedulesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
