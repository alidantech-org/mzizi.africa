import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { EventsEntity } from "#/modules/event/schema/entities/events.entity.ts";
import * as Events from "#/modules/event/schema/types/events/index.ts";

/**
 * Repository of Events: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class EventsRepository
  extends EntityRepository<
    EventsEntity,
    Events.Types.EventsSortableField,
    Events.Types.EventsEditableField,
    Events.Types.EventsSelectableField,
    Events.Types.IEventsCreatable
  >
  implements IUpdatableRepository<EventsEntity, Events.Types.IEventsUpdatable>
{
  constructor(
    @InjectRepository(EventsEntity)
    repository: Repository<EventsEntity>,
  ) {
    super(repository, Events.Config.EVENTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Events.Types.IEventsUpdatable,
  ): Promise<EventsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find events by basis provision id, paged by the shared query. */
  async findByBasisProvision(
    query: BaseQueryDto<EventsEntity>,
    basisProvisionId: NonNullable<EventsEntity["basisProvisionId"]>,
  ): Promise<IFindAllResponse<EventsEntity>> {
    return await this.findByQuery(query, { basisProvisionId, deletedAt: IsNull() });
  }

  /** Find events by calendar id, paged by the shared query. */
  async findByCalendar(
    query: BaseQueryDto<EventsEntity>,
    calendarId: NonNullable<EventsEntity["calendarId"]>,
  ): Promise<IFindAllResponse<EventsEntity>> {
    return await this.findByQuery(query, { calendarId, deletedAt: IsNull() });
  }

  /** Find events by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<EventsEntity>,
    countryId: NonNullable<EventsEntity["countryId"]>,
  ): Promise<IFindAllResponse<EventsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find events by event kind id, paged by the shared query. */
  async findByEventKind(
    query: BaseQueryDto<EventsEntity>,
    eventKindId: NonNullable<EventsEntity["eventKindId"]>,
  ): Promise<IFindAllResponse<EventsEntity>> {
    return await this.findByQuery(query, { eventKindId, deletedAt: IsNull() });
  }

  /** Find events by organiser entity id, paged by the shared query. */
  async findByOrganiserEntity(
    query: BaseQueryDto<EventsEntity>,
    organiserEntityId: NonNullable<EventsEntity["organiserEntityId"]>,
  ): Promise<IFindAllResponse<EventsEntity>> {
    return await this.findByQuery(query, { organiserEntityId, deletedAt: IsNull() });
  }

  /** Find events by scope feature id, paged by the shared query. */
  async findByScopeFeature(
    query: BaseQueryDto<EventsEntity>,
    scopeFeatureId: NonNullable<EventsEntity["scopeFeatureId"]>,
  ): Promise<IFindAllResponse<EventsEntity>> {
    return await this.findByQuery(query, { scopeFeatureId, deletedAt: IsNull() });
  }

  /** Find events by scope level kind id, paged by the shared query. */
  async findByScopeLevelKind(
    query: BaseQueryDto<EventsEntity>,
    scopeLevelKindId: NonNullable<EventsEntity["scopeLevelKindId"]>,
  ): Promise<IFindAllResponse<EventsEntity>> {
    return await this.findByQuery(query, { scopeLevelKindId, deletedAt: IsNull() });
  }

  /** Find events by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<EventsEntity>,
    sourceCitationId: NonNullable<EventsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<EventsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the events with this code (unique). */
  async findByCode(code: NonNullable<EventsEntity["code"]>): Promise<EventsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
