import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { SubjectsEntity } from "#/modules/event/schema/entities/subjects.entity.ts";
import * as Subjects from "#/modules/event/schema/types/subjects/index.ts";

/**
 * Repository of Subjects: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class SubjectsRepository
  extends EntityRepository<
    SubjectsEntity,
    Subjects.Types.SubjectsSortableField,
    Subjects.Types.SubjectsEditableField,
    Subjects.Types.SubjectsSelectableField,
    Subjects.Types.ISubjectsCreatable
  >
  implements IUpdatableRepository<SubjectsEntity, Subjects.Types.ISubjectsUpdatable>
{
  constructor(
    @InjectRepository(SubjectsEntity)
    repository: Repository<SubjectsEntity>,
  ) {
    super(repository, Subjects.Config.SUBJECTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Subjects.Types.ISubjectsUpdatable,
  ): Promise<SubjectsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find subjects by event id, paged by the shared query. */
  async findByEvent(
    query: BaseQueryDto<SubjectsEntity>,
    eventId: NonNullable<SubjectsEntity["eventId"]>,
  ): Promise<IFindAllResponse<SubjectsEntity>> {
    return await this.findByQuery(query, { eventId, deletedAt: IsNull() });
  }

  /** Find subjects by role id, paged by the shared query. */
  async findByRole(
    query: BaseQueryDto<SubjectsEntity>,
    roleId: NonNullable<SubjectsEntity["roleId"]>,
  ): Promise<IFindAllResponse<SubjectsEntity>> {
    return await this.findByQuery(query, { roleId, deletedAt: IsNull() });
  }

  /** Find subjects by subject table, paged by the shared query. */
  async findBySubjectTable(
    query: BaseQueryDto<SubjectsEntity>,
    subjectTable: NonNullable<SubjectsEntity["subjectTable"]>,
  ): Promise<IFindAllResponse<SubjectsEntity>> {
    return await this.findByQuery(query, { subjectTable, deletedAt: IsNull() });
  }

  /** Find the subjects with this code (unique). */
  async findByCode(code: NonNullable<SubjectsEntity["code"]>): Promise<SubjectsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
