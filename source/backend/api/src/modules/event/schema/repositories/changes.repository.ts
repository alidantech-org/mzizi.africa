import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { EventChangesEntity } from "#/modules/event/schema/entities/changes.entity.ts";
import * as Changes from "#/modules/event/schema/types/changes/index.ts";

/**
 * Repository of Changes: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ChangesRepository
  extends EntityRepository<
    EventChangesEntity,
    Changes.Types.ChangesSortableField,
    Changes.Types.ChangesEditableField,
    Changes.Types.ChangesSelectableField,
    Changes.Types.IChangesCreatable
  >
  implements IUpdatableRepository<EventChangesEntity, Changes.Types.IChangesUpdatable>
{
  constructor(
    @InjectRepository(EventChangesEntity)
    repository: Repository<EventChangesEntity>,
  ) {
    super(repository, Changes.Config.CHANGES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Changes.Types.IChangesUpdatable,
  ): Promise<EventChangesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find changes by authority entity id, paged by the shared query. */
  async findByAuthorityEntity(
    query: BaseQueryDto<EventChangesEntity>,
    authorityEntityId: NonNullable<EventChangesEntity["authorityEntityId"]>,
  ): Promise<IFindAllResponse<EventChangesEntity>> {
    return await this.findByQuery(query, { authorityEntityId, deletedAt: IsNull() });
  }

  /** Find changes by basis provision id, paged by the shared query. */
  async findByBasisProvision(
    query: BaseQueryDto<EventChangesEntity>,
    basisProvisionId: NonNullable<EventChangesEntity["basisProvisionId"]>,
  ): Promise<IFindAllResponse<EventChangesEntity>> {
    return await this.findByQuery(query, { basisProvisionId, deletedAt: IsNull() });
  }

  /** Find changes by change kind id, paged by the shared query. */
  async findByChangeKind(
    query: BaseQueryDto<EventChangesEntity>,
    changeKindId: NonNullable<EventChangesEntity["changeKindId"]>,
  ): Promise<IFindAllResponse<EventChangesEntity>> {
    return await this.findByQuery(query, { changeKindId, deletedAt: IsNull() });
  }

  /** Find changes by occurrence id, paged by the shared query. */
  async findByOccurrence(
    query: BaseQueryDto<EventChangesEntity>,
    occurrenceId: NonNullable<EventChangesEntity["occurrenceId"]>,
  ): Promise<IFindAllResponse<EventChangesEntity>> {
    return await this.findByQuery(query, { occurrenceId, deletedAt: IsNull() });
  }

  /** Find changes by reason id, paged by the shared query. */
  async findByReason(
    query: BaseQueryDto<EventChangesEntity>,
    reasonId: NonNullable<EventChangesEntity["reasonId"]>,
  ): Promise<IFindAllResponse<EventChangesEntity>> {
    return await this.findByQuery(query, { reasonId, deletedAt: IsNull() });
  }

  /** Find changes by replacement occurrence id, paged by the shared query. */
  async findByReplacementOccurrence(
    query: BaseQueryDto<EventChangesEntity>,
    replacementOccurrenceId: NonNullable<EventChangesEntity["replacementOccurrenceId"]>,
  ): Promise<IFindAllResponse<EventChangesEntity>> {
    return await this.findByQuery(query, { replacementOccurrenceId, deletedAt: IsNull() });
  }

  /** Find changes by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<EventChangesEntity>,
    sourceCitationId: NonNullable<EventChangesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<EventChangesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the changes with this code (unique). */
  async findByCode(
    code: NonNullable<EventChangesEntity["code"]>,
  ): Promise<EventChangesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
