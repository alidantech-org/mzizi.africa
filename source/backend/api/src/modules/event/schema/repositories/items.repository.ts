import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ItemsEntity } from "#/modules/event/schema/entities/items.entity.ts";
import * as Items from "#/modules/event/schema/types/items/index.ts";

/**
 * Repository of Items: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ItemsRepository
  extends EntityRepository<
    ItemsEntity,
    Items.Types.ItemsSortableField,
    Items.Types.ItemsEditableField,
    Items.Types.ItemsSelectableField,
    Items.Types.IItemsCreatable
  >
  implements IUpdatableRepository<ItemsEntity, Items.Types.IItemsUpdatable>
{
  constructor(
    @InjectRepository(ItemsEntity)
    repository: Repository<ItemsEntity>,
  ) {
    super(repository, Items.Config.ITEMS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Items.Types.IItemsUpdatable): Promise<ItemsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find items by event id, paged by the shared query. */
  async findByEvent(
    query: BaseQueryDto<ItemsEntity>,
    eventId: NonNullable<ItemsEntity["eventId"]>,
  ): Promise<IFindAllResponse<ItemsEntity>> {
    return await this.findByQuery(query, { eventId, deletedAt: IsNull() });
  }

  /** Find items by occurrence id, paged by the shared query. */
  async findByOccurrence(
    query: BaseQueryDto<ItemsEntity>,
    occurrenceId: NonNullable<ItemsEntity["occurrenceId"]>,
  ): Promise<IFindAllResponse<ItemsEntity>> {
    return await this.findByQuery(query, { occurrenceId, deletedAt: IsNull() });
  }

  /** Find items by schedule id, paged by the shared query. */
  async findBySchedule(
    query: BaseQueryDto<ItemsEntity>,
    scheduleId: NonNullable<ItemsEntity["scheduleId"]>,
  ): Promise<IFindAllResponse<ItemsEntity>> {
    return await this.findByQuery(query, { scheduleId, deletedAt: IsNull() });
  }
}
