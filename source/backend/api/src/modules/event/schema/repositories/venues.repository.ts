import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { VenuesEntity } from "#/modules/event/schema/entities/venues.entity.ts";
import * as Venues from "#/modules/event/schema/types/venues/index.ts";

/**
 * Repository of Venues: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class VenuesRepository
  extends EntityRepository<
    VenuesEntity,
    Venues.Types.VenuesSortableField,
    Venues.Types.VenuesEditableField,
    Venues.Types.VenuesSelectableField,
    Venues.Types.IVenuesCreatable
  >
  implements IUpdatableRepository<VenuesEntity, Venues.Types.IVenuesUpdatable>
{
  constructor(
    @InjectRepository(VenuesEntity)
    repository: Repository<VenuesEntity>,
  ) {
    super(repository, Venues.Config.VENUES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Venues.Types.IVenuesUpdatable,
  ): Promise<VenuesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find venues by feature id, paged by the shared query. */
  async findByFeature(
    query: BaseQueryDto<VenuesEntity>,
    featureId: NonNullable<VenuesEntity["featureId"]>,
  ): Promise<IFindAllResponse<VenuesEntity>> {
    return await this.findByQuery(query, { featureId, deletedAt: IsNull() });
  }

  /** Find venues by occurrence id, paged by the shared query. */
  async findByOccurrence(
    query: BaseQueryDto<VenuesEntity>,
    occurrenceId: NonNullable<VenuesEntity["occurrenceId"]>,
  ): Promise<IFindAllResponse<VenuesEntity>> {
    return await this.findByQuery(query, { occurrenceId, deletedAt: IsNull() });
  }

  /** Find venues by role id, paged by the shared query. */
  async findByRole(
    query: BaseQueryDto<VenuesEntity>,
    roleId: NonNullable<VenuesEntity["roleId"]>,
  ): Promise<IFindAllResponse<VenuesEntity>> {
    return await this.findByQuery(query, { roleId, deletedAt: IsNull() });
  }
}
