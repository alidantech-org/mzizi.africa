import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { OccurrencesEntity } from "#/modules/event/schema/entities/occurrences.entity.ts";
import * as Occurrences from "#/modules/event/schema/types/occurrences/index.ts";

/**
 * Repository of Occurrences: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class OccurrencesRepository
  extends EntityRepository<
    OccurrencesEntity,
    Occurrences.Types.OccurrencesSortableField,
    Occurrences.Types.OccurrencesEditableField,
    Occurrences.Types.OccurrencesSelectableField,
    Occurrences.Types.IOccurrencesCreatable
  >
  implements IUpdatableRepository<OccurrencesEntity, Occurrences.Types.IOccurrencesUpdatable>
{
  constructor(
    @InjectRepository(OccurrencesEntity)
    repository: Repository<OccurrencesEntity>,
  ) {
    super(repository, Occurrences.Config.OCCURRENCES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Occurrences.Types.IOccurrencesUpdatable,
  ): Promise<OccurrencesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find occurrences by continues occurrence id, paged by the shared query. */
  async findByContinuesOccurrence(
    query: BaseQueryDto<OccurrencesEntity>,
    continuesOccurrenceId: NonNullable<OccurrencesEntity["continuesOccurrenceId"]>,
  ): Promise<IFindAllResponse<OccurrencesEntity>> {
    return await this.findByQuery(query, { continuesOccurrenceId, deletedAt: IsNull() });
  }

  /** Find occurrences by event id, paged by the shared query. */
  async findByEvent(
    query: BaseQueryDto<OccurrencesEntity>,
    eventId: NonNullable<OccurrencesEntity["eventId"]>,
  ): Promise<IFindAllResponse<OccurrencesEntity>> {
    return await this.findByQuery(query, { eventId, deletedAt: IsNull() });
  }

  /** Find occurrences by format id, paged by the shared query. */
  async findByFormat(
    query: BaseQueryDto<OccurrencesEntity>,
    formatId: NonNullable<OccurrencesEntity["formatId"]>,
  ): Promise<IFindAllResponse<OccurrencesEntity>> {
    return await this.findByQuery(query, { formatId, deletedAt: IsNull() });
  }

  /** Find occurrences by knowledge id, paged by the shared query. */
  async findByKnowledge(
    query: BaseQueryDto<OccurrencesEntity>,
    knowledgeId: NonNullable<OccurrencesEntity["knowledgeId"]>,
  ): Promise<IFindAllResponse<OccurrencesEntity>> {
    return await this.findByQuery(query, { knowledgeId, deletedAt: IsNull() });
  }

  /** Find occurrences by organiser entity id, paged by the shared query. */
  async findByOrganiserEntity(
    query: BaseQueryDto<OccurrencesEntity>,
    organiserEntityId: NonNullable<OccurrencesEntity["organiserEntityId"]>,
  ): Promise<IFindAllResponse<OccurrencesEntity>> {
    return await this.findByQuery(query, { organiserEntityId, deletedAt: IsNull() });
  }

  /** Find occurrences by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<OccurrencesEntity>,
    sourceCitationId: NonNullable<OccurrencesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<OccurrencesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find occurrences by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<OccurrencesEntity>,
    statusId: NonNullable<OccurrencesEntity["statusId"]>,
  ): Promise<IFindAllResponse<OccurrencesEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }

  /** Find occurrences by venue feature id, paged by the shared query. */
  async findByVenueFeature(
    query: BaseQueryDto<OccurrencesEntity>,
    venueFeatureId: NonNullable<OccurrencesEntity["venueFeatureId"]>,
  ): Promise<IFindAllResponse<OccurrencesEntity>> {
    return await this.findByQuery(query, { venueFeatureId, deletedAt: IsNull() });
  }

  /** Find the occurrences with this code (unique). */
  async findByCode(
    code: NonNullable<OccurrencesEntity["code"]>,
  ): Promise<OccurrencesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
