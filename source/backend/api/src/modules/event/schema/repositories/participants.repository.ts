import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ParticipantsEntity } from "#/modules/event/schema/entities/participants.entity.ts";
import * as Participants from "#/modules/event/schema/types/participants/index.ts";

/**
 * Repository of Participants: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ParticipantsRepository
  extends EntityRepository<
    ParticipantsEntity,
    Participants.Types.ParticipantsSortableField,
    Participants.Types.ParticipantsEditableField,
    Participants.Types.ParticipantsSelectableField,
    Participants.Types.IParticipantsCreatable
  >
  implements IUpdatableRepository<ParticipantsEntity, Participants.Types.IParticipantsUpdatable>
{
  constructor(
    @InjectRepository(ParticipantsEntity)
    repository: Repository<ParticipantsEntity>,
  ) {
    super(repository, Participants.Config.PARTICIPANTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Participants.Types.IParticipantsUpdatable,
  ): Promise<ParticipantsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find participants by entity id, paged by the shared query. */
  async findByEntity(
    query: BaseQueryDto<ParticipantsEntity>,
    entityId: NonNullable<ParticipantsEntity["entityId"]>,
  ): Promise<IFindAllResponse<ParticipantsEntity>> {
    return await this.findByQuery(query, { entityId, deletedAt: IsNull() });
  }

  /** Find participants by individual id, paged by the shared query. */
  async findByIndividual(
    query: BaseQueryDto<ParticipantsEntity>,
    individualId: NonNullable<ParticipantsEntity["individualId"]>,
  ): Promise<IFindAllResponse<ParticipantsEntity>> {
    return await this.findByQuery(query, { individualId, deletedAt: IsNull() });
  }

  /** Find participants by occurrence id, paged by the shared query. */
  async findByOccurrence(
    query: BaseQueryDto<ParticipantsEntity>,
    occurrenceId: NonNullable<ParticipantsEntity["occurrenceId"]>,
  ): Promise<IFindAllResponse<ParticipantsEntity>> {
    return await this.findByQuery(query, { occurrenceId, deletedAt: IsNull() });
  }

  /** Find participants by role id, paged by the shared query. */
  async findByRole(
    query: BaseQueryDto<ParticipantsEntity>,
    roleId: NonNullable<ParticipantsEntity["roleId"]>,
  ): Promise<IFindAllResponse<ParticipantsEntity>> {
    return await this.findByQuery(query, { roleId, deletedAt: IsNull() });
  }
}
