import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { CalendarsEntity } from "#/modules/event/schema/entities/calendars.entity.ts";
import * as Calendars from "#/modules/event/schema/types/calendars/index.ts";

/**
 * Repository of Calendars: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class CalendarsRepository
  extends EntityRepository<
    CalendarsEntity,
    Calendars.Types.CalendarsSortableField,
    Calendars.Types.CalendarsEditableField,
    Calendars.Types.CalendarsSelectableField,
    Calendars.Types.ICalendarsCreatable
  >
  implements IUpdatableRepository<CalendarsEntity, Calendars.Types.ICalendarsUpdatable>
{
  constructor(
    @InjectRepository(CalendarsEntity)
    repository: Repository<CalendarsEntity>,
  ) {
    super(repository, Calendars.Config.CALENDARS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Calendars.Types.ICalendarsUpdatable,
  ): Promise<CalendarsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find calendars by calendar kind id, paged by the shared query. */
  async findByCalendarKind(
    query: BaseQueryDto<CalendarsEntity>,
    calendarKindId: NonNullable<CalendarsEntity["calendarKindId"]>,
  ): Promise<IFindAllResponse<CalendarsEntity>> {
    return await this.findByQuery(query, { calendarKindId, deletedAt: IsNull() });
  }

  /** Find calendars by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<CalendarsEntity>,
    countryId: NonNullable<CalendarsEntity["countryId"]>,
  ): Promise<IFindAllResponse<CalendarsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find calendars by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<CalendarsEntity>,
    sourceCitationId: NonNullable<CalendarsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<CalendarsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the calendars with this code (unique). */
  async findByCode(code: NonNullable<CalendarsEntity["code"]>): Promise<CalendarsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
