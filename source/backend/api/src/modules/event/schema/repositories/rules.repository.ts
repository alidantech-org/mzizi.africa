import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { RulesEntity } from "#/modules/event/schema/entities/rules.entity.ts";
import * as Rules from "#/modules/event/schema/types/rules/index.ts";

/**
 * Repository of Rules: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class RulesRepository
  extends EntityRepository<
    RulesEntity,
    Rules.Types.RulesSortableField,
    Rules.Types.RulesEditableField,
    Rules.Types.RulesSelectableField,
    Rules.Types.IRulesCreatable
  >
  implements IUpdatableRepository<RulesEntity, Rules.Types.IRulesUpdatable>
{
  constructor(
    @InjectRepository(RulesEntity)
    repository: Repository<RulesEntity>,
  ) {
    super(repository, Rules.Config.RULES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Rules.Types.IRulesUpdatable): Promise<RulesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find rules by adjustment id, paged by the shared query. */
  async findByAdjustment(
    query: BaseQueryDto<RulesEntity>,
    adjustmentId: NonNullable<RulesEntity["adjustmentId"]>,
  ): Promise<IFindAllResponse<RulesEntity>> {
    return await this.findByQuery(query, { adjustmentId, deletedAt: IsNull() });
  }

  /** Find rules by event id, paged by the shared query. */
  async findByEvent(
    query: BaseQueryDto<RulesEntity>,
    eventId: NonNullable<RulesEntity["eventId"]>,
  ): Promise<IFindAllResponse<RulesEntity>> {
    return await this.findByQuery(query, { eventId, deletedAt: IsNull() });
  }

  /** Find rules by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<RulesEntity>,
    fromToPrecision: NonNullable<RulesEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<RulesEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find rules by rule kind id, paged by the shared query. */
  async findByRuleKind(
    query: BaseQueryDto<RulesEntity>,
    ruleKindId: NonNullable<RulesEntity["ruleKindId"]>,
  ): Promise<IFindAllResponse<RulesEntity>> {
    return await this.findByQuery(query, { ruleKindId, deletedAt: IsNull() });
  }

  /** Find rules by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<RulesEntity>,
    sourceCitationId: NonNullable<RulesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<RulesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }
}
