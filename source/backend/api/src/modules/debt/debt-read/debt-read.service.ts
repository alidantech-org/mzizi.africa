
import type { LoanDisbursementListQueryDto } from "#/modules/debt/dto/loan-disbursement-list-query.dto.ts";
import type { LoanDisbursementResponseDto } from "#/modules/debt/dto/loan-disbursement-response.dto.ts";
import type { LoanDisbursementsListResponseDto } from "#/modules/debt/dto/loan-disbursements-list-response.dto.ts";
import type { LoanListQueryDto } from "#/modules/debt/dto/loan-list-query.dto.ts";
import type { LoanRepaymentListQueryDto } from "#/modules/debt/dto/loan-repayment-list-query.dto.ts";
import type { LoanRepaymentResponseDto } from "#/modules/debt/dto/loan-repayment-response.dto.ts";
import type { LoanRepaymentsListResponseDto } from "#/modules/debt/dto/loan-repayments-list-response.dto.ts";
import type { LoanResponseDto } from "#/modules/debt/dto/loan-response.dto.ts";
import type { LoansListResponseDto } from "#/modules/debt/dto/loans-list-response.dto.ts";

/**
 * The Debt Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class DebtDebtReadService {
  abstract findLoanDisbursements(input: LoanDisbursementListQueryDto): Promise<LoanDisbursementsListResponseDto>;
  abstract findLoanRepayments(input: LoanRepaymentListQueryDto): Promise<LoanRepaymentsListResponseDto>;
  abstract findLoans(input: LoanListQueryDto): Promise<LoansListResponseDto>;
  abstract getLoanById(input: { loanId: string }): Promise<LoanResponseDto>;
  abstract getLoanDisbursementById(input: { disbursementId: string }): Promise<LoanDisbursementResponseDto>;
  abstract getLoanRepaymentById(input: { repaymentId: string }): Promise<LoanRepaymentResponseDto>;
}