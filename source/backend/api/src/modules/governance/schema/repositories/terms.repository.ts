import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { TermsEntity } from "#/modules/governance/schema/entities/terms.entity.ts";
import * as Terms from "#/modules/governance/schema/types/terms/index.ts";

/**
 * Repository of Terms: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class TermsRepository
  extends EntityRepository<
    TermsEntity,
    Terms.Types.TermsSortableField,
    Terms.Types.TermsEditableField,
    Terms.Types.TermsSelectableField,
    Terms.Types.ITermsCreatable
  >
  implements IUpdatableRepository<TermsEntity, Terms.Types.ITermsUpdatable>
{
  constructor(
    @InjectRepository(TermsEntity)
    repository: Repository<TermsEntity>,
  ) {
    super(repository, Terms.Config.TERMS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Terms.Types.ITermsUpdatable): Promise<TermsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find terms by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<TermsEntity>,
    countryId: NonNullable<TermsEntity["countryId"]>,
  ): Promise<IFindAllResponse<TermsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find terms by institution id, paged by the shared query. */
  async findByInstitution(
    query: BaseQueryDto<TermsEntity>,
    institutionId: NonNullable<TermsEntity["institutionId"]>,
  ): Promise<IFindAllResponse<TermsEntity>> {
    return await this.findByQuery(query, { institutionId, deletedAt: IsNull() });
  }

  /** Find terms by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<TermsEntity>,
    sourceCitationId: NonNullable<TermsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<TermsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find terms by term kind id, paged by the shared query. */
  async findByTermKind(
    query: BaseQueryDto<TermsEntity>,
    termKindId: NonNullable<TermsEntity["termKindId"]>,
  ): Promise<IFindAllResponse<TermsEntity>> {
    return await this.findByQuery(query, { termKindId, deletedAt: IsNull() });
  }

  /** Find terms by unit feature id, paged by the shared query. */
  async findByUnitFeature(
    query: BaseQueryDto<TermsEntity>,
    unitFeatureId: NonNullable<TermsEntity["unitFeatureId"]>,
  ): Promise<IFindAllResponse<TermsEntity>> {
    return await this.findByQuery(query, { unitFeatureId, deletedAt: IsNull() });
  }

  /** Find the terms with this code (unique). */
  async findByCode(code: NonNullable<TermsEntity["code"]>): Promise<TermsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
