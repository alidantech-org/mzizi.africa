import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ProceduresEntity } from "#/modules/governance/schema/entities/procedures.entity.ts";
import * as Procedures from "#/modules/governance/schema/types/procedures/index.ts";

/**
 * Repository of Procedures: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ProceduresRepository
  extends EntityRepository<
    ProceduresEntity,
    Procedures.Types.ProceduresSortableField,
    Procedures.Types.ProceduresEditableField,
    Procedures.Types.ProceduresSelectableField,
    Procedures.Types.IProceduresCreatable
  >
  implements IUpdatableRepository<ProceduresEntity, Procedures.Types.IProceduresUpdatable>
{
  constructor(
    @InjectRepository(ProceduresEntity)
    repository: Repository<ProceduresEntity>,
  ) {
    super(repository, Procedures.Config.PROCEDURES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Procedures.Types.IProceduresUpdatable,
  ): Promise<ProceduresEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find procedures by basis provision id, paged by the shared query. */
  async findByBasisProvision(
    query: BaseQueryDto<ProceduresEntity>,
    basisProvisionId: NonNullable<ProceduresEntity["basisProvisionId"]>,
  ): Promise<IFindAllResponse<ProceduresEntity>> {
    return await this.findByQuery(query, { basisProvisionId, deletedAt: IsNull() });
  }

  /** Find procedures by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<ProceduresEntity>,
    countryId: NonNullable<ProceduresEntity["countryId"]>,
  ): Promise<IFindAllResponse<ProceduresEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find procedures by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<ProceduresEntity>,
    fromToPrecision: NonNullable<ProceduresEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<ProceduresEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find procedures by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<ProceduresEntity>,
    kindId: NonNullable<ProceduresEntity["kindId"]>,
  ): Promise<IFindAllResponse<ProceduresEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find procedures by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<ProceduresEntity>,
    sourceCitationId: NonNullable<ProceduresEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<ProceduresEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the procedures with this code (unique). */
  async findByCode(code: NonNullable<ProceduresEntity["code"]>): Promise<ProceduresEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
