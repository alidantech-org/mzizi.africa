import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { OfficesEntity } from "#/modules/governance/schema/entities/offices.entity.ts";
import * as Offices from "#/modules/governance/schema/types/offices/index.ts";

/**
 * Repository of Offices: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class OfficesRepository
  extends EntityRepository<
    OfficesEntity,
    Offices.Types.OfficesSortableField,
    Offices.Types.OfficesEditableField,
    Offices.Types.OfficesSelectableField,
    Offices.Types.IOfficesCreatable
  >
  implements IUpdatableRepository<OfficesEntity, Offices.Types.IOfficesUpdatable>
{
  constructor(
    @InjectRepository(OfficesEntity)
    repository: Repository<OfficesEntity>,
  ) {
    super(repository, Offices.Config.OFFICES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Offices.Types.IOfficesUpdatable,
  ): Promise<OfficesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find offices by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<OfficesEntity>,
    fromToPrecision: NonNullable<OfficesEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<OfficesEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find offices by institution id, paged by the shared query. */
  async findByInstitution(
    query: BaseQueryDto<OfficesEntity>,
    institutionId: NonNullable<OfficesEntity["institutionId"]>,
  ): Promise<IFindAllResponse<OfficesEntity>> {
    return await this.findByQuery(query, { institutionId, deletedAt: IsNull() });
  }

  /** Find offices by office kind id, paged by the shared query. */
  async findByOfficeKind(
    query: BaseQueryDto<OfficesEntity>,
    officeKindId: NonNullable<OfficesEntity["officeKindId"]>,
  ): Promise<IFindAllResponse<OfficesEntity>> {
    return await this.findByQuery(query, { officeKindId, deletedAt: IsNull() });
  }

  /** Find offices by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<OfficesEntity>,
    sourceCitationId: NonNullable<OfficesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<OfficesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find offices by unit feature id, paged by the shared query. */
  async findByUnitFeature(
    query: BaseQueryDto<OfficesEntity>,
    unitFeatureId: NonNullable<OfficesEntity["unitFeatureId"]>,
  ): Promise<IFindAllResponse<OfficesEntity>> {
    return await this.findByQuery(query, { unitFeatureId, deletedAt: IsNull() });
  }

  /** Find the offices with this code (unique). */
  async findByCode(code: NonNullable<OfficesEntity["code"]>): Promise<OfficesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
