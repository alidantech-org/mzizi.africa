import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { HoldersEntity } from "#/modules/governance/schema/entities/holders.entity.ts";
import * as Holders from "#/modules/governance/schema/types/holders/index.ts";

/**
 * Repository of Holders: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class HoldersRepository
  extends EntityRepository<
    HoldersEntity,
    Holders.Types.HoldersSortableField,
    Holders.Types.HoldersEditableField,
    Holders.Types.HoldersSelectableField,
    Holders.Types.IHoldersCreatable
  >
  implements IUpdatableRepository<HoldersEntity, Holders.Types.IHoldersUpdatable>
{
  constructor(
    @InjectRepository(HoldersEntity)
    repository: Repository<HoldersEntity>,
  ) {
    super(repository, Holders.Config.HOLDERS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Holders.Types.IHoldersUpdatable,
  ): Promise<HoldersEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find holders by appointed by entity id, paged by the shared query. */
  async findByAppointedByEntity(
    query: BaseQueryDto<HoldersEntity>,
    appointedByEntityId: NonNullable<HoldersEntity["appointedByEntityId"]>,
  ): Promise<IFindAllResponse<HoldersEntity>> {
    return await this.findByQuery(query, { appointedByEntityId, deletedAt: IsNull() });
  }

  /** Find holders by appointment kind id, paged by the shared query. */
  async findByAppointmentKind(
    query: BaseQueryDto<HoldersEntity>,
    appointmentKindId: NonNullable<HoldersEntity["appointmentKindId"]>,
  ): Promise<IFindAllResponse<HoldersEntity>> {
    return await this.findByQuery(query, { appointmentKindId, deletedAt: IsNull() });
  }

  /** Find holders by individual id, paged by the shared query. */
  async findByIndividual(
    query: BaseQueryDto<HoldersEntity>,
    individualId: NonNullable<HoldersEntity["individualId"]>,
  ): Promise<IFindAllResponse<HoldersEntity>> {
    return await this.findByQuery(query, { individualId, deletedAt: IsNull() });
  }

  /** Find holders by office id, paged by the shared query. */
  async findByOffice(
    query: BaseQueryDto<HoldersEntity>,
    officeId: NonNullable<HoldersEntity["officeId"]>,
  ): Promise<IFindAllResponse<HoldersEntity>> {
    return await this.findByQuery(query, { officeId, deletedAt: IsNull() });
  }

  /** Find holders by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<HoldersEntity>,
    sourceCitationId: NonNullable<HoldersEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<HoldersEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the holders with this code (unique). */
  async findByCode(code: NonNullable<HoldersEntity["code"]>): Promise<HoldersEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
