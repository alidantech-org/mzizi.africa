import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { MandatesEntity } from "#/modules/governance/schema/entities/mandates.entity.ts";
import * as Mandates from "#/modules/governance/schema/types/mandates/index.ts";

/**
 * Repository of Mandates: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class MandatesRepository
  extends EntityRepository<
    MandatesEntity,
    Mandates.Types.MandatesSortableField,
    Mandates.Types.MandatesEditableField,
    Mandates.Types.MandatesSelectableField,
    Mandates.Types.IMandatesCreatable
  >
  implements IUpdatableRepository<MandatesEntity, Mandates.Types.IMandatesUpdatable>
{
  constructor(
    @InjectRepository(MandatesEntity)
    repository: Repository<MandatesEntity>,
  ) {
    super(repository, Mandates.Config.MANDATES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Mandates.Types.IMandatesUpdatable,
  ): Promise<MandatesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find mandates by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<MandatesEntity>,
    fromToPrecision: NonNullable<MandatesEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<MandatesEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find mandates by institution id, paged by the shared query. */
  async findByInstitution(
    query: BaseQueryDto<MandatesEntity>,
    institutionId: NonNullable<MandatesEntity["institutionId"]>,
  ): Promise<IFindAllResponse<MandatesEntity>> {
    return await this.findByQuery(query, { institutionId, deletedAt: IsNull() });
  }

  /** Find mandates by mandate kind id, paged by the shared query. */
  async findByMandateKind(
    query: BaseQueryDto<MandatesEntity>,
    mandateKindId: NonNullable<MandatesEntity["mandateKindId"]>,
  ): Promise<IFindAllResponse<MandatesEntity>> {
    return await this.findByQuery(query, { mandateKindId, deletedAt: IsNull() });
  }

  /** Find mandates by office id, paged by the shared query. */
  async findByOffice(
    query: BaseQueryDto<MandatesEntity>,
    officeId: NonNullable<MandatesEntity["officeId"]>,
  ): Promise<IFindAllResponse<MandatesEntity>> {
    return await this.findByQuery(query, { officeId, deletedAt: IsNull() });
  }

  /** Find mandates by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<MandatesEntity>,
    sourceCitationId: NonNullable<MandatesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<MandatesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find mandates by term id, paged by the shared query. */
  async findByTerm(
    query: BaseQueryDto<MandatesEntity>,
    termId: NonNullable<MandatesEntity["termId"]>,
  ): Promise<IFindAllResponse<MandatesEntity>> {
    return await this.findByQuery(query, { termId, deletedAt: IsNull() });
  }
}
