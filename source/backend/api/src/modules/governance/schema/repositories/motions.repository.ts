import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { MotionsEntity } from "#/modules/governance/schema/entities/motions.entity.ts";
import * as Motions from "#/modules/governance/schema/types/motions/index.ts";

/**
 * Repository of Motions: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class MotionsRepository
  extends EntityRepository<
    MotionsEntity,
    Motions.Types.MotionsSortableField,
    Motions.Types.MotionsEditableField,
    Motions.Types.MotionsSelectableField,
    Motions.Types.IMotionsCreatable
  >
  implements IUpdatableRepository<MotionsEntity, Motions.Types.IMotionsUpdatable>
{
  constructor(
    @InjectRepository(MotionsEntity)
    repository: Repository<MotionsEntity>,
  ) {
    super(repository, Motions.Config.MOTIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Motions.Types.IMotionsUpdatable,
  ): Promise<MotionsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find motions by bill id, paged by the shared query. */
  async findByBill(
    query: BaseQueryDto<MotionsEntity>,
    billId: NonNullable<MotionsEntity["billId"]>,
  ): Promise<IFindAllResponse<MotionsEntity>> {
    return await this.findByQuery(query, { billId, deletedAt: IsNull() });
  }

  /** Find motions by budget version id, paged by the shared query. */
  async findByBudgetVersion(
    query: BaseQueryDto<MotionsEntity>,
    budgetVersionId: NonNullable<MotionsEntity["budgetVersionId"]>,
  ): Promise<IFindAllResponse<MotionsEntity>> {
    return await this.findByQuery(query, { budgetVersionId, deletedAt: IsNull() });
  }

  /** Find motions by fiscal period id, paged by the shared query. */
  async findByFiscalPeriod(
    query: BaseQueryDto<MotionsEntity>,
    fiscalPeriodId: NonNullable<MotionsEntity["fiscalPeriodId"]>,
  ): Promise<IFindAllResponse<MotionsEntity>> {
    return await this.findByQuery(query, { fiscalPeriodId, deletedAt: IsNull() });
  }

  /** Find motions by instrument id, paged by the shared query. */
  async findByInstrument(
    query: BaseQueryDto<MotionsEntity>,
    instrumentId: NonNullable<MotionsEntity["instrumentId"]>,
  ): Promise<IFindAllResponse<MotionsEntity>> {
    return await this.findByQuery(query, { instrumentId, deletedAt: IsNull() });
  }

  /** Find motions by motion kind id, paged by the shared query. */
  async findByMotionKind(
    query: BaseQueryDto<MotionsEntity>,
    motionKindId: NonNullable<MotionsEntity["motionKindId"]>,
  ): Promise<IFindAllResponse<MotionsEntity>> {
    return await this.findByQuery(query, { motionKindId, deletedAt: IsNull() });
  }

  /** Find motions by moved by holder id, paged by the shared query. */
  async findByMovedByHolder(
    query: BaseQueryDto<MotionsEntity>,
    movedByHolderId: NonNullable<MotionsEntity["movedByHolderId"]>,
  ): Promise<IFindAllResponse<MotionsEntity>> {
    return await this.findByQuery(query, { movedByHolderId, deletedAt: IsNull() });
  }

  /** Find motions by outcome id, paged by the shared query. */
  async findByOutcome(
    query: BaseQueryDto<MotionsEntity>,
    outcomeId: NonNullable<MotionsEntity["outcomeId"]>,
  ): Promise<IFindAllResponse<MotionsEntity>> {
    return await this.findByQuery(query, { outcomeId, deletedAt: IsNull() });
  }

  /** Find motions by provision id, paged by the shared query. */
  async findByProvision(
    query: BaseQueryDto<MotionsEntity>,
    provisionId: NonNullable<MotionsEntity["provisionId"]>,
  ): Promise<IFindAllResponse<MotionsEntity>> {
    return await this.findByQuery(query, { provisionId, deletedAt: IsNull() });
  }

  /** Find motions by sitting id, paged by the shared query. */
  async findBySitting(
    query: BaseQueryDto<MotionsEntity>,
    sittingId: NonNullable<MotionsEntity["sittingId"]>,
  ): Promise<IFindAllResponse<MotionsEntity>> {
    return await this.findByQuery(query, { sittingId, deletedAt: IsNull() });
  }

  /** Find motions by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<MotionsEntity>,
    sourceCitationId: NonNullable<MotionsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<MotionsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the motions with this code (unique). */
  async findByCode(code: NonNullable<MotionsEntity["code"]>): Promise<MotionsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
