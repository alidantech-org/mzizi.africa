import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { FulfilmentsEntity } from "#/modules/governance/schema/entities/fulfilments.entity.ts";
import * as Fulfilments from "#/modules/governance/schema/types/fulfilments/index.ts";

/**
 * Repository of Fulfilments: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class FulfilmentsRepository
  extends EntityRepository<
    FulfilmentsEntity,
    Fulfilments.Types.FulfilmentsSortableField,
    Fulfilments.Types.FulfilmentsEditableField,
    Fulfilments.Types.FulfilmentsSelectableField,
    Fulfilments.Types.IFulfilmentsCreatable
  >
  implements IUpdatableRepository<FulfilmentsEntity, Fulfilments.Types.IFulfilmentsUpdatable>
{
  constructor(
    @InjectRepository(FulfilmentsEntity)
    repository: Repository<FulfilmentsEntity>,
  ) {
    super(repository, Fulfilments.Config.FULFILMENTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Fulfilments.Types.IFulfilmentsUpdatable,
  ): Promise<FulfilmentsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find fulfilments by appropriation id, paged by the shared query. */
  async findByAppropriation(
    query: BaseQueryDto<FulfilmentsEntity>,
    appropriationId: NonNullable<FulfilmentsEntity["appropriationId"]>,
  ): Promise<IFindAllResponse<FulfilmentsEntity>> {
    return await this.findByQuery(query, { appropriationId, deletedAt: IsNull() });
  }

  /** Find fulfilments by bill id, paged by the shared query. */
  async findByBill(
    query: BaseQueryDto<FulfilmentsEntity>,
    billId: NonNullable<FulfilmentsEntity["billId"]>,
  ): Promise<IFindAllResponse<FulfilmentsEntity>> {
    return await this.findByQuery(query, { billId, deletedAt: IsNull() });
  }

  /** Find fulfilments by contract id, paged by the shared query. */
  async findByContract(
    query: BaseQueryDto<FulfilmentsEntity>,
    contractId: NonNullable<FulfilmentsEntity["contractId"]>,
  ): Promise<IFindAllResponse<FulfilmentsEntity>> {
    return await this.findByQuery(query, { contractId, deletedAt: IsNull() });
  }

  /** Find fulfilments by evidence status id, paged by the shared query. */
  async findByEvidenceStatus(
    query: BaseQueryDto<FulfilmentsEntity>,
    evidenceStatusId: NonNullable<FulfilmentsEntity["evidenceStatusId"]>,
  ): Promise<IFindAllResponse<FulfilmentsEntity>> {
    return await this.findByQuery(query, { evidenceStatusId, deletedAt: IsNull() });
  }

  /** Find fulfilments by instrument id, paged by the shared query. */
  async findByInstrument(
    query: BaseQueryDto<FulfilmentsEntity>,
    instrumentId: NonNullable<FulfilmentsEntity["instrumentId"]>,
  ): Promise<IFindAllResponse<FulfilmentsEntity>> {
    return await this.findByQuery(query, { instrumentId, deletedAt: IsNull() });
  }

  /** Find fulfilments by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<FulfilmentsEntity>,
    kindId: NonNullable<FulfilmentsEntity["kindId"]>,
  ): Promise<IFindAllResponse<FulfilmentsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find fulfilments by project id, paged by the shared query. */
  async findByProject(
    query: BaseQueryDto<FulfilmentsEntity>,
    projectId: NonNullable<FulfilmentsEntity["projectId"]>,
  ): Promise<IFindAllResponse<FulfilmentsEntity>> {
    return await this.findByQuery(query, { projectId, deletedAt: IsNull() });
  }

  /** Find fulfilments by promise id, paged by the shared query. */
  async findByPromise(
    query: BaseQueryDto<FulfilmentsEntity>,
    promiseId: NonNullable<FulfilmentsEntity["promiseId"]>,
  ): Promise<IFindAllResponse<FulfilmentsEntity>> {
    return await this.findByQuery(query, { promiseId, deletedAt: IsNull() });
  }

  /** Find fulfilments by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<FulfilmentsEntity>,
    sourceCitationId: NonNullable<FulfilmentsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<FulfilmentsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }
}
