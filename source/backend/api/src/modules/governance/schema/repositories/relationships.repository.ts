import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { GovernanceRelationshipsEntity } from "#/modules/governance/schema/entities/relationships.entity.ts";
import * as Relationships from "#/modules/governance/schema/types/relationships/index.ts";

/**
 * Repository of Relationships: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class RelationshipsRepository
  extends EntityRepository<
    GovernanceRelationshipsEntity,
    Relationships.Types.RelationshipsSortableField,
    Relationships.Types.RelationshipsEditableField,
    Relationships.Types.RelationshipsSelectableField,
    Relationships.Types.IRelationshipsCreatable
  >
  implements
    IUpdatableRepository<GovernanceRelationshipsEntity, Relationships.Types.IRelationshipsUpdatable>
{
  constructor(
    @InjectRepository(GovernanceRelationshipsEntity)
    repository: Repository<GovernanceRelationshipsEntity>,
  ) {
    super(repository, Relationships.Config.RELATIONSHIPS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Relationships.Types.IRelationshipsUpdatable,
  ): Promise<GovernanceRelationshipsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find relationships by object institution id, paged by the shared query. */
  async findByObjectInstitution(
    query: BaseQueryDto<GovernanceRelationshipsEntity>,
    objectInstitutionId: NonNullable<GovernanceRelationshipsEntity["objectInstitutionId"]>,
  ): Promise<IFindAllResponse<GovernanceRelationshipsEntity>> {
    return await this.findByQuery(query, { objectInstitutionId, deletedAt: IsNull() });
  }

  /** Find relationships by relationship kind id, paged by the shared query. */
  async findByRelationshipKind(
    query: BaseQueryDto<GovernanceRelationshipsEntity>,
    relationshipKindId: NonNullable<GovernanceRelationshipsEntity["relationshipKindId"]>,
  ): Promise<IFindAllResponse<GovernanceRelationshipsEntity>> {
    return await this.findByQuery(query, { relationshipKindId, deletedAt: IsNull() });
  }

  /** Find relationships by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<GovernanceRelationshipsEntity>,
    sourceCitationId: NonNullable<GovernanceRelationshipsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<GovernanceRelationshipsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find relationships by subject institution id, paged by the shared query. */
  async findBySubjectInstitution(
    query: BaseQueryDto<GovernanceRelationshipsEntity>,
    subjectInstitutionId: NonNullable<GovernanceRelationshipsEntity["subjectInstitutionId"]>,
  ): Promise<IFindAllResponse<GovernanceRelationshipsEntity>> {
    return await this.findByQuery(query, { subjectInstitutionId, deletedAt: IsNull() });
  }
}
