import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { SittingsEntity } from "#/modules/governance/schema/entities/sittings.entity.ts";
import * as Sittings from "#/modules/governance/schema/types/sittings/index.ts";

/**
 * Repository of Sittings: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class SittingsRepository
  extends EntityRepository<
    SittingsEntity,
    Sittings.Types.SittingsSortableField,
    Sittings.Types.SittingsEditableField,
    Sittings.Types.SittingsSelectableField,
    Sittings.Types.ISittingsCreatable
  >
  implements IUpdatableRepository<SittingsEntity, Sittings.Types.ISittingsUpdatable>
{
  constructor(
    @InjectRepository(SittingsEntity)
    repository: Repository<SittingsEntity>,
  ) {
    super(repository, Sittings.Config.SITTINGS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Sittings.Types.ISittingsUpdatable,
  ): Promise<SittingsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find sittings by institution id, paged by the shared query. */
  async findByInstitution(
    query: BaseQueryDto<SittingsEntity>,
    institutionId: NonNullable<SittingsEntity["institutionId"]>,
  ): Promise<IFindAllResponse<SittingsEntity>> {
    return await this.findByQuery(query, { institutionId, deletedAt: IsNull() });
  }

  /** Find sittings by sitting kind id, paged by the shared query. */
  async findBySittingKind(
    query: BaseQueryDto<SittingsEntity>,
    sittingKindId: NonNullable<SittingsEntity["sittingKindId"]>,
  ): Promise<IFindAllResponse<SittingsEntity>> {
    return await this.findByQuery(query, { sittingKindId, deletedAt: IsNull() });
  }

  /** Find sittings by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<SittingsEntity>,
    sourceCitationId: NonNullable<SittingsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<SittingsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find sittings by term id, paged by the shared query. */
  async findByTerm(
    query: BaseQueryDto<SittingsEntity>,
    termId: NonNullable<SittingsEntity["termId"]>,
  ): Promise<IFindAllResponse<SittingsEntity>> {
    return await this.findByQuery(query, { termId, deletedAt: IsNull() });
  }

  /** Find the sittings with this code (unique). */
  async findByCode(code: NonNullable<SittingsEntity["code"]>): Promise<SittingsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }

  /** Find the sittings with this occurrence id (unique). */
  async findByOccurrence(
    occurrenceId: NonNullable<SittingsEntity["occurrenceId"]>,
  ): Promise<SittingsEntity | null> {
    return await this.findOne({ occurrenceId, deletedAt: IsNull() });
  }
}
