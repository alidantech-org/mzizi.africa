import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { HansardsEntity } from "#/modules/governance/schema/entities/hansards.entity.ts";
import * as Hansards from "#/modules/governance/schema/types/hansards/index.ts";

/**
 * Repository of Hansards: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class HansardsRepository
  extends EntityRepository<
    HansardsEntity,
    Hansards.Types.HansardsSortableField,
    Hansards.Types.HansardsEditableField,
    Hansards.Types.HansardsSelectableField,
    Hansards.Types.IHansardsCreatable
  >
  implements IUpdatableRepository<HansardsEntity, Hansards.Types.IHansardsUpdatable>
{
  constructor(
    @InjectRepository(HansardsEntity)
    repository: Repository<HansardsEntity>,
  ) {
    super(repository, Hansards.Config.HANSARDS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Hansards.Types.IHansardsUpdatable,
  ): Promise<HansardsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find hansards by artifact id, paged by the shared query. */
  async findByArtifact(
    query: BaseQueryDto<HansardsEntity>,
    artifactId: NonNullable<HansardsEntity["artifactId"]>,
  ): Promise<IFindAllResponse<HansardsEntity>> {
    return await this.findByQuery(query, { artifactId, deletedAt: IsNull() });
  }

  /** Find hansards by language id, paged by the shared query. */
  async findByLanguage(
    query: BaseQueryDto<HansardsEntity>,
    languageId: NonNullable<HansardsEntity["languageId"]>,
  ): Promise<IFindAllResponse<HansardsEntity>> {
    return await this.findByQuery(query, { languageId, deletedAt: IsNull() });
  }

  /** Find hansards by sitting id, paged by the shared query. */
  async findBySitting(
    query: BaseQueryDto<HansardsEntity>,
    sittingId: NonNullable<HansardsEntity["sittingId"]>,
  ): Promise<IFindAllResponse<HansardsEntity>> {
    return await this.findByQuery(query, { sittingId, deletedAt: IsNull() });
  }

  /** Find hansards by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<HansardsEntity>,
    sourceCitationId: NonNullable<HansardsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<HansardsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the hansards with this code (unique). */
  async findByCode(code: NonNullable<HansardsEntity["code"]>): Promise<HansardsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
