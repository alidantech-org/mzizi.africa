import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { SpeechesEntity } from "#/modules/governance/schema/entities/speeches.entity.ts";
import * as Speeches from "#/modules/governance/schema/types/speeches/index.ts";

/**
 * Repository of Speeches: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class SpeechesRepository
  extends EntityRepository<
    SpeechesEntity,
    Speeches.Types.SpeechesSortableField,
    Speeches.Types.SpeechesEditableField,
    Speeches.Types.SpeechesSelectableField,
    Speeches.Types.ISpeechesCreatable
  >
  implements IUpdatableRepository<SpeechesEntity, Speeches.Types.ISpeechesUpdatable>
{
  constructor(
    @InjectRepository(SpeechesEntity)
    repository: Repository<SpeechesEntity>,
  ) {
    super(repository, Speeches.Config.SPEECHES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Speeches.Types.ISpeechesUpdatable,
  ): Promise<SpeechesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find speeches by bill id, paged by the shared query. */
  async findByBill(
    query: BaseQueryDto<SpeechesEntity>,
    billId: NonNullable<SpeechesEntity["billId"]>,
  ): Promise<IFindAllResponse<SpeechesEntity>> {
    return await this.findByQuery(query, { billId, deletedAt: IsNull() });
  }

  /** Find speeches by hansard id, paged by the shared query. */
  async findByHansard(
    query: BaseQueryDto<SpeechesEntity>,
    hansardId: NonNullable<SpeechesEntity["hansardId"]>,
  ): Promise<IFindAllResponse<SpeechesEntity>> {
    return await this.findByQuery(query, { hansardId, deletedAt: IsNull() });
  }

  /** Find speeches by holder id, paged by the shared query. */
  async findByHolder(
    query: BaseQueryDto<SpeechesEntity>,
    holderId: NonNullable<SpeechesEntity["holderId"]>,
  ): Promise<IFindAllResponse<SpeechesEntity>> {
    return await this.findByQuery(query, { holderId, deletedAt: IsNull() });
  }

  /** Find speeches by motion id, paged by the shared query. */
  async findByMotion(
    query: BaseQueryDto<SpeechesEntity>,
    motionId: NonNullable<SpeechesEntity["motionId"]>,
  ): Promise<IFindAllResponse<SpeechesEntity>> {
    return await this.findByQuery(query, { motionId, deletedAt: IsNull() });
  }

  /** Find speeches by sitting id, paged by the shared query. */
  async findBySitting(
    query: BaseQueryDto<SpeechesEntity>,
    sittingId: NonNullable<SpeechesEntity["sittingId"]>,
  ): Promise<IFindAllResponse<SpeechesEntity>> {
    return await this.findByQuery(query, { sittingId, deletedAt: IsNull() });
  }

  /** Find speeches by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<SpeechesEntity>,
    sourceCitationId: NonNullable<SpeechesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<SpeechesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find speeches by speech kind id, paged by the shared query. */
  async findBySpeechKind(
    query: BaseQueryDto<SpeechesEntity>,
    speechKindId: NonNullable<SpeechesEntity["speechKindId"]>,
  ): Promise<IFindAllResponse<SpeechesEntity>> {
    return await this.findByQuery(query, { speechKindId, deletedAt: IsNull() });
  }

  /** Find the speeches with this code (unique). */
  async findByCode(code: NonNullable<SpeechesEntity["code"]>): Promise<SpeechesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
