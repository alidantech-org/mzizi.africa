import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { PowersEntity } from "#/modules/governance/schema/entities/powers.entity.ts";
import * as Powers from "#/modules/governance/schema/types/powers/index.ts";

/**
 * Repository of Powers: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class PowersRepository
  extends EntityRepository<
    PowersEntity,
    Powers.Types.PowersSortableField,
    Powers.Types.PowersEditableField,
    Powers.Types.PowersSelectableField,
    Powers.Types.IPowersCreatable
  >
  implements IUpdatableRepository<PowersEntity, Powers.Types.IPowersUpdatable>
{
  constructor(
    @InjectRepository(PowersEntity)
    repository: Repository<PowersEntity>,
  ) {
    super(repository, Powers.Config.POWERS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Powers.Types.IPowersUpdatable,
  ): Promise<PowersEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find powers by basis provision id, paged by the shared query. */
  async findByBasisProvision(
    query: BaseQueryDto<PowersEntity>,
    basisProvisionId: NonNullable<PowersEntity["basisProvisionId"]>,
  ): Promise<IFindAllResponse<PowersEntity>> {
    return await this.findByQuery(query, { basisProvisionId, deletedAt: IsNull() });
  }

  /** Find powers by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<PowersEntity>,
    fromToPrecision: NonNullable<PowersEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<PowersEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find powers by holder institution id, paged by the shared query. */
  async findByHolderInstitution(
    query: BaseQueryDto<PowersEntity>,
    holderInstitutionId: NonNullable<PowersEntity["holderInstitutionId"]>,
  ): Promise<IFindAllResponse<PowersEntity>> {
    return await this.findByQuery(query, { holderInstitutionId, deletedAt: IsNull() });
  }

  /** Find powers by holder position id, paged by the shared query. */
  async findByHolderPosition(
    query: BaseQueryDto<PowersEntity>,
    holderPositionId: NonNullable<PowersEntity["holderPositionId"]>,
  ): Promise<IFindAllResponse<PowersEntity>> {
    return await this.findByQuery(query, { holderPositionId, deletedAt: IsNull() });
  }

  /** Find powers by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<PowersEntity>,
    kindId: NonNullable<PowersEntity["kindId"]>,
  ): Promise<IFindAllResponse<PowersEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find powers by procedure id, paged by the shared query. */
  async findByProcedure(
    query: BaseQueryDto<PowersEntity>,
    procedureId: NonNullable<PowersEntity["procedureId"]>,
  ): Promise<IFindAllResponse<PowersEntity>> {
    return await this.findByQuery(query, { procedureId, deletedAt: IsNull() });
  }

  /** Find powers by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<PowersEntity>,
    sourceCitationId: NonNullable<PowersEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<PowersEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find powers by target institution id, paged by the shared query. */
  async findByTargetInstitution(
    query: BaseQueryDto<PowersEntity>,
    targetInstitutionId: NonNullable<PowersEntity["targetInstitutionId"]>,
  ): Promise<IFindAllResponse<PowersEntity>> {
    return await this.findByQuery(query, { targetInstitutionId, deletedAt: IsNull() });
  }

  /** Find powers by target position id, paged by the shared query. */
  async findByTargetPosition(
    query: BaseQueryDto<PowersEntity>,
    targetPositionId: NonNullable<PowersEntity["targetPositionId"]>,
  ): Promise<IFindAllResponse<PowersEntity>> {
    return await this.findByQuery(query, { targetPositionId, deletedAt: IsNull() });
  }

  /** Find powers by threshold id, paged by the shared query. */
  async findByThreshold(
    query: BaseQueryDto<PowersEntity>,
    thresholdId: NonNullable<PowersEntity["thresholdId"]>,
  ): Promise<IFindAllResponse<PowersEntity>> {
    return await this.findByQuery(query, { thresholdId, deletedAt: IsNull() });
  }

  /** Find the powers with this code (unique). */
  async findByCode(code: NonNullable<PowersEntity["code"]>): Promise<PowersEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
