import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ReportsEntity } from "#/modules/governance/schema/entities/reports.entity.ts";
import * as Reports from "#/modules/governance/schema/types/reports/index.ts";

/**
 * Repository of Reports: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ReportsRepository
  extends EntityRepository<
    ReportsEntity,
    Reports.Types.ReportsSortableField,
    Reports.Types.ReportsEditableField,
    Reports.Types.ReportsSelectableField,
    Reports.Types.IReportsCreatable
  >
  implements IUpdatableRepository<ReportsEntity, Reports.Types.IReportsUpdatable>
{
  constructor(
    @InjectRepository(ReportsEntity)
    repository: Repository<ReportsEntity>,
  ) {
    super(repository, Reports.Config.REPORTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Reports.Types.IReportsUpdatable,
  ): Promise<ReportsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find reports by artifact id, paged by the shared query. */
  async findByArtifact(
    query: BaseQueryDto<ReportsEntity>,
    artifactId: NonNullable<ReportsEntity["artifactId"]>,
  ): Promise<IFindAllResponse<ReportsEntity>> {
    return await this.findByQuery(query, { artifactId, deletedAt: IsNull() });
  }

  /** Find reports by obligation id, paged by the shared query. */
  async findByObligation(
    query: BaseQueryDto<ReportsEntity>,
    obligationId: NonNullable<ReportsEntity["obligationId"]>,
  ): Promise<IFindAllResponse<ReportsEntity>> {
    return await this.findByQuery(query, { obligationId, deletedAt: IsNull() });
  }

  /** Find reports by reporter entity id, paged by the shared query. */
  async findByReporterEntity(
    query: BaseQueryDto<ReportsEntity>,
    reporterEntityId: NonNullable<ReportsEntity["reporterEntityId"]>,
  ): Promise<IFindAllResponse<ReportsEntity>> {
    return await this.findByQuery(query, { reporterEntityId, deletedAt: IsNull() });
  }

  /** Find reports by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<ReportsEntity>,
    sourceCitationId: NonNullable<ReportsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<ReportsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find reports by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<ReportsEntity>,
    statusId: NonNullable<ReportsEntity["statusId"]>,
  ): Promise<IFindAllResponse<ReportsEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }

  /** Find the reports with this code (unique). */
  async findByCode(code: NonNullable<ReportsEntity["code"]>): Promise<ReportsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
