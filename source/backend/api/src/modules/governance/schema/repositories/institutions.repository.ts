import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { InstitutionsEntity } from "#/modules/governance/schema/entities/institutions.entity.ts";
import * as Institutions from "#/modules/governance/schema/types/institutions/index.ts";

/**
 * Repository of Institutions: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class InstitutionsRepository
  extends EntityRepository<
    InstitutionsEntity,
    Institutions.Types.InstitutionsSortableField,
    Institutions.Types.InstitutionsEditableField,
    Institutions.Types.InstitutionsSelectableField,
    Institutions.Types.IInstitutionsCreatable
  >
  implements IUpdatableRepository<InstitutionsEntity, Institutions.Types.IInstitutionsUpdatable>
{
  constructor(
    @InjectRepository(InstitutionsEntity)
    repository: Repository<InstitutionsEntity>,
  ) {
    super(repository, Institutions.Config.INSTITUTIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Institutions.Types.IInstitutionsUpdatable,
  ): Promise<InstitutionsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find institutions by arm id, paged by the shared query. */
  async findByArm(
    query: BaseQueryDto<InstitutionsEntity>,
    armId: NonNullable<InstitutionsEntity["armId"]>,
  ): Promise<IFindAllResponse<InstitutionsEntity>> {
    return await this.findByQuery(query, { armId, deletedAt: IsNull() });
  }

  /** Find institutions by entity id, paged by the shared query. */
  async findByEntity(
    query: BaseQueryDto<InstitutionsEntity>,
    entityId: NonNullable<InstitutionsEntity["entityId"]>,
  ): Promise<IFindAllResponse<InstitutionsEntity>> {
    return await this.findByQuery(query, { entityId, deletedAt: IsNull() });
  }

  /** Find institutions by establishment basis id, paged by the shared query. */
  async findByEstablishmentBasis(
    query: BaseQueryDto<InstitutionsEntity>,
    establishmentBasisId: NonNullable<InstitutionsEntity["establishmentBasisId"]>,
  ): Promise<IFindAllResponse<InstitutionsEntity>> {
    return await this.findByQuery(query, { establishmentBasisId, deletedAt: IsNull() });
  }

  /** Find institutions by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<InstitutionsEntity>,
    fromToPrecision: NonNullable<InstitutionsEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<InstitutionsEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find institutions by institution kind id, paged by the shared query. */
  async findByInstitutionKind(
    query: BaseQueryDto<InstitutionsEntity>,
    institutionKindId: NonNullable<InstitutionsEntity["institutionKindId"]>,
  ): Promise<IFindAllResponse<InstitutionsEntity>> {
    return await this.findByQuery(query, { institutionKindId, deletedAt: IsNull() });
  }

  /** Find institutions by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<InstitutionsEntity>,
    sourceCitationId: NonNullable<InstitutionsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<InstitutionsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the institutions with this code (unique). */
  async findByCode(
    code: NonNullable<InstitutionsEntity["code"]>,
  ): Promise<InstitutionsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
