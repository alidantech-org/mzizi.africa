import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { AgendaEntity } from "#/modules/governance/schema/entities/agenda.entity.ts";
import * as Agenda from "#/modules/governance/schema/types/agenda/index.ts";

/**
 * Repository of Agenda: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class AgendaRepository
  extends EntityRepository<
    AgendaEntity,
    Agenda.Types.AgendaSortableField,
    Agenda.Types.AgendaEditableField,
    Agenda.Types.AgendaSelectableField,
    Agenda.Types.IAgendaCreatable
  >
  implements IUpdatableRepository<AgendaEntity, Agenda.Types.IAgendaUpdatable>
{
  constructor(
    @InjectRepository(AgendaEntity)
    repository: Repository<AgendaEntity>,
  ) {
    super(repository, Agenda.Config.AGENDA_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Agenda.Types.IAgendaUpdatable,
  ): Promise<AgendaEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find agenda by agenda kind id, paged by the shared query. */
  async findByAgendaKind(
    query: BaseQueryDto<AgendaEntity>,
    agendaKindId: NonNullable<AgendaEntity["agendaKindId"]>,
  ): Promise<IFindAllResponse<AgendaEntity>> {
    return await this.findByQuery(query, { agendaKindId, deletedAt: IsNull() });
  }

  /** Find agenda by bill id, paged by the shared query. */
  async findByBill(
    query: BaseQueryDto<AgendaEntity>,
    billId: NonNullable<AgendaEntity["billId"]>,
  ): Promise<IFindAllResponse<AgendaEntity>> {
    return await this.findByQuery(query, { billId, deletedAt: IsNull() });
  }

  /** Find agenda by motion id, paged by the shared query. */
  async findByMotion(
    query: BaseQueryDto<AgendaEntity>,
    motionId: NonNullable<AgendaEntity["motionId"]>,
  ): Promise<IFindAllResponse<AgendaEntity>> {
    return await this.findByQuery(query, { motionId, deletedAt: IsNull() });
  }

  /** Find agenda by sitting id, paged by the shared query. */
  async findBySitting(
    query: BaseQueryDto<AgendaEntity>,
    sittingId: NonNullable<AgendaEntity["sittingId"]>,
  ): Promise<IFindAllResponse<AgendaEntity>> {
    return await this.findByQuery(query, { sittingId, deletedAt: IsNull() });
  }

  /** Find agenda by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<AgendaEntity>,
    sourceCitationId: NonNullable<AgendaEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<AgendaEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }
}
