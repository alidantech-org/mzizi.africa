import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { FunctionsEntity } from "#/modules/governance/schema/entities/functions.entity.ts";
import * as Functions from "#/modules/governance/schema/types/functions/index.ts";

/**
 * Repository of Functions: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class FunctionsRepository
  extends EntityRepository<
    FunctionsEntity,
    Functions.Types.FunctionsSortableField,
    Functions.Types.FunctionsEditableField,
    Functions.Types.FunctionsSelectableField,
    Functions.Types.IFunctionsCreatable
  >
  implements IUpdatableRepository<FunctionsEntity, Functions.Types.IFunctionsUpdatable>
{
  constructor(
    @InjectRepository(FunctionsEntity)
    repository: Repository<FunctionsEntity>,
  ) {
    super(repository, Functions.Config.FUNCTIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Functions.Types.IFunctionsUpdatable,
  ): Promise<FunctionsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find functions by basis provision id, paged by the shared query. */
  async findByBasisProvision(
    query: BaseQueryDto<FunctionsEntity>,
    basisProvisionId: NonNullable<FunctionsEntity["basisProvisionId"]>,
  ): Promise<IFindAllResponse<FunctionsEntity>> {
    return await this.findByQuery(query, { basisProvisionId, deletedAt: IsNull() });
  }

  /** Find functions by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<FunctionsEntity>,
    countryId: NonNullable<FunctionsEntity["countryId"]>,
  ): Promise<IFindAllResponse<FunctionsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find functions by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<FunctionsEntity>,
    fromToPrecision: NonNullable<FunctionsEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<FunctionsEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find functions by parent function id, paged by the shared query. */
  async findByParentFunction(
    query: BaseQueryDto<FunctionsEntity>,
    parentFunctionId: NonNullable<FunctionsEntity["parentFunctionId"]>,
  ): Promise<IFindAllResponse<FunctionsEntity>> {
    return await this.findByQuery(query, { parentFunctionId, deletedAt: IsNull() });
  }

  /** Find functions by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<FunctionsEntity>,
    sourceCitationId: NonNullable<FunctionsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<FunctionsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find functions by topic id, paged by the shared query. */
  async findByTopic(
    query: BaseQueryDto<FunctionsEntity>,
    topicId: NonNullable<FunctionsEntity["topicId"]>,
  ): Promise<IFindAllResponse<FunctionsEntity>> {
    return await this.findByQuery(query, { topicId, deletedAt: IsNull() });
  }

  /** Find the functions with this code (unique). */
  async findByCode(code: NonNullable<FunctionsEntity["code"]>): Promise<FunctionsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
