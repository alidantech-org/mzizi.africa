import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { AssignmentsEntity } from "#/modules/governance/schema/entities/assignments.entity.ts";
import * as Assignments from "#/modules/governance/schema/types/assignments/index.ts";

/**
 * Repository of Assignments: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class AssignmentsRepository
  extends EntityRepository<
    AssignmentsEntity,
    Assignments.Types.AssignmentsSortableField,
    Assignments.Types.AssignmentsEditableField,
    Assignments.Types.AssignmentsSelectableField,
    Assignments.Types.IAssignmentsCreatable
  >
  implements IUpdatableRepository<AssignmentsEntity, Assignments.Types.IAssignmentsUpdatable>
{
  constructor(
    @InjectRepository(AssignmentsEntity)
    repository: Repository<AssignmentsEntity>,
  ) {
    super(repository, Assignments.Config.ASSIGNMENTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Assignments.Types.IAssignmentsUpdatable,
  ): Promise<AssignmentsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find assignments by basis provision id, paged by the shared query. */
  async findByBasisProvision(
    query: BaseQueryDto<AssignmentsEntity>,
    basisProvisionId: NonNullable<AssignmentsEntity["basisProvisionId"]>,
  ): Promise<IFindAllResponse<AssignmentsEntity>> {
    return await this.findByQuery(query, { basisProvisionId, deletedAt: IsNull() });
  }

  /** Find assignments by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<AssignmentsEntity>,
    fromToPrecision: NonNullable<AssignmentsEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<AssignmentsEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find assignments by function id, paged by the shared query. */
  async findByFunction(
    query: BaseQueryDto<AssignmentsEntity>,
    functionId: NonNullable<AssignmentsEntity["functionId"]>,
  ): Promise<IFindAllResponse<AssignmentsEntity>> {
    return await this.findByQuery(query, { functionId, deletedAt: IsNull() });
  }

  /** Find assignments by institution id, paged by the shared query. */
  async findByInstitution(
    query: BaseQueryDto<AssignmentsEntity>,
    institutionId: NonNullable<AssignmentsEntity["institutionId"]>,
  ): Promise<IFindAllResponse<AssignmentsEntity>> {
    return await this.findByQuery(query, { institutionId, deletedAt: IsNull() });
  }

  /** Find assignments by obligor kind id, paged by the shared query. */
  async findByObligorKind(
    query: BaseQueryDto<AssignmentsEntity>,
    obligorKindId: NonNullable<AssignmentsEntity["obligorKindId"]>,
  ): Promise<IFindAllResponse<AssignmentsEntity>> {
    return await this.findByQuery(query, { obligorKindId, deletedAt: IsNull() });
  }

  /** Find assignments by share id, paged by the shared query. */
  async findByShare(
    query: BaseQueryDto<AssignmentsEntity>,
    shareId: NonNullable<AssignmentsEntity["shareId"]>,
  ): Promise<IFindAllResponse<AssignmentsEntity>> {
    return await this.findByQuery(query, { shareId, deletedAt: IsNull() });
  }

  /** Find assignments by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<AssignmentsEntity>,
    sourceCitationId: NonNullable<AssignmentsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<AssignmentsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find assignments by start institution id, paged by the shared query. */
  async findByStartInstitution(
    query: BaseQueryDto<AssignmentsEntity>,
    startInstitutionId: NonNullable<AssignmentsEntity["startInstitutionId"]>,
  ): Promise<IFindAllResponse<AssignmentsEntity>> {
    return await this.findByQuery(query, { startInstitutionId, deletedAt: IsNull() });
  }

  /** Find assignments by start position id, paged by the shared query. */
  async findByStartPosition(
    query: BaseQueryDto<AssignmentsEntity>,
    startPositionId: NonNullable<AssignmentsEntity["startPositionId"]>,
  ): Promise<IFindAllResponse<AssignmentsEntity>> {
    return await this.findByQuery(query, { startPositionId, deletedAt: IsNull() });
  }

  /** Find the assignments with this code (unique). */
  async findByCode(
    code: NonNullable<AssignmentsEntity["code"]>,
  ): Promise<AssignmentsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
