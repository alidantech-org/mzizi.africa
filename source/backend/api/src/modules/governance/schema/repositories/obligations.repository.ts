import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ObligationsEntity } from "#/modules/governance/schema/entities/obligations.entity.ts";
import * as Obligations from "#/modules/governance/schema/types/obligations/index.ts";

/**
 * Repository of Obligations: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ObligationsRepository
  extends EntityRepository<
    ObligationsEntity,
    Obligations.Types.ObligationsSortableField,
    Obligations.Types.ObligationsEditableField,
    Obligations.Types.ObligationsSelectableField,
    Obligations.Types.IObligationsCreatable
  >
  implements IUpdatableRepository<ObligationsEntity, Obligations.Types.IObligationsUpdatable>
{
  constructor(
    @InjectRepository(ObligationsEntity)
    repository: Repository<ObligationsEntity>,
  ) {
    super(repository, Obligations.Config.OBLIGATIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Obligations.Types.IObligationsUpdatable,
  ): Promise<ObligationsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find obligations by basis provision id, paged by the shared query. */
  async findByBasisProvision(
    query: BaseQueryDto<ObligationsEntity>,
    basisProvisionId: NonNullable<ObligationsEntity["basisProvisionId"]>,
  ): Promise<IFindAllResponse<ObligationsEntity>> {
    return await this.findByQuery(query, { basisProvisionId, deletedAt: IsNull() });
  }

  /** Find obligations by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<ObligationsEntity>,
    countryId: NonNullable<ObligationsEntity["countryId"]>,
  ): Promise<IFindAllResponse<ObligationsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find obligations by frequency id, paged by the shared query. */
  async findByFrequency(
    query: BaseQueryDto<ObligationsEntity>,
    frequencyId: NonNullable<ObligationsEntity["frequencyId"]>,
  ): Promise<IFindAllResponse<ObligationsEntity>> {
    return await this.findByQuery(query, { frequencyId, deletedAt: IsNull() });
  }

  /** Find obligations by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<ObligationsEntity>,
    fromToPrecision: NonNullable<ObligationsEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<ObligationsEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find obligations by obligation kind id, paged by the shared query. */
  async findByObligationKind(
    query: BaseQueryDto<ObligationsEntity>,
    obligationKindId: NonNullable<ObligationsEntity["obligationKindId"]>,
  ): Promise<IFindAllResponse<ObligationsEntity>> {
    return await this.findByQuery(query, { obligationKindId, deletedAt: IsNull() });
  }

  /** Find obligations by obligor institution id, paged by the shared query. */
  async findByObligorInstitution(
    query: BaseQueryDto<ObligationsEntity>,
    obligorInstitutionId: NonNullable<ObligationsEntity["obligorInstitutionId"]>,
  ): Promise<IFindAllResponse<ObligationsEntity>> {
    return await this.findByQuery(query, { obligorInstitutionId, deletedAt: IsNull() });
  }

  /** Find obligations by obligor kind id, paged by the shared query. */
  async findByObligorKind(
    query: BaseQueryDto<ObligationsEntity>,
    obligorKindId: NonNullable<ObligationsEntity["obligorKindId"]>,
  ): Promise<IFindAllResponse<ObligationsEntity>> {
    return await this.findByQuery(query, { obligorKindId, deletedAt: IsNull() });
  }

  /** Find obligations by recipient entity id, paged by the shared query. */
  async findByRecipientEntity(
    query: BaseQueryDto<ObligationsEntity>,
    recipientEntityId: NonNullable<ObligationsEntity["recipientEntityId"]>,
  ): Promise<IFindAllResponse<ObligationsEntity>> {
    return await this.findByQuery(query, { recipientEntityId, deletedAt: IsNull() });
  }

  /** Find obligations by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<ObligationsEntity>,
    sourceCitationId: NonNullable<ObligationsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<ObligationsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the obligations with this code (unique). */
  async findByCode(
    code: NonNullable<ObligationsEntity["code"]>,
  ): Promise<ObligationsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
