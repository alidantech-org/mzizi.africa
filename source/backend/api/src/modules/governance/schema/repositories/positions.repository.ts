  /** Find positions by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<PositionsEntity>,
    sourceCitationId: NonNullable<PositionsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<PositionsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

