import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { VotesEntity } from "#/modules/governance/schema/entities/votes.entity.ts";
import * as Votes from "#/modules/governance/schema/types/votes/index.ts";

/**
 * Repository of Votes: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class VotesRepository
  extends EntityRepository<
    VotesEntity,
    Votes.Types.VotesSortableField,
    Votes.Types.VotesEditableField,
    Votes.Types.VotesSelectableField,
    Votes.Types.IVotesCreatable
  >
  implements IUpdatableRepository<VotesEntity, Votes.Types.IVotesUpdatable>
{
  constructor(
    @InjectRepository(VotesEntity)
    repository: Repository<VotesEntity>,
  ) {
    super(repository, Votes.Config.VOTES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Votes.Types.IVotesUpdatable): Promise<VotesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find votes by holder id, paged by the shared query. */
  async findByHolder(
    query: BaseQueryDto<VotesEntity>,
    holderId: NonNullable<VotesEntity["holderId"]>,
  ): Promise<IFindAllResponse<VotesEntity>> {
    return await this.findByQuery(query, { holderId, deletedAt: IsNull() });
  }

  /** Find votes by motion id, paged by the shared query. */
  async findByMotion(
    query: BaseQueryDto<VotesEntity>,
    motionId: NonNullable<VotesEntity["motionId"]>,
  ): Promise<IFindAllResponse<VotesEntity>> {
    return await this.findByQuery(query, { motionId, deletedAt: IsNull() });
  }

  /** Find votes by position id, paged by the shared query. */
  async findByPosition(
    query: BaseQueryDto<VotesEntity>,
    positionId: NonNullable<VotesEntity["positionId"]>,
  ): Promise<IFindAllResponse<VotesEntity>> {
    return await this.findByQuery(query, { positionId, deletedAt: IsNull() });
  }

  /** Find votes by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<VotesEntity>,
    sourceCitationId: NonNullable<VotesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<VotesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }
}
