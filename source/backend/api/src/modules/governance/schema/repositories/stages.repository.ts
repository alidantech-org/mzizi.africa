import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { StagesEntity } from "#/modules/governance/schema/entities/stages.entity.ts";
import * as Stages from "#/modules/governance/schema/types/stages/index.ts";

/**
 * Repository of Stages: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class StagesRepository
  extends EntityRepository<
    StagesEntity,
    Stages.Types.StagesSortableField,
    Stages.Types.StagesEditableField,
    Stages.Types.StagesSelectableField,
    Stages.Types.IStagesCreatable
  >
  implements IUpdatableRepository<StagesEntity, Stages.Types.IStagesUpdatable>
{
  constructor(
    @InjectRepository(StagesEntity)
    repository: Repository<StagesEntity>,
  ) {
    super(repository, Stages.Config.STAGES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Stages.Types.IStagesUpdatable,
  ): Promise<StagesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find stages by bill id, paged by the shared query. */
  async findByBill(
    query: BaseQueryDto<StagesEntity>,
    billId: NonNullable<StagesEntity["billId"]>,
  ): Promise<IFindAllResponse<StagesEntity>> {
    return await this.findByQuery(query, { billId, deletedAt: IsNull() });
  }

  /** Find stages by motion id, paged by the shared query. */
  async findByMotion(
    query: BaseQueryDto<StagesEntity>,
    motionId: NonNullable<StagesEntity["motionId"]>,
  ): Promise<IFindAllResponse<StagesEntity>> {
    return await this.findByQuery(query, { motionId, deletedAt: IsNull() });
  }

  /** Find stages by outcome id, paged by the shared query. */
  async findByOutcome(
    query: BaseQueryDto<StagesEntity>,
    outcomeId: NonNullable<StagesEntity["outcomeId"]>,
  ): Promise<IFindAllResponse<StagesEntity>> {
    return await this.findByQuery(query, { outcomeId, deletedAt: IsNull() });
  }

  /** Find stages by sitting id, paged by the shared query. */
  async findBySitting(
    query: BaseQueryDto<StagesEntity>,
    sittingId: NonNullable<StagesEntity["sittingId"]>,
  ): Promise<IFindAllResponse<StagesEntity>> {
    return await this.findByQuery(query, { sittingId, deletedAt: IsNull() });
  }

  /** Find stages by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<StagesEntity>,
    sourceCitationId: NonNullable<StagesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<StagesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find stages by stage kind id, paged by the shared query. */
  async findByStageKind(
    query: BaseQueryDto<StagesEntity>,
    stageKindId: NonNullable<StagesEntity["stageKindId"]>,
  ): Promise<IFindAllResponse<StagesEntity>> {
    return await this.findByQuery(query, { stageKindId, deletedAt: IsNull() });
  }
}
