import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { BillsEntity } from "#/modules/governance/schema/entities/bills.entity.ts";
import * as Bills from "#/modules/governance/schema/types/bills/index.ts";

/**
 * Repository of Bills: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class BillsRepository
  extends EntityRepository<
    BillsEntity,
    Bills.Types.BillsSortableField,
    Bills.Types.BillsEditableField,
    Bills.Types.BillsSelectableField,
    Bills.Types.IBillsCreatable
  >
  implements IUpdatableRepository<BillsEntity, Bills.Types.IBillsUpdatable>
{
  constructor(
    @InjectRepository(BillsEntity)
    repository: Repository<BillsEntity>,
  ) {
    super(repository, Bills.Config.BILLS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Bills.Types.IBillsUpdatable): Promise<BillsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find bills by bill kind id, paged by the shared query. */
  async findByBillKind(
    query: BaseQueryDto<BillsEntity>,
    billKindId: NonNullable<BillsEntity["billKindId"]>,
  ): Promise<IFindAllResponse<BillsEntity>> {
    return await this.findByQuery(query, { billKindId, deletedAt: IsNull() });
  }

  /** Find bills by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<BillsEntity>,
    countryId: NonNullable<BillsEntity["countryId"]>,
  ): Promise<IFindAllResponse<BillsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find bills by institution id, paged by the shared query. */
  async findByInstitution(
    query: BaseQueryDto<BillsEntity>,
    institutionId: NonNullable<BillsEntity["institutionId"]>,
  ): Promise<IFindAllResponse<BillsEntity>> {
    return await this.findByQuery(query, { institutionId, deletedAt: IsNull() });
  }

  /** Find bills by instrument id, paged by the shared query. */
  async findByInstrument(
    query: BaseQueryDto<BillsEntity>,
    instrumentId: NonNullable<BillsEntity["instrumentId"]>,
  ): Promise<IFindAllResponse<BillsEntity>> {
    return await this.findByQuery(query, { instrumentId, deletedAt: IsNull() });
  }

  /** Find bills by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<BillsEntity>,
    sourceCitationId: NonNullable<BillsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<BillsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find bills by sponsor holder id, paged by the shared query. */
  async findBySponsorHolder(
    query: BaseQueryDto<BillsEntity>,
    sponsorHolderId: NonNullable<BillsEntity["sponsorHolderId"]>,
  ): Promise<IFindAllResponse<BillsEntity>> {
    return await this.findByQuery(query, { sponsorHolderId, deletedAt: IsNull() });
  }

  /** Find bills by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<BillsEntity>,
    statusId: NonNullable<BillsEntity["statusId"]>,
  ): Promise<IFindAllResponse<BillsEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }

  /** Find bills by term id, paged by the shared query. */
  async findByTerm(
    query: BaseQueryDto<BillsEntity>,
    termId: NonNullable<BillsEntity["termId"]>,
  ): Promise<IFindAllResponse<BillsEntity>> {
    return await this.findByQuery(query, { termId, deletedAt: IsNull() });
  }

  /** Find the bills with this code (unique). */
  async findByCode(code: NonNullable<BillsEntity["code"]>): Promise<BillsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
