import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { AuthorityScopesEntity } from "#/modules/governance/schema/entities/authority-scopes.entity.ts";
import * as AuthorityScopes from "#/modules/governance/schema/types/authority-scopes/index.ts";

/**
 * Repository of Authority Scopes: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class AuthorityScopesRepository
  extends EntityRepository<
    AuthorityScopesEntity,
    AuthorityScopes.Types.AuthorityScopesSortableField,
    AuthorityScopes.Types.AuthorityScopesEditableField,
    AuthorityScopes.Types.AuthorityScopesSelectableField,
    AuthorityScopes.Types.IAuthorityScopesCreatable
  >
  implements
    IUpdatableRepository<AuthorityScopesEntity, AuthorityScopes.Types.IAuthorityScopesUpdatable>
{
  constructor(
    @InjectRepository(AuthorityScopesEntity)
    repository: Repository<AuthorityScopesEntity>,
  ) {
    super(repository, AuthorityScopes.Config.AUTHORITY_SCOPES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: AuthorityScopes.Types.IAuthorityScopesUpdatable,
  ): Promise<AuthorityScopesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find authority scopes by authority kind id, paged by the shared query. */
  async findByAuthorityKind(
    query: BaseQueryDto<AuthorityScopesEntity>,
    authorityKindId: NonNullable<AuthorityScopesEntity["authorityKindId"]>,
  ): Promise<IFindAllResponse<AuthorityScopesEntity>> {
    return await this.findByQuery(query, { authorityKindId, deletedAt: IsNull() });
  }

  /** Find authority scopes by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<AuthorityScopesEntity>,
    countryId: NonNullable<AuthorityScopesEntity["countryId"]>,
  ): Promise<IFindAllResponse<AuthorityScopesEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find authority scopes by institution id, paged by the shared query. */
  async findByInstitution(
    query: BaseQueryDto<AuthorityScopesEntity>,
    institutionId: NonNullable<AuthorityScopesEntity["institutionId"]>,
  ): Promise<IFindAllResponse<AuthorityScopesEntity>> {
    return await this.findByQuery(query, { institutionId, deletedAt: IsNull() });
  }

  /** Find authority scopes by office id, paged by the shared query. */
  async findByOffice(
    query: BaseQueryDto<AuthorityScopesEntity>,
    officeId: NonNullable<AuthorityScopesEntity["officeId"]>,
  ): Promise<IFindAllResponse<AuthorityScopesEntity>> {
    return await this.findByQuery(query, { officeId, deletedAt: IsNull() });
  }

  /** Find authority scopes by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<AuthorityScopesEntity>,
    sourceCitationId: NonNullable<AuthorityScopesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<AuthorityScopesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find authority scopes by unit feature id, paged by the shared query. */
  async findByUnitFeature(
    query: BaseQueryDto<AuthorityScopesEntity>,
    unitFeatureId: NonNullable<AuthorityScopesEntity["unitFeatureId"]>,
  ): Promise<IFindAllResponse<AuthorityScopesEntity>> {
    return await this.findByQuery(query, { unitFeatureId, deletedAt: IsNull() });
  }
}
