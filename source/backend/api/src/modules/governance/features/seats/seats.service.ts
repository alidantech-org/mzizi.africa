import { Injectable } from "@nestjs/common";
import type { OfficeCollectionDto } from "#/modules/governance/schema/dto/office-collection.dto.ts";
import type { OfficeDetailDto } from "#/modules/governance/schema/dto/office-detail.dto.ts";
import type { OfficeKeyDto } from "#/modules/governance/schema/dto/office-key.dto.ts";
import type { PlaceOfficesDto } from "#/modules/governance/schema/dto/place-offices.dto.ts";
import { GetOfficeUseCase } from "#/modules/governance/features/seats/use-cases/get-office.repository.ts";
import { ListPlaceOfficesUseCase } from "#/modules/governance/features/seats/use-cases/list-place-offices.repository.ts";

/**
 * The Seats contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class GovernanceSeatsService {
  abstract getOffice(input: OfficeKeyDto): Promise<OfficeDetailDto>;
  abstract listPlaceOffices(input: PlaceOfficesDto): Promise<OfficeCollectionDto>;
}

@Injectable()
export class GovernanceSeatsServiceImpl extends GovernanceSeatsService {
  constructor(
    private readonly getOfficeUseCase: GetOfficeUseCase,
    private readonly listPlaceOfficesUseCase: ListPlaceOfficesUseCase,
  ) {
    super();
  }

  getOffice(input: OfficeKeyDto): Promise<OfficeDetailDto> {
    return this.getOfficeUseCase.execute(input);
  }

  listPlaceOffices(input: PlaceOfficesDto): Promise<OfficeCollectionDto> {
    return this.listPlaceOfficesUseCase.execute(input);
  }
}
