import { Injectable } from "@nestjs/common";
import type { GovernanceIdentityScopeDto } from "#/modules/governance/schema/dto/governance-identity-scope.dto.ts";
import type { InstitutionCollectionDto } from "#/modules/governance/schema/dto/institution-collection.dto.ts";
import type { InstitutionDetailDto } from "#/modules/governance/schema/dto/institution-detail.dto.ts";
import type { InstitutionKeyDto } from "#/modules/governance/schema/dto/institution-key.dto.ts";
import type { InstitutionWindowDto } from "#/modules/governance/schema/dto/institution-window.dto.ts";
import type { PowerCollectionDto } from "#/modules/governance/schema/dto/power-collection.dto.ts";
import type { RelationshipCollectionDto } from "#/modules/governance/schema/dto/relationship-collection.dto.ts";
import { GetInstitutionUseCase } from "#/modules/governance/features/bodies/use-cases/get-institution.repository.ts";
import { ListInstitutionsUseCase } from "#/modules/governance/features/bodies/use-cases/list-institutions.repository.ts";
import { ListMembersUseCase } from "#/modules/governance/features/bodies/use-cases/list-members.repository.ts";
import { ListPowersUseCase } from "#/modules/governance/features/bodies/use-cases/list-powers.repository.ts";

/**
 * The Bodies contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class GovernanceBodiesService {
  abstract getInstitution(input: InstitutionKeyDto): Promise<InstitutionDetailDto>;
  abstract listInstitutions(input: InstitutionWindowDto): Promise<InstitutionCollectionDto>;
  abstract listMembers(input: GovernanceIdentityScopeDto): Promise<RelationshipCollectionDto>;
  abstract listPowers(input: GovernanceIdentityScopeDto): Promise<PowerCollectionDto>;
}

@Injectable()
export class GovernanceBodiesServiceImpl extends GovernanceBodiesService {
  constructor(
    private readonly getInstitutionUseCase: GetInstitutionUseCase,
    private readonly listInstitutionsUseCase: ListInstitutionsUseCase,
    private readonly listMembersUseCase: ListMembersUseCase,
    private readonly listPowersUseCase: ListPowersUseCase,
  ) {
    super();
  }

  getInstitution(input: InstitutionKeyDto): Promise<InstitutionDetailDto> {
    return this.getInstitutionUseCase.execute(input);
  }

  listInstitutions(input: InstitutionWindowDto): Promise<InstitutionCollectionDto> {
    return this.listInstitutionsUseCase.execute(input);
  }

  listMembers(input: GovernanceIdentityScopeDto): Promise<RelationshipCollectionDto> {
    return this.listMembersUseCase.execute(input);
  }

  listPowers(input: GovernanceIdentityScopeDto): Promise<PowerCollectionDto> {
    return this.listPowersUseCase.execute(input);
  }
}
