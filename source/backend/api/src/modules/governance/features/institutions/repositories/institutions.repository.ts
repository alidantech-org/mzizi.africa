  /** One office with everyone who has held it, newest first. */
  async getOffice(input: Row, context: ReadContext = {}): Promise<Row> {
    const params: Row = {
      officeId: input.officeId,
    };
    if (params.officeId === undefined) throw new Error("officeId is required");
    const query = this.repositoryOf(OfficesRepository, OfficesEntity).query("r", context.manager);
    query.select([]);
    if (params.officeId !== undefined) {
      query.andWhere("r.id = :w_officeId", { w_officeId: params.officeId });
    }
    query.andWhere("r.deletedAt IS NULL");
    query.addSelect("r.code", "code");
    query.addSelect("r.id", "id");
    query.addSelect("r.institutionId", "institutionId");
    query.leftJoin(ValueEntity, "r_officeKindId", "r_officeKindId.id = r.officeKindId");
    query.addSelect("r_officeKindId.code", "kind");
    query.addSelect("r.unitFeatureId", "unitFeatureId");
    query.addSelect("r.id", "__key_id");
    query.orderBy("r.id", "ASC");
    query.limit(1);
    const raws = await query.getRawMany<Row>();
    if (raws.length === 0)
      throw missing("not_found", "The requested resource does not exist.", 404);
    const rows: Row[] = raws.map((raw) => ({
      code: raw.code,
      id: raw.id,
      institutionId: raw.institutionId,
      kind: raw.kind,
      unitFeatureId: raw.unitFeatureId,
    }));
    const holdersByOwner = await this.load_GetOffice_holders(
      raws.map((raw) => raw.__key_id),
      context,
    );
    rows.forEach((row, index) => {
      const owned = holdersByOwner.get(raws[index]?.__key_id);
      row.holders = owned ?? [];
    });
    return rows[0] as Row;
  }

