import { Injectable } from "@nestjs/common";
import type { InstitutionCollectionDto } from "#/modules/governance/schema/dto/institution-collection.dto.ts";
import type { InstitutionDetailDto } from "#/modules/governance/schema/dto/institution-detail.dto.ts";
import type { InstitutionKeyDto } from "#/modules/governance/schema/dto/institution-key.dto.ts";
import type { InstitutionWindowDto } from "#/modules/governance/schema/dto/institution-window.dto.ts";
import type { OfficeDetailDto } from "#/modules/governance/schema/dto/office-detail.dto.ts";
import type { OfficeKeyDto } from "#/modules/governance/schema/dto/office-key.dto.ts";
import { BrowseInstitutionsUseCase } from "#/modules/governance/features/institutions/use-cases/browse-institutions.usecase.ts";
import { GetInstitutionUseCase } from "#/modules/governance/features/institutions/use-cases/get-institution.usecase.ts";
import { GetOfficeUseCase } from "#/modules/governance/features/institutions/use-cases/get-office.usecase.ts";

/**
 * The Institutions contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class GovernanceInstitutionsService {
  abstract browseInstitutions(input: InstitutionWindowDto): Promise<InstitutionCollectionDto>;
  abstract getInstitution(input: InstitutionKeyDto): Promise<InstitutionDetailDto>;
  abstract getOffice(input: OfficeKeyDto): Promise<OfficeDetailDto>;
}

@Injectable()
export class GovernanceInstitutionsServiceImpl extends GovernanceInstitutionsService {
  constructor(
    private readonly browseInstitutionsUseCase: BrowseInstitutionsUseCase,
    private readonly getInstitutionUseCase: GetInstitutionUseCase,
    private readonly getOfficeUseCase: GetOfficeUseCase,
  ) {
    super();
  }

  browseInstitutions(input: InstitutionWindowDto): Promise<InstitutionCollectionDto> {
    return this.browseInstitutionsUseCase.execute(input);
  }

  getInstitution(input: InstitutionKeyDto): Promise<InstitutionDetailDto> {
    return this.getInstitutionUseCase.execute(input);
  }

  getOffice(input: OfficeKeyDto): Promise<OfficeDetailDto> {
    return this.getOfficeUseCase.execute(input);
  }
}
