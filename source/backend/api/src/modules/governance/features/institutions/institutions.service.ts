
import type { InstitutionCollectionDto } from "#/modules/governance/schema/dto/institution-collection.dto.ts";
import type { InstitutionDetailDto } from "#/modules/governance/schema/dto/institution-detail.dto.ts";
import type { InstitutionKeyDto } from "#/modules/governance/schema/dto/institution-key.dto.ts";
import type { InstitutionWindowDto } from "#/modules/governance/schema/dto/institution-window.dto.ts";
import type { OfficeDetailDto } from "#/modules/governance/schema/dto/office-detail.dto.ts";
import type { OfficeKeyDto } from "#/modules/governance/schema/dto/office-key.dto.ts";

/**
 * The Institutions contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class GovernanceInstitutionsService {
  abstract browseInstitutions(input: InstitutionWindowDto): Promise<InstitutionCollectionDto>;
  abstract getInstitution(input: InstitutionKeyDto): Promise<InstitutionDetailDto>;
  abstract getOffice(input: OfficeKeyDto): Promise<OfficeDetailDto>;
}