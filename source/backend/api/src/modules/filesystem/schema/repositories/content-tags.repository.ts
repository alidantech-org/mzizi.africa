import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ContentTagsEntity } from "#/modules/filesystem/schema/entities/content-tags.entity.ts";
import * as ContentTags from "#/modules/filesystem/schema/types/content-tags/index.ts";

/**
 * Repository of Content Tags: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ContentTagsRepository
  extends EntityRepository<
    ContentTagsEntity,
    ContentTags.Types.ContentTagsSortableField,
    ContentTags.Types.ContentTagsEditableField,
    ContentTags.Types.ContentTagsSelectableField,
    ContentTags.Types.IContentTagsCreatable
  >
  implements IUpdatableRepository<ContentTagsEntity, ContentTags.Types.IContentTagsUpdatable>
{
  constructor(
    @InjectRepository(ContentTagsEntity)
    repository: Repository<ContentTagsEntity>,
  ) {
    super(repository, ContentTags.Config.CONTENT_TAGS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: ContentTags.Types.IContentTagsUpdatable,
  ): Promise<ContentTagsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find content tags by content id, paged by the shared query. */
  async findByContent(
    query: BaseQueryDto<ContentTagsEntity>,
    contentId: NonNullable<ContentTagsEntity["contentId"]>,
  ): Promise<IFindAllResponse<ContentTagsEntity>> {
    return await this.findByQuery(query, { contentId, deletedAt: IsNull() });
  }

  /** Find content tags by tag id, paged by the shared query. */
  async findByTag(
    query: BaseQueryDto<ContentTagsEntity>,
    tagId: NonNullable<ContentTagsEntity["tagId"]>,
  ): Promise<IFindAllResponse<ContentTagsEntity>> {
    return await this.findByQuery(query, { tagId, deletedAt: IsNull() });
  }
}
