import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { FilesEntity } from "#/modules/filesystem/schema/entities/files.entity.ts";
import * as Files from "#/modules/filesystem/schema/types/files/index.ts";

/**
 * Repository of Files: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class FilesRepository
  extends EntityRepository<
    FilesEntity,
    Files.Types.FilesSortableField,
    Files.Types.FilesEditableField,
    Files.Types.FilesSelectableField,
    Files.Types.IFilesCreatable
  >
  implements IUpdatableRepository<FilesEntity, Files.Types.IFilesUpdatable>
{
  constructor(
    @InjectRepository(FilesEntity)
    repository: Repository<FilesEntity>,
  ) {
    super(repository, Files.Config.FILES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Files.Types.IFilesUpdatable): Promise<FilesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find files by current version id, paged by the shared query. */
  async findByCurrentVersion(
    query: BaseQueryDto<FilesEntity>,
    currentVersionId: NonNullable<FilesEntity["currentVersionId"]>,
  ): Promise<IFindAllResponse<FilesEntity>> {
    return await this.findByQuery(query, { currentVersionId, deletedAt: IsNull() });
  }

  /** Find files by folder id, paged by the shared query. */
  async findByFolder(
    query: BaseQueryDto<FilesEntity>,
    folderId: NonNullable<FilesEntity["folderId"]>,
  ): Promise<IFindAllResponse<FilesEntity>> {
    return await this.findByQuery(query, { folderId, deletedAt: IsNull() });
  }

  /** Find files by retention, paged by the shared query. */
  async findByRetention(
    query: BaseQueryDto<FilesEntity>,
    retention: NonNullable<FilesEntity["retention"]>,
  ): Promise<IFindAllResponse<FilesEntity>> {
    return await this.findByQuery(query, { retention, deletedAt: IsNull() });
  }

  /** Find the files with this code (unique). */
  async findByCode(code: NonNullable<FilesEntity["code"]>): Promise<FilesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
