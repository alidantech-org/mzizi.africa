import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { TaggingsEntity } from "#/modules/filesystem/schema/entities/taggings.entity.ts";
import * as Taggings from "#/modules/filesystem/schema/types/taggings/index.ts";

/**
 * Repository of Taggings: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class TaggingsRepository
  extends EntityRepository<
    TaggingsEntity,
    Taggings.Types.TaggingsSortableField,
    Taggings.Types.TaggingsEditableField,
    Taggings.Types.TaggingsSelectableField,
    Taggings.Types.ITaggingsCreatable
  >
  implements IUpdatableRepository<TaggingsEntity, Taggings.Types.ITaggingsUpdatable>
{
  constructor(
    @InjectRepository(TaggingsEntity)
    repository: Repository<TaggingsEntity>,
  ) {
    super(repository, Taggings.Config.TAGGINGS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Taggings.Types.ITaggingsUpdatable,
  ): Promise<TaggingsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find taggings by file id, paged by the shared query. */
  async findByFile(
    query: BaseQueryDto<TaggingsEntity>,
    fileId: NonNullable<TaggingsEntity["fileId"]>,
  ): Promise<IFindAllResponse<TaggingsEntity>> {
    return await this.findByQuery(query, { fileId, deletedAt: IsNull() });
  }

  /** Find taggings by folder id, paged by the shared query. */
  async findByFolder(
    query: BaseQueryDto<TaggingsEntity>,
    folderId: NonNullable<TaggingsEntity["folderId"]>,
  ): Promise<IFindAllResponse<TaggingsEntity>> {
    return await this.findByQuery(query, { folderId, deletedAt: IsNull() });
  }

  /** Find taggings by tag id, paged by the shared query. */
  async findByTag(
    query: BaseQueryDto<TaggingsEntity>,
    tagId: NonNullable<TaggingsEntity["tagId"]>,
  ): Promise<IFindAllResponse<TaggingsEntity>> {
    return await this.findByQuery(query, { tagId, deletedAt: IsNull() });
  }
}
