import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { FileRelationsEntity } from "#/modules/filesystem/schema/entities/file-relations.entity.ts";
import * as FileRelations from "#/modules/filesystem/schema/types/file-relations/index.ts";

/**
 * Repository of File Relations: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class FileRelationsRepository
  extends EntityRepository<
    FileRelationsEntity,
    FileRelations.Types.FileRelationsSortableField,
    FileRelations.Types.FileRelationsEditableField,
    FileRelations.Types.FileRelationsSelectableField,
    FileRelations.Types.IFileRelationsCreatable
  >
  implements IUpdatableRepository<FileRelationsEntity, FileRelations.Types.IFileRelationsUpdatable>
{
  constructor(
    @InjectRepository(FileRelationsEntity)
    repository: Repository<FileRelationsEntity>,
  ) {
    super(repository, FileRelations.Config.FILE_RELATIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: FileRelations.Types.IFileRelationsUpdatable,
  ): Promise<FileRelationsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find file relations by derived version id, paged by the shared query. */
  async findByDerivedVersion(
    query: BaseQueryDto<FileRelationsEntity>,
    derivedVersionId: NonNullable<FileRelationsEntity["derivedVersionId"]>,
  ): Promise<IFindAllResponse<FileRelationsEntity>> {
    return await this.findByQuery(query, { derivedVersionId, deletedAt: IsNull() });
  }

  /** Find file relations by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<FileRelationsEntity>,
    kindId: NonNullable<FileRelationsEntity["kindId"]>,
  ): Promise<IFindAllResponse<FileRelationsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find file relations by source version id, paged by the shared query. */
  async findBySourceVersion(
    query: BaseQueryDto<FileRelationsEntity>,
    sourceVersionId: NonNullable<FileRelationsEntity["sourceVersionId"]>,
  ): Promise<IFindAllResponse<FileRelationsEntity>> {
    return await this.findByQuery(query, { sourceVersionId, deletedAt: IsNull() });
  }
}
