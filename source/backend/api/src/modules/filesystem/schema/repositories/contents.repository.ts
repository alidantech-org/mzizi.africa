import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ContentsEntity } from "#/modules/filesystem/schema/entities/contents.entity.ts";
import * as Contents from "#/modules/filesystem/schema/types/contents/index.ts";

/**
 * Repository of Contents: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ContentsRepository
  extends EntityRepository<
    ContentsEntity,
    Contents.Types.ContentsSortableField,
    Contents.Types.ContentsEditableField,
    Contents.Types.ContentsSelectableField,
    Contents.Types.IContentsCreatable
  >
  implements IUpdatableRepository<ContentsEntity, Contents.Types.IContentsUpdatable>
{
  constructor(
    @InjectRepository(ContentsEntity)
    repository: Repository<ContentsEntity>,
  ) {
    super(repository, Contents.Config.CONTENTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Contents.Types.IContentsUpdatable,
  ): Promise<ContentsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find contents by category id, paged by the shared query. */
  async findByCategory(
    query: BaseQueryDto<ContentsEntity>,
    categoryId: NonNullable<ContentsEntity["categoryId"]>,
  ): Promise<IFindAllResponse<ContentsEntity>> {
    return await this.findByQuery(query, { categoryId, deletedAt: IsNull() });
  }

  /** Find contents by classification id, paged by the shared query. */
  async findByClassification(
    query: BaseQueryDto<ContentsEntity>,
    classificationId: NonNullable<ContentsEntity["classificationId"]>,
  ): Promise<IFindAllResponse<ContentsEntity>> {
    return await this.findByQuery(query, { classificationId, deletedAt: IsNull() });
  }

  /** Find contents by file version id, paged by the shared query. */
  async findByFileVersion(
    query: BaseQueryDto<ContentsEntity>,
    fileVersionId: NonNullable<ContentsEntity["fileVersionId"]>,
  ): Promise<IFindAllResponse<ContentsEntity>> {
    return await this.findByQuery(query, { fileVersionId, deletedAt: IsNull() });
  }

  /** Find contents by language id, paged by the shared query. */
  async findByLanguage(
    query: BaseQueryDto<ContentsEntity>,
    languageId: NonNullable<ContentsEntity["languageId"]>,
  ): Promise<IFindAllResponse<ContentsEntity>> {
    return await this.findByQuery(query, { languageId, deletedAt: IsNull() });
  }

  /** Find contents by subject table, paged by the shared query. */
  async findBySubjectTable(
    query: BaseQueryDto<ContentsEntity>,
    subjectTable: NonNullable<ContentsEntity["subjectTable"]>,
  ): Promise<IFindAllResponse<ContentsEntity>> {
    return await this.findByQuery(query, { subjectTable, deletedAt: IsNull() });
  }

  /** Find the contents with this code (unique). */
  async findByCode(code: NonNullable<ContentsEntity["code"]>): Promise<ContentsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
