import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { FileVersionsEntity } from "#/modules/filesystem/schema/entities/file-versions.entity.ts";
import * as FileVersions from "#/modules/filesystem/schema/types/file-versions/index.ts";

/**
 * Repository of File Versions: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class FileVersionsRepository
  extends EntityRepository<
    FileVersionsEntity,
    FileVersions.Types.FileVersionsSortableField,
    FileVersions.Types.FileVersionsEditableField,
    FileVersions.Types.FileVersionsSelectableField,
    FileVersions.Types.IFileVersionsCreatable
  >
  implements IUpdatableRepository<FileVersionsEntity, FileVersions.Types.IFileVersionsUpdatable>
{
  constructor(
    @InjectRepository(FileVersionsEntity)
    repository: Repository<FileVersionsEntity>,
  ) {
    super(repository, FileVersions.Config.FILE_VERSIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: FileVersions.Types.IFileVersionsUpdatable,
  ): Promise<FileVersionsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find file versions by access, paged by the shared query. */
  async findByAccess(
    query: BaseQueryDto<FileVersionsEntity>,
    access: NonNullable<FileVersionsEntity["access"]>,
  ): Promise<IFindAllResponse<FileVersionsEntity>> {
    return await this.findByQuery(query, { access, deletedAt: IsNull() });
  }

  /** Find file versions by file extension id, paged by the shared query. */
  async findByFileExtension(
    query: BaseQueryDto<FileVersionsEntity>,
    fileExtensionId: NonNullable<FileVersionsEntity["fileExtensionId"]>,
  ): Promise<IFindAllResponse<FileVersionsEntity>> {
    return await this.findByQuery(query, { fileExtensionId, deletedAt: IsNull() });
  }

  /** Find file versions by file id, paged by the shared query. */
  async findByFile(
    query: BaseQueryDto<FileVersionsEntity>,
    fileId: NonNullable<FileVersionsEntity["fileId"]>,
  ): Promise<IFindAllResponse<FileVersionsEntity>> {
    return await this.findByQuery(query, { fileId, deletedAt: IsNull() });
  }
}
