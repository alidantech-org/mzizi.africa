import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { MediaEntity } from "#/modules/filesystem/schema/entities/media.entity.ts";
import * as Media from "#/modules/filesystem/schema/types/media/index.ts";

/**
 * Repository of Media: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class MediaRepository
  extends EntityRepository<
    MediaEntity,
    Media.Types.MediaSortableField,
    Media.Types.MediaEditableField,
    Media.Types.MediaSelectableField,
    Media.Types.IMediaCreatable
  >
  implements IUpdatableRepository<MediaEntity, Media.Types.IMediaUpdatable>
{
  constructor(
    @InjectRepository(MediaEntity)
    repository: Repository<MediaEntity>,
  ) {
    super(repository, Media.Config.MEDIA_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Media.Types.IMediaUpdatable): Promise<MediaEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find media by file version id, paged by the shared query. */
  async findByFileVersion(
    query: BaseQueryDto<MediaEntity>,
    fileVersionId: NonNullable<MediaEntity["fileVersionId"]>,
  ): Promise<IFindAllResponse<MediaEntity>> {
    return await this.findByQuery(query, { fileVersionId, deletedAt: IsNull() });
  }

  /** Find media by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<MediaEntity>,
    kindId: NonNullable<MediaEntity["kindId"]>,
  ): Promise<IFindAllResponse<MediaEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find media by subject table, paged by the shared query. */
  async findBySubjectTable(
    query: BaseQueryDto<MediaEntity>,
    subjectTable: NonNullable<MediaEntity["subjectTable"]>,
  ): Promise<IFindAllResponse<MediaEntity>> {
    return await this.findByQuery(query, { subjectTable, deletedAt: IsNull() });
  }

  /** Find the media with this code (unique). */
  async findByCode(code: NonNullable<MediaEntity["code"]>): Promise<MediaEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
