import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { FoldersEntity } from "#/modules/filesystem/schema/entities/folders.entity.ts";
import * as Folders from "#/modules/filesystem/schema/types/folders/index.ts";

/**
 * Repository of Folders: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class FoldersRepository
  extends EntityRepository<
    FoldersEntity,
    Folders.Types.FoldersSortableField,
    Folders.Types.FoldersEditableField,
    Folders.Types.FoldersSelectableField,
    Folders.Types.IFoldersCreatable
  >
  implements IUpdatableRepository<FoldersEntity, Folders.Types.IFoldersUpdatable>
{
  constructor(
    @InjectRepository(FoldersEntity)
    repository: Repository<FoldersEntity>,
  ) {
    super(repository, Folders.Config.FOLDERS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Folders.Types.IFoldersUpdatable,
  ): Promise<FoldersEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find folders by access, paged by the shared query. */
  async findByAccess(
    query: BaseQueryDto<FoldersEntity>,
    access: NonNullable<FoldersEntity["access"]>,
  ): Promise<IFindAllResponse<FoldersEntity>> {
    return await this.findByQuery(query, { access, deletedAt: IsNull() });
  }

  /** Find folders by parent id, paged by the shared query. */
  async findByParent(
    query: BaseQueryDto<FoldersEntity>,
    parentId: NonNullable<FoldersEntity["parentId"]>,
  ): Promise<IFindAllResponse<FoldersEntity>> {
    return await this.findByQuery(query, { parentId, deletedAt: IsNull() });
  }

  /** Find folders by role id, paged by the shared query. */
  async findByRole(
    query: BaseQueryDto<FoldersEntity>,
    roleId: NonNullable<FoldersEntity["roleId"]>,
  ): Promise<IFindAllResponse<FoldersEntity>> {
    return await this.findByQuery(query, { roleId, deletedAt: IsNull() });
  }

  /** Find the folders with this code (unique). */
  async findByCode(code: NonNullable<FoldersEntity["code"]>): Promise<FoldersEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
