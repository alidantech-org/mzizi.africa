import { Injectable } from "@nestjs/common";
import type { CountryTimelineDto } from "#/modules/history/schema/dto/country-timeline.dto.ts";
import type { EraCollectionDto } from "#/modules/history/schema/dto/era-collection.dto.ts";
import type { HistoryCollectionDto } from "#/modules/history/schema/dto/history-collection.dto.ts";
import { ListErasUseCase } from "#/modules/history/features/timeline/use-cases/list-eras.repository.ts";
import { ListHistoryUseCase } from "#/modules/history/features/timeline/use-cases/list-history.repository.ts";

/**
 * The Timeline contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class HistoryTimelineService {
  abstract listEras(input: CountryTimelineDto): Promise<EraCollectionDto>;
  abstract listHistory(input: CountryTimelineDto): Promise<HistoryCollectionDto>;
}

@Injectable()
export class HistoryTimelineServiceImpl extends HistoryTimelineService {
  constructor(
    private readonly listErasUseCase: ListErasUseCase,
    private readonly listHistoryUseCase: ListHistoryUseCase,
  ) {
    super();
  }

  listEras(input: CountryTimelineDto): Promise<EraCollectionDto> {
    return this.listErasUseCase.execute(input);
  }

  listHistory(input: CountryTimelineDto): Promise<HistoryCollectionDto> {
    return this.listHistoryUseCase.execute(input);
  }
}
