import { Injectable } from "@nestjs/common";
import type { AddressKeyDto } from "#/modules/identity/schema/dto/address-key.dto.ts";
import type { AddressMatchesDto } from "#/modules/identity/schema/dto/address-matches.dto.ts";
import type { IdentityDetailDto } from "#/modules/identity/schema/dto/identity-detail.dto.ts";
import type { IdentityKeyDto } from "#/modules/identity/schema/dto/identity-key.dto.ts";
import type { NameMatchesDto } from "#/modules/identity/schema/dto/name-matches.dto.ts";
import type { NameSearchDto } from "#/modules/identity/schema/dto/name-search.dto.ts";
import { GetIdentityUseCase } from "#/modules/identity/features/things/use-cases/get-identity.repository.ts";
import { ResolveAddressUseCase } from "#/modules/identity/features/things/use-cases/resolve-address.repository.ts";
import { SearchNamesUseCase } from "#/modules/identity/features/things/use-cases/search-names.repository.ts";

/**
 * The Things contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class IdentityThingsService {
  abstract getIdentity(input: IdentityKeyDto): Promise<IdentityDetailDto>;
  abstract resolveAddress(input: AddressKeyDto): Promise<AddressMatchesDto>;
  abstract searchNames(input: NameSearchDto): Promise<NameMatchesDto>;
}

@Injectable()
export class IdentityThingsServiceImpl extends IdentityThingsService {
  constructor(
    private readonly getIdentityUseCase: GetIdentityUseCase,
    private readonly resolveAddressUseCase: ResolveAddressUseCase,
    private readonly searchNamesUseCase: SearchNamesUseCase,
  ) {
    super();
  }

  getIdentity(input: IdentityKeyDto): Promise<IdentityDetailDto> {
    return this.getIdentityUseCase.execute(input);
  }

  resolveAddress(input: AddressKeyDto): Promise<AddressMatchesDto> {
    return this.resolveAddressUseCase.execute(input);
  }

  searchNames(input: NameSearchDto): Promise<NameMatchesDto> {
    return this.searchNamesUseCase.execute(input);
  }
}
