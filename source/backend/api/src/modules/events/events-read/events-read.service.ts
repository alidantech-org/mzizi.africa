
import type { EventLinkListQueryDto } from "#/modules/events/dto/event-link-list-query.dto.ts";
import type { EventLinkResponseDto } from "#/modules/events/dto/event-link-response.dto.ts";
import type { EventLinksListResponseDto } from "#/modules/events/dto/event-links-list-response.dto.ts";
import type { EventListQueryDto } from "#/modules/events/dto/event-list-query.dto.ts";
import type { EventResponseDto } from "#/modules/events/dto/event-response.dto.ts";
import type { EventsListResponseDto } from "#/modules/events/dto/events-list-response.dto.ts";

/**
 * The Events Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class EventsEventsReadService {
  abstract findEventLinks(input: EventLinkListQueryDto): Promise<EventLinksListResponseDto>;
  abstract findEvents(input: EventListQueryDto): Promise<EventsListResponseDto>;
  abstract getEventById(input: { eventId: string }): Promise<EventResponseDto>;
  abstract getEventLinkById(input: { linkId: string }): Promise<EventLinkResponseDto>;
}