/**
 * The Statistics Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class StatisticsStatisticsReadService {
  abstract findIndicatorCategories(input: IndicatorCategoryListQueryDto): Promise<IndicatorCategoriesListResponseDto>;
  abstract findIndicatorColumns(input: IndicatorColumnListQueryDto): Promise<IndicatorColumnsListResponseDto>;
  abstract findIndicators(input: IndicatorListQueryDto): Promise<IndicatorsListResponseDto>;
  abstract findObservations(input: ObservationListQueryDto): Promise<ObservationsListResponseDto>;
  abstract findPeriods(input: PeriodListQueryDto): Promise<PeriodsListResponseDto>;
  abstract findStatisticsTables(input: StatisticsTableListQueryDto): Promise<StatisticsTablesListResponseDto>;
  abstract getIndicatorById(input: { indicatorId: string }): Promise<IndicatorResponseDto>;
  abstract getIndicatorCategoryById(input: { categoryId: string }): Promise<IndicatorCategoryResponseDto>;
  abstract getIndicatorColumnById(input: { columnId: string }): Promise<IndicatorColumnResponseDto>;
  abstract getObservationById(input: { observationId: string }): Promise<ObservationResponseDto>;
  abstract getPeriodById(input: { periodId: string }): Promise<PeriodResponseDto>;
  abstract getStatisticsTableById(input: { tableId: string }): Promise<StatisticsTableResponseDto>;
}