import { Injectable } from "@nestjs/common";
import type { FigureCollectionDto } from "#/modules/statistics/schema/dto/figure-collection.dto.ts";
import type { IndicatorFigureCollectionDto } from "#/modules/statistics/schema/dto/indicator-figure-collection.dto.ts";
import type { IndicatorFiguresDto } from "#/modules/statistics/schema/dto/indicator-figures.dto.ts";
import type { ObservationCollectionDto } from "#/modules/statistics/schema/dto/observation-collection.dto.ts";
import type { ObservationScopeDto } from "#/modules/statistics/schema/dto/observation-scope.dto.ts";
import type { PlaceFiguresDto } from "#/modules/statistics/schema/dto/place-figures.dto.ts";
import { ListIndicatorFiguresUseCase } from "#/modules/statistics/features/figures/use-cases/list-indicator-figures.repository.ts";
import { ListObservationsUseCase } from "#/modules/statistics/features/figures/use-cases/list-observations.repository.ts";
import { ListPlaceFiguresUseCase } from "#/modules/statistics/features/figures/use-cases/list-place-figures.repository.ts";

/**
 * The Figures contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class StatisticsFiguresService {
  abstract listIndicatorFigures(input: IndicatorFiguresDto): Promise<IndicatorFigureCollectionDto>;
  abstract listObservations(input: ObservationScopeDto): Promise<ObservationCollectionDto>;
  abstract listPlaceFigures(input: PlaceFiguresDto): Promise<FigureCollectionDto>;
}

@Injectable()
export class StatisticsFiguresServiceImpl extends StatisticsFiguresService {
  constructor(
    private readonly listIndicatorFiguresUseCase: ListIndicatorFiguresUseCase,
    private readonly listObservationsUseCase: ListObservationsUseCase,
    private readonly listPlaceFiguresUseCase: ListPlaceFiguresUseCase,
  ) {
    super();
  }

  listIndicatorFigures(input: IndicatorFiguresDto): Promise<IndicatorFigureCollectionDto> {
    return this.listIndicatorFiguresUseCase.execute(input);
  }

  listObservations(input: ObservationScopeDto): Promise<ObservationCollectionDto> {
    return this.listObservationsUseCase.execute(input);
  }

  listPlaceFigures(input: PlaceFiguresDto): Promise<FigureCollectionDto> {
    return this.listPlaceFiguresUseCase.execute(input);
  }
}
