import { Injectable } from "@nestjs/common";
import type { IndicatorCollectionDto } from "#/modules/statistics/schema/dto/indicator-collection.dto.ts";
import type { IndicatorDetailDto } from "#/modules/statistics/schema/dto/indicator-detail.dto.ts";
import type { IndicatorKeyDto } from "#/modules/statistics/schema/dto/indicator-key.dto.ts";
import type { IndicatorWindowDto } from "#/modules/statistics/schema/dto/indicator-window.dto.ts";
import { GetIndicatorUseCase } from "#/modules/statistics/features/indicators/use-cases/get-indicator.repository.ts";
import { ListIndicatorsUseCase } from "#/modules/statistics/features/indicators/use-cases/list-indicators.repository.ts";

/**
 * The Indicators contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class StatisticsIndicatorsService {
  abstract getIndicator(input: IndicatorKeyDto): Promise<IndicatorDetailDto>;
  abstract listIndicators(input: IndicatorWindowDto): Promise<IndicatorCollectionDto>;
}

@Injectable()
export class StatisticsIndicatorsServiceImpl extends StatisticsIndicatorsService {
  constructor(
    private readonly getIndicatorUseCase: GetIndicatorUseCase,
    private readonly listIndicatorsUseCase: ListIndicatorsUseCase,
  ) {
    super();
  }

  getIndicator(input: IndicatorKeyDto): Promise<IndicatorDetailDto> {
    return this.getIndicatorUseCase.execute(input);
  }

  listIndicators(input: IndicatorWindowDto): Promise<IndicatorCollectionDto> {
    return this.listIndicatorsUseCase.execute(input);
  }
}
