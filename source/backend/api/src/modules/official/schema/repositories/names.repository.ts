import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { OfficialNamesEntity } from "#/modules/official/schema/entities/names.entity.ts";
import * as Names from "#/modules/official/schema/types/names/index.ts";

/**
 * Repository of Names: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class NamesRepository
  extends EntityRepository<
    OfficialNamesEntity,
    Names.Types.NamesSortableField,
    Names.Types.NamesEditableField,
    Names.Types.NamesSelectableField,
    Names.Types.INamesCreatable
  >
  implements IUpdatableRepository<OfficialNamesEntity, Names.Types.INamesUpdatable>
{
  constructor(
    @InjectRepository(OfficialNamesEntity)
    repository: Repository<OfficialNamesEntity>,
  ) {
    super(repository, Names.Config.NAMES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Names.Types.INamesUpdatable,
  ): Promise<OfficialNamesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find names by entity id, paged by the shared query. */
  async findByEntity(
    query: BaseQueryDto<OfficialNamesEntity>,
    entityId: NonNullable<OfficialNamesEntity["entityId"]>,
  ): Promise<IFindAllResponse<OfficialNamesEntity>> {
    return await this.findByQuery(query, { entityId, deletedAt: IsNull() });
  }

  /** Find names by individual id, paged by the shared query. */
  async findByIndividual(
    query: BaseQueryDto<OfficialNamesEntity>,
    individualId: NonNullable<OfficialNamesEntity["individualId"]>,
  ): Promise<IFindAllResponse<OfficialNamesEntity>> {
    return await this.findByQuery(query, { individualId, deletedAt: IsNull() });
  }

  /** Find names by language id, paged by the shared query. */
  async findByLanguage(
    query: BaseQueryDto<OfficialNamesEntity>,
    languageId: NonNullable<OfficialNamesEntity["languageId"]>,
  ): Promise<IFindAllResponse<OfficialNamesEntity>> {
    return await this.findByQuery(query, { languageId, deletedAt: IsNull() });
  }

  /** Find names by name kind id, paged by the shared query. */
  async findByNameKind(
    query: BaseQueryDto<OfficialNamesEntity>,
    nameKindId: NonNullable<OfficialNamesEntity["nameKindId"]>,
  ): Promise<IFindAllResponse<OfficialNamesEntity>> {
    return await this.findByQuery(query, { nameKindId, deletedAt: IsNull() });
  }

  /** Find names by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<OfficialNamesEntity>,
    sourceCitationId: NonNullable<OfficialNamesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<OfficialNamesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }
}
