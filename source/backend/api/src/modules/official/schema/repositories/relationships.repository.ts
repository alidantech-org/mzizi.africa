import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { OfficialRelationshipsEntity } from "#/modules/official/schema/entities/relationships.entity.ts";
import * as Relationships from "#/modules/official/schema/types/relationships/index.ts";

/**
 * Repository of Relationships: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class RelationshipsRepository
  extends EntityRepository<
    OfficialRelationshipsEntity,
    Relationships.Types.RelationshipsSortableField,
    Relationships.Types.RelationshipsEditableField,
    Relationships.Types.RelationshipsSelectableField,
    Relationships.Types.IRelationshipsCreatable
  >
  implements
    IUpdatableRepository<OfficialRelationshipsEntity, Relationships.Types.IRelationshipsUpdatable>
{
  constructor(
    @InjectRepository(OfficialRelationshipsEntity)
    repository: Repository<OfficialRelationshipsEntity>,
  ) {
    super(repository, Relationships.Config.RELATIONSHIPS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Relationships.Types.IRelationshipsUpdatable,
  ): Promise<OfficialRelationshipsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find relationships by from entity id, paged by the shared query. */
  async findByFromEntity(
    query: BaseQueryDto<OfficialRelationshipsEntity>,
    fromEntityId: NonNullable<OfficialRelationshipsEntity["fromEntityId"]>,
  ): Promise<IFindAllResponse<OfficialRelationshipsEntity>> {
    return await this.findByQuery(query, { fromEntityId, deletedAt: IsNull() });
  }

  /** Find relationships by from individual id, paged by the shared query. */
  async findByFromIndividual(
    query: BaseQueryDto<OfficialRelationshipsEntity>,
    fromIndividualId: NonNullable<OfficialRelationshipsEntity["fromIndividualId"]>,
  ): Promise<IFindAllResponse<OfficialRelationshipsEntity>> {
    return await this.findByQuery(query, { fromIndividualId, deletedAt: IsNull() });
  }

  /** Find relationships by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<OfficialRelationshipsEntity>,
    kindId: NonNullable<OfficialRelationshipsEntity["kindId"]>,
  ): Promise<IFindAllResponse<OfficialRelationshipsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find relationships by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<OfficialRelationshipsEntity>,
    sourceCitationId: NonNullable<OfficialRelationshipsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<OfficialRelationshipsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find relationships by to entity id, paged by the shared query. */
  async findByToEntity(
    query: BaseQueryDto<OfficialRelationshipsEntity>,
    toEntityId: NonNullable<OfficialRelationshipsEntity["toEntityId"]>,
  ): Promise<IFindAllResponse<OfficialRelationshipsEntity>> {
    return await this.findByQuery(query, { toEntityId, deletedAt: IsNull() });
  }

  /** Find relationships by to individual id, paged by the shared query. */
  async findByToIndividual(
    query: BaseQueryDto<OfficialRelationshipsEntity>,
    toIndividualId: NonNullable<OfficialRelationshipsEntity["toIndividualId"]>,
  ): Promise<IFindAllResponse<OfficialRelationshipsEntity>> {
    return await this.findByQuery(query, { toIndividualId, deletedAt: IsNull() });
  }

  /** Find the relationships with this code (unique). */
  async findByCode(
    code: NonNullable<OfficialRelationshipsEntity["code"]>,
  ): Promise<OfficialRelationshipsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
