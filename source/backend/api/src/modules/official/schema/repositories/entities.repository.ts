import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { EntitiesEntity } from "#/modules/official/schema/entities/entities.entity.ts";
import * as Entities from "#/modules/official/schema/types/entities/index.ts";

/**
 * Repository of Entities: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class EntitiesRepository
  extends EntityRepository<
    EntitiesEntity,
    Entities.Types.EntitiesSortableField,
    Entities.Types.EntitiesEditableField,
    Entities.Types.EntitiesSelectableField,
    Entities.Types.IEntitiesCreatable
  >
  implements IUpdatableRepository<EntitiesEntity, Entities.Types.IEntitiesUpdatable>
{
  constructor(
    @InjectRepository(EntitiesEntity)
    repository: Repository<EntitiesEntity>,
  ) {
    super(repository, Entities.Config.ENTITIES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Entities.Types.IEntitiesUpdatable,
  ): Promise<EntitiesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find entities by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<EntitiesEntity>,
    kindId: NonNullable<EntitiesEntity["kindId"]>,
  ): Promise<IFindAllResponse<EntitiesEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find entities by registration country id, paged by the shared query. */
  async findByRegistrationCountry(
    query: BaseQueryDto<EntitiesEntity>,
    registrationCountryId: NonNullable<EntitiesEntity["registrationCountryId"]>,
  ): Promise<IFindAllResponse<EntitiesEntity>> {
    return await this.findByQuery(query, { registrationCountryId, deletedAt: IsNull() });
  }

  /** Find entities by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<EntitiesEntity>,
    sourceCitationId: NonNullable<EntitiesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<EntitiesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the entities with this code (unique). */
  async findByCode(code: NonNullable<EntitiesEntity["code"]>): Promise<EntitiesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
