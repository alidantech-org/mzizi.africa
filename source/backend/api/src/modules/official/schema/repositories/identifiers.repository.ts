import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { OfficialIdentifiersEntity } from "#/modules/official/schema/entities/identifiers.entity.ts";
import * as Identifiers from "#/modules/official/schema/types/identifiers/index.ts";

/**
 * Repository of Identifiers: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class IdentifiersRepository
  extends EntityRepository<
    OfficialIdentifiersEntity,
    Identifiers.Types.IdentifiersSortableField,
    Identifiers.Types.IdentifiersEditableField,
    Identifiers.Types.IdentifiersSelectableField,
    Identifiers.Types.IIdentifiersCreatable
  >
  implements
    IUpdatableRepository<OfficialIdentifiersEntity, Identifiers.Types.IIdentifiersUpdatable>
{
  constructor(
    @InjectRepository(OfficialIdentifiersEntity)
    repository: Repository<OfficialIdentifiersEntity>,
  ) {
    super(repository, Identifiers.Config.IDENTIFIERS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Identifiers.Types.IIdentifiersUpdatable,
  ): Promise<OfficialIdentifiersEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find identifiers by entity id, paged by the shared query. */
  async findByEntity(
    query: BaseQueryDto<OfficialIdentifiersEntity>,
    entityId: NonNullable<OfficialIdentifiersEntity["entityId"]>,
  ): Promise<IFindAllResponse<OfficialIdentifiersEntity>> {
    return await this.findByQuery(query, { entityId, deletedAt: IsNull() });
  }

  /** Find identifiers by individual id, paged by the shared query. */
  async findByIndividual(
    query: BaseQueryDto<OfficialIdentifiersEntity>,
    individualId: NonNullable<OfficialIdentifiersEntity["individualId"]>,
  ): Promise<IFindAllResponse<OfficialIdentifiersEntity>> {
    return await this.findByQuery(query, { individualId, deletedAt: IsNull() });
  }

  /** Find identifiers by issuer entity id, paged by the shared query. */
  async findByIssuerEntity(
    query: BaseQueryDto<OfficialIdentifiersEntity>,
    issuerEntityId: NonNullable<OfficialIdentifiersEntity["issuerEntityId"]>,
  ): Promise<IFindAllResponse<OfficialIdentifiersEntity>> {
    return await this.findByQuery(query, { issuerEntityId, deletedAt: IsNull() });
  }

  /** Find identifiers by scheme id, paged by the shared query. */
  async findByScheme(
    query: BaseQueryDto<OfficialIdentifiersEntity>,
    schemeId: NonNullable<OfficialIdentifiersEntity["schemeId"]>,
  ): Promise<IFindAllResponse<OfficialIdentifiersEntity>> {
    return await this.findByQuery(query, { schemeId, deletedAt: IsNull() });
  }

  /** Find identifiers by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<OfficialIdentifiersEntity>,
    sourceCitationId: NonNullable<OfficialIdentifiersEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<OfficialIdentifiersEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }
}
