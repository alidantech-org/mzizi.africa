import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ContactsEntity } from "#/modules/official/schema/entities/contacts.entity.ts";
import * as Contacts from "#/modules/official/schema/types/contacts/index.ts";

/**
 * Repository of Contacts: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ContactsRepository
  extends EntityRepository<
    ContactsEntity,
    Contacts.Types.ContactsSortableField,
    Contacts.Types.ContactsEditableField,
    Contacts.Types.ContactsSelectableField,
    Contacts.Types.IContactsCreatable
  >
  implements IUpdatableRepository<ContactsEntity, Contacts.Types.IContactsUpdatable>
{
  constructor(
    @InjectRepository(ContactsEntity)
    repository: Repository<ContactsEntity>,
  ) {
    super(repository, Contacts.Config.CONTACTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Contacts.Types.IContactsUpdatable,
  ): Promise<ContactsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find contacts by entity id, paged by the shared query. */
  async findByEntity(
    query: BaseQueryDto<ContactsEntity>,
    entityId: NonNullable<ContactsEntity["entityId"]>,
  ): Promise<IFindAllResponse<ContactsEntity>> {
    return await this.findByQuery(query, { entityId, deletedAt: IsNull() });
  }

  /** Find contacts by individual id, paged by the shared query. */
  async findByIndividual(
    query: BaseQueryDto<ContactsEntity>,
    individualId: NonNullable<ContactsEntity["individualId"]>,
  ): Promise<IFindAllResponse<ContactsEntity>> {
    return await this.findByQuery(query, { individualId, deletedAt: IsNull() });
  }

  /** Find contacts by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<ContactsEntity>,
    kindId: NonNullable<ContactsEntity["kindId"]>,
  ): Promise<IFindAllResponse<ContactsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find contacts by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<ContactsEntity>,
    sourceCitationId: NonNullable<ContactsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<ContactsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find contacts by visibility id, paged by the shared query. */
  async findByVisibility(
    query: BaseQueryDto<ContactsEntity>,
    visibilityId: NonNullable<ContactsEntity["visibilityId"]>,
  ): Promise<IFindAllResponse<ContactsEntity>> {
    return await this.findByQuery(query, { visibilityId, deletedAt: IsNull() });
  }
}
