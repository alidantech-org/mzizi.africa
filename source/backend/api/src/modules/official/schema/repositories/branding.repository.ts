import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { BrandingEntity } from "#/modules/official/schema/entities/branding.entity.ts";
import * as Branding from "#/modules/official/schema/types/branding/index.ts";

/**
 * Repository of Branding: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class BrandingRepository
  extends EntityRepository<
    BrandingEntity,
    Branding.Types.BrandingSortableField,
    Branding.Types.BrandingEditableField,
    Branding.Types.BrandingSelectableField,
    Branding.Types.IBrandingCreatable
  >
  implements IUpdatableRepository<BrandingEntity, Branding.Types.IBrandingUpdatable>
{
  constructor(
    @InjectRepository(BrandingEntity)
    repository: Repository<BrandingEntity>,
  ) {
    super(repository, Branding.Config.BRANDING_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Branding.Types.IBrandingUpdatable,
  ): Promise<BrandingEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find branding by entity id, paged by the shared query. */
  async findByEntity(
    query: BaseQueryDto<BrandingEntity>,
    entityId: NonNullable<BrandingEntity["entityId"]>,
  ): Promise<IFindAllResponse<BrandingEntity>> {
    return await this.findByQuery(query, { entityId, deletedAt: IsNull() });
  }

  /** Find branding by individual id, paged by the shared query. */
  async findByIndividual(
    query: BaseQueryDto<BrandingEntity>,
    individualId: NonNullable<BrandingEntity["individualId"]>,
  ): Promise<IFindAllResponse<BrandingEntity>> {
    return await this.findByQuery(query, { individualId, deletedAt: IsNull() });
  }

  /** Find branding by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<BrandingEntity>,
    kindId: NonNullable<BrandingEntity["kindId"]>,
  ): Promise<IFindAllResponse<BrandingEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find branding by language id, paged by the shared query. */
  async findByLanguage(
    query: BaseQueryDto<BrandingEntity>,
    languageId: NonNullable<BrandingEntity["languageId"]>,
  ): Promise<IFindAllResponse<BrandingEntity>> {
    return await this.findByQuery(query, { languageId, deletedAt: IsNull() });
  }

  /** Find branding by media id, paged by the shared query. */
  async findByMedia(
    query: BaseQueryDto<BrandingEntity>,
    mediaId: NonNullable<BrandingEntity["mediaId"]>,
  ): Promise<IFindAllResponse<BrandingEntity>> {
    return await this.findByQuery(query, { mediaId, deletedAt: IsNull() });
  }

  /** Find branding by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<BrandingEntity>,
    sourceCitationId: NonNullable<BrandingEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<BrandingEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the branding with this code (unique). */
  async findByCode(code: NonNullable<BrandingEntity["code"]>): Promise<BrandingEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
