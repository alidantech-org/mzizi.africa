import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { IndividualsEntity } from "#/modules/official/schema/entities/individuals.entity.ts";
import * as Individuals from "#/modules/official/schema/types/individuals/index.ts";

/**
 * Repository of Individuals: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class IndividualsRepository
  extends EntityRepository<
    IndividualsEntity,
    Individuals.Types.IndividualsSortableField,
    Individuals.Types.IndividualsEditableField,
    Individuals.Types.IndividualsSelectableField,
    Individuals.Types.IIndividualsCreatable
  >
  implements IUpdatableRepository<IndividualsEntity, Individuals.Types.IIndividualsUpdatable>
{
  constructor(
    @InjectRepository(IndividualsEntity)
    repository: Repository<IndividualsEntity>,
  ) {
    super(repository, Individuals.Config.INDIVIDUALS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Individuals.Types.IIndividualsUpdatable,
  ): Promise<IndividualsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find individuals by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<IndividualsEntity>,
    sourceCitationId: NonNullable<IndividualsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<IndividualsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the individuals with this code (unique). */
  async findByCode(
    code: NonNullable<IndividualsEntity["code"]>,
  ): Promise<IndividualsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
