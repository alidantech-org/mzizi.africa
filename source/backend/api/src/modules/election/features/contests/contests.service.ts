import { Injectable } from "@nestjs/common";
import type { CountryElectionsDto } from "#/modules/election/schema/dto/country-elections.dto.ts";
import type { ElectionCollectionDto } from "#/modules/election/schema/dto/election-collection.dto.ts";
import type { ElectionDetailDto } from "#/modules/election/schema/dto/election-detail.dto.ts";
import type { ElectionKeyDto } from "#/modules/election/schema/dto/election-key.dto.ts";
import type { PlaceTalliesDto } from "#/modules/election/schema/dto/place-tallies.dto.ts";
import type { TallyCollectionDto } from "#/modules/election/schema/dto/tally-collection.dto.ts";
import { GetElectionUseCase } from "#/modules/election/features/contests/use-cases/get-election.repository.ts";
import { ListElectionsUseCase } from "#/modules/election/features/contests/use-cases/list-elections.repository.ts";
import { ListTalliesUseCase } from "#/modules/election/features/contests/use-cases/list-tallies.repository.ts";

/**
 * The Contests contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class ElectionContestsService {
  abstract getElection(input: ElectionKeyDto): Promise<ElectionDetailDto>;
  abstract listElections(input: CountryElectionsDto): Promise<ElectionCollectionDto>;
  abstract listTallies(input: PlaceTalliesDto): Promise<TallyCollectionDto>;
}

@Injectable()
export class ElectionContestsServiceImpl extends ElectionContestsService {
  constructor(
    private readonly getElectionUseCase: GetElectionUseCase,
    private readonly listElectionsUseCase: ListElectionsUseCase,
    private readonly listTalliesUseCase: ListTalliesUseCase,
  ) {
    super();
  }

  getElection(input: ElectionKeyDto): Promise<ElectionDetailDto> {
    return this.getElectionUseCase.execute(input);
  }

  listElections(input: CountryElectionsDto): Promise<ElectionCollectionDto> {
    return this.listElectionsUseCase.execute(input);
  }

  listTallies(input: PlaceTalliesDto): Promise<TallyCollectionDto> {
    return this.listTalliesUseCase.execute(input);
  }
}
