  /** The procedures of the owners, grouped by the owner's key. */
  private async load_GetStructureScreen_procedures(
    owners: unknown[],
    context: ReadContext,
  ): Promise<Map<unknown, Row[]>> {
    if (owners.length === 0) return new Map();
    const query = this.repositoryOf(ProceduresRepository, ProceduresEntity).query(
      "r1",
      context.manager,
    );
    query.select([]);
    query.where("r1.countryId IN (:...owners)", { owners });
    query.addSelect("r1.countryId", "__owner");
    query.addSelect("r1.countryId", "__hit");
    query.addSelect("r1.sourceCitationId", "citationId");
    query.addSelect("r1.code", "code");
    query.addSelect("r1.description", "description");
    query.addSelect("r1.id", "id");
    query.leftJoin(ValueEntity, "r1_kindId", "r1_kindId.id = r1.kindId");
    query.addSelect("r1_kindId.label", "kind");
    query.orderBy("r1.code", "ASC");
    query.addOrderBy("r1.id", "ASC");
    const raws = await query.getRawMany<Row>();
    const rows: Row[] = raws.map((raw) => ({
      citationId: raw.citationId,
      code: raw.code,
      description: raw.description,
      id: raw.id,
      kind: raw.kind,
    }));
    const grouped = new Map<unknown, Row[]>();
    raws.forEach((raw, index) => {
      if (raw.__hit === null || raw.__hit === undefined) return;
      const list = grouped.get(raw.__owner) ?? [];
      list.push(rows[index] as Row);
      grouped.set(raw.__owner, list);
    });
    return grouped;
  }
