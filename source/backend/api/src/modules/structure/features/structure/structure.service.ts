import { Injectable } from "@nestjs/common";
import type { CountryContextDocumentDto } from "#/modules/structure/schema/dto/country-context-document.dto.ts";
import type { StructureDocumentDto } from "#/modules/structure/schema/dto/structure-document.dto.ts";
import type { StructureInputDto } from "#/modules/structure/schema/dto/structure-input.dto.ts";
import { GetCountryContextUseCase } from "#/modules/structure/features/structure/use-cases/get-country-context.usecase.ts";
import { GetStructureScreenUseCase } from "#/modules/structure/features/structure/use-cases/get-structure-screen.usecase.ts";

/**
 * The Structure contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class StructureStructureService {
  abstract getCountryContext(input: StructureInputDto): Promise<CountryContextDocumentDto>;
  abstract getStructureScreen(input: StructureInputDto): Promise<StructureDocumentDto>;
}

@Injectable()
export class StructureStructureServiceImpl extends StructureStructureService {
  constructor(
    private readonly getCountryContextUseCase: GetCountryContextUseCase,
    private readonly getStructureScreenUseCase: GetStructureScreenUseCase,
  ) {
    super();
  }

  getCountryContext(input: StructureInputDto): Promise<CountryContextDocumentDto> {
    return this.getCountryContextUseCase.execute(input);
  }

  getStructureScreen(input: StructureInputDto): Promise<StructureDocumentDto> {
    return this.getStructureScreenUseCase.execute(input);
  }
}
