import { Injectable } from "@nestjs/common";
import type { EngagementInputDto } from "#/modules/interactions/schema/dto/engagement-input.dto.ts";
import type { EngagementDto } from "#/modules/interactions/schema/dto/engagement.dto.ts";
import type { LikeInputDto } from "#/modules/interactions/schema/dto/like-input.dto.ts";
import type { RecordedDto } from "#/modules/interactions/schema/dto/recorded.dto.ts";
import type { ViewInputDto } from "#/modules/interactions/schema/dto/view-input.dto.ts";
import { GetEngagementUseCase } from "#/modules/interactions/features/interactions/use-cases/get-engagement.usecase.ts";
import { LikeUseCase } from "#/modules/interactions/features/interactions/use-cases/like.usecase.ts";
import { RecordViewUseCase } from "#/modules/interactions/features/interactions/use-cases/record-view.usecase.ts";
import { UnlikeUseCase } from "#/modules/interactions/features/interactions/use-cases/unlike.usecase.ts";

/**
 * The Interactions contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class InteractionsInteractionsService {
  abstract getEngagement(input: EngagementInputDto): Promise<EngagementDto>;
  abstract like(input: { body: LikeInputDto }): Promise<EngagementDto>;
  abstract recordView(input: { body: ViewInputDto }): Promise<RecordedDto>;
  abstract unlike(input: { body: LikeInputDto }): Promise<EngagementDto>;
}

@Injectable()
export class InteractionsInteractionsServiceImpl extends InteractionsInteractionsService {
  constructor(
    private readonly getEngagementUseCase: GetEngagementUseCase,
    private readonly likeUseCase: LikeUseCase,
    private readonly recordViewUseCase: RecordViewUseCase,
    private readonly unlikeUseCase: UnlikeUseCase,
  ) {
    super();
  }

  getEngagement(input: EngagementInputDto): Promise<EngagementDto> {
    return this.getEngagementUseCase.execute(input);
  }

  like(input: { body: LikeInputDto }): Promise<EngagementDto> {
    return this.likeUseCase.execute(input);
  }

  recordView(input: { body: ViewInputDto }): Promise<RecordedDto> {
    return this.recordViewUseCase.execute(input);
  }

  unlike(input: { body: LikeInputDto }): Promise<EngagementDto> {
    return this.unlikeUseCase.execute(input);
  }
}
