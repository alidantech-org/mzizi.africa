import { Injectable } from "@nestjs/common";
import type { SchemeDetailDto } from "#/modules/vocabulary/schema/dto/scheme-detail.dto.ts";
import type { SchemeKeyDto } from "#/modules/vocabulary/schema/dto/scheme-key.dto.ts";
import type { TermCollectionDto } from "#/modules/vocabulary/schema/dto/term-collection.dto.ts";
import type { TermWindowDto } from "#/modules/vocabulary/schema/dto/term-window.dto.ts";
import { GetSchemeUseCase } from "#/modules/vocabulary/features/terms/use-cases/get-scheme.repository.ts";
import { ListTermsUseCase } from "#/modules/vocabulary/features/terms/use-cases/list-terms.repository.ts";

/**
 * The Terms contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class VocabularyTermsService {
  abstract getScheme(input: SchemeKeyDto): Promise<SchemeDetailDto>;
  abstract listTerms(input: TermWindowDto): Promise<TermCollectionDto>;
}

@Injectable()
export class VocabularyTermsServiceImpl extends VocabularyTermsService {
  constructor(
    private readonly getSchemeUseCase: GetSchemeUseCase,
    private readonly listTermsUseCase: ListTermsUseCase,
  ) {
    super();
  }

  getScheme(input: SchemeKeyDto): Promise<SchemeDetailDto> {
    return this.getSchemeUseCase.execute(input);
  }

  listTerms(input: TermWindowDto): Promise<TermCollectionDto> {
    return this.listTermsUseCase.execute(input);
  }
}
