import { Injectable } from "@nestjs/common";
import type { BillCollectionDto } from "#/modules/legislature/schema/dto/bill-collection.dto.ts";
import type { BillDetailDto } from "#/modules/legislature/schema/dto/bill-detail.dto.ts";
import type { BillKeyDto } from "#/modules/legislature/schema/dto/bill-key.dto.ts";
import type { BillWindowDto } from "#/modules/legislature/schema/dto/bill-window.dto.ts";
import type { MotionVotesDto } from "#/modules/legislature/schema/dto/motion-votes.dto.ts";
import type { VoteCollectionDto } from "#/modules/legislature/schema/dto/vote-collection.dto.ts";
import { GetBillUseCase } from "#/modules/legislature/features/lawmaking/use-cases/get-bill.repository.ts";
import { ListBillsUseCase } from "#/modules/legislature/features/lawmaking/use-cases/list-bills.repository.ts";
import { ListVotesUseCase } from "#/modules/legislature/features/lawmaking/use-cases/list-votes.repository.ts";

/**
 * The Lawmaking contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class LegislatureLawmakingService {
  abstract getBill(input: BillKeyDto): Promise<BillDetailDto>;
  abstract listBills(input: BillWindowDto): Promise<BillCollectionDto>;
  abstract listVotes(input: MotionVotesDto): Promise<VoteCollectionDto>;
}

@Injectable()
export class LegislatureLawmakingServiceImpl extends LegislatureLawmakingService {
  constructor(
    private readonly getBillUseCase: GetBillUseCase,
    private readonly listBillsUseCase: ListBillsUseCase,
    private readonly listVotesUseCase: ListVotesUseCase,
  ) {
    super();
  }

  getBill(input: BillKeyDto): Promise<BillDetailDto> {
    return this.getBillUseCase.execute(input);
  }

  listBills(input: BillWindowDto): Promise<BillCollectionDto> {
    return this.listBillsUseCase.execute(input);
  }

  listVotes(input: MotionVotesDto): Promise<VoteCollectionDto> {
    return this.listVotesUseCase.execute(input);
  }
}
