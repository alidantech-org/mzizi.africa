import { Injectable } from "@nestjs/common";
import type { ArticleCollectionDto } from "#/modules/media/schema/dto/article-collection.dto.ts";
import type { ArticleDetailDto } from "#/modules/media/schema/dto/article-detail.dto.ts";
import type { ArticleKeyDto } from "#/modules/media/schema/dto/article-key.dto.ts";
import type { IdentityMediaDto } from "#/modules/media/schema/dto/identity-media.dto.ts";
import type { UseCollectionDto } from "#/modules/media/schema/dto/use-collection.dto.ts";
import { GetArticleUseCase } from "#/modules/media/features/library/use-cases/get-article.repository.ts";
import { ListArticlesUseCase } from "#/modules/media/features/library/use-cases/list-articles.repository.ts";
import { ListAssetsUseCase } from "#/modules/media/features/library/use-cases/list-assets.repository.ts";

/**
 * The Library contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class MediaLibraryService {
  abstract getArticle(input: ArticleKeyDto): Promise<ArticleDetailDto>;
  abstract listArticles(input: IdentityMediaDto): Promise<ArticleCollectionDto>;
  abstract listAssets(input: IdentityMediaDto): Promise<UseCollectionDto>;
}

@Injectable()
export class MediaLibraryServiceImpl extends MediaLibraryService {
  constructor(
    private readonly getArticleUseCase: GetArticleUseCase,
    private readonly listArticlesUseCase: ListArticlesUseCase,
    private readonly listAssetsUseCase: ListAssetsUseCase,
  ) {
    super();
  }

  getArticle(input: ArticleKeyDto): Promise<ArticleDetailDto> {
    return this.getArticleUseCase.execute(input);
  }

  listArticles(input: IdentityMediaDto): Promise<ArticleCollectionDto> {
    return this.listArticlesUseCase.execute(input);
  }

  listAssets(input: IdentityMediaDto): Promise<UseCollectionDto> {
    return this.listAssetsUseCase.execute(input);
  }
}
