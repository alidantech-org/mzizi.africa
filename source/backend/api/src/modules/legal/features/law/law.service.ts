import { Injectable } from "@nestjs/common";
import type { EffectCollectionDto } from "#/modules/legal/schema/dto/effect-collection.dto.ts";
import type { IdentityEffectsDto } from "#/modules/legal/schema/dto/identity-effects.dto.ts";
import type { InstrumentCollectionDto } from "#/modules/legal/schema/dto/instrument-collection.dto.ts";
import type { InstrumentDetailDto } from "#/modules/legal/schema/dto/instrument-detail.dto.ts";
import type { InstrumentKeyDto } from "#/modules/legal/schema/dto/instrument-key.dto.ts";
import type { InstrumentWindowDto } from "#/modules/legal/schema/dto/instrument-window.dto.ts";
import type { ProvisionCollectionDto } from "#/modules/legal/schema/dto/provision-collection.dto.ts";
import type { ProvisionScopeDto } from "#/modules/legal/schema/dto/provision-scope.dto.ts";
import { GetInstrumentUseCase } from "#/modules/legal/features/law/use-cases/get-instrument.repository.ts";
import { ListEffectsUseCase } from "#/modules/legal/features/law/use-cases/list-effects.repository.ts";
import { ListInstrumentsUseCase } from "#/modules/legal/features/law/use-cases/list-instruments.repository.ts";
import { ListProvisionsUseCase } from "#/modules/legal/features/law/use-cases/list-provisions.repository.ts";

/**
 * The Law contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class LegalLawService {
  abstract getInstrument(input: InstrumentKeyDto): Promise<InstrumentDetailDto>;
  abstract listEffects(input: IdentityEffectsDto): Promise<EffectCollectionDto>;
  abstract listInstruments(input: InstrumentWindowDto): Promise<InstrumentCollectionDto>;
  abstract listProvisions(input: ProvisionScopeDto): Promise<ProvisionCollectionDto>;
}

@Injectable()
export class LegalLawServiceImpl extends LegalLawService {
  constructor(
    private readonly getInstrumentUseCase: GetInstrumentUseCase,
    private readonly listEffectsUseCase: ListEffectsUseCase,
    private readonly listInstrumentsUseCase: ListInstrumentsUseCase,
    private readonly listProvisionsUseCase: ListProvisionsUseCase,
  ) {
    super();
  }

  getInstrument(input: InstrumentKeyDto): Promise<InstrumentDetailDto> {
    return this.getInstrumentUseCase.execute(input);
  }

  listEffects(input: IdentityEffectsDto): Promise<EffectCollectionDto> {
    return this.listEffectsUseCase.execute(input);
  }

  listInstruments(input: InstrumentWindowDto): Promise<InstrumentCollectionDto> {
    return this.listInstrumentsUseCase.execute(input);
  }

  listProvisions(input: ProvisionScopeDto): Promise<ProvisionCollectionDto> {
    return this.listProvisionsUseCase.execute(input);
  }
}
