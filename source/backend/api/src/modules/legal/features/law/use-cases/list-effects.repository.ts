export async function listEffectsRepository(
  runtime: PersistenceRuntime,
  input: IdentityEffectsDto,
  context: TrustedContext,
): Promise<EffectCollectionDto> {
  try {
    const result = await runtime.execute(plan, instanceToPlain(input), context);
    if (result === null || typeof result !== "object" || Array.isArray(result))
      throw new Error("Expected response object");
    const output = plainToInstance(EffectCollectionDto, result);
    await validateOrReject(output);
    return output;
  } catch (error) {
    if (error instanceof PersistenceFailure)
      throw new HttpException(
        { code: error.failure.code, message: error.message },
        error.failure.status,
      );
    throw error;
  }
}

