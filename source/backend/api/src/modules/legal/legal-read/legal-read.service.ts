/**
 * The Legal Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class LegalLegalReadService {
  abstract findLegalAmendmentChanges(input: LegalAmendmentChangeListQueryDto): Promise<LegalAmendmentChangesListResponseDto>;
  abstract findLegalAmendments(input: LegalAmendmentListQueryDto): Promise<LegalAmendmentsListResponseDto>;
  abstract findLegalAuthorityLinks(input: LegalAuthorityLinkListQueryDto): Promise<LegalAuthorityLinksListResponseDto>;
  abstract findLegalInstruments(input: LegalInstrumentListQueryDto): Promise<LegalInstrumentsListResponseDto>;
  abstract findLegalProvisions(input: LegalProvisionListQueryDto): Promise<LegalProvisionsListResponseDto>;
  abstract getLegalAmendmentById(input: { amendmentId: string }): Promise<LegalAmendmentResponseDto>;
  abstract getLegalAmendmentChangeById(input: { changeId: string }): Promise<LegalAmendmentChangeResponseDto>;
  abstract getLegalAuthorityLinkById(input: { linkId: string }): Promise<LegalAuthorityLinkResponseDto>;
  abstract getLegalInstrumentById(input: { instrumentId: string }): Promise<LegalInstrumentResponseDto>;
  abstract getLegalProvisionById(input: { provisionId: string }): Promise<LegalProvisionResponseDto>;
}