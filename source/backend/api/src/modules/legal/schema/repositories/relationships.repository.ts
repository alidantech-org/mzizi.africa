import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { LegalRelationshipsEntity } from "#/modules/legal/schema/entities/relationships.entity.ts";
import * as Relationships from "#/modules/legal/schema/types/relationships/index.ts";

/**
 * Repository of Relationships: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class RelationshipsRepository
  extends EntityRepository<
    LegalRelationshipsEntity,
    Relationships.Types.RelationshipsSortableField,
    Relationships.Types.RelationshipsEditableField,
    Relationships.Types.RelationshipsSelectableField,
    Relationships.Types.IRelationshipsCreatable
  >
  implements
    IUpdatableRepository<LegalRelationshipsEntity, Relationships.Types.IRelationshipsUpdatable>
{
  constructor(
    @InjectRepository(LegalRelationshipsEntity)
    repository: Repository<LegalRelationshipsEntity>,
  ) {
    super(repository, Relationships.Config.RELATIONSHIPS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Relationships.Types.IRelationshipsUpdatable,
  ): Promise<LegalRelationshipsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find relationships by affected wording id, paged by the shared query. */
  async findByAffectedWording(
    query: BaseQueryDto<LegalRelationshipsEntity>,
    affectedWordingId: NonNullable<LegalRelationshipsEntity["affectedWordingId"]>,
  ): Promise<IFindAllResponse<LegalRelationshipsEntity>> {
    return await this.findByQuery(query, { affectedWordingId, deletedAt: IsNull() });
  }

  /** Find relationships by authority wording id, paged by the shared query. */
  async findByAuthorityWording(
    query: BaseQueryDto<LegalRelationshipsEntity>,
    authorityWordingId: NonNullable<LegalRelationshipsEntity["authorityWordingId"]>,
  ): Promise<IFindAllResponse<LegalRelationshipsEntity>> {
    return await this.findByQuery(query, { authorityWordingId, deletedAt: IsNull() });
  }

  /** Find relationships by citation id, paged by the shared query. */
  async findByCitation(
    query: BaseQueryDto<LegalRelationshipsEntity>,
    citationId: NonNullable<LegalRelationshipsEntity["citationId"]>,
  ): Promise<IFindAllResponse<LegalRelationshipsEntity>> {
    return await this.findByQuery(query, { citationId, deletedAt: IsNull() });
  }

  /** Find relationships by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<LegalRelationshipsEntity>,
    kindId: NonNullable<LegalRelationshipsEntity["kindId"]>,
  ): Promise<IFindAllResponse<LegalRelationshipsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find relationships by object instrument id, paged by the shared query. */
  async findByObjectInstrument(
    query: BaseQueryDto<LegalRelationshipsEntity>,
    objectInstrumentId: NonNullable<LegalRelationshipsEntity["objectInstrumentId"]>,
  ): Promise<IFindAllResponse<LegalRelationshipsEntity>> {
    return await this.findByQuery(query, { objectInstrumentId, deletedAt: IsNull() });
  }

  /** Find relationships by resulting wording id, paged by the shared query. */
  async findByResultingWording(
    query: BaseQueryDto<LegalRelationshipsEntity>,
    resultingWordingId: NonNullable<LegalRelationshipsEntity["resultingWordingId"]>,
  ): Promise<IFindAllResponse<LegalRelationshipsEntity>> {
    return await this.findByQuery(query, { resultingWordingId, deletedAt: IsNull() });
  }

  /** Find relationships by subject instrument id, paged by the shared query. */
  async findBySubjectInstrument(
    query: BaseQueryDto<LegalRelationshipsEntity>,
    subjectInstrumentId: NonNullable<LegalRelationshipsEntity["subjectInstrumentId"]>,
  ): Promise<IFindAllResponse<LegalRelationshipsEntity>> {
    return await this.findByQuery(query, { subjectInstrumentId, deletedAt: IsNull() });
  }

  /** Find the relationships with this code (unique). */
  async findByCode(
    code: NonNullable<LegalRelationshipsEntity["code"]>,
  ): Promise<LegalRelationshipsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
