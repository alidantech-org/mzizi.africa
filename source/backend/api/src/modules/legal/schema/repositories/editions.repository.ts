import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { LegalEditionsEntity } from "#/modules/legal/schema/entities/editions.entity.ts";
import * as Editions from "#/modules/legal/schema/types/editions/index.ts";

/**
 * Repository of Editions: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class EditionsRepository
  extends EntityRepository<
    LegalEditionsEntity,
    Editions.Types.EditionsSortableField,
    Editions.Types.EditionsEditableField,
    Editions.Types.EditionsSelectableField,
    Editions.Types.IEditionsCreatable
  >
  implements IUpdatableRepository<LegalEditionsEntity, Editions.Types.IEditionsUpdatable>
{
  constructor(
    @InjectRepository(LegalEditionsEntity)
    repository: Repository<LegalEditionsEntity>,
  ) {
    super(repository, Editions.Config.EDITIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Editions.Types.IEditionsUpdatable,
  ): Promise<LegalEditionsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find editions by instrument id, paged by the shared query. */
  async findByInstrument(
    query: BaseQueryDto<LegalEditionsEntity>,
    instrumentId: NonNullable<LegalEditionsEntity["instrumentId"]>,
  ): Promise<IFindAllResponse<LegalEditionsEntity>> {
    return await this.findByQuery(query, { instrumentId, deletedAt: IsNull() });
  }

  /** Find editions by supersedes id, paged by the shared query. */
  async findBySupersedes(
    query: BaseQueryDto<LegalEditionsEntity>,
    supersedesId: NonNullable<LegalEditionsEntity["supersedesId"]>,
  ): Promise<IFindAllResponse<LegalEditionsEntity>> {
    return await this.findByQuery(query, { supersedesId, deletedAt: IsNull() });
  }

  /** Find the editions with this code (unique). */
  async findByCode(
    code: NonNullable<LegalEditionsEntity["code"]>,
  ): Promise<LegalEditionsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
