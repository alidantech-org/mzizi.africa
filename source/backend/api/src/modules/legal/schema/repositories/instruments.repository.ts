import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { InstrumentsEntity } from "#/modules/legal/schema/entities/instruments.entity.ts";
import * as Instruments from "#/modules/legal/schema/types/instruments/index.ts";

/**
 * Repository of Instruments: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class InstrumentsRepository
  extends EntityRepository<
    InstrumentsEntity,
    Instruments.Types.InstrumentsSortableField,
    Instruments.Types.InstrumentsEditableField,
    Instruments.Types.InstrumentsSelectableField,
    Instruments.Types.IInstrumentsCreatable
  >
  implements IUpdatableRepository<InstrumentsEntity, Instruments.Types.IInstrumentsUpdatable>
{
  constructor(
    @InjectRepository(InstrumentsEntity)
    repository: Repository<InstrumentsEntity>,
  ) {
    super(repository, Instruments.Config.INSTRUMENTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Instruments.Types.IInstrumentsUpdatable,
  ): Promise<InstrumentsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find instruments by issuing entity id, paged by the shared query. */
  async findByIssuingEntity(
    query: BaseQueryDto<InstrumentsEntity>,
    issuingEntityId: NonNullable<InstrumentsEntity["issuingEntityId"]>,
  ): Promise<IFindAllResponse<InstrumentsEntity>> {
    return await this.findByQuery(query, { issuingEntityId, deletedAt: IsNull() });
  }

  /** Find instruments by issuing unit id, paged by the shared query. */
  async findByIssuingUnit(
    query: BaseQueryDto<InstrumentsEntity>,
    issuingUnitId: NonNullable<InstrumentsEntity["issuingUnitId"]>,
  ): Promise<IFindAllResponse<InstrumentsEntity>> {
    return await this.findByQuery(query, { issuingUnitId, deletedAt: IsNull() });
  }

  /** Find instruments by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<InstrumentsEntity>,
    kindId: NonNullable<InstrumentsEntity["kindId"]>,
  ): Promise<IFindAllResponse<InstrumentsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find instruments by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<InstrumentsEntity>,
    statusId: NonNullable<InstrumentsEntity["statusId"]>,
  ): Promise<IFindAllResponse<InstrumentsEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }

  /** Find the instruments with this code (unique). */
  async findByCode(
    code: NonNullable<InstrumentsEntity["code"]>,
  ): Promise<InstrumentsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
