import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ReferencesEntity } from "#/modules/legal/schema/entities/references.entity.ts";
import * as References from "#/modules/legal/schema/types/references/index.ts";

/**
 * Repository of References: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ReferencesRepository
  extends EntityRepository<
    ReferencesEntity,
    References.Types.ReferencesSortableField,
    References.Types.ReferencesEditableField,
    References.Types.ReferencesSelectableField,
    References.Types.IReferencesCreatable
  >
  implements IUpdatableRepository<ReferencesEntity, References.Types.IReferencesUpdatable>
{
  constructor(
    @InjectRepository(ReferencesEntity)
    repository: Repository<ReferencesEntity>,
  ) {
    super(repository, References.Config.REFERENCES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: References.Types.IReferencesUpdatable,
  ): Promise<ReferencesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find references by method, paged by the shared query. */
  async findByMethod(
    query: BaseQueryDto<ReferencesEntity>,
    method: NonNullable<ReferencesEntity["method"]>,
  ): Promise<IFindAllResponse<ReferencesEntity>> {
    return await this.findByQuery(query, { method, deletedAt: IsNull() });
  }

  /** Find references by relation, paged by the shared query. */
  async findByRelation(
    query: BaseQueryDto<ReferencesEntity>,
    relation: NonNullable<ReferencesEntity["relation"]>,
  ): Promise<IFindAllResponse<ReferencesEntity>> {
    return await this.findByQuery(query, { relation, deletedAt: IsNull() });
  }

  /** Find references by review status, paged by the shared query. */
  async findByReviewStatus(
    query: BaseQueryDto<ReferencesEntity>,
    reviewStatus: NonNullable<ReferencesEntity["reviewStatus"]>,
  ): Promise<IFindAllResponse<ReferencesEntity>> {
    return await this.findByQuery(query, { reviewStatus, deletedAt: IsNull() });
  }

  /** Find references by target provision id, paged by the shared query. */
  async findByTargetProvision(
    query: BaseQueryDto<ReferencesEntity>,
    targetProvisionId: NonNullable<ReferencesEntity["targetProvisionId"]>,
  ): Promise<IFindAllResponse<ReferencesEntity>> {
    return await this.findByQuery(query, { targetProvisionId, deletedAt: IsNull() });
  }

  /** Find references by target wording id, paged by the shared query. */
  async findByTargetWording(
    query: BaseQueryDto<ReferencesEntity>,
    targetWordingId: NonNullable<ReferencesEntity["targetWordingId"]>,
  ): Promise<IFindAllResponse<ReferencesEntity>> {
    return await this.findByQuery(query, { targetWordingId, deletedAt: IsNull() });
  }

  /** Find references by translation id, paged by the shared query. */
  async findByTranslation(
    query: BaseQueryDto<ReferencesEntity>,
    translationId: NonNullable<ReferencesEntity["translationId"]>,
  ): Promise<IFindAllResponse<ReferencesEntity>> {
    return await this.findByQuery(query, { translationId, deletedAt: IsNull() });
  }

  /** Find references by wording id, paged by the shared query. */
  async findByWording(
    query: BaseQueryDto<ReferencesEntity>,
    wordingId: NonNullable<ReferencesEntity["wordingId"]>,
  ): Promise<IFindAllResponse<ReferencesEntity>> {
    return await this.findByQuery(query, { wordingId, deletedAt: IsNull() });
  }

  /** Find the references with this code (unique). */
  async findByCode(code: NonNullable<ReferencesEntity["code"]>): Promise<ReferencesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
