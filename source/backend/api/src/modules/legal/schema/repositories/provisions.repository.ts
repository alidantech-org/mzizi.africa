import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ProvisionsEntity } from "#/modules/legal/schema/entities/provisions.entity.ts";
import * as Provisions from "#/modules/legal/schema/types/provisions/index.ts";

/**
 * Repository of Provisions: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ProvisionsRepository
  extends EntityRepository<
    ProvisionsEntity,
    Provisions.Types.ProvisionsSortableField,
    Provisions.Types.ProvisionsEditableField,
    Provisions.Types.ProvisionsSelectableField,
    Provisions.Types.IProvisionsCreatable
  >
  implements IUpdatableRepository<ProvisionsEntity, Provisions.Types.IProvisionsUpdatable>
{
  constructor(
    @InjectRepository(ProvisionsEntity)
    repository: Repository<ProvisionsEntity>,
  ) {
    super(repository, Provisions.Config.PROVISIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Provisions.Types.IProvisionsUpdatable,
  ): Promise<ProvisionsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find provisions by instrument id, paged by the shared query. */
  async findByInstrument(
    query: BaseQueryDto<ProvisionsEntity>,
    instrumentId: NonNullable<ProvisionsEntity["instrumentId"]>,
  ): Promise<IFindAllResponse<ProvisionsEntity>> {
    return await this.findByQuery(query, { instrumentId, deletedAt: IsNull() });
  }

  /** Find provisions by kind, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<ProvisionsEntity>,
    kind: NonNullable<ProvisionsEntity["kind"]>,
  ): Promise<IFindAllResponse<ProvisionsEntity>> {
    return await this.findByQuery(query, { kind, deletedAt: IsNull() });
  }

  /** Find provisions by parent id, paged by the shared query. */
  async findByParent(
    query: BaseQueryDto<ProvisionsEntity>,
    parentId: NonNullable<ProvisionsEntity["parentId"]>,
  ): Promise<IFindAllResponse<ProvisionsEntity>> {
    return await this.findByQuery(query, { parentId, deletedAt: IsNull() });
  }

  /** Find the provisions with this code (unique). */
  async findByCode(code: NonNullable<ProvisionsEntity["code"]>): Promise<ProvisionsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
