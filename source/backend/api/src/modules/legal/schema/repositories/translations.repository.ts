import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { TranslationsEntity } from "#/modules/legal/schema/entities/translations.entity.ts";
import * as Translations from "#/modules/legal/schema/types/translations/index.ts";

/**
 * Repository of Translations: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class TranslationsRepository
  extends EntityRepository<
    TranslationsEntity,
    Translations.Types.TranslationsSortableField,
    Translations.Types.TranslationsEditableField,
    Translations.Types.TranslationsSelectableField,
    Translations.Types.ITranslationsCreatable
  >
  implements IUpdatableRepository<TranslationsEntity, Translations.Types.ITranslationsUpdatable>
{
  constructor(
    @InjectRepository(TranslationsEntity)
    repository: Repository<TranslationsEntity>,
  ) {
    super(repository, Translations.Config.TRANSLATIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Translations.Types.ITranslationsUpdatable,
  ): Promise<TranslationsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find translations by language id, paged by the shared query. */
  async findByLanguage(
    query: BaseQueryDto<TranslationsEntity>,
    languageId: NonNullable<TranslationsEntity["languageId"]>,
  ): Promise<IFindAllResponse<TranslationsEntity>> {
    return await this.findByQuery(query, { languageId, deletedAt: IsNull() });
  }

  /** Find translations by method, paged by the shared query. */
  async findByMethod(
    query: BaseQueryDto<TranslationsEntity>,
    method: NonNullable<TranslationsEntity["method"]>,
  ): Promise<IFindAllResponse<TranslationsEntity>> {
    return await this.findByQuery(query, { method, deletedAt: IsNull() });
  }

  /** Find translations by review status, paged by the shared query. */
  async findByReviewStatus(
    query: BaseQueryDto<TranslationsEntity>,
    reviewStatus: NonNullable<TranslationsEntity["reviewStatus"]>,
  ): Promise<IFindAllResponse<TranslationsEntity>> {
    return await this.findByQuery(query, { reviewStatus, deletedAt: IsNull() });
  }

  /** Find translations by wording id, paged by the shared query. */
  async findByWording(
    query: BaseQueryDto<TranslationsEntity>,
    wordingId: NonNullable<TranslationsEntity["wordingId"]>,
  ): Promise<IFindAllResponse<TranslationsEntity>> {
    return await this.findByQuery(query, { wordingId, deletedAt: IsNull() });
  }

  /** Find the translations with this code (unique). */
  async findByCode(
    code: NonNullable<TranslationsEntity["code"]>,
  ): Promise<TranslationsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
