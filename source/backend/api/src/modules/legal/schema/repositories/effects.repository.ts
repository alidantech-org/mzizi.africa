import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { EffectsEntity } from "#/modules/legal/schema/entities/effects.entity.ts";
import * as Effects from "#/modules/legal/schema/types/effects/index.ts";

/**
 * Repository of Effects: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class EffectsRepository
  extends EntityRepository<
    EffectsEntity,
    Effects.Types.EffectsSortableField,
    Effects.Types.EffectsEditableField,
    Effects.Types.EffectsSelectableField,
    Effects.Types.IEffectsCreatable
  >
  implements IUpdatableRepository<EffectsEntity, Effects.Types.IEffectsUpdatable>
{
  constructor(
    @InjectRepository(EffectsEntity)
    repository: Repository<EffectsEntity>,
  ) {
    super(repository, Effects.Config.EFFECTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Effects.Types.IEffectsUpdatable,
  ): Promise<EffectsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find effects by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<EffectsEntity>,
    fromToPrecision: NonNullable<EffectsEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<EffectsEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find effects by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<EffectsEntity>,
    kindId: NonNullable<EffectsEntity["kindId"]>,
  ): Promise<IFindAllResponse<EffectsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find effects by review status, paged by the shared query. */
  async findByReviewStatus(
    query: BaseQueryDto<EffectsEntity>,
    reviewStatus: NonNullable<EffectsEntity["reviewStatus"]>,
  ): Promise<IFindAllResponse<EffectsEntity>> {
    return await this.findByQuery(query, { reviewStatus, deletedAt: IsNull() });
  }

  /** Find effects by subject table, paged by the shared query. */
  async findBySubjectTable(
    query: BaseQueryDto<EffectsEntity>,
    subjectTable: NonNullable<EffectsEntity["subjectTable"]>,
  ): Promise<IFindAllResponse<EffectsEntity>> {
    return await this.findByQuery(query, { subjectTable, deletedAt: IsNull() });
  }

  /** Find effects by wording id, paged by the shared query. */
  async findByWording(
    query: BaseQueryDto<EffectsEntity>,
    wordingId: NonNullable<EffectsEntity["wordingId"]>,
  ): Promise<IFindAllResponse<EffectsEntity>> {
    return await this.findByQuery(query, { wordingId, deletedAt: IsNull() });
  }

  /** Find the effects with this code (unique). */
  async findByCode(code: NonNullable<EffectsEntity["code"]>): Promise<EffectsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
