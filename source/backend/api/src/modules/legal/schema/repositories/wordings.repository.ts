import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { WordingsEntity } from "#/modules/legal/schema/entities/wordings.entity.ts";
import * as Wordings from "#/modules/legal/schema/types/wordings/index.ts";

/**
 * Repository of Wordings: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class WordingsRepository
  extends EntityRepository<
    WordingsEntity,
    Wordings.Types.WordingsSortableField,
    Wordings.Types.WordingsEditableField,
    Wordings.Types.WordingsSelectableField,
    Wordings.Types.IWordingsCreatable
  >
  implements IUpdatableRepository<WordingsEntity, Wordings.Types.IWordingsUpdatable>
{
  constructor(
    @InjectRepository(WordingsEntity)
    repository: Repository<WordingsEntity>,
  ) {
    super(repository, Wordings.Config.WORDINGS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Wordings.Types.IWordingsUpdatable,
  ): Promise<WordingsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find wordings by citation id, paged by the shared query. */
  async findByCitation(
    query: BaseQueryDto<WordingsEntity>,
    citationId: NonNullable<WordingsEntity["citationId"]>,
  ): Promise<IFindAllResponse<WordingsEntity>> {
    return await this.findByQuery(query, { citationId, deletedAt: IsNull() });
  }

  /** Find wordings by edition id, paged by the shared query. */
  async findByEdition(
    query: BaseQueryDto<WordingsEntity>,
    editionId: NonNullable<WordingsEntity["editionId"]>,
  ): Promise<IFindAllResponse<WordingsEntity>> {
    return await this.findByQuery(query, { editionId, deletedAt: IsNull() });
  }

  /** Find wordings by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<WordingsEntity>,
    fromToPrecision: NonNullable<WordingsEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<WordingsEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find wordings by instrument id, paged by the shared query. */
  async findByInstrument(
    query: BaseQueryDto<WordingsEntity>,
    instrumentId: NonNullable<WordingsEntity["instrumentId"]>,
  ): Promise<IFindAllResponse<WordingsEntity>> {
    return await this.findByQuery(query, { instrumentId, deletedAt: IsNull() });
  }

  /** Find wordings by language id, paged by the shared query. */
  async findByLanguage(
    query: BaseQueryDto<WordingsEntity>,
    languageId: NonNullable<WordingsEntity["languageId"]>,
  ): Promise<IFindAllResponse<WordingsEntity>> {
    return await this.findByQuery(query, { languageId, deletedAt: IsNull() });
  }

  /** Find wordings by provision id, paged by the shared query. */
  async findByProvision(
    query: BaseQueryDto<WordingsEntity>,
    provisionId: NonNullable<WordingsEntity["provisionId"]>,
  ): Promise<IFindAllResponse<WordingsEntity>> {
    return await this.findByQuery(query, { provisionId, deletedAt: IsNull() });
  }

  /** Find wordings by supersedes id, paged by the shared query. */
  async findBySupersedes(
    query: BaseQueryDto<WordingsEntity>,
    supersedesId: NonNullable<WordingsEntity["supersedesId"]>,
  ): Promise<IFindAllResponse<WordingsEntity>> {
    return await this.findByQuery(query, { supersedesId, deletedAt: IsNull() });
  }

  /** Find the wordings with this code (unique). */
  async findByCode(code: NonNullable<WordingsEntity["code"]>): Promise<WordingsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
