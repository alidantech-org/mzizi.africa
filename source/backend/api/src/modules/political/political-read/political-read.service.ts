/**
 * The Political Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class PoliticalPoliticalReadService {
  abstract findIdeologies(input: IdeologyListQueryDto): Promise<IdeologiesListResponseDto>;
  abstract findParties(input: PartyListQueryDto): Promise<PartiesListResponseDto>;
  abstract findPartyIdeologies(input: PartyIdeologyListQueryDto): Promise<PartyIdeologiesListResponseDto>;
  abstract findPartyMemberships(input: PartyMembershipListQueryDto): Promise<PartyMembershipsListResponseDto>;
  abstract findPartyPositionHolders(input: PartyPositionHolderListQueryDto): Promise<PartyPositionHoldersListResponseDto>;
  abstract findPartyPositions(input: PartyPositionListQueryDto): Promise<PartyPositionsListResponseDto>;
  abstract findPartyUnits(input: PartyUnitListQueryDto): Promise<PartyUnitsListResponseDto>;
  abstract getIdeologyById(input: { ideologyId: string }): Promise<IdeologyResponseDto>;
  abstract getPartyById(input: { partyId: string }): Promise<PartyResponseDto>;
  abstract getPartyIdeologyById(input: { partyIdeologyId: string }): Promise<PartyIdeologyResponseDto>;
  abstract getPartyMembershipById(input: { membershipId: string }): Promise<PartyMembershipResponseDto>;
  abstract getPartyPositionById(input: { positionId: string }): Promise<PartyPositionResponseDto>;
  abstract getPartyPositionHolderById(input: { holderId: string }): Promise<PartyPositionHolderResponseDto>;
  abstract getPartyUnitById(input: { unitId: string }): Promise<PartyUnitResponseDto>;
}