import { Injectable } from "@nestjs/common";
import type { BudgetListDto } from "#/modules/ledger/schema/dto/budget-list.dto.ts";
import type { CoalitionListDto } from "#/modules/ledger/schema/dto/coalition-list.dto.ts";
import type { CoverageListDto } from "#/modules/ledger/schema/dto/coverage-list.dto.ts";
import type { FundListDto } from "#/modules/ledger/schema/dto/fund-list.dto.ts";
import type { LedgerInputDto } from "#/modules/ledger/schema/dto/ledger-input.dto.ts";
import type { ManifestoListDto } from "#/modules/ledger/schema/dto/manifesto-list.dto.ts";
import { GetCoverageUseCase } from "#/modules/ledger/features/ledger/use-cases/get-coverage.usecase.ts";
import { ListBudgetsUseCase } from "#/modules/ledger/features/ledger/use-cases/list-budgets.usecase.ts";
import { ListCoalitionsUseCase } from "#/modules/ledger/features/ledger/use-cases/list-coalitions.usecase.ts";
import { ListFundsUseCase } from "#/modules/ledger/features/ledger/use-cases/list-funds.usecase.ts";
import { ListManifestosUseCase } from "#/modules/ledger/features/ledger/use-cases/list-manifestos.usecase.ts";

/**
 * The Ledger contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class LedgerLedgerService {
  abstract getCoverage(): Promise<CoverageListDto>;
  abstract listBudgets(input: LedgerInputDto): Promise<BudgetListDto>;
  abstract listCoalitions(): Promise<CoalitionListDto>;
  abstract listFunds(input: LedgerInputDto): Promise<FundListDto>;
  abstract listManifestos(): Promise<ManifestoListDto>;
}

@Injectable()
export class LedgerLedgerServiceImpl extends LedgerLedgerService {
  constructor(
    private readonly getCoverageUseCase: GetCoverageUseCase,
    private readonly listBudgetsUseCase: ListBudgetsUseCase,
    private readonly listCoalitionsUseCase: ListCoalitionsUseCase,
    private readonly listFundsUseCase: ListFundsUseCase,
    private readonly listManifestosUseCase: ListManifestosUseCase,
  ) {
    super();
  }

  getCoverage(): Promise<CoverageListDto> {
    return this.getCoverageUseCase.execute();
  }

  listBudgets(input: LedgerInputDto): Promise<BudgetListDto> {
    return this.listBudgetsUseCase.execute(input);
  }

  listCoalitions(): Promise<CoalitionListDto> {
    return this.listCoalitionsUseCase.execute();
  }

  listFunds(input: LedgerInputDto): Promise<FundListDto> {
    return this.listFundsUseCase.execute(input);
  }

  listManifestos(): Promise<ManifestoListDto> {
    return this.listManifestosUseCase.execute();
  }
}
