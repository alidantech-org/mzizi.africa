/**
 * The Explorer contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class ExplorerExplorerService {
  abstract getCopyBundle(input: CopyInputDto): Promise<CopyBundleDto>;
  abstract getExplorerBoundaries(input: BoundariesInputDto): Promise<BoundariesDto>;
  abstract getExplorerContext(input: PlaceInputDto): Promise<ContextDto>;
  abstract getExplorerLocation(input: LocationInputDto): Promise<LocationDto>;
  abstract getExplorerNavigation(input: NavigationInputDto): Promise<NavigationDto>;
  abstract getExplorerOverview(input: PlaceInputDto): Promise<OverviewDto>;
  abstract getSetupBootstrap(input: BootstrapInputDto): Promise<BootstrapDto>;
  abstract listExplorerChildren(input: ChildrenInputDto): Promise<PlacesDto>;
  abstract resolveExplorerAddresses(input: AddressesInputDto): Promise<AddressesDto>;
  abstract resolveExplorerCoordinates(input: CoordinatesInputDto): Promise<ResolutionDto>;
  abstract searchExplorerPlaces(input: SearchInputDto): Promise<PlacesDto>;
}

@Injectable()
export class ExplorerExplorerServiceImpl extends ExplorerExplorerService {
  constructor(
    private readonly getCopyBundleUseCase: GetCopyBundleUseCase,
    private readonly getExplorerBoundariesUseCase: GetExplorerBoundariesUseCase,
    private readonly getExplorerContextUseCase: GetExplorerContextUseCase,
    private readonly getExplorerLocationUseCase: GetExplorerLocationUseCase,
    private readonly getExplorerNavigationUseCase: GetExplorerNavigationUseCase,
    private readonly getExplorerOverviewUseCase: GetExplorerOverviewUseCase,
    private readonly getSetupBootstrapUseCase: GetSetupBootstrapUseCase,
    private readonly listExplorerChildrenUseCase: ListExplorerChildrenUseCase,
    private readonly resolveExplorerAddressesUseCase: ResolveExplorerAddressesUseCase,
    private readonly resolveExplorerCoordinatesUseCase: ResolveExplorerCoordinatesUseCase,
    private readonly searchExplorerPlacesUseCase: SearchExplorerPlacesUseCase,
  ) {
    super();
  }

  getCopyBundle(input: CopyInputDto): Promise<CopyBundleDto> {
    return this.getCopyBundleUseCase.execute(input);
  }

  getExplorerBoundaries(input: BoundariesInputDto): Promise<BoundariesDto> {
    return this.getExplorerBoundariesUseCase.execute(input);
  }

  getExplorerContext(input: PlaceInputDto): Promise<ContextDto> {
    return this.getExplorerContextUseCase.execute(input);
  }

  getExplorerLocation(input: LocationInputDto): Promise<LocationDto> {
    return this.getExplorerLocationUseCase.execute(input);
  }

  getExplorerNavigation(input: NavigationInputDto): Promise<NavigationDto> {
    return this.getExplorerNavigationUseCase.execute(input);
  }

  getExplorerOverview(input: PlaceInputDto): Promise<OverviewDto> {
    return this.getExplorerOverviewUseCase.execute(input);
  }

  getSetupBootstrap(input: BootstrapInputDto): Promise<BootstrapDto> {
    return this.getSetupBootstrapUseCase.execute(input);
  }

  listExplorerChildren(input: ChildrenInputDto): Promise<PlacesDto> {
    return this.listExplorerChildrenUseCase.execute(input);
  }

  resolveExplorerAddresses(input: AddressesInputDto): Promise<AddressesDto> {
    return this.resolveExplorerAddressesUseCase.execute(input);
  }

  resolveExplorerCoordinates(input: CoordinatesInputDto): Promise<ResolutionDto> {
    return this.resolveExplorerCoordinatesUseCase.execute(input);
  }

  searchExplorerPlaces(input: SearchInputDto): Promise<PlacesDto> {
    return this.searchExplorerPlacesUseCase.execute(input);
  }
}
