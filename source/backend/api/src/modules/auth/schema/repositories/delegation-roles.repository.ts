import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { type Repository } from "typeorm";
import { EntityRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { DelegationRolesEntity } from "#/modules/auth/schema/entities/delegation-roles.entity.ts";
import * as DelegationRoles from "#/modules/auth/schema/types/delegation-roles/index.ts";

/**
 * Repository of Delegation Roles: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class DelegationRolesRepository extends EntityRepository<
  DelegationRolesEntity,
  DelegationRoles.Types.DelegationRolesSortableField,
  DelegationRoles.Types.DelegationRolesEditableField,
  DelegationRoles.Types.DelegationRolesSelectableField,
  DelegationRoles.Types.IDelegationRolesCreatable
> {
  constructor(
    @InjectRepository(DelegationRolesEntity)
    repository: Repository<DelegationRolesEntity>,
  ) {
    super(repository, DelegationRoles.Config.DELEGATION_ROLES_QUERY_OPTIONS);
  }

  /** Find delegation roles by delegation id, paged by the shared query. */
  async findByDelegation(
    query: BaseQueryDto<DelegationRolesEntity>,
    delegationId: NonNullable<DelegationRolesEntity["delegationId"]>,
  ): Promise<IFindAllResponse<DelegationRolesEntity>> {
    return await this.findByQuery(query, { delegationId });
  }

  /** Find delegation roles by role id, paged by the shared query. */
  async findByRole(
    query: BaseQueryDto<DelegationRolesEntity>,
    roleId: NonNullable<DelegationRolesEntity["roleId"]>,
  ): Promise<IFindAllResponse<DelegationRolesEntity>> {
    return await this.findByQuery(query, { roleId });
  }
}
