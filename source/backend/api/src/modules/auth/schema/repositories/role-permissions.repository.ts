import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { type Repository } from "typeorm";
import { EntityRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { RolePermissionsEntity } from "#/modules/auth/schema/entities/role-permissions.entity.ts";
import * as RolePermissions from "#/modules/auth/schema/types/role-permissions/index.ts";

/**
 * Repository of Role Permissions: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class RolePermissionsRepository extends EntityRepository<
  RolePermissionsEntity,
  RolePermissions.Types.RolePermissionsSortableField,
  RolePermissions.Types.RolePermissionsEditableField,
  RolePermissions.Types.RolePermissionsSelectableField,
  RolePermissions.Types.IRolePermissionsCreatable
> {
  constructor(
    @InjectRepository(RolePermissionsEntity)
    repository: Repository<RolePermissionsEntity>,
  ) {
    super(repository, RolePermissions.Config.ROLE_PERMISSIONS_QUERY_OPTIONS);
  }

  /** Find role permissions by granted by, paged by the shared query. */
  async findByGrantedBy(
    query: BaseQueryDto<RolePermissionsEntity>,
    grantedBy: NonNullable<RolePermissionsEntity["grantedBy"]>,
  ): Promise<IFindAllResponse<RolePermissionsEntity>> {
    return await this.findByQuery(query, { grantedBy });
  }

  /** Find role permissions by permission id, paged by the shared query. */
  async findByPermission(
    query: BaseQueryDto<RolePermissionsEntity>,
    permissionId: NonNullable<RolePermissionsEntity["permissionId"]>,
  ): Promise<IFindAllResponse<RolePermissionsEntity>> {
    return await this.findByQuery(query, { permissionId });
  }

  /** Find role permissions by role id, paged by the shared query. */
  async findByRole(
    query: BaseQueryDto<RolePermissionsEntity>,
    roleId: NonNullable<RolePermissionsEntity["roleId"]>,
  ): Promise<IFindAllResponse<RolePermissionsEntity>> {
    return await this.findByQuery(query, { roleId });
  }
}
