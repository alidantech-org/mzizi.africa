import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { RoleAssignmentsEntity } from "#/modules/auth/schema/entities/role-assignments.entity.ts";
import * as RoleAssignments from "#/modules/auth/schema/types/role-assignments/index.ts";

/**
 * Repository of Role Assignments: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class RoleAssignmentsRepository
  extends EntityRepository<
    RoleAssignmentsEntity,
    RoleAssignments.Types.RoleAssignmentsSortableField,
    RoleAssignments.Types.RoleAssignmentsEditableField,
    RoleAssignments.Types.RoleAssignmentsSelectableField,
    RoleAssignments.Types.IRoleAssignmentsCreatable
  >
  implements
    IUpdatableRepository<RoleAssignmentsEntity, RoleAssignments.Types.IRoleAssignmentsUpdatable>
{
  constructor(
    @InjectRepository(RoleAssignmentsEntity)
    repository: Repository<RoleAssignmentsEntity>,
  ) {
    super(repository, RoleAssignments.Config.ROLE_ASSIGNMENTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: RoleAssignments.Types.IRoleAssignmentsUpdatable,
  ): Promise<RoleAssignmentsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find role assignments by account id, paged by the shared query. */
  async findByAccount(
    query: BaseQueryDto<RoleAssignmentsEntity>,
    accountId: NonNullable<RoleAssignmentsEntity["accountId"]>,
  ): Promise<IFindAllResponse<RoleAssignmentsEntity>> {
    return await this.findByQuery(query, { accountId });
  }

  /** Find role assignments by delegation id, paged by the shared query. */
  async findByDelegation(
    query: BaseQueryDto<RoleAssignmentsEntity>,
    delegationId: NonNullable<RoleAssignmentsEntity["delegationId"]>,
  ): Promise<IFindAllResponse<RoleAssignmentsEntity>> {
    return await this.findByQuery(query, { delegationId });
  }

  /** Find role assignments by granted by, paged by the shared query. */
  async findByGrantedBy(
    query: BaseQueryDto<RoleAssignmentsEntity>,
    grantedBy: NonNullable<RoleAssignmentsEntity["grantedBy"]>,
  ): Promise<IFindAllResponse<RoleAssignmentsEntity>> {
    return await this.findByQuery(query, { grantedBy });
  }

  /** Find role assignments by membership id, paged by the shared query. */
  async findByMembership(
    query: BaseQueryDto<RoleAssignmentsEntity>,
    membershipId: NonNullable<RoleAssignmentsEntity["membershipId"]>,
  ): Promise<IFindAllResponse<RoleAssignmentsEntity>> {
    return await this.findByQuery(query, { membershipId });
  }

  /** Find role assignments by revoked by, paged by the shared query. */
  async findByRevokedBy(
    query: BaseQueryDto<RoleAssignmentsEntity>,
    revokedBy: NonNullable<RoleAssignmentsEntity["revokedBy"]>,
  ): Promise<IFindAllResponse<RoleAssignmentsEntity>> {
    return await this.findByQuery(query, { revokedBy });
  }

  /** Find role assignments by role id, paged by the shared query. */
  async findByRole(
    query: BaseQueryDto<RoleAssignmentsEntity>,
    roleId: NonNullable<RoleAssignmentsEntity["roleId"]>,
  ): Promise<IFindAllResponse<RoleAssignmentsEntity>> {
    return await this.findByQuery(query, { roleId });
  }

  /** Find role assignments by scope id, paged by the shared query. */
  async findByScope(
    query: BaseQueryDto<RoleAssignmentsEntity>,
    scopeId: NonNullable<RoleAssignmentsEntity["scopeId"]>,
  ): Promise<IFindAllResponse<RoleAssignmentsEntity>> {
    return await this.findByQuery(query, { scopeId });
  }
}
