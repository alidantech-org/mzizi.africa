import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { PermissionsEntity } from "#/modules/auth/schema/entities/permissions.entity.ts";
import * as Permissions from "#/modules/auth/schema/types/permissions/index.ts";

/**
 * Repository of Permissions: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class PermissionsRepository
  extends EntityRepository<
    PermissionsEntity,
    Permissions.Types.PermissionsSortableField,
    Permissions.Types.PermissionsEditableField,
    Permissions.Types.PermissionsSelectableField,
    Permissions.Types.IPermissionsCreatable
  >
  implements IUpdatableRepository<PermissionsEntity, Permissions.Types.IPermissionsUpdatable>
{
  constructor(
    @InjectRepository(PermissionsEntity)
    repository: Repository<PermissionsEntity>,
  ) {
    super(repository, Permissions.Config.PERMISSIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Permissions.Types.IPermissionsUpdatable,
  ): Promise<PermissionsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find permissions by action, paged by the shared query. */
  async findByAction(
    query: BaseQueryDto<PermissionsEntity>,
    action: NonNullable<PermissionsEntity["action"]>,
  ): Promise<IFindAllResponse<PermissionsEntity>> {
    return await this.findByQuery(query, { action });
  }

  /** Find the permissions with this code (unique). */
  async findByCode(
    code: NonNullable<PermissionsEntity["code"]>,
  ): Promise<PermissionsEntity | null> {
    return await this.findOne({ code });
  }
}
