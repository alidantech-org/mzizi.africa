import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { DelegationsEntity } from "#/modules/auth/schema/entities/delegations.entity.ts";
import * as Delegations from "#/modules/auth/schema/types/delegations/index.ts";

/**
 * Repository of Delegations: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class DelegationsRepository
  extends EntityRepository<
    DelegationsEntity,
    Delegations.Types.DelegationsSortableField,
    Delegations.Types.DelegationsEditableField,
    Delegations.Types.DelegationsSelectableField,
    Delegations.Types.IDelegationsCreatable
  >
  implements IUpdatableRepository<DelegationsEntity, Delegations.Types.IDelegationsUpdatable>
{
  constructor(
    @InjectRepository(DelegationsEntity)
    repository: Repository<DelegationsEntity>,
  ) {
    super(repository, Delegations.Config.DELEGATIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Delegations.Types.IDelegationsUpdatable,
  ): Promise<DelegationsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find delegations by delegate account id, paged by the shared query. */
  async findByDelegateAccount(
    query: BaseQueryDto<DelegationsEntity>,
    delegateAccountId: NonNullable<DelegationsEntity["delegateAccountId"]>,
  ): Promise<IFindAllResponse<DelegationsEntity>> {
    return await this.findByQuery(query, { delegateAccountId });
  }

  /** Find delegations by delegator account id, paged by the shared query. */
  async findByDelegatorAccount(
    query: BaseQueryDto<DelegationsEntity>,
    delegatorAccountId: NonNullable<DelegationsEntity["delegatorAccountId"]>,
  ): Promise<IFindAllResponse<DelegationsEntity>> {
    return await this.findByQuery(query, { delegatorAccountId });
  }

  /** Find delegations by revoked by, paged by the shared query. */
  async findByRevokedBy(
    query: BaseQueryDto<DelegationsEntity>,
    revokedBy: NonNullable<DelegationsEntity["revokedBy"]>,
  ): Promise<IFindAllResponse<DelegationsEntity>> {
    return await this.findByQuery(query, { revokedBy });
  }

  /** Find delegations by scope id, paged by the shared query. */
  async findByScope(
    query: BaseQueryDto<DelegationsEntity>,
    scopeId: NonNullable<DelegationsEntity["scopeId"]>,
  ): Promise<IFindAllResponse<DelegationsEntity>> {
    return await this.findByQuery(query, { scopeId });
  }
}
