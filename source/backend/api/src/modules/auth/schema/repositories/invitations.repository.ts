import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { InvitationsEntity } from "#/modules/auth/schema/entities/invitations.entity.ts";
import * as Invitations from "#/modules/auth/schema/types/invitations/index.ts";

/**
 * Repository of Invitations: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class InvitationsRepository
  extends EntityRepository<
    InvitationsEntity,
    Invitations.Types.InvitationsSortableField,
    Invitations.Types.InvitationsEditableField,
    Invitations.Types.InvitationsSelectableField,
    Invitations.Types.IInvitationsCreatable
  >
  implements IUpdatableRepository<InvitationsEntity, Invitations.Types.IInvitationsUpdatable>
{
  constructor(
    @InjectRepository(InvitationsEntity)
    repository: Repository<InvitationsEntity>,
  ) {
    super(repository, Invitations.Config.INVITATIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Invitations.Types.IInvitationsUpdatable,
  ): Promise<InvitationsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find invitations by accepted account id, paged by the shared query. */
  async findByAcceptedAccount(
    query: BaseQueryDto<InvitationsEntity>,
    acceptedAccountId: NonNullable<InvitationsEntity["acceptedAccountId"]>,
  ): Promise<IFindAllResponse<InvitationsEntity>> {
    return await this.findByQuery(query, { acceptedAccountId });
  }

  /** Find invitations by invited by, paged by the shared query. */
  async findByInvitedBy(
    query: BaseQueryDto<InvitationsEntity>,
    invitedBy: NonNullable<InvitationsEntity["invitedBy"]>,
  ): Promise<IFindAllResponse<InvitationsEntity>> {
    return await this.findByQuery(query, { invitedBy });
  }

  /** Find the invitations with this token digest (unique). */
  async findByTokenDigest(
    tokenDigest: NonNullable<InvitationsEntity["tokenDigest"]>,
  ): Promise<InvitationsEntity | null> {
    return await this.findOne({ tokenDigest });
  }
}
