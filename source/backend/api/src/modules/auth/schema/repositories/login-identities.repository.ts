import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { LoginIdentitiesEntity } from "#/modules/auth/schema/entities/login-identities.entity.ts";
import * as LoginIdentities from "#/modules/auth/schema/types/login-identities/index.ts";

/**
 * Repository of Login Identities: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class LoginIdentitiesRepository
  extends EntityRepository<
    LoginIdentitiesEntity,
    LoginIdentities.Types.LoginIdentitiesSortableField,
    LoginIdentities.Types.LoginIdentitiesEditableField,
    LoginIdentities.Types.LoginIdentitiesSelectableField,
    LoginIdentities.Types.ILoginIdentitiesCreatable
  >
  implements
    IUpdatableRepository<LoginIdentitiesEntity, LoginIdentities.Types.ILoginIdentitiesUpdatable>
{
  constructor(
    @InjectRepository(LoginIdentitiesEntity)
    repository: Repository<LoginIdentitiesEntity>,
  ) {
    super(repository, LoginIdentities.Config.LOGIN_IDENTITIES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: LoginIdentities.Types.ILoginIdentitiesUpdatable,
  ): Promise<LoginIdentitiesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find login identities by account id, paged by the shared query. */
  async findByAccount(
    query: BaseQueryDto<LoginIdentitiesEntity>,
    accountId: NonNullable<LoginIdentitiesEntity["accountId"]>,
  ): Promise<IFindAllResponse<LoginIdentitiesEntity>> {
    return await this.findByQuery(query, { accountId });
  }
}
