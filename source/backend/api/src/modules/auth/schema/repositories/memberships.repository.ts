import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { MembershipsEntity } from "#/modules/auth/schema/entities/memberships.entity.ts";
import * as Memberships from "#/modules/auth/schema/types/memberships/index.ts";

/**
 * Repository of Memberships: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class MembershipsRepository
  extends EntityRepository<
    MembershipsEntity,
    Memberships.Types.MembershipsSortableField,
    Memberships.Types.MembershipsEditableField,
    Memberships.Types.MembershipsSelectableField,
    Memberships.Types.IMembershipsCreatable
  >
  implements IUpdatableRepository<MembershipsEntity, Memberships.Types.IMembershipsUpdatable>
{
  constructor(
    @InjectRepository(MembershipsEntity)
    repository: Repository<MembershipsEntity>,
  ) {
    super(repository, Memberships.Config.MEMBERSHIPS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Memberships.Types.IMembershipsUpdatable,
  ): Promise<MembershipsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find memberships by account id, paged by the shared query. */
  async findByAccount(
    query: BaseQueryDto<MembershipsEntity>,
    accountId: NonNullable<MembershipsEntity["accountId"]>,
  ): Promise<IFindAllResponse<MembershipsEntity>> {
    return await this.findByQuery(query, { accountId });
  }

  /** Find memberships by revoked by, paged by the shared query. */
  async findByRevokedBy(
    query: BaseQueryDto<MembershipsEntity>,
    revokedBy: NonNullable<MembershipsEntity["revokedBy"]>,
  ): Promise<IFindAllResponse<MembershipsEntity>> {
    return await this.findByQuery(query, { revokedBy });
  }

  /** Find memberships by status, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<MembershipsEntity>,
    status: NonNullable<MembershipsEntity["status"]>,
  ): Promise<IFindAllResponse<MembershipsEntity>> {
    return await this.findByQuery(query, { status });
  }

  /** Find memberships by verified by, paged by the shared query. */
  async findByVerifiedBy(
    query: BaseQueryDto<MembershipsEntity>,
    verifiedBy: NonNullable<MembershipsEntity["verifiedBy"]>,
  ): Promise<IFindAllResponse<MembershipsEntity>> {
    return await this.findByQuery(query, { verifiedBy });
  }
}
