import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { AccountsEntity } from "#/modules/auth/schema/entities/accounts.entity.ts";
import * as Accounts from "#/modules/auth/schema/types/accounts/index.ts";

/**
 * Repository of Accounts: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class AccountsRepository
  extends EntityRepository<
    AccountsEntity,
    Accounts.Types.AccountsSortableField,
    Accounts.Types.AccountsEditableField,
    Accounts.Types.AccountsSelectableField,
    Accounts.Types.IAccountsCreatable
  >
  implements IUpdatableRepository<AccountsEntity, Accounts.Types.IAccountsUpdatable>
{
  constructor(
    @InjectRepository(AccountsEntity)
    repository: Repository<AccountsEntity>,
  ) {
    super(repository, Accounts.Config.ACCOUNTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Accounts.Types.IAccountsUpdatable,
  ): Promise<AccountsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find accounts by actor kind, paged by the shared query. */
  async findByActorKind(
    query: BaseQueryDto<AccountsEntity>,
    actorKind: NonNullable<AccountsEntity["actorKind"]>,
  ): Promise<IFindAllResponse<AccountsEntity>> {
    return await this.findByQuery(query, { actorKind });
  }

  /** Find accounts by status, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<AccountsEntity>,
    status: NonNullable<AccountsEntity["status"]>,
  ): Promise<IFindAllResponse<AccountsEntity>> {
    return await this.findByQuery(query, { status });
  }
}
