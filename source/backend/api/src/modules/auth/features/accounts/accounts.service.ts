import { Injectable } from "@nestjs/common";
import type { AccountCollectionDto } from "#/modules/auth/schema/dto/account-collection.dto.ts";
import type { AccountReadDto } from "#/modules/auth/schema/dto/account-read.dto.ts";
import type { AccountWindowDto } from "#/modules/auth/schema/dto/account-window.dto.ts";
import { GetMyAccountUseCase } from "#/modules/auth/features/accounts/use-cases/get-my-account.usecase.ts";
import { ListAccountsUseCase } from "#/modules/auth/features/accounts/use-cases/list-accounts.usecase.ts";

/**
 * The Accounts contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class AuthAccountsService {
  abstract getMyAccount(): Promise<AccountReadDto>;
  abstract listAccounts(input: AccountWindowDto): Promise<AccountCollectionDto>;
}

@Injectable()
export class AuthAccountsServiceImpl extends AuthAccountsService {
  constructor(
    private readonly getMyAccountUseCase: GetMyAccountUseCase,
    private readonly listAccountsUseCase: ListAccountsUseCase,
  ) {
    super();
  }

  getMyAccount(): Promise<AccountReadDto> {
    return this.getMyAccountUseCase.execute();
  }

  listAccounts(input: AccountWindowDto): Promise<AccountCollectionDto> {
    return this.listAccountsUseCase.execute(input);
  }
}
