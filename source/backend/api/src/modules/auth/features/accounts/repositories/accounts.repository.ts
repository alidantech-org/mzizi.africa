import { Injectable, UnauthorizedException } from "@nestjs/common";
import { ModuleRef } from "@nestjs/core";
import { getDataSourceToken } from "@nestjs/typeorm";
import type {
  DataSource,
  EntityManager,
  EntityTarget,
  ObjectLiteral,
  Repository,
  SelectQueryBuilder,
} from "typeorm";
import {
  instant,
  missing,
  pageWindow,
  type ReadContext,
  type Row,
} from "#/database/base/read-helpers.ts";
import type { BaseRepository } from "#/database/base/base.repository.ts";
import { AccountsEntity } from "#/modules/auth/schema/entities/accounts.entity.ts";
import { AccountsRepository } from "#/modules/auth/schema/repositories/accounts.repository.ts";

/**
 * Reads of the Accounts feature: one named method per declared query, written out
 * from the contract. Regenerated by Dryv; entity repositories supply the connection.
 */
@Injectable()
export class AuthAccountsRepository {
  constructor(private readonly moduleRef: ModuleRef) {}

  /** Resolved on first use, so the application assembles without a database connection. */
  private get dataSource(): DataSource {
    return this.moduleRef.get<DataSource>(getDataSourceToken(), { strict: false });
  }

  private repositoryOf<
    E extends ObjectLiteral,
    R extends BaseRepository<E> & {
      query(alias: string, manager?: EntityManager): SelectQueryBuilder<E>;
    },
  >(repository: new (target: Repository<E>) => R, entity: EntityTarget<E>): R {
    return new repository(this.dataSource.getRepository(entity));
  }

  /** The signed-in person's own account. */
  async getMyAccount(input: Row, context: ReadContext = {}): Promise<Row> {
    const params: Row = {
      accountId: context.policies?.["#/policies/auth.SignedIn"]?.["accountId"],
    };
    if (params.accountId === undefined)
      throw new UnauthorizedException(
        "The #/policies/auth.SignedIn policy does not provide accountId",
      );
    const query = this.repositoryOf(AccountsRepository, AccountsEntity).query("r", context.manager);
    query.select([]);
    if (params.accountId !== undefined) {
      query.andWhere("r.id = :w_accountId", { w_accountId: params.accountId });
    }
    query.addSelect("r.actorKind", "actorKind");
    query.addSelect("r.displayName", "displayName");
    query.addSelect("r.id", "id");
    query.addSelect("r.lastAuthenticatedAt", "lastAuthenticatedAt");
    query.addSelect("r.status", "status");
    query.limit(1);
    const raws = await query.getRawMany<Row>();
    if (raws.length === 0)
      throw missing("not_found", "The requested resource does not exist.", 404);
    const rows: Row[] = raws.map((raw) => ({
      actorKind: raw.actorKind,
      displayName: raw.displayName,
      id: raw.id,
      lastAuthenticatedAt: instant(raw.lastAuthenticatedAt),
      status: raw.status,
    }));
    return rows[0] as Row;
  }

  /** Page through accounts, optionally by status. Administrators only. */
  async listAccounts(input: Row, context: ReadContext = {}): Promise<Row[]> {
    const params: Row = {
      limit: input.limit,
      offset: input.offset,
      status: input.status,
    };
    const query = this.repositoryOf(AccountsRepository, AccountsEntity).query("r", context.manager);
    query.select([]);
    if (params.status !== undefined) {
      query.andWhere("r.status = :w_status", { w_status: params.status });
    }
    query.addSelect("r.actorKind", "actorKind");
    query.addSelect("r.displayName", "displayName");
    query.addSelect("r.id", "id");
    query.addSelect("r.status", "status");
    query.orderBy("r.displayName", "ASC");
    query.addOrderBy("r.id", "ASC");
    const page = pageWindow(params.limit, params.offset, 200);
    query.limit(page.limit).offset(page.offset);
    const raws = await query.getRawMany<Row>();
    const rows: Row[] = raws.map((raw) => ({
      actorKind: raw.actorKind,
      displayName: raw.displayName,
      id: raw.id,
      status: raw.status,
    }));
    return rows;
  }
}
