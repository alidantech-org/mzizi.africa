import { Injectable } from "@nestjs/common";
import type { CountryPartiesDto } from "#/modules/politics/schema/dto/country-parties.dto.ts";
import type { PartyCollectionDto } from "#/modules/politics/schema/dto/party-collection.dto.ts";
import type { PartyDetailDto } from "#/modules/politics/schema/dto/party-detail.dto.ts";
import type { PartyKeyDto } from "#/modules/politics/schema/dto/party-key.dto.ts";
import { GetPartyUseCase } from "#/modules/politics/features/parties/use-cases/get-party.repository.ts";
import { ListPartiesUseCase } from "#/modules/politics/features/parties/use-cases/list-parties.repository.ts";

/**
 * The Parties contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class PoliticsPartiesService {
  abstract getParty(input: PartyKeyDto): Promise<PartyDetailDto>;
  abstract listParties(input: CountryPartiesDto): Promise<PartyCollectionDto>;
}

@Injectable()
export class PoliticsPartiesServiceImpl extends PoliticsPartiesService {
  constructor(
    private readonly getPartyUseCase: GetPartyUseCase,
    private readonly listPartiesUseCase: ListPartiesUseCase,
  ) {
    super();
  }

  getParty(input: PartyKeyDto): Promise<PartyDetailDto> {
    return this.getPartyUseCase.execute(input);
  }

  listParties(input: CountryPartiesDto): Promise<PartyCollectionDto> {
    return this.listPartiesUseCase.execute(input);
  }
}
