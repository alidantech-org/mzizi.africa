import { Injectable } from "@nestjs/common";
import type { CountryCollectionDto } from "#/modules/reference/schema/dto/country-collection.dto.ts";
import type { CountryDetailDto } from "#/modules/reference/schema/dto/country-detail.dto.ts";
import type { CountryKeyDto } from "#/modules/reference/schema/dto/country-key.dto.ts";
import type { ReferenceWindowDto } from "#/modules/reference/schema/dto/reference-window.dto.ts";
import { GetCountryUseCase } from "#/modules/reference/features/countries/use-cases/get-country.repository.ts";
import { ListCountriesUseCase } from "#/modules/reference/features/countries/use-cases/list-countries.repository.ts";

/**
 * The Countries contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class ReferenceCountriesService {
  abstract getCountry(input: CountryKeyDto): Promise<CountryDetailDto>;
  abstract listCountries(input: ReferenceWindowDto): Promise<CountryCollectionDto>;
}

@Injectable()
export class ReferenceCountriesServiceImpl extends ReferenceCountriesService {
  constructor(
    private readonly getCountryUseCase: GetCountryUseCase,
    private readonly listCountriesUseCase: ListCountriesUseCase,
  ) {
    super();
  }

  getCountry(input: CountryKeyDto): Promise<CountryDetailDto> {
    return this.getCountryUseCase.execute(input);
  }

  listCountries(input: ReferenceWindowDto): Promise<CountryCollectionDto> {
    return this.listCountriesUseCase.execute(input);
  }
}
