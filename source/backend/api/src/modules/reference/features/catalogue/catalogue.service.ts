
import type { FoundMemberDto } from "#/modules/reference/schema/dto/found-member.dto.ts";
import type { MemberCollectionDto } from "#/modules/reference/schema/dto/member-collection.dto.ts";
import type { MemberKeyDto } from "#/modules/reference/schema/dto/member-key.dto.ts";
import type { MemberWindowDto } from "#/modules/reference/schema/dto/member-window.dto.ts";
import type { SchemeCollectionDto } from "#/modules/reference/schema/dto/scheme-collection.dto.ts";
import type { SchemeWindowDto } from "#/modules/reference/schema/dto/scheme-window.dto.ts";

/**
 * The Catalogue contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class ReferenceCatalogueService {
  abstract browseSchemeMembers(input: MemberWindowDto): Promise<MemberCollectionDto>;
  abstract browseSchemes(input: SchemeWindowDto): Promise<SchemeCollectionDto>;
  abstract lookupMember(input: MemberKeyDto): Promise<FoundMemberDto>;
}