import { Injectable } from "@nestjs/common";
import type { FoundMemberDto } from "#/modules/reference/schema/dto/found-member.dto.ts";
import type { MemberCollectionDto } from "#/modules/reference/schema/dto/member-collection.dto.ts";
import type { MemberKeyDto } from "#/modules/reference/schema/dto/member-key.dto.ts";
import type { MemberWindowDto } from "#/modules/reference/schema/dto/member-window.dto.ts";
import type { SchemeCollectionDto } from "#/modules/reference/schema/dto/scheme-collection.dto.ts";
import type { SchemeWindowDto } from "#/modules/reference/schema/dto/scheme-window.dto.ts";
import { BrowseSchemeMembersUseCase } from "#/modules/reference/features/catalogue/use-cases/browse-scheme-members.usecase.ts";
import { BrowseSchemesUseCase } from "#/modules/reference/features/catalogue/use-cases/browse-schemes.usecase.ts";
import { LookupMemberUseCase } from "#/modules/reference/features/catalogue/use-cases/lookup-member.usecase.ts";

/**
 * The Catalogue contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class ReferenceCatalogueService {
  abstract browseSchemeMembers(input: MemberWindowDto): Promise<MemberCollectionDto>;
  abstract browseSchemes(input: SchemeWindowDto): Promise<SchemeCollectionDto>;
  abstract lookupMember(input: MemberKeyDto): Promise<FoundMemberDto>;
}

@Injectable()
export class ReferenceCatalogueServiceImpl extends ReferenceCatalogueService {
  constructor(
    private readonly browseSchemeMembersUseCase: BrowseSchemeMembersUseCase,
    private readonly browseSchemesUseCase: BrowseSchemesUseCase,
    private readonly lookupMemberUseCase: LookupMemberUseCase,
  ) {
    super();
  }

  browseSchemeMembers(input: MemberWindowDto): Promise<MemberCollectionDto> {
    return this.browseSchemeMembersUseCase.execute(input);
  }

  browseSchemes(input: SchemeWindowDto): Promise<SchemeCollectionDto> {
    return this.browseSchemesUseCase.execute(input);
  }

  lookupMember(input: MemberKeyDto): Promise<FoundMemberDto> {
    return this.lookupMemberUseCase.execute(input);
  }
}
