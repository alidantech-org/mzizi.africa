import { Injectable } from "@nestjs/common";
import { ModuleRef } from "@nestjs/core";
import { getDataSourceToken } from "@nestjs/typeorm";
import type {
  DataSource,
  EntityManager,
  EntityTarget,
  ObjectLiteral,
  Repository,
  SelectQueryBuilder,
} from "typeorm";
import {
  missing,
  pageWindow,
  prefixPattern,
  type ReadContext,
  type Row,
} from "#/database/base/read-helpers.ts";
import type { BaseRepository } from "#/database/base/base.repository.ts";
import { SchemeEntity } from "#/modules/reference/schema/entities/scheme.entity.ts";
import { ValueEntity } from "#/modules/reference/schema/entities/value.entity.ts";
import { SchemeRepository } from "#/modules/reference/schema/repositories/scheme.repository.ts";
import { ValueRepository } from "#/modules/reference/schema/repositories/value.repository.ts";

/**
 * Reads of the Catalogue feature: one named method per declared query, written out
 * from the contract. Regenerated by Dryv; entity repositories supply the connection.
 */
@Injectable()
export class ReferenceCatalogueRepository {
  constructor(private readonly moduleRef: ModuleRef) {}

  /** Resolved on first use, so the application assembles without a database connection. */
  private get dataSource(): DataSource {
    return this.moduleRef.get<DataSource>(getDataSourceToken(), { strict: false });
  }

  private repositoryOf<
    E extends ObjectLiteral,
    R extends BaseRepository<E> & {
      query(alias: string, manager?: EntityManager): SelectQueryBuilder<E>;
    },
  >(repository: new (target: Repository<E>) => R, entity: EntityTarget<E>): R {
    return new repository(this.dataSource.getRepository(entity));
  }

  /** Page through the members of one scheme, including superseded members. */
  async browseSchemeMembers(input: Row, context: ReadContext = {}): Promise<Row[]> {
    const params: Row = {
      limit: input.limit,
      offset: input.offset,
      schemeId: input.schemeId,
    };
    if (params.schemeId === undefined) throw new Error("schemeId is required");
    const query = this.repositoryOf(ValueRepository, ValueEntity).query("r", context.manager);
    query.select([]);
    if (params.schemeId !== undefined) {
      query.andWhere("r.schemeId = :w_schemeId", { w_schemeId: params.schemeId });
    }
    query.andWhere("r.deletedAt IS NULL");
    query.addSelect("r.code", "code");
    query.addSelect("r.id", "id");
    query.addSelect("r.label", "label");
    query.addSelect("r.supersedesId", "supersedesId");
    query.orderBy("r.code", "ASC");
    query.addOrderBy("r.id", "ASC");
    const page = pageWindow(params.limit, params.offset, 200);
    query.limit(page.limit).offset(page.offset);
    const raws = await query.getRawMany<Row>();
    const rows: Row[] = raws.map((raw) => ({
      code: raw.code,
      id: raw.id,
      label: raw.label,
      supersedesId: raw.supersedesId,
    }));
    return rows;
  }

  /** Page through classification schemes in code order. */
  async browseSchemes(input: Row, context: ReadContext = {}): Promise<Row[]> {
    const params: Row = {
      code: input.code,
      limit: input.limit,
      offset: input.offset,
    };
    const query = this.repositoryOf(SchemeRepository, SchemeEntity).query("r", context.manager);
    query.select([]);
    if (params.code !== undefined) {
      query.andWhere("r.code LIKE :w_code", { w_code: prefixPattern(params.code) });
    }
    query.andWhere("r.deletedAt IS NULL");
    query.addSelect("r.code", "code");
    query.addSelect("r.id", "id");
    query.addSelect("r.title", "title");
    query.orderBy("r.code", "ASC");
    query.addOrderBy("r.id", "ASC");
    const page = pageWindow(params.limit, params.offset, 200);
    query.limit(page.limit).offset(page.offset);
    const raws = await query.getRawMany<Row>();
    const rows: Row[] = raws.map((raw) => ({ code: raw.code, id: raw.id, title: raw.title }));
    return rows;
  }

  /** Find one classification member from its code (codes are unique across every scheme). */
  async lookupMember(input: Row, context: ReadContext = {}): Promise<Row> {
    const params: Row = {
      code: input.code,
    };
    if (params.code === undefined) throw new Error("code is required");
    const query = this.repositoryOf(ValueRepository, ValueEntity).query("r", context.manager);
    query.select([]);
    if (params.code !== undefined) {
      query.andWhere("r.code = :w_code", { w_code: params.code });
    }
    query.andWhere("r.deletedAt IS NULL");
    query.addSelect("r.code", "code");
    query.addSelect("r.id", "id");
    query.addSelect("r.label", "label");
    query.leftJoin(SchemeEntity, "r_schemeId", "r_schemeId.id = r.schemeId");
    query.addSelect("r_schemeId.code", "scheme");
    query.limit(1);
    const raws = await query.getRawMany<Row>();
    if (raws.length === 0)
      throw missing("not_found", "The requested resource does not exist.", 404);
    const rows: Row[] = raws.map((raw) => ({
      code: raw.code,
      id: raw.id,
      label: raw.label,
      scheme: raw.scheme,
    }));
    return rows[0] as Row;
  }
}
