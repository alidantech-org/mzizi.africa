import { Injectable } from "@nestjs/common";
import type { CurrencyCollectionDto } from "#/modules/reference/schema/dto/currency-collection.dto.ts";
import type { ReferenceWindowDto } from "#/modules/reference/schema/dto/reference-window.dto.ts";
import type { UnitCollectionDto } from "#/modules/reference/schema/dto/unit-collection.dto.ts";
import { ListCurrenciesUseCase } from "#/modules/reference/features/measures/use-cases/list-currencies.repository.ts";
import { ListUnitsUseCase } from "#/modules/reference/features/measures/use-cases/list-units.repository.ts";

/**
 * The Measures contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class ReferenceMeasuresService {
  abstract listCurrencies(input: ReferenceWindowDto): Promise<CurrencyCollectionDto>;
  abstract listUnits(input: ReferenceWindowDto): Promise<UnitCollectionDto>;
}

@Injectable()
export class ReferenceMeasuresServiceImpl extends ReferenceMeasuresService {
  constructor(
    private readonly listCurrenciesUseCase: ListCurrenciesUseCase,
    private readonly listUnitsUseCase: ListUnitsUseCase,
  ) {
    super();
  }

  listCurrencies(input: ReferenceWindowDto): Promise<CurrencyCollectionDto> {
    return this.listCurrenciesUseCase.execute(input);
  }

  listUnits(input: ReferenceWindowDto): Promise<UnitCollectionDto> {
    return this.listUnitsUseCase.execute(input);
  }
}
