
import type { ClassificationRecordListQueryDto } from "#/modules/reference/dto/classification-record-list-query.dto.ts";
import type { ClassificationRecordResponseDto } from "#/modules/reference/dto/classification-record-response.dto.ts";
import type { ClassificationRecordsListResponseDto } from "#/modules/reference/dto/classification-records-list-response.dto.ts";
import type { JurisdictionListQueryDto } from "#/modules/reference/dto/jurisdiction-list-query.dto.ts";
import type { JurisdictionResponseDto } from "#/modules/reference/dto/jurisdiction-response.dto.ts";
import type { JurisdictionsListResponseDto } from "#/modules/reference/dto/jurisdictions-list-response.dto.ts";

/**
 * The Reference Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class ReferenceReferenceReadService {
  abstract findClassificationRecords(input: ClassificationRecordListQueryDto): Promise<ClassificationRecordsListResponseDto>;
  abstract findJurisdictions(input: JurisdictionListQueryDto): Promise<JurisdictionsListResponseDto>;
  abstract getClassificationRecordById(input: { recordId: string }): Promise<ClassificationRecordResponseDto>;
  abstract getJurisdictionById(input: { jurisdictionId: string }): Promise<JurisdictionResponseDto>;
}