import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ValueLabelEntity } from "#/modules/reference/schema/entities/value-label.entity.ts";
import * as ValueLabel from "#/modules/reference/schema/types/value-label/index.ts";

/**
 * Repository of Value Label: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ValueLabelRepository
  extends EntityRepository<
    ValueLabelEntity,
    ValueLabel.Types.ValueLabelSortableField,
    ValueLabel.Types.ValueLabelEditableField,
    ValueLabel.Types.ValueLabelSelectableField,
    ValueLabel.Types.IValueLabelCreatable
  >
  implements IUpdatableRepository<ValueLabelEntity, ValueLabel.Types.IValueLabelUpdatable>
{
  constructor(
    @InjectRepository(ValueLabelEntity)
    repository: Repository<ValueLabelEntity>,
  ) {
    super(repository, ValueLabel.Config.VALUE_LABEL_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: ValueLabel.Types.IValueLabelUpdatable,
  ): Promise<ValueLabelEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find value label by label kind, paged by the shared query. */
  async findByLabelKind(
    query: BaseQueryDto<ValueLabelEntity>,
    labelKind: NonNullable<ValueLabelEntity["labelKind"]>,
  ): Promise<IFindAllResponse<ValueLabelEntity>> {
    return await this.findByQuery(query, { labelKind, deletedAt: IsNull() });
  }

  /** Find value label by value id, paged by the shared query. */
  async findByValue(
    query: BaseQueryDto<ValueLabelEntity>,
    valueId: NonNullable<ValueLabelEntity["valueId"]>,
  ): Promise<IFindAllResponse<ValueLabelEntity>> {
    return await this.findByQuery(query, { valueId, deletedAt: IsNull() });
  }
}
