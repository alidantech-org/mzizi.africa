import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { TopicEntity } from "#/modules/reference/schema/entities/topic.entity.ts";
import * as Topic from "#/modules/reference/schema/types/topic/index.ts";

/**
 * Repository of Topic: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class TopicRepository
  extends EntityRepository<
    TopicEntity,
    Topic.Types.TopicSortableField,
    Topic.Types.TopicEditableField,
    Topic.Types.TopicSelectableField,
    Topic.Types.ITopicCreatable
  >
  implements IUpdatableRepository<TopicEntity, Topic.Types.ITopicUpdatable>
{
  constructor(
    @InjectRepository(TopicEntity)
    repository: Repository<TopicEntity>,
  ) {
    super(repository, Topic.Config.TOPIC_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Topic.Types.ITopicUpdatable): Promise<TopicEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find topic by parent id, paged by the shared query. */
  async findByParent(
    query: BaseQueryDto<TopicEntity>,
    parentId: NonNullable<TopicEntity["parentId"]>,
  ): Promise<IFindAllResponse<TopicEntity>> {
    return await this.findByQuery(query, { parentId, deletedAt: IsNull() });
  }

  /** Find the topic with this code (unique). */
  async findByCode(code: NonNullable<TopicEntity["code"]>): Promise<TopicEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
