import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { UnitEntity } from "#/modules/reference/schema/entities/unit.entity.ts";
import * as Unit from "#/modules/reference/schema/types/unit/index.ts";

/**
 * Repository of Unit: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class UnitRepository
  extends EntityRepository<
    UnitEntity,
    Unit.Types.UnitSortableField,
    Unit.Types.UnitEditableField,
    Unit.Types.UnitSelectableField,
    Unit.Types.IUnitCreatable
  >
  implements IUpdatableRepository<UnitEntity, Unit.Types.IUnitUpdatable>
{
  constructor(
    @InjectRepository(UnitEntity)
    repository: Repository<UnitEntity>,
  ) {
    super(repository, Unit.Config.UNIT_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Unit.Types.IUnitUpdatable): Promise<UnitEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find unit by base id, paged by the shared query. */
  async findByBase(
    query: BaseQueryDto<UnitEntity>,
    baseId: NonNullable<UnitEntity["baseId"]>,
  ): Promise<IFindAllResponse<UnitEntity>> {
    return await this.findByQuery(query, { baseId, deletedAt: IsNull() });
  }

  /** Find the unit with this code (unique). */
  async findByCode(code: NonNullable<UnitEntity["code"]>): Promise<UnitEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
