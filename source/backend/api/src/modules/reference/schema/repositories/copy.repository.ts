import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { CopyEntity } from "#/modules/reference/schema/entities/copy.entity.ts";
import * as Copy from "#/modules/reference/schema/types/copy/index.ts";

/**
 * Repository of Copy: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class CopyRepository
  extends EntityRepository<
    CopyEntity,
    Copy.Types.CopySortableField,
    Copy.Types.CopyEditableField,
    Copy.Types.CopySelectableField,
    Copy.Types.ICopyCreatable
  >
  implements IUpdatableRepository<CopyEntity, Copy.Types.ICopyUpdatable>
{
  constructor(
    @InjectRepository(CopyEntity)
    repository: Repository<CopyEntity>,
  ) {
    super(repository, Copy.Config.COPY_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Copy.Types.ICopyUpdatable): Promise<CopyEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find copy by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<CopyEntity>,
    countryId: NonNullable<CopyEntity["countryId"]>,
  ): Promise<IFindAllResponse<CopyEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find copy by language id, paged by the shared query. */
  async findByLanguage(
    query: BaseQueryDto<CopyEntity>,
    languageId: NonNullable<CopyEntity["languageId"]>,
  ): Promise<IFindAllResponse<CopyEntity>> {
    return await this.findByQuery(query, { languageId, deletedAt: IsNull() });
  }
}
