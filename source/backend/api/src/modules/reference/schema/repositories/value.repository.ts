import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ValueEntity } from "#/modules/reference/schema/entities/value.entity.ts";
import * as Value from "#/modules/reference/schema/types/value/index.ts";

/**
 * Repository of Value: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ValueRepository
  extends EntityRepository<
    ValueEntity,
    Value.Types.ValueSortableField,
    Value.Types.ValueEditableField,
    Value.Types.ValueSelectableField,
    Value.Types.IValueCreatable
  >
  implements IUpdatableRepository<ValueEntity, Value.Types.IValueUpdatable>
{
  constructor(
    @InjectRepository(ValueEntity)
    repository: Repository<ValueEntity>,
  ) {
    super(repository, Value.Config.VALUE_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Value.Types.IValueUpdatable): Promise<ValueEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find value by scheme id, paged by the shared query. */
  async findByScheme(
    query: BaseQueryDto<ValueEntity>,
    schemeId: NonNullable<ValueEntity["schemeId"]>,
  ): Promise<IFindAllResponse<ValueEntity>> {
    return await this.findByQuery(query, { schemeId, deletedAt: IsNull() });
  }

  /** Find value by supersedes id, paged by the shared query. */
  async findBySupersedes(
    query: BaseQueryDto<ValueEntity>,
    supersedesId: NonNullable<ValueEntity["supersedesId"]>,
  ): Promise<IFindAllResponse<ValueEntity>> {
    return await this.findByQuery(query, { supersedesId, deletedAt: IsNull() });
  }

  /** Find the value with this code (unique). */
  async findByCode(code: NonNullable<ValueEntity["code"]>): Promise<ValueEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
