import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { LanguageEntity } from "#/modules/reference/schema/entities/language.entity.ts";
import * as Language from "#/modules/reference/schema/types/language/index.ts";

/**
 * Repository of Language: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class LanguageRepository
  extends EntityRepository<
    LanguageEntity,
    Language.Types.LanguageSortableField,
    Language.Types.LanguageEditableField,
    Language.Types.LanguageSelectableField,
    Language.Types.ILanguageCreatable
  >
  implements IUpdatableRepository<LanguageEntity, Language.Types.ILanguageUpdatable>
{
  constructor(
    @InjectRepository(LanguageEntity)
    repository: Repository<LanguageEntity>,
  ) {
    super(repository, Language.Config.LANGUAGE_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Language.Types.ILanguageUpdatable,
  ): Promise<LanguageEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find language by direction id, paged by the shared query. */
  async findByDirection(
    query: BaseQueryDto<LanguageEntity>,
    directionId: NonNullable<LanguageEntity["directionId"]>,
  ): Promise<IFindAllResponse<LanguageEntity>> {
    return await this.findByQuery(query, { directionId, deletedAt: IsNull() });
  }

  /** Find language by family id, paged by the shared query. */
  async findByFamily(
    query: BaseQueryDto<LanguageEntity>,
    familyId: NonNullable<LanguageEntity["familyId"]>,
  ): Promise<IFindAllResponse<LanguageEntity>> {
    return await this.findByQuery(query, { familyId, deletedAt: IsNull() });
  }

  /** Find language by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<LanguageEntity>,
    kindId: NonNullable<LanguageEntity["kindId"]>,
  ): Promise<IFindAllResponse<LanguageEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find language by parent id, paged by the shared query. */
  async findByParent(
    query: BaseQueryDto<LanguageEntity>,
    parentId: NonNullable<LanguageEntity["parentId"]>,
  ): Promise<IFindAllResponse<LanguageEntity>> {
    return await this.findByQuery(query, { parentId, deletedAt: IsNull() });
  }

  /** Find language by script id, paged by the shared query. */
  async findByScript(
    query: BaseQueryDto<LanguageEntity>,
    scriptId: NonNullable<LanguageEntity["scriptId"]>,
  ): Promise<IFindAllResponse<LanguageEntity>> {
    return await this.findByQuery(query, { scriptId, deletedAt: IsNull() });
  }

  /** Find language by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<LanguageEntity>,
    statusId: NonNullable<LanguageEntity["statusId"]>,
  ): Promise<IFindAllResponse<LanguageEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }

  /** Find the language with this code (unique). */
  async findByCode(code: NonNullable<LanguageEntity["code"]>): Promise<LanguageEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }

  /** Find the language with this glottocode (unique). */
  async findByGlottocode(
    glottocode: NonNullable<LanguageEntity["glottocode"]>,
  ): Promise<LanguageEntity | null> {
    return await this.findOne({ glottocode, deletedAt: IsNull() });
  }

  /** Find the language with this iso6391 (unique). */
  async findByIso6391(
    iso6391: NonNullable<LanguageEntity["iso6391"]>,
  ): Promise<LanguageEntity | null> {
    return await this.findOne({ iso6391, deletedAt: IsNull() });
  }

  /** Find the language with this iso6393 (unique). */
  async findByIso6393(
    iso6393: NonNullable<LanguageEntity["iso6393"]>,
  ): Promise<LanguageEntity | null> {
    return await this.findOne({ iso6393, deletedAt: IsNull() });
  }
}
