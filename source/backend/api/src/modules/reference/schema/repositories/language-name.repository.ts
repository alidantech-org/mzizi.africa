import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { LanguageNameEntity } from "#/modules/reference/schema/entities/language-name.entity.ts";
import * as LanguageName from "#/modules/reference/schema/types/language-name/index.ts";

/**
 * Repository of Language Name: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class LanguageNameRepository
  extends EntityRepository<
    LanguageNameEntity,
    LanguageName.Types.LanguageNameSortableField,
    LanguageName.Types.LanguageNameEditableField,
    LanguageName.Types.LanguageNameSelectableField,
    LanguageName.Types.ILanguageNameCreatable
  >
  implements IUpdatableRepository<LanguageNameEntity, LanguageName.Types.ILanguageNameUpdatable>
{
  constructor(
    @InjectRepository(LanguageNameEntity)
    repository: Repository<LanguageNameEntity>,
  ) {
    super(repository, LanguageName.Config.LANGUAGE_NAME_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: LanguageName.Types.ILanguageNameUpdatable,
  ): Promise<LanguageNameEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find language name by in language id, paged by the shared query. */
  async findByInLanguage(
    query: BaseQueryDto<LanguageNameEntity>,
    inLanguageId: NonNullable<LanguageNameEntity["inLanguageId"]>,
  ): Promise<IFindAllResponse<LanguageNameEntity>> {
    return await this.findByQuery(query, { inLanguageId, deletedAt: IsNull() });
  }

  /** Find language name by language id, paged by the shared query. */
  async findByLanguage(
    query: BaseQueryDto<LanguageNameEntity>,
    languageId: NonNullable<LanguageNameEntity["languageId"]>,
  ): Promise<IFindAllResponse<LanguageNameEntity>> {
    return await this.findByQuery(query, { languageId, deletedAt: IsNull() });
  }

  /** Find language name by name kind, paged by the shared query. */
  async findByNameKind(
    query: BaseQueryDto<LanguageNameEntity>,
    nameKind: NonNullable<LanguageNameEntity["nameKind"]>,
  ): Promise<IFindAllResponse<LanguageNameEntity>> {
    return await this.findByQuery(query, { nameKind, deletedAt: IsNull() });
  }
}
