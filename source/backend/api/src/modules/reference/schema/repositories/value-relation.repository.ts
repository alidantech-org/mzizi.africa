import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ValueRelationEntity } from "#/modules/reference/schema/entities/value-relation.entity.ts";
import * as ValueRelation from "#/modules/reference/schema/types/value-relation/index.ts";

/**
 * Repository of Value Relation: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ValueRelationRepository
  extends EntityRepository<
    ValueRelationEntity,
    ValueRelation.Types.ValueRelationSortableField,
    ValueRelation.Types.ValueRelationEditableField,
    ValueRelation.Types.ValueRelationSelectableField,
    ValueRelation.Types.IValueRelationCreatable
  >
  implements IUpdatableRepository<ValueRelationEntity, ValueRelation.Types.IValueRelationUpdatable>
{
  constructor(
    @InjectRepository(ValueRelationEntity)
    repository: Repository<ValueRelationEntity>,
  ) {
    super(repository, ValueRelation.Config.VALUE_RELATION_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: ValueRelation.Types.IValueRelationUpdatable,
  ): Promise<ValueRelationEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find value relation by relation kind, paged by the shared query. */
  async findByRelationKind(
    query: BaseQueryDto<ValueRelationEntity>,
    relationKind: NonNullable<ValueRelationEntity["relationKind"]>,
  ): Promise<IFindAllResponse<ValueRelationEntity>> {
    return await this.findByQuery(query, { relationKind, deletedAt: IsNull() });
  }

  /** Find value relation by source value id, paged by the shared query. */
  async findBySourceValue(
    query: BaseQueryDto<ValueRelationEntity>,
    sourceValueId: NonNullable<ValueRelationEntity["sourceValueId"]>,
  ): Promise<IFindAllResponse<ValueRelationEntity>> {
    return await this.findByQuery(query, { sourceValueId, deletedAt: IsNull() });
  }

  /** Find value relation by target value id, paged by the shared query. */
  async findByTargetValue(
    query: BaseQueryDto<ValueRelationEntity>,
    targetValueId: NonNullable<ValueRelationEntity["targetValueId"]>,
  ): Promise<IFindAllResponse<ValueRelationEntity>> {
    return await this.findByQuery(query, { targetValueId, deletedAt: IsNull() });
  }
}
