import type { TendersListResponseDto } from "#/modules/procurement/dto/tenders-list-response.dto.ts";

/**
 * The Procurement Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class ProcurementProcurementReadService {
  abstract findBids(input: BidListQueryDto): Promise<BidsListResponseDto>;
  abstract findContractMilestones(input: ContractMilestoneListQueryDto): Promise<ContractMilestonesListResponseDto>;
  abstract findContractVariations(input: ContractVariationListQueryDto): Promise<ContractVariationsListResponseDto>;
  abstract findProcurementContracts(input: ProcurementContractListQueryDto): Promise<ProcurementContractsListResponseDto>;
  abstract findTenders(input: TenderListQueryDto): Promise<TendersListResponseDto>;
  abstract getBidById(input: { bidId: string }): Promise<BidResponseDto>;
  abstract getContractMilestoneById(input: { milestoneId: string }): Promise<ContractMilestoneResponseDto>;
  abstract getContractVariationById(input: { variationId: string }): Promise<ContractVariationResponseDto>;
  abstract getProcurementContractById(input: { contractId: string }): Promise<ProcurementContractResponseDto>;
  abstract getTenderById(input: { tenderId: string }): Promise<TenderResponseDto>;
}