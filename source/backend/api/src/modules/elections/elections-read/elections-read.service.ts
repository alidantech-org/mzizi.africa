/**
 * The Elections Read contract the controller calls. Regenerated by Dryv; the project
 * implements it in its own class, which the feature module binds to this token.
 */
export abstract class ElectionsElectionsReadService {
  abstract findCandidates(input: CandidateListQueryDto): Promise<CandidatesListResponseDto>;
  abstract findElectionResults(input: ElectionResultListQueryDto): Promise<ElectionResultsListResponseDto>;
  abstract findElections(input: ElectionListQueryDto): Promise<ElectionsListResponseDto>;
  abstract findManifestoCommitments(input: ManifestoCommitmentListQueryDto): Promise<ManifestoCommitmentsListResponseDto>;
  abstract findManifestos(input: ManifestoListQueryDto): Promise<ManifestosListResponseDto>;
  abstract findSeats(input: SeatListQueryDto): Promise<SeatsListResponseDto>;
  abstract getCandidateById(input: { candidateId: string }): Promise<CandidateResponseDto>;
  abstract getElectionById(input: { electionId: string }): Promise<ElectionResponseDto>;
  abstract getElectionResultById(input: { resultId: string }): Promise<ElectionResultResponseDto>;
  abstract getManifestoById(input: { manifestoId: string }): Promise<ManifestoResponseDto>;
  abstract getManifestoCommitmentById(input: { commitmentId: string }): Promise<ManifestoCommitmentResponseDto>;
  abstract getSeatById(input: { seatId: string }): Promise<SeatResponseDto>;
}