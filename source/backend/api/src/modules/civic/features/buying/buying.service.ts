import { Injectable } from "@nestjs/common";
import type { CountryTendersDto } from "#/modules/civic/schema/dto/country-tenders.dto.ts";
import type { TenderCollectionDto } from "#/modules/civic/schema/dto/tender-collection.dto.ts";
import type { TenderDetailDto } from "#/modules/civic/schema/dto/tender-detail.dto.ts";
import type { TenderKeyDto } from "#/modules/civic/schema/dto/tender-key.dto.ts";
import { GetTenderUseCase } from "#/modules/civic/features/buying/use-cases/get-tender.repository.ts";
import { ListTendersUseCase } from "#/modules/civic/features/buying/use-cases/list-tenders.repository.ts";

/**
 * The Buying contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class CivicBuyingService {
  abstract getTender(input: TenderKeyDto): Promise<TenderDetailDto>;
  abstract listTenders(input: CountryTendersDto): Promise<TenderCollectionDto>;
}

@Injectable()
export class CivicBuyingServiceImpl extends CivicBuyingService {
  constructor(
    private readonly getTenderUseCase: GetTenderUseCase,
    private readonly listTendersUseCase: ListTendersUseCase,
  ) {
    super();
  }

  getTender(input: TenderKeyDto): Promise<TenderDetailDto> {
    return this.getTenderUseCase.execute(input);
  }

  listTenders(input: CountryTendersDto): Promise<TenderCollectionDto> {
    return this.listTendersUseCase.execute(input);
  }
}
