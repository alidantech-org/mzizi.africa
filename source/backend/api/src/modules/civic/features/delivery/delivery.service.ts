import { Injectable } from "@nestjs/common";
import type { CountryFacilitiesDto } from "#/modules/civic/schema/dto/country-facilities.dto.ts";
import type { FacilityCollectionDto } from "#/modules/civic/schema/dto/facility-collection.dto.ts";
import type { PlaceProjectsDto } from "#/modules/civic/schema/dto/place-projects.dto.ts";
import type { ProjectCollectionDto } from "#/modules/civic/schema/dto/project-collection.dto.ts";
import type { ProjectDetailDto } from "#/modules/civic/schema/dto/project-detail.dto.ts";
import type { ProjectKeyDto } from "#/modules/civic/schema/dto/project-key.dto.ts";
import { GetProjectUseCase } from "#/modules/civic/features/delivery/use-cases/get-project.repository.ts";
import { ListFacilitiesUseCase } from "#/modules/civic/features/delivery/use-cases/list-facilities.repository.ts";
import { ListPlaceProjectsUseCase } from "#/modules/civic/features/delivery/use-cases/list-place-projects.repository.ts";

/**
 * The Delivery contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class CivicDeliveryService {
  abstract getProject(input: ProjectKeyDto): Promise<ProjectDetailDto>;
  abstract listFacilities(input: CountryFacilitiesDto): Promise<FacilityCollectionDto>;
  abstract listPlaceProjects(input: PlaceProjectsDto): Promise<ProjectCollectionDto>;
}

@Injectable()
export class CivicDeliveryServiceImpl extends CivicDeliveryService {
  constructor(
    private readonly getProjectUseCase: GetProjectUseCase,
    private readonly listFacilitiesUseCase: ListFacilitiesUseCase,
    private readonly listPlaceProjectsUseCase: ListPlaceProjectsUseCase,
  ) {
    super();
  }

  getProject(input: ProjectKeyDto): Promise<ProjectDetailDto> {
    return this.getProjectUseCase.execute(input);
  }

  listFacilities(input: CountryFacilitiesDto): Promise<FacilityCollectionDto> {
    return this.listFacilitiesUseCase.execute(input);
  }

  listPlaceProjects(input: PlaceProjectsDto): Promise<ProjectCollectionDto> {
    return this.listPlaceProjectsUseCase.execute(input);
  }
}
