import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { BeneficiariesEntity } from "#/modules/civic/schema/entities/beneficiaries.entity.ts";
import * as Beneficiaries from "#/modules/civic/schema/types/beneficiaries/index.ts";

/**
 * Repository of Beneficiaries: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class BeneficiariesRepository
  extends EntityRepository<
    BeneficiariesEntity,
    Beneficiaries.Types.BeneficiariesSortableField,
    Beneficiaries.Types.BeneficiariesEditableField,
    Beneficiaries.Types.BeneficiariesSelectableField,
    Beneficiaries.Types.IBeneficiariesCreatable
  >
  implements IUpdatableRepository<BeneficiariesEntity, Beneficiaries.Types.IBeneficiariesUpdatable>
{
  constructor(
    @InjectRepository(BeneficiariesEntity)
    repository: Repository<BeneficiariesEntity>,
  ) {
    super(repository, Beneficiaries.Config.BENEFICIARIES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Beneficiaries.Types.IBeneficiariesUpdatable,
  ): Promise<BeneficiariesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find beneficiaries by benefit kind id, paged by the shared query. */
  async findByBenefitKind(
    query: BaseQueryDto<BeneficiariesEntity>,
    benefitKindId: NonNullable<BeneficiariesEntity["benefitKindId"]>,
  ): Promise<IFindAllResponse<BeneficiariesEntity>> {
    return await this.findByQuery(query, { benefitKindId, deletedAt: IsNull() });
  }

  /** Find beneficiaries by contract id, paged by the shared query. */
  async findByContract(
    query: BaseQueryDto<BeneficiariesEntity>,
    contractId: NonNullable<BeneficiariesEntity["contractId"]>,
  ): Promise<IFindAllResponse<BeneficiariesEntity>> {
    return await this.findByQuery(query, { contractId, deletedAt: IsNull() });
  }

  /** Find beneficiaries by procurement id, paged by the shared query. */
  async findByProcurement(
    query: BaseQueryDto<BeneficiariesEntity>,
    procurementId: NonNullable<BeneficiariesEntity["procurementId"]>,
  ): Promise<IFindAllResponse<BeneficiariesEntity>> {
    return await this.findByQuery(query, { procurementId, deletedAt: IsNull() });
  }

  /** Find beneficiaries by project id, paged by the shared query. */
  async findByProject(
    query: BaseQueryDto<BeneficiariesEntity>,
    projectId: NonNullable<BeneficiariesEntity["projectId"]>,
  ): Promise<IFindAllResponse<BeneficiariesEntity>> {
    return await this.findByQuery(query, { projectId, deletedAt: IsNull() });
  }

  /** Find beneficiaries by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<BeneficiariesEntity>,
    sourceCitationId: NonNullable<BeneficiariesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<BeneficiariesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find beneficiaries by subject table, paged by the shared query. */
  async findBySubjectTable(
    query: BaseQueryDto<BeneficiariesEntity>,
    subjectTable: NonNullable<BeneficiariesEntity["subjectTable"]>,
  ): Promise<IFindAllResponse<BeneficiariesEntity>> {
    return await this.findByQuery(query, { subjectTable, deletedAt: IsNull() });
  }

  /** Find the beneficiaries with this code (unique). */
  async findByCode(
    code: NonNullable<BeneficiariesEntity["code"]>,
  ): Promise<BeneficiariesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
