import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ProjectsEntity } from "#/modules/civic/schema/entities/projects.entity.ts";
import * as Projects from "#/modules/civic/schema/types/projects/index.ts";

/**
 * Repository of Projects: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ProjectsRepository
  extends EntityRepository<
    ProjectsEntity,
    Projects.Types.ProjectsSortableField,
    Projects.Types.ProjectsEditableField,
    Projects.Types.ProjectsSelectableField,
    Projects.Types.IProjectsCreatable
  >
  implements IUpdatableRepository<ProjectsEntity, Projects.Types.IProjectsUpdatable>
{
  constructor(
    @InjectRepository(ProjectsEntity)
    repository: Repository<ProjectsEntity>,
  ) {
    super(repository, Projects.Config.PROJECTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Projects.Types.IProjectsUpdatable,
  ): Promise<ProjectsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find projects by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<ProjectsEntity>,
    countryId: NonNullable<ProjectsEntity["countryId"]>,
  ): Promise<IFindAllResponse<ProjectsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find projects by implementing entity id, paged by the shared query. */
  async findByImplementingEntity(
    query: BaseQueryDto<ProjectsEntity>,
    implementingEntityId: NonNullable<ProjectsEntity["implementingEntityId"]>,
  ): Promise<IFindAllResponse<ProjectsEntity>> {
    return await this.findByQuery(query, { implementingEntityId, deletedAt: IsNull() });
  }

  /** Find projects by responsible institution id, paged by the shared query. */
  async findByResponsibleInstitution(
    query: BaseQueryDto<ProjectsEntity>,
    responsibleInstitutionId: NonNullable<ProjectsEntity["responsibleInstitutionId"]>,
  ): Promise<IFindAllResponse<ProjectsEntity>> {
    return await this.findByQuery(query, { responsibleInstitutionId, deletedAt: IsNull() });
  }

  /** Find projects by scope unit feature id, paged by the shared query. */
  async findByScopeUnitFeature(
    query: BaseQueryDto<ProjectsEntity>,
    scopeUnitFeatureId: NonNullable<ProjectsEntity["scopeUnitFeatureId"]>,
  ): Promise<IFindAllResponse<ProjectsEntity>> {
    return await this.findByQuery(query, { scopeUnitFeatureId, deletedAt: IsNull() });
  }

  /** Find projects by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<ProjectsEntity>,
    sourceCitationId: NonNullable<ProjectsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<ProjectsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find projects by sponsor entity id, paged by the shared query. */
  async findBySponsorEntity(
    query: BaseQueryDto<ProjectsEntity>,
    sponsorEntityId: NonNullable<ProjectsEntity["sponsorEntityId"]>,
  ): Promise<IFindAllResponse<ProjectsEntity>> {
    return await this.findByQuery(query, { sponsorEntityId, deletedAt: IsNull() });
  }

  /** Find projects by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<ProjectsEntity>,
    statusId: NonNullable<ProjectsEntity["statusId"]>,
  ): Promise<IFindAllResponse<ProjectsEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }

  /** Find the projects with this code (unique). */
  async findByCode(code: NonNullable<ProjectsEntity["code"]>): Promise<ProjectsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
