import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ProjectFeaturesEntity } from "#/modules/civic/schema/entities/project-features.entity.ts";
import * as ProjectFeatures from "#/modules/civic/schema/types/project-features/index.ts";

/**
 * Repository of Project Features: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ProjectFeaturesRepository
  extends EntityRepository<
    ProjectFeaturesEntity,
    ProjectFeatures.Types.ProjectFeaturesSortableField,
    ProjectFeatures.Types.ProjectFeaturesEditableField,
    ProjectFeatures.Types.ProjectFeaturesSelectableField,
    ProjectFeatures.Types.IProjectFeaturesCreatable
  >
  implements
    IUpdatableRepository<ProjectFeaturesEntity, ProjectFeatures.Types.IProjectFeaturesUpdatable>
{
  constructor(
    @InjectRepository(ProjectFeaturesEntity)
    repository: Repository<ProjectFeaturesEntity>,
  ) {
    super(repository, ProjectFeatures.Config.PROJECT_FEATURES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: ProjectFeatures.Types.IProjectFeaturesUpdatable,
  ): Promise<ProjectFeaturesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find project features by feature id, paged by the shared query. */
  async findByFeature(
    query: BaseQueryDto<ProjectFeaturesEntity>,
    featureId: NonNullable<ProjectFeaturesEntity["featureId"]>,
  ): Promise<IFindAllResponse<ProjectFeaturesEntity>> {
    return await this.findByQuery(query, { featureId, deletedAt: IsNull() });
  }

  /** Find project features by feature kind id, paged by the shared query. */
  async findByFeatureKind(
    query: BaseQueryDto<ProjectFeaturesEntity>,
    featureKindId: NonNullable<ProjectFeaturesEntity["featureKindId"]>,
  ): Promise<IFindAllResponse<ProjectFeaturesEntity>> {
    return await this.findByQuery(query, { featureKindId, deletedAt: IsNull() });
  }

  /** Find project features by project id, paged by the shared query. */
  async findByProject(
    query: BaseQueryDto<ProjectFeaturesEntity>,
    projectId: NonNullable<ProjectFeaturesEntity["projectId"]>,
  ): Promise<IFindAllResponse<ProjectFeaturesEntity>> {
    return await this.findByQuery(query, { projectId, deletedAt: IsNull() });
  }

  /** Find project features by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<ProjectFeaturesEntity>,
    sourceCitationId: NonNullable<ProjectFeaturesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<ProjectFeaturesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }
}
