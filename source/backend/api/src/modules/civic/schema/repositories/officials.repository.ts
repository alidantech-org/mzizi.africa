import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { OfficialsEntity } from "#/modules/civic/schema/entities/officials.entity.ts";
import * as Officials from "#/modules/civic/schema/types/officials/index.ts";

/**
 * Repository of Officials: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class OfficialsRepository
  extends EntityRepository<
    OfficialsEntity,
    Officials.Types.OfficialsSortableField,
    Officials.Types.OfficialsEditableField,
    Officials.Types.OfficialsSelectableField,
    Officials.Types.IOfficialsCreatable
  >
  implements IUpdatableRepository<OfficialsEntity, Officials.Types.IOfficialsUpdatable>
{
  constructor(
    @InjectRepository(OfficialsEntity)
    repository: Repository<OfficialsEntity>,
  ) {
    super(repository, Officials.Config.OFFICIALS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Officials.Types.IOfficialsUpdatable,
  ): Promise<OfficialsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find officials by contract id, paged by the shared query. */
  async findByContract(
    query: BaseQueryDto<OfficialsEntity>,
    contractId: NonNullable<OfficialsEntity["contractId"]>,
  ): Promise<IFindAllResponse<OfficialsEntity>> {
    return await this.findByQuery(query, { contractId, deletedAt: IsNull() });
  }

  /** Find officials by individual id, paged by the shared query. */
  async findByIndividual(
    query: BaseQueryDto<OfficialsEntity>,
    individualId: NonNullable<OfficialsEntity["individualId"]>,
  ): Promise<IFindAllResponse<OfficialsEntity>> {
    return await this.findByQuery(query, { individualId, deletedAt: IsNull() });
  }

  /** Find officials by office id, paged by the shared query. */
  async findByOffice(
    query: BaseQueryDto<OfficialsEntity>,
    officeId: NonNullable<OfficialsEntity["officeId"]>,
  ): Promise<IFindAllResponse<OfficialsEntity>> {
    return await this.findByQuery(query, { officeId, deletedAt: IsNull() });
  }

  /** Find officials by procurement id, paged by the shared query. */
  async findByProcurement(
    query: BaseQueryDto<OfficialsEntity>,
    procurementId: NonNullable<OfficialsEntity["procurementId"]>,
  ): Promise<IFindAllResponse<OfficialsEntity>> {
    return await this.findByQuery(query, { procurementId, deletedAt: IsNull() });
  }

  /** Find officials by role id, paged by the shared query. */
  async findByRole(
    query: BaseQueryDto<OfficialsEntity>,
    roleId: NonNullable<OfficialsEntity["roleId"]>,
  ): Promise<IFindAllResponse<OfficialsEntity>> {
    return await this.findByQuery(query, { roleId, deletedAt: IsNull() });
  }

  /** Find officials by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<OfficialsEntity>,
    sourceCitationId: NonNullable<OfficialsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<OfficialsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }
}
