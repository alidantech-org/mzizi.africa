import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ServicesEntity } from "#/modules/civic/schema/entities/services.entity.ts";
import * as Services from "#/modules/civic/schema/types/services/index.ts";

/**
 * Repository of Services: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ServicesRepository
  extends EntityRepository<
    ServicesEntity,
    Services.Types.ServicesSortableField,
    Services.Types.ServicesEditableField,
    Services.Types.ServicesSelectableField,
    Services.Types.IServicesCreatable
  >
  implements IUpdatableRepository<ServicesEntity, Services.Types.IServicesUpdatable>
{
  constructor(
    @InjectRepository(ServicesEntity)
    repository: Repository<ServicesEntity>,
  ) {
    super(repository, Services.Config.SERVICES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Services.Types.IServicesUpdatable,
  ): Promise<ServicesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find services by place feature id, paged by the shared query. */
  async findByPlaceFeature(
    query: BaseQueryDto<ServicesEntity>,
    placeFeatureId: NonNullable<ServicesEntity["placeFeatureId"]>,
  ): Promise<IFindAllResponse<ServicesEntity>> {
    return await this.findByQuery(query, { placeFeatureId, deletedAt: IsNull() });
  }

  /** Find services by provider entity id, paged by the shared query. */
  async findByProviderEntity(
    query: BaseQueryDto<ServicesEntity>,
    providerEntityId: NonNullable<ServicesEntity["providerEntityId"]>,
  ): Promise<IFindAllResponse<ServicesEntity>> {
    return await this.findByQuery(query, { providerEntityId, deletedAt: IsNull() });
  }

  /** Find services by responsible institution id, paged by the shared query. */
  async findByResponsibleInstitution(
    query: BaseQueryDto<ServicesEntity>,
    responsibleInstitutionId: NonNullable<ServicesEntity["responsibleInstitutionId"]>,
  ): Promise<IFindAllResponse<ServicesEntity>> {
    return await this.findByQuery(query, { responsibleInstitutionId, deletedAt: IsNull() });
  }

  /** Find services by scope unit feature id, paged by the shared query. */
  async findByScopeUnitFeature(
    query: BaseQueryDto<ServicesEntity>,
    scopeUnitFeatureId: NonNullable<ServicesEntity["scopeUnitFeatureId"]>,
  ): Promise<IFindAllResponse<ServicesEntity>> {
    return await this.findByQuery(query, { scopeUnitFeatureId, deletedAt: IsNull() });
  }

  /** Find services by service kind id, paged by the shared query. */
  async findByServiceKind(
    query: BaseQueryDto<ServicesEntity>,
    serviceKindId: NonNullable<ServicesEntity["serviceKindId"]>,
  ): Promise<IFindAllResponse<ServicesEntity>> {
    return await this.findByQuery(query, { serviceKindId, deletedAt: IsNull() });
  }

  /** Find services by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<ServicesEntity>,
    sourceCitationId: NonNullable<ServicesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<ServicesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the services with this code (unique). */
  async findByCode(code: NonNullable<ServicesEntity["code"]>): Promise<ServicesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
