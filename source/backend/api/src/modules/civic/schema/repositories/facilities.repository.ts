import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { FacilitiesEntity } from "#/modules/civic/schema/entities/facilities.entity.ts";
import * as Facilities from "#/modules/civic/schema/types/facilities/index.ts";

/**
 * Repository of Facilities: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class FacilitiesRepository
  extends EntityRepository<
    FacilitiesEntity,
    Facilities.Types.FacilitiesSortableField,
    Facilities.Types.FacilitiesEditableField,
    Facilities.Types.FacilitiesSelectableField,
    Facilities.Types.IFacilitiesCreatable
  >
  implements IUpdatableRepository<FacilitiesEntity, Facilities.Types.IFacilitiesUpdatable>
{
  constructor(
    @InjectRepository(FacilitiesEntity)
    repository: Repository<FacilitiesEntity>,
  ) {
    super(repository, Facilities.Config.FACILITIES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Facilities.Types.IFacilitiesUpdatable,
  ): Promise<FacilitiesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find facilities by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<FacilitiesEntity>,
    countryId: NonNullable<FacilitiesEntity["countryId"]>,
  ): Promise<IFindAllResponse<FacilitiesEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find facilities by facility class id, paged by the shared query. */
  async findByFacilityClass(
    query: BaseQueryDto<FacilitiesEntity>,
    facilityClassId: NonNullable<FacilitiesEntity["facilityClassId"]>,
  ): Promise<IFindAllResponse<FacilitiesEntity>> {
    return await this.findByQuery(query, { facilityClassId, deletedAt: IsNull() });
  }

  /** Find facilities by operator entity id, paged by the shared query. */
  async findByOperatorEntity(
    query: BaseQueryDto<FacilitiesEntity>,
    operatorEntityId: NonNullable<FacilitiesEntity["operatorEntityId"]>,
  ): Promise<IFindAllResponse<FacilitiesEntity>> {
    return await this.findByQuery(query, { operatorEntityId, deletedAt: IsNull() });
  }

  /** Find facilities by owner entity id, paged by the shared query. */
  async findByOwnerEntity(
    query: BaseQueryDto<FacilitiesEntity>,
    ownerEntityId: NonNullable<FacilitiesEntity["ownerEntityId"]>,
  ): Promise<IFindAllResponse<FacilitiesEntity>> {
    return await this.findByQuery(query, { ownerEntityId, deletedAt: IsNull() });
  }

  /** Find facilities by ownership id, paged by the shared query. */
  async findByOwnership(
    query: BaseQueryDto<FacilitiesEntity>,
    ownershipId: NonNullable<FacilitiesEntity["ownershipId"]>,
  ): Promise<IFindAllResponse<FacilitiesEntity>> {
    return await this.findByQuery(query, { ownershipId, deletedAt: IsNull() });
  }

  /** Find facilities by responsible institution id, paged by the shared query. */
  async findByResponsibleInstitution(
    query: BaseQueryDto<FacilitiesEntity>,
    responsibleInstitutionId: NonNullable<FacilitiesEntity["responsibleInstitutionId"]>,
  ): Promise<IFindAllResponse<FacilitiesEntity>> {
    return await this.findByQuery(query, { responsibleInstitutionId, deletedAt: IsNull() });
  }

  /** Find facilities by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<FacilitiesEntity>,
    sourceCitationId: NonNullable<FacilitiesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<FacilitiesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find facilities by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<FacilitiesEntity>,
    statusId: NonNullable<FacilitiesEntity["statusId"]>,
  ): Promise<IFindAllResponse<FacilitiesEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }

  /** Find the facilities with this code (unique). */
  async findByCode(code: NonNullable<FacilitiesEntity["code"]>): Promise<FacilitiesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }

  /** Find the facilities with this feature id (unique). */
  async findByFeature(
    featureId: NonNullable<FacilitiesEntity["featureId"]>,
  ): Promise<FacilitiesEntity | null> {
    return await this.findOne({ featureId, deletedAt: IsNull() });
  }
}
