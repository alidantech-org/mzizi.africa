import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ProcurementsEntity } from "#/modules/civic/schema/entities/procurements.entity.ts";
import * as Procurements from "#/modules/civic/schema/types/procurements/index.ts";

/**
 * Repository of Procurements: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ProcurementsRepository
  extends EntityRepository<
    ProcurementsEntity,
    Procurements.Types.ProcurementsSortableField,
    Procurements.Types.ProcurementsEditableField,
    Procurements.Types.ProcurementsSelectableField,
    Procurements.Types.IProcurementsCreatable
  >
  implements IUpdatableRepository<ProcurementsEntity, Procurements.Types.IProcurementsUpdatable>
{
  constructor(
    @InjectRepository(ProcurementsEntity)
    repository: Repository<ProcurementsEntity>,
  ) {
    super(repository, Procurements.Config.PROCUREMENTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Procurements.Types.IProcurementsUpdatable,
  ): Promise<ProcurementsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find procurements by buyer entity id, paged by the shared query. */
  async findByBuyerEntity(
    query: BaseQueryDto<ProcurementsEntity>,
    buyerEntityId: NonNullable<ProcurementsEntity["buyerEntityId"]>,
  ): Promise<IFindAllResponse<ProcurementsEntity>> {
    return await this.findByQuery(query, { buyerEntityId, deletedAt: IsNull() });
  }

  /** Find procurements by category id, paged by the shared query. */
  async findByCategory(
    query: BaseQueryDto<ProcurementsEntity>,
    categoryId: NonNullable<ProcurementsEntity["categoryId"]>,
  ): Promise<IFindAllResponse<ProcurementsEntity>> {
    return await this.findByQuery(query, { categoryId, deletedAt: IsNull() });
  }

  /** Find procurements by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<ProcurementsEntity>,
    countryId: NonNullable<ProcurementsEntity["countryId"]>,
  ): Promise<IFindAllResponse<ProcurementsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find procurements by currency id, paged by the shared query. */
  async findByCurrency(
    query: BaseQueryDto<ProcurementsEntity>,
    currencyId: NonNullable<ProcurementsEntity["currencyId"]>,
  ): Promise<IFindAllResponse<ProcurementsEntity>> {
    return await this.findByQuery(query, { currencyId, deletedAt: IsNull() });
  }

  /** Find procurements by evaluation basis id, paged by the shared query. */
  async findByEvaluationBasis(
    query: BaseQueryDto<ProcurementsEntity>,
    evaluationBasisId: NonNullable<ProcurementsEntity["evaluationBasisId"]>,
  ): Promise<IFindAllResponse<ProcurementsEntity>> {
    return await this.findByQuery(query, { evaluationBasisId, deletedAt: IsNull() });
  }

  /** Find procurements by nature id, paged by the shared query. */
  async findByNature(
    query: BaseQueryDto<ProcurementsEntity>,
    natureId: NonNullable<ProcurementsEntity["natureId"]>,
  ): Promise<IFindAllResponse<ProcurementsEntity>> {
    return await this.findByQuery(query, { natureId, deletedAt: IsNull() });
  }

  /** Find procurements by procedure kind id, paged by the shared query. */
  async findByProcedureKind(
    query: BaseQueryDto<ProcurementsEntity>,
    procedureKindId: NonNullable<ProcurementsEntity["procedureKindId"]>,
  ): Promise<IFindAllResponse<ProcurementsEntity>> {
    return await this.findByQuery(query, { procedureKindId, deletedAt: IsNull() });
  }

  /** Find procurements by project id, paged by the shared query. */
  async findByProject(
    query: BaseQueryDto<ProcurementsEntity>,
    projectId: NonNullable<ProcurementsEntity["projectId"]>,
  ): Promise<IFindAllResponse<ProcurementsEntity>> {
    return await this.findByQuery(query, { projectId, deletedAt: IsNull() });
  }

  /** Find procurements by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<ProcurementsEntity>,
    sourceCitationId: NonNullable<ProcurementsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<ProcurementsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find procurements by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<ProcurementsEntity>,
    statusId: NonNullable<ProcurementsEntity["statusId"]>,
  ): Promise<IFindAllResponse<ProcurementsEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }

  /** Find the procurements with this code (unique). */
  async findByCode(
    code: NonNullable<ProcurementsEntity["code"]>,
  ): Promise<ProcurementsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
