import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { BidsEntity } from "#/modules/civic/schema/entities/bids.entity.ts";
import * as Bids from "#/modules/civic/schema/types/bids/index.ts";

/**
 * Repository of Bids: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class BidsRepository
  extends EntityRepository<
    BidsEntity,
    Bids.Types.BidsSortableField,
    Bids.Types.BidsEditableField,
    Bids.Types.BidsSelectableField,
    Bids.Types.IBidsCreatable
  >
  implements IUpdatableRepository<BidsEntity, Bids.Types.IBidsUpdatable>
{
  constructor(
    @InjectRepository(BidsEntity)
    repository: Repository<BidsEntity>,
  ) {
    super(repository, Bids.Config.BIDS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(id: string, data: Bids.Types.IBidsUpdatable): Promise<BidsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find bids by bidder entity id, paged by the shared query. */
  async findByBidderEntity(
    query: BaseQueryDto<BidsEntity>,
    bidderEntityId: NonNullable<BidsEntity["bidderEntityId"]>,
  ): Promise<IFindAllResponse<BidsEntity>> {
    return await this.findByQuery(query, { bidderEntityId, deletedAt: IsNull() });
  }

  /** Find bids by currency id, paged by the shared query. */
  async findByCurrency(
    query: BaseQueryDto<BidsEntity>,
    currencyId: NonNullable<BidsEntity["currencyId"]>,
  ): Promise<IFindAllResponse<BidsEntity>> {
    return await this.findByQuery(query, { currencyId, deletedAt: IsNull() });
  }

  /** Find bids by outcome id, paged by the shared query. */
  async findByOutcome(
    query: BaseQueryDto<BidsEntity>,
    outcomeId: NonNullable<BidsEntity["outcomeId"]>,
  ): Promise<IFindAllResponse<BidsEntity>> {
    return await this.findByQuery(query, { outcomeId, deletedAt: IsNull() });
  }

  /** Find bids by procurement id, paged by the shared query. */
  async findByProcurement(
    query: BaseQueryDto<BidsEntity>,
    procurementId: NonNullable<BidsEntity["procurementId"]>,
  ): Promise<IFindAllResponse<BidsEntity>> {
    return await this.findByQuery(query, { procurementId, deletedAt: IsNull() });
  }

  /** Find bids by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<BidsEntity>,
    sourceCitationId: NonNullable<BidsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<BidsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the bids with this code (unique). */
  async findByCode(code: NonNullable<BidsEntity["code"]>): Promise<BidsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
