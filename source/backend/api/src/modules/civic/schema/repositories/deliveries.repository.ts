import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { DeliveriesEntity } from "#/modules/civic/schema/entities/deliveries.entity.ts";
import * as Deliveries from "#/modules/civic/schema/types/deliveries/index.ts";

/**
 * Repository of Deliveries: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class DeliveriesRepository
  extends EntityRepository<
    DeliveriesEntity,
    Deliveries.Types.DeliveriesSortableField,
    Deliveries.Types.DeliveriesEditableField,
    Deliveries.Types.DeliveriesSelectableField,
    Deliveries.Types.IDeliveriesCreatable
  >
  implements IUpdatableRepository<DeliveriesEntity, Deliveries.Types.IDeliveriesUpdatable>
{
  constructor(
    @InjectRepository(DeliveriesEntity)
    repository: Repository<DeliveriesEntity>,
  ) {
    super(repository, Deliveries.Config.DELIVERIES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Deliveries.Types.IDeliveriesUpdatable,
  ): Promise<DeliveriesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find deliveries by contract id, paged by the shared query. */
  async findByContract(
    query: BaseQueryDto<DeliveriesEntity>,
    contractId: NonNullable<DeliveriesEntity["contractId"]>,
  ): Promise<IFindAllResponse<DeliveriesEntity>> {
    return await this.findByQuery(query, { contractId, deletedAt: IsNull() });
  }

  /** Find deliveries by currency id, paged by the shared query. */
  async findByCurrency(
    query: BaseQueryDto<DeliveriesEntity>,
    currencyId: NonNullable<DeliveriesEntity["currencyId"]>,
  ): Promise<IFindAllResponse<DeliveriesEntity>> {
    return await this.findByQuery(query, { currencyId, deletedAt: IsNull() });
  }

  /** Find deliveries by delivery kind id, paged by the shared query. */
  async findByDeliveryKind(
    query: BaseQueryDto<DeliveriesEntity>,
    deliveryKindId: NonNullable<DeliveriesEntity["deliveryKindId"]>,
  ): Promise<IFindAllResponse<DeliveriesEntity>> {
    return await this.findByQuery(query, { deliveryKindId, deletedAt: IsNull() });
  }

  /** Find deliveries by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<DeliveriesEntity>,
    sourceCitationId: NonNullable<DeliveriesEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<DeliveriesEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find deliveries by unit feature id, paged by the shared query. */
  async findByUnitFeature(
    query: BaseQueryDto<DeliveriesEntity>,
    unitFeatureId: NonNullable<DeliveriesEntity["unitFeatureId"]>,
  ): Promise<IFindAllResponse<DeliveriesEntity>> {
    return await this.findByQuery(query, { unitFeatureId, deletedAt: IsNull() });
  }

  /** Find the deliveries with this code (unique). */
  async findByCode(code: NonNullable<DeliveriesEntity["code"]>): Promise<DeliveriesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
