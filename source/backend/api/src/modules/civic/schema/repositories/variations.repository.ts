import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { VariationsEntity } from "#/modules/civic/schema/entities/variations.entity.ts";
import * as Variations from "#/modules/civic/schema/types/variations/index.ts";

/**
 * Repository of Variations: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class VariationsRepository
  extends EntityRepository<
    VariationsEntity,
    Variations.Types.VariationsSortableField,
    Variations.Types.VariationsEditableField,
    Variations.Types.VariationsSelectableField,
    Variations.Types.IVariationsCreatable
  >
  implements IUpdatableRepository<VariationsEntity, Variations.Types.IVariationsUpdatable>
{
  constructor(
    @InjectRepository(VariationsEntity)
    repository: Repository<VariationsEntity>,
  ) {
    super(repository, Variations.Config.VARIATIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Variations.Types.IVariationsUpdatable,
  ): Promise<VariationsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find variations by contract id, paged by the shared query. */
  async findByContract(
    query: BaseQueryDto<VariationsEntity>,
    contractId: NonNullable<VariationsEntity["contractId"]>,
  ): Promise<IFindAllResponse<VariationsEntity>> {
    return await this.findByQuery(query, { contractId, deletedAt: IsNull() });
  }

  /** Find variations by currency id, paged by the shared query. */
  async findByCurrency(
    query: BaseQueryDto<VariationsEntity>,
    currencyId: NonNullable<VariationsEntity["currencyId"]>,
  ): Promise<IFindAllResponse<VariationsEntity>> {
    return await this.findByQuery(query, { currencyId, deletedAt: IsNull() });
  }

  /** Find variations by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<VariationsEntity>,
    kindId: NonNullable<VariationsEntity["kindId"]>,
  ): Promise<IFindAllResponse<VariationsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find variations by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<VariationsEntity>,
    sourceCitationId: NonNullable<VariationsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<VariationsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find the variations with this code (unique). */
  async findByCode(code: NonNullable<VariationsEntity["code"]>): Promise<VariationsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
