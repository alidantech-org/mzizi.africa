import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { PartnersEntity } from "#/modules/civic/schema/entities/partners.entity.ts";
import * as Partners from "#/modules/civic/schema/types/partners/index.ts";

/**
 * Repository of Partners: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class PartnersRepository
  extends EntityRepository<
    PartnersEntity,
    Partners.Types.PartnersSortableField,
    Partners.Types.PartnersEditableField,
    Partners.Types.PartnersSelectableField,
    Partners.Types.IPartnersCreatable
  >
  implements IUpdatableRepository<PartnersEntity, Partners.Types.IPartnersUpdatable>
{
  constructor(
    @InjectRepository(PartnersEntity)
    repository: Repository<PartnersEntity>,
  ) {
    super(repository, Partners.Config.PARTNERS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Partners.Types.IPartnersUpdatable,
  ): Promise<PartnersEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find partners by bid id, paged by the shared query. */
  async findByBid(
    query: BaseQueryDto<PartnersEntity>,
    bidId: NonNullable<PartnersEntity["bidId"]>,
  ): Promise<IFindAllResponse<PartnersEntity>> {
    return await this.findByQuery(query, { bidId, deletedAt: IsNull() });
  }

  /** Find partners by contract id, paged by the shared query. */
  async findByContract(
    query: BaseQueryDto<PartnersEntity>,
    contractId: NonNullable<PartnersEntity["contractId"]>,
  ): Promise<IFindAllResponse<PartnersEntity>> {
    return await this.findByQuery(query, { contractId, deletedAt: IsNull() });
  }

  /** Find partners by partner entity id, paged by the shared query. */
  async findByPartnerEntity(
    query: BaseQueryDto<PartnersEntity>,
    partnerEntityId: NonNullable<PartnersEntity["partnerEntityId"]>,
  ): Promise<IFindAllResponse<PartnersEntity>> {
    return await this.findByQuery(query, { partnerEntityId, deletedAt: IsNull() });
  }

  /** Find partners by role id, paged by the shared query. */
  async findByRole(
    query: BaseQueryDto<PartnersEntity>,
    roleId: NonNullable<PartnersEntity["roleId"]>,
  ): Promise<IFindAllResponse<PartnersEntity>> {
    return await this.findByQuery(query, { roleId, deletedAt: IsNull() });
  }

  /** Find partners by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<PartnersEntity>,
    sourceCitationId: NonNullable<PartnersEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<PartnersEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }
}
