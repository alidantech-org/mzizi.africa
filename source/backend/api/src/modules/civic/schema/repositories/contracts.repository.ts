import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ContractsEntity } from "#/modules/civic/schema/entities/contracts.entity.ts";
import * as Contracts from "#/modules/civic/schema/types/contracts/index.ts";

/**
 * Repository of Contracts: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ContractsRepository
  extends EntityRepository<
    ContractsEntity,
    Contracts.Types.ContractsSortableField,
    Contracts.Types.ContractsEditableField,
    Contracts.Types.ContractsSelectableField,
    Contracts.Types.IContractsCreatable
  >
  implements IUpdatableRepository<ContractsEntity, Contracts.Types.IContractsUpdatable>
{
  constructor(
    @InjectRepository(ContractsEntity)
    repository: Repository<ContractsEntity>,
  ) {
    super(repository, Contracts.Config.CONTRACTS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Contracts.Types.IContractsUpdatable,
  ): Promise<ContractsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find contracts by contractor entity id, paged by the shared query. */
  async findByContractorEntity(
    query: BaseQueryDto<ContractsEntity>,
    contractorEntityId: NonNullable<ContractsEntity["contractorEntityId"]>,
  ): Promise<IFindAllResponse<ContractsEntity>> {
    return await this.findByQuery(query, { contractorEntityId, deletedAt: IsNull() });
  }

  /** Find contracts by currency id, paged by the shared query. */
  async findByCurrency(
    query: BaseQueryDto<ContractsEntity>,
    currencyId: NonNullable<ContractsEntity["currencyId"]>,
  ): Promise<IFindAllResponse<ContractsEntity>> {
    return await this.findByQuery(query, { currencyId, deletedAt: IsNull() });
  }

  /** Find contracts by nature id, paged by the shared query. */
  async findByNature(
    query: BaseQueryDto<ContractsEntity>,
    natureId: NonNullable<ContractsEntity["natureId"]>,
  ): Promise<IFindAllResponse<ContractsEntity>> {
    return await this.findByQuery(query, { natureId, deletedAt: IsNull() });
  }

  /** Find contracts by procurement id, paged by the shared query. */
  async findByProcurement(
    query: BaseQueryDto<ContractsEntity>,
    procurementId: NonNullable<ContractsEntity["procurementId"]>,
  ): Promise<IFindAllResponse<ContractsEntity>> {
    return await this.findByQuery(query, { procurementId, deletedAt: IsNull() });
  }

  /** Find contracts by project id, paged by the shared query. */
  async findByProject(
    query: BaseQueryDto<ContractsEntity>,
    projectId: NonNullable<ContractsEntity["projectId"]>,
  ): Promise<IFindAllResponse<ContractsEntity>> {
    return await this.findByQuery(query, { projectId, deletedAt: IsNull() });
  }

  /** Find contracts by source citation id, paged by the shared query. */
  async findBySourceCitation(
    query: BaseQueryDto<ContractsEntity>,
    sourceCitationId: NonNullable<ContractsEntity["sourceCitationId"]>,
  ): Promise<IFindAllResponse<ContractsEntity>> {
    return await this.findByQuery(query, { sourceCitationId, deletedAt: IsNull() });
  }

  /** Find contracts by status id, paged by the shared query. */
  async findByStatus(
    query: BaseQueryDto<ContractsEntity>,
    statusId: NonNullable<ContractsEntity["statusId"]>,
  ): Promise<IFindAllResponse<ContractsEntity>> {
    return await this.findByQuery(query, { statusId, deletedAt: IsNull() });
  }

  /** Find the contracts with this code (unique). */
  async findByCode(code: NonNullable<ContractsEntity["code"]>): Promise<ContractsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
