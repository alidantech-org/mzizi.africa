import { Injectable } from "@nestjs/common";
import type { CopyBundleDto } from "#/modules/frontend/schema/dto/copy-bundle.dto.ts";
import type { CopyRequestDto } from "#/modules/frontend/schema/dto/copy-request.dto.ts";
import type { HomeRequestDto } from "#/modules/frontend/schema/dto/home-request.dto.ts";
import type { HomeScreenDto } from "#/modules/frontend/schema/dto/home-screen.dto.ts";
import type { InstitutionRequestDto } from "#/modules/frontend/schema/dto/institution-request.dto.ts";
import type { InstitutionScreenDto } from "#/modules/frontend/schema/dto/institution-screen.dto.ts";
import type { PlaceRequestDto } from "#/modules/frontend/schema/dto/place-request.dto.ts";
import type { PlaceScreenDto } from "#/modules/frontend/schema/dto/place-screen.dto.ts";
import type { RankingRequestDto } from "#/modules/frontend/schema/dto/ranking-request.dto.ts";
import type { RankingScreenDto } from "#/modules/frontend/schema/dto/ranking-screen.dto.ts";
import type { SearchRequestDto } from "#/modules/frontend/schema/dto/search-request.dto.ts";
import type { SearchResultsDto } from "#/modules/frontend/schema/dto/search-results.dto.ts";
import { GetCopyBundleUseCase } from "#/modules/frontend/features/screens/use-cases/get-copy-bundle.repository.ts";
import { GetHomeScreenUseCase } from "#/modules/frontend/features/screens/use-cases/get-home-screen.repository.ts";
import { GetInstitutionScreenUseCase } from "#/modules/frontend/features/screens/use-cases/get-institution-screen.repository.ts";
import { GetPlaceScreenUseCase } from "#/modules/frontend/features/screens/use-cases/get-place-screen.repository.ts";
import { GetRankingScreenUseCase } from "#/modules/frontend/features/screens/use-cases/get-ranking-screen.repository.ts";
import { SearchScreenUseCase } from "#/modules/frontend/features/screens/use-cases/search-screen.repository.ts";

/**
 * The Screens contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class FrontendScreensService {
  abstract getCopyBundle(input: CopyRequestDto): Promise<CopyBundleDto>;
  abstract getHomeScreen(input: HomeRequestDto): Promise<HomeScreenDto>;
  abstract getInstitutionScreen(input: InstitutionRequestDto): Promise<InstitutionScreenDto>;
  abstract getPlaceScreen(input: PlaceRequestDto): Promise<PlaceScreenDto>;
  abstract getRankingScreen(input: RankingRequestDto): Promise<RankingScreenDto>;
  abstract searchScreen(input: SearchRequestDto): Promise<SearchResultsDto>;
}

@Injectable()
export class FrontendScreensServiceImpl extends FrontendScreensService {
  constructor(
    private readonly getCopyBundleUseCase: GetCopyBundleUseCase,
    private readonly getHomeScreenUseCase: GetHomeScreenUseCase,
    private readonly getInstitutionScreenUseCase: GetInstitutionScreenUseCase,
    private readonly getPlaceScreenUseCase: GetPlaceScreenUseCase,
    private readonly getRankingScreenUseCase: GetRankingScreenUseCase,
    private readonly searchScreenUseCase: SearchScreenUseCase,
  ) {
    super();
  }

  getCopyBundle(input: CopyRequestDto): Promise<CopyBundleDto> {
    return this.getCopyBundleUseCase.execute(input);
  }

  getHomeScreen(input: HomeRequestDto): Promise<HomeScreenDto> {
    return this.getHomeScreenUseCase.execute(input);
  }

  getInstitutionScreen(input: InstitutionRequestDto): Promise<InstitutionScreenDto> {
    return this.getInstitutionScreenUseCase.execute(input);
  }

  getPlaceScreen(input: PlaceRequestDto): Promise<PlaceScreenDto> {
    return this.getPlaceScreenUseCase.execute(input);
  }

  getRankingScreen(input: RankingRequestDto): Promise<RankingScreenDto> {
    return this.getRankingScreenUseCase.execute(input);
  }

  searchScreen(input: SearchRequestDto): Promise<SearchResultsDto> {
    return this.searchScreenUseCase.execute(input);
  }
}
