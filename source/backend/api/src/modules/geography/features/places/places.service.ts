import { Injectable } from "@nestjs/common";
import type { ChildCollectionDto } from "#/modules/geography/schema/dto/child-collection.dto.ts";
import type { ChildWindowDto } from "#/modules/geography/schema/dto/child-window.dto.ts";
import type { FeatureKeyDto } from "#/modules/geography/schema/dto/feature-key.dto.ts";
import type { FeatureWindowDto } from "#/modules/geography/schema/dto/feature-window.dto.ts";
import type { PlaceAtPointDto } from "#/modules/geography/schema/dto/place-at-point.dto.ts";
import type { PlaceCollectionDto } from "#/modules/geography/schema/dto/place-collection.dto.ts";
import type { PlaceDetailDto } from "#/modules/geography/schema/dto/place-detail.dto.ts";
import type { PointQueryDto } from "#/modules/geography/schema/dto/point-query.dto.ts";
import { FindPlacesAtPointUseCase } from "#/modules/geography/features/places/use-cases/find-places-at-point.repository.ts";
import { GetPlaceUseCase } from "#/modules/geography/features/places/use-cases/get-place.repository.ts";
import { ListChildrenUseCase } from "#/modules/geography/features/places/use-cases/list-children.repository.ts";
import { ListPlacesUseCase } from "#/modules/geography/features/places/use-cases/list-places.repository.ts";

/**
 * The Places contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class GeographyPlacesService {
  abstract findPlacesAtPoint(input: PointQueryDto): Promise<PlaceAtPointDto>;
  abstract getPlace(input: FeatureKeyDto): Promise<PlaceDetailDto>;
  abstract listChildren(input: ChildWindowDto): Promise<ChildCollectionDto>;
  abstract listPlaces(input: FeatureWindowDto): Promise<PlaceCollectionDto>;
}

@Injectable()
export class GeographyPlacesServiceImpl extends GeographyPlacesService {
  constructor(
    private readonly findPlacesAtPointUseCase: FindPlacesAtPointUseCase,
    private readonly getPlaceUseCase: GetPlaceUseCase,
    private readonly listChildrenUseCase: ListChildrenUseCase,
    private readonly listPlacesUseCase: ListPlacesUseCase,
  ) {
    super();
  }

  findPlacesAtPoint(input: PointQueryDto): Promise<PlaceAtPointDto> {
    return this.findPlacesAtPointUseCase.execute(input);
  }

  getPlace(input: FeatureKeyDto): Promise<PlaceDetailDto> {
    return this.getPlaceUseCase.execute(input);
  }

  listChildren(input: ChildWindowDto): Promise<ChildCollectionDto> {
    return this.listChildrenUseCase.execute(input);
  }

  listPlaces(input: FeatureWindowDto): Promise<PlaceCollectionDto> {
    return this.listPlacesUseCase.execute(input);
  }
}
