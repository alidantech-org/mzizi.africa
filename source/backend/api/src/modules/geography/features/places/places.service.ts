import { Injectable } from "@nestjs/common";
import type { UnitCollectionDto } from "#/modules/geography/schema/dto/unit-collection.dto.ts";
import type { UnitDetailDto } from "#/modules/geography/schema/dto/unit-detail.dto.ts";
import type { UnitKeyDto } from "#/modules/geography/schema/dto/unit-key.dto.ts";
import type { UnitWindowDto } from "#/modules/geography/schema/dto/unit-window.dto.ts";
import { BrowseUnitsUseCase } from "#/modules/geography/features/places/use-cases/browse-units.usecase.ts";
import { GetUnitUseCase } from "#/modules/geography/features/places/use-cases/get-unit.usecase.ts";

/**
 * The Places contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class GeographyPlacesService {
  abstract browseUnits(input: UnitWindowDto): Promise<UnitCollectionDto>;
  abstract getUnit(input: UnitKeyDto): Promise<UnitDetailDto>;
}

@Injectable()
export class GeographyPlacesServiceImpl extends GeographyPlacesService {
  constructor(
    private readonly browseUnitsUseCase: BrowseUnitsUseCase,
    private readonly getUnitUseCase: GetUnitUseCase,
  ) {
    super();
  }

  browseUnits(input: UnitWindowDto): Promise<UnitCollectionDto> {
    return this.browseUnitsUseCase.execute(input);
  }

  getUnit(input: UnitKeyDto): Promise<UnitDetailDto> {
    return this.getUnitUseCase.execute(input);
  }
}
