import { Injectable } from "@nestjs/common";
import type { ChildOutlineCollectionDto } from "#/modules/geography/schema/dto/child-outline-collection.dto.ts";
import type { ChildWindowDto } from "#/modules/geography/schema/dto/child-window.dto.ts";
import type { OutlineCollectionDto } from "#/modules/geography/schema/dto/outline-collection.dto.ts";
import type { OutlineWindowDto } from "#/modules/geography/schema/dto/outline-window.dto.ts";
import { GetOutlineUseCase } from "#/modules/geography/features/maps/use-cases/get-outline.repository.ts";
import { ListChildOutlinesUseCase } from "#/modules/geography/features/maps/use-cases/list-child-outlines.repository.ts";

/**
 * The Maps contract the controller calls, then its implementation: each method
 * delegates to the use case for that operation. Regenerated by Dryv; the use cases hold the logic.
 */
export abstract class GeographyMapsService {
  abstract getOutline(input: OutlineWindowDto): Promise<OutlineCollectionDto>;
  abstract listChildOutlines(input: ChildWindowDto): Promise<ChildOutlineCollectionDto>;
}

@Injectable()
export class GeographyMapsServiceImpl extends GeographyMapsService {
  constructor(
    private readonly getOutlineUseCase: GetOutlineUseCase,
    private readonly listChildOutlinesUseCase: ListChildOutlinesUseCase,
  ) {
    super();
  }

  getOutline(input: OutlineWindowDto): Promise<OutlineCollectionDto> {
    return this.getOutlineUseCase.execute(input);
  }

  listChildOutlines(input: ChildWindowDto): Promise<ChildOutlineCollectionDto> {
    return this.listChildOutlinesUseCase.execute(input);
  }
}
