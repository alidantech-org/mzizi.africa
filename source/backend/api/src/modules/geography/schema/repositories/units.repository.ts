import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { type Repository } from "typeorm";
import { EntityRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { UnitsEntity } from "#/modules/geography/schema/entities/units.entity.ts";
import * as Units from "#/modules/geography/schema/types/units/index.ts";

/**
 * Repository of Units: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class UnitsRepository extends EntityRepository<
  UnitsEntity,
  Units.Types.UnitsSortableField,
  Units.Types.UnitsEditableField,
  Units.Types.UnitsSelectableField,
  Units.Types.IUnitsCreatable
> {
  constructor(
    @InjectRepository(UnitsEntity)
    repository: Repository<UnitsEntity>,
  ) {
    super(repository, Units.Config.UNITS_QUERY_OPTIONS);
  }

  /** Find units by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<UnitsEntity>,
    countryId: NonNullable<UnitsEntity["countryId"]>,
  ): Promise<IFindAllResponse<UnitsEntity>> {
    return await this.findByQuery(query, { countryId });
  }

  /** Find units by feature id, paged by the shared query. */
  async findByFeature(
    query: BaseQueryDto<UnitsEntity>,
    featureId: NonNullable<UnitsEntity["featureId"]>,
  ): Promise<IFindAllResponse<UnitsEntity>> {
    return await this.findByQuery(query, { featureId });
  }
}
