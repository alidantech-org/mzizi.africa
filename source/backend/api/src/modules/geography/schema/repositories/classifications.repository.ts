import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { ClassificationsEntity } from "#/modules/geography/schema/entities/classifications.entity.ts";
import * as Classifications from "#/modules/geography/schema/types/classifications/index.ts";

/**
 * Repository of Classifications: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class ClassificationsRepository
  extends EntityRepository<
    ClassificationsEntity,
    Classifications.Types.ClassificationsSortableField,
    Classifications.Types.ClassificationsEditableField,
    Classifications.Types.ClassificationsSelectableField,
    Classifications.Types.IClassificationsCreatable
  >
  implements
    IUpdatableRepository<ClassificationsEntity, Classifications.Types.IClassificationsUpdatable>
{
  constructor(
    @InjectRepository(ClassificationsEntity)
    repository: Repository<ClassificationsEntity>,
  ) {
    super(repository, Classifications.Config.CLASSIFICATIONS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Classifications.Types.IClassificationsUpdatable,
  ): Promise<ClassificationsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find classifications by feature id, paged by the shared query. */
  async findByFeature(
    query: BaseQueryDto<ClassificationsEntity>,
    featureId: NonNullable<ClassificationsEntity["featureId"]>,
  ): Promise<IFindAllResponse<ClassificationsEntity>> {
    return await this.findByQuery(query, { featureId, deletedAt: IsNull() });
  }

  /** Find classifications by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<ClassificationsEntity>,
    fromToPrecision: NonNullable<ClassificationsEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<ClassificationsEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find classifications by value id, paged by the shared query. */
  async findByValue(
    query: BaseQueryDto<ClassificationsEntity>,
    valueId: NonNullable<ClassificationsEntity["valueId"]>,
  ): Promise<IFindAllResponse<ClassificationsEntity>> {
    return await this.findByQuery(query, { valueId, deletedAt: IsNull() });
  }
}
