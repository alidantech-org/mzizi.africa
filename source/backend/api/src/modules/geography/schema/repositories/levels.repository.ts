import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { LevelsEntity } from "#/modules/geography/schema/entities/levels.entity.ts";
import * as Levels from "#/modules/geography/schema/types/levels/index.ts";

/**
 * Repository of Levels: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class LevelsRepository
  extends EntityRepository<
    LevelsEntity,
    Levels.Types.LevelsSortableField,
    Levels.Types.LevelsEditableField,
    Levels.Types.LevelsSelectableField,
    Levels.Types.ILevelsCreatable
  >
  implements IUpdatableRepository<LevelsEntity, Levels.Types.ILevelsUpdatable>
{
  constructor(
    @InjectRepository(LevelsEntity)
    repository: Repository<LevelsEntity>,
  ) {
    super(repository, Levels.Config.LEVELS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Levels.Types.ILevelsUpdatable,
  ): Promise<LevelsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find levels by country id, paged by the shared query. */
  async findByCountry(
    query: BaseQueryDto<LevelsEntity>,
    countryId: NonNullable<LevelsEntity["countryId"]>,
  ): Promise<IFindAllResponse<LevelsEntity>> {
    return await this.findByQuery(query, { countryId, deletedAt: IsNull() });
  }

  /** Find levels by feature kind id, paged by the shared query. */
  async findByFeatureKind(
    query: BaseQueryDto<LevelsEntity>,
    featureKindId: NonNullable<LevelsEntity["featureKindId"]>,
  ): Promise<IFindAllResponse<LevelsEntity>> {
    return await this.findByQuery(query, { featureKindId, deletedAt: IsNull() });
  }

  /** Find levels by hierarchy kind id, paged by the shared query. */
  async findByHierarchyKind(
    query: BaseQueryDto<LevelsEntity>,
    hierarchyKindId: NonNullable<LevelsEntity["hierarchyKindId"]>,
  ): Promise<IFindAllResponse<LevelsEntity>> {
    return await this.findByQuery(query, { hierarchyKindId, deletedAt: IsNull() });
  }

  /** Find levels by root feature id, paged by the shared query. */
  async findByRootFeature(
    query: BaseQueryDto<LevelsEntity>,
    rootFeatureId: NonNullable<LevelsEntity["rootFeatureId"]>,
  ): Promise<IFindAllResponse<LevelsEntity>> {
    return await this.findByQuery(query, { rootFeatureId, deletedAt: IsNull() });
  }

  /** Find the levels with this code (unique). */
  async findByCode(code: NonNullable<LevelsEntity["code"]>): Promise<LevelsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
