import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { GeographyRelationshipsEntity } from "#/modules/geography/schema/entities/relationships.entity.ts";
import * as Relationships from "#/modules/geography/schema/types/relationships/index.ts";

/**
 * Repository of Relationships: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class RelationshipsRepository
  extends EntityRepository<
    GeographyRelationshipsEntity,
    Relationships.Types.RelationshipsSortableField,
    Relationships.Types.RelationshipsEditableField,
    Relationships.Types.RelationshipsSelectableField,
    Relationships.Types.IRelationshipsCreatable
  >
  implements
    IUpdatableRepository<GeographyRelationshipsEntity, Relationships.Types.IRelationshipsUpdatable>
{
  constructor(
    @InjectRepository(GeographyRelationshipsEntity)
    repository: Repository<GeographyRelationshipsEntity>,
  ) {
    super(repository, Relationships.Config.RELATIONSHIPS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Relationships.Types.IRelationshipsUpdatable,
  ): Promise<GeographyRelationshipsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find relationships by object feature id, paged by the shared query. */
  async findByObjectFeature(
    query: BaseQueryDto<GeographyRelationshipsEntity>,
    objectFeatureId: NonNullable<GeographyRelationshipsEntity["objectFeatureId"]>,
  ): Promise<IFindAllResponse<GeographyRelationshipsEntity>> {
    return await this.findByQuery(query, { objectFeatureId, deletedAt: IsNull() });
  }

  /** Find relationships by relationship kind id, paged by the shared query. */
  async findByRelationshipKind(
    query: BaseQueryDto<GeographyRelationshipsEntity>,
    relationshipKindId: NonNullable<GeographyRelationshipsEntity["relationshipKindId"]>,
  ): Promise<IFindAllResponse<GeographyRelationshipsEntity>> {
    return await this.findByQuery(query, { relationshipKindId, deletedAt: IsNull() });
  }

  /** Find relationships by source id, paged by the shared query. */
  async findBySource(
    query: BaseQueryDto<GeographyRelationshipsEntity>,
    sourceId: NonNullable<GeographyRelationshipsEntity["sourceId"]>,
  ): Promise<IFindAllResponse<GeographyRelationshipsEntity>> {
    return await this.findByQuery(query, { sourceId, deletedAt: IsNull() });
  }

  /** Find relationships by subject feature id, paged by the shared query. */
  async findBySubjectFeature(
    query: BaseQueryDto<GeographyRelationshipsEntity>,
    subjectFeatureId: NonNullable<GeographyRelationshipsEntity["subjectFeatureId"]>,
  ): Promise<IFindAllResponse<GeographyRelationshipsEntity>> {
    return await this.findByQuery(query, { subjectFeatureId, deletedAt: IsNull() });
  }

  /** Find relationships by system id, paged by the shared query. */
  async findBySystem(
    query: BaseQueryDto<GeographyRelationshipsEntity>,
    systemId: NonNullable<GeographyRelationshipsEntity["systemId"]>,
  ): Promise<IFindAllResponse<GeographyRelationshipsEntity>> {
    return await this.findByQuery(query, { systemId, deletedAt: IsNull() });
  }
}
