import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { type Repository } from "typeorm";
import { EntityRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { PlacesEntity } from "#/modules/geography/schema/entities/places.entity.ts";
import * as Places from "#/modules/geography/schema/types/places/index.ts";

/**
 * Repository of Places: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class PlacesRepository extends EntityRepository<
  PlacesEntity,
  Places.Types.PlacesSortableField,
  Places.Types.PlacesEditableField,
  Places.Types.PlacesSelectableField,
  Places.Types.IPlacesCreatable
> {
  constructor(
    @InjectRepository(PlacesEntity)
    repository: Repository<PlacesEntity>,
  ) {
    super(repository, Places.Config.PLACES_QUERY_OPTIONS);
  }

  /** Find places by feature id, paged by the shared query. */
  async findByFeature(
    query: BaseQueryDto<PlacesEntity>,
    featureId: NonNullable<PlacesEntity["featureId"]>,
  ): Promise<IFindAllResponse<PlacesEntity>> {
    return await this.findByQuery(query, { featureId });
  }
}
