import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { GeometriesEntity } from "#/modules/geography/schema/entities/geometries.entity.ts";
import * as Geometries from "#/modules/geography/schema/types/geometries/index.ts";

/**
 * Repository of Geometries: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class GeometriesRepository
  extends EntityRepository<
    GeometriesEntity,
    Geometries.Types.GeometriesSortableField,
    Geometries.Types.GeometriesEditableField,
    Geometries.Types.GeometriesSelectableField,
    Geometries.Types.IGeometriesCreatable
  >
  implements IUpdatableRepository<GeometriesEntity, Geometries.Types.IGeometriesUpdatable>
{
  constructor(
    @InjectRepository(GeometriesEntity)
    repository: Repository<GeometriesEntity>,
  ) {
    super(repository, Geometries.Config.GEOMETRIES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Geometries.Types.IGeometriesUpdatable,
  ): Promise<GeometriesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find geometries by basis id, paged by the shared query. */
  async findByBasis(
    query: BaseQueryDto<GeometriesEntity>,
    basisId: NonNullable<GeometriesEntity["basisId"]>,
  ): Promise<IFindAllResponse<GeometriesEntity>> {
    return await this.findByQuery(query, { basisId, deletedAt: IsNull() });
  }

  /** Find geometries by feature id, paged by the shared query. */
  async findByFeature(
    query: BaseQueryDto<GeometriesEntity>,
    featureId: NonNullable<GeometriesEntity["featureId"]>,
  ): Promise<IFindAllResponse<GeometriesEntity>> {
    return await this.findByQuery(query, { featureId, deletedAt: IsNull() });
  }

  /** Find geometries by from to precision, paged by the shared query. */
  async findByFromToPrecision(
    query: BaseQueryDto<GeometriesEntity>,
    fromToPrecision: NonNullable<GeometriesEntity["fromToPrecision"]>,
  ): Promise<IFindAllResponse<GeometriesEntity>> {
    return await this.findByQuery(query, { fromToPrecision, deletedAt: IsNull() });
  }

  /** Find geometries by geometry role id, paged by the shared query. */
  async findByGeometryRole(
    query: BaseQueryDto<GeometriesEntity>,
    geometryRoleId: NonNullable<GeometriesEntity["geometryRoleId"]>,
  ): Promise<IFindAllResponse<GeometriesEntity>> {
    return await this.findByQuery(query, { geometryRoleId, deletedAt: IsNull() });
  }

  /** Find geometries by supersedes id, paged by the shared query. */
  async findBySupersedes(
    query: BaseQueryDto<GeometriesEntity>,
    supersedesId: NonNullable<GeometriesEntity["supersedesId"]>,
  ): Promise<IFindAllResponse<GeometriesEntity>> {
    return await this.findByQuery(query, { supersedesId, deletedAt: IsNull() });
  }
}
