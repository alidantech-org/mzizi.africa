import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { AssetsEntity } from "#/modules/geography/schema/entities/assets.entity.ts";
import * as Assets from "#/modules/geography/schema/types/assets/index.ts";

/**
 * Repository of Assets: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class AssetsRepository
  extends EntityRepository<
    AssetsEntity,
    Assets.Types.AssetsSortableField,
    Assets.Types.AssetsEditableField,
    Assets.Types.AssetsSelectableField,
    Assets.Types.IAssetsCreatable
  >
  implements IUpdatableRepository<AssetsEntity, Assets.Types.IAssetsUpdatable>
{
  constructor(
    @InjectRepository(AssetsEntity)
    repository: Repository<AssetsEntity>,
  ) {
    super(repository, Assets.Config.ASSETS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Assets.Types.IAssetsUpdatable,
  ): Promise<AssetsEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find assets by feature id, paged by the shared query. */
  async findByFeature(
    query: BaseQueryDto<AssetsEntity>,
    featureId: NonNullable<AssetsEntity["featureId"]>,
  ): Promise<IFindAllResponse<AssetsEntity>> {
    return await this.findByQuery(query, { featureId, deletedAt: IsNull() });
  }

  /** Find assets by file version id, paged by the shared query. */
  async findByFileVersion(
    query: BaseQueryDto<AssetsEntity>,
    fileVersionId: NonNullable<AssetsEntity["fileVersionId"]>,
  ): Promise<IFindAllResponse<AssetsEntity>> {
    return await this.findByQuery(query, { fileVersionId, deletedAt: IsNull() });
  }

  /** Find assets by geometry id, paged by the shared query. */
  async findByGeometry(
    query: BaseQueryDto<AssetsEntity>,
    geometryId: NonNullable<AssetsEntity["geometryId"]>,
  ): Promise<IFindAllResponse<AssetsEntity>> {
    return await this.findByQuery(query, { geometryId, deletedAt: IsNull() });
  }

  /** Find assets by kind id, paged by the shared query. */
  async findByKind(
    query: BaseQueryDto<AssetsEntity>,
    kindId: NonNullable<AssetsEntity["kindId"]>,
  ): Promise<IFindAllResponse<AssetsEntity>> {
    return await this.findByQuery(query, { kindId, deletedAt: IsNull() });
  }

  /** Find assets by purpose id, paged by the shared query. */
  async findByPurpose(
    query: BaseQueryDto<AssetsEntity>,
    purposeId: NonNullable<AssetsEntity["purposeId"]>,
  ): Promise<IFindAllResponse<AssetsEntity>> {
    return await this.findByQuery(query, { purposeId, deletedAt: IsNull() });
  }

  /** Find the assets with this code (unique). */
  async findByCode(code: NonNullable<AssetsEntity["code"]>): Promise<AssetsEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
