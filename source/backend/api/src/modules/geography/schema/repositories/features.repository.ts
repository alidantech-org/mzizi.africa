import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { FeaturesEntity } from "#/modules/geography/schema/entities/features.entity.ts";
import * as Features from "#/modules/geography/schema/types/features/index.ts";

/**
 * Repository of Features: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class FeaturesRepository
  extends EntityRepository<
    FeaturesEntity,
    Features.Types.FeaturesSortableField,
    Features.Types.FeaturesEditableField,
    Features.Types.FeaturesSelectableField,
    Features.Types.IFeaturesCreatable
  >
  implements IUpdatableRepository<FeaturesEntity, Features.Types.IFeaturesUpdatable>
{
  constructor(
    @InjectRepository(FeaturesEntity)
    repository: Repository<FeaturesEntity>,
  ) {
    super(repository, Features.Config.FEATURES_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Features.Types.IFeaturesUpdatable,
  ): Promise<FeaturesEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find features by feature type id, paged by the shared query. */
  async findByFeatureType(
    query: BaseQueryDto<FeaturesEntity>,
    featureTypeId: NonNullable<FeaturesEntity["featureTypeId"]>,
  ): Promise<IFindAllResponse<FeaturesEntity>> {
    return await this.findByQuery(query, { featureTypeId, deletedAt: IsNull() });
  }

  /** Find the features with this code (unique). */
  async findByCode(code: NonNullable<FeaturesEntity["code"]>): Promise<FeaturesEntity | null> {
    return await this.findOne({ code, deletedAt: IsNull() });
  }
}
