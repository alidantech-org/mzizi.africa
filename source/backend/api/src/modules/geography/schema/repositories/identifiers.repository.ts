import { Injectable } from "@nestjs/common";
import { InjectRepository } from "@nestjs/typeorm";
import { IsNull, type Repository } from "typeorm";
import { EntityRepository, type IUpdatableRepository } from "#/database/base/entity-repository.ts";
import { BaseQueryDto } from "#/database/base/base-query.dto.ts";
import type { IFindAllResponse } from "#/database/base/query.types.ts";
import { GeographyIdentifiersEntity } from "#/modules/geography/schema/entities/identifiers.entity.ts";
import * as Identifiers from "#/modules/geography/schema/types/identifiers/index.ts";

/**
 * Repository of Identifiers: the base repository configured with the entity's
 * generated query fields. Regenerated by Dryv; the feature repositories build the contract's
 * named queries on top of it.
 */
@Injectable()
export class IdentifiersRepository
  extends EntityRepository<
    GeographyIdentifiersEntity,
    Identifiers.Types.IdentifiersSortableField,
    Identifiers.Types.IdentifiersEditableField,
    Identifiers.Types.IdentifiersSelectableField,
    Identifiers.Types.IIdentifiersCreatable
  >
  implements
    IUpdatableRepository<GeographyIdentifiersEntity, Identifiers.Types.IIdentifiersUpdatable>
{
  constructor(
    @InjectRepository(GeographyIdentifiersEntity)
    repository: Repository<GeographyIdentifiersEntity>,
  ) {
    super(repository, Identifiers.Config.IDENTIFIERS_QUERY_OPTIONS);
  }

  /** Updates a row from only the editable fields of `data`. */
  async updateEditable(
    id: string,
    data: Identifiers.Types.IIdentifiersUpdatable,
  ): Promise<GeographyIdentifiersEntity | null> {
    const stamped = await this.stampUpdate(id, data);
    return stamped === null ? null : await this.update(id, stamped);
  }

  /** Find identifiers by feature id, paged by the shared query. */
  async findByFeature(
    query: BaseQueryDto<GeographyIdentifiersEntity>,
    featureId: NonNullable<GeographyIdentifiersEntity["featureId"]>,
  ): Promise<IFindAllResponse<GeographyIdentifiersEntity>> {
    return await this.findByQuery(query, { featureId, deletedAt: IsNull() });
  }

  /** Find identifiers by identifier scheme id, paged by the shared query. */
  async findByIdentifierScheme(
    query: BaseQueryDto<GeographyIdentifiersEntity>,
    identifierSchemeId: NonNullable<GeographyIdentifiersEntity["identifierSchemeId"]>,
  ): Promise<IFindAllResponse<GeographyIdentifiersEntity>> {
    return await this.findByQuery(query, { identifierSchemeId, deletedAt: IsNull() });
  }

  /** Find identifiers by source id, paged by the shared query. */
  async findBySource(
    query: BaseQueryDto<GeographyIdentifiersEntity>,
    sourceId: NonNullable<GeographyIdentifiersEntity["sourceId"]>,
  ): Promise<IFindAllResponse<GeographyIdentifiersEntity>> {
    return await this.findByQuery(query, { sourceId, deletedAt: IsNull() });
  }
}
