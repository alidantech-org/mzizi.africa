"""Occurrences: one row of occurrences."""

from __future__ import annotations

from datetime import date, datetime
from typing import Annotated, ClassVar
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from mzizi_engine.api.schemas.postgres.shared.enums.date_precision import DatePrecision
from mzizi_engine.api.schemas.postgres.shared.enums.identity_kind import IdentityKind


class HistoryOccurrencesRow(BaseModel):
    """A historical occurrence of significance (Kenya's independence, the 2010 constitution, devolution in 2013)."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    table: ClassVar[str] = "history.occurrences"

    code: Annotated[
        str,
        Field(
            min_length=1,
            max_length=255,
            pattern="^[a-z0-9]+(-[a-z0-9]+)*(~[a-z0-9]+(-[a-z0-9]+)*)*(\\.[a-z0-9]+(-[a-z0-9]+)*(~[a-z0-9]+(-[a-z0-9]+)*)*){0,15}$",
        ),
    ]
    country_id: UUID | None = None
    created_at: datetime
    deleted_at: datetime | None = None
    ends_on: date | None = None
    from_year: Annotated[int, Field(ge=-10000, le=3000)] | None = None
    id: UUID
    identity_kind: IdentityKind
    kind_term: UUID
    precision: DatePrecision
    starts_on: date | None = None
    to_year: Annotated[int, Field(ge=-10000, le=3000)] | None = None
    updated_at: datetime
    version: Annotated[int, Field(ge=1)]
