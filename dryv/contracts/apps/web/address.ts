/** Public explorer address contract. Geography stays in the path; product state has explicit query keys. */
import * as dryv from "@dryvcode/author";
import { sharedProperties as p } from "#/schemas/_shared.ts";
export const addresses = dryv
  .group({ name: "addresses" })
  .description("The public web explorer's navigation and query grammar.");
const choices = addresses.properties({
  ExplorerView: dryv.property.enum({
    Overview: "overview",
    Explore: "explore",
    Places: "places",
    Leaders: "leaders",
    Institutions: "institutions",
    Laws: "laws",
    Parliament: "parliament",
    Politics: "politics",
    Finance: "finance",
    Procurement: "procurement",
    Infrastructure: "infrastructure",
    Elections: "elections",
    Statistics: "statistics",
    Rankings: "rankings",
    Compare: "compare",
    Calendar: "calendar",
    Content: "content",
    Sources: "sources",
    Search: "search",
    Evidence: "evidence",
    Coverage: "coverage",
    Promises: "promises",
    Report: "report",
  }),
  InterfaceLanguage: dryv.property.enum({ English: "en", Kiswahili: "sw" }),
  PageSize: dryv.property.number.integer({ range: { min: 1, max: 200 } }),
});
export const ExplorerAddress = addresses
  .schema("ExplorerAddress", {
    view: dryv.field(choices.ExplorerView).default("overview").tags("query:view"),
    tab: dryv.field(p.NonEmptyString100).optional().tags("query:view.tab"),
    entity: dryv.field(p.NonEmptyString100).optional().tags("query:view.entity"),
    id: dryv.field(p.NonEmptyString500).optional().tags("query:view.id"),
    provision: dryv.field(p.NonEmptyString500).optional().tags("query:view.provision"),
    indicator: dryv.field(p.NonEmptyString255).optional().tags("query:view.indicator"),
    metric: dryv.field(p.NonEmptyString255).optional().tags("query:view.metric"),
    contest: dryv.field(p.NonEmptyString100).optional().tags("query:view.contest"),
    compareTo: dryv.field(p.NonEmptyString500).optional().tags("query:view.compareTo"),
    q: dryv.field(p.NonEmptyString500).optional().tags("query:filters.q"),
    kind: dryv.field(p.NonEmptyString100).optional().tags("query:filters.kind"),
    status: dryv.field(p.NonEmptyString100).optional().tags("query:filters.status"),
    classCode: dryv.field(p.NonEmptyString255).optional().tags("query:filters.class"),
    level: dryv.field(p.NonEmptyString100).optional().tags("query:filters.level"),
    institution: dryv.field(p.NonEmptyString255).optional().tags("query:filters.institution"),
    tag: dryv.field(p.NonEmptyString100).optional().tags("query:filters.tag"),
    year: dryv.field(p.Integer).optional().tags("query:filters.year"),
    month: dryv.field(p.NonEmptyString100).optional().tags("query:filters.month"),
    sortBy: dryv.field(p.NonEmptyString100).optional().tags("query:sort.by"),
    sortOrder: dryv.field(p.NonEmptyString100).optional().tags("query:sort.order"),
    pageNo: dryv.field(p.PositiveInteger).optional().tags("query:page.no"),
    pageLimit: dryv.field(choices.PageSize).optional().tags("query:page.limit"),
    mode: dryv.field(p.NonEmptyString100).optional().tags("query:display.mode"),
    lens: dryv.field(p.NonEmptyString100).optional().tags("query:display.lens"),
    suggestions: dryv.field(p.NonEmptyString100).optional().tags("query:display.suggestions"),
    lang: dryv.field(choices.InterfaceLanguage).optional().tags("query:lang"),
  })
  .tags(
    "explorer:address",
    "legacy-section:data/statistics=statistics",
    "legacy-section:data/compare=compare",
    "legacy-section:government/law=laws",
    "legacy-section:government/institutions=institutions",
    "navigation:00:Place:overview",
    "navigation:01:Place:places",
    "navigation:02:Place:explore",
    "navigation:10:Public life:leaders",
    "navigation:11:Public life:institutions",
    "navigation:12:Public life:laws",
    "navigation:13:Public life:parliament",
    "navigation:14:Public life:politics",
    "navigation:15:Public life:elections",
    "navigation:20:Measures and resources:statistics",
    "navigation:21:Measures and resources:compare",
    "navigation:22:Measures and resources:rankings",
    "navigation:23:Measures and resources:finance",
    "navigation:24:Measures and resources:procurement",
    "navigation:25:Measures and resources:infrastructure",
    "navigation:26:Measures and resources:promises",
    "navigation:30:Evidence and activity:calendar",
    "navigation:31:Evidence and activity:content",
    "navigation:32:Evidence and activity:sources",
    "navigation:33:Evidence and activity:evidence",
    "navigation:34:Evidence and activity:coverage",
    "navigation:35:Evidence and activity:report",
    "navigation:36:Evidence and activity:search",
    "view-fields:overview:",
    "view-fields:places:q,kind,level",
    "view-fields:explore:q,kind,level,mode",
    "view-fields:leaders:tab,entity,id,institution,kind,status,mode",
    "view-fields:institutions:tab,entity,id,institution,kind,status,mode",
    "view-fields:laws:tab,entity,id,provision,q,kind,status,institution,year",
    "view-fields:parliament:tab,entity,id,q,kind,status,institution,year",
    "view-fields:politics:tab,entity,id,q,kind,status,year",
    "view-fields:elections:tab,entity,id,contest,year,kind,status,mode",
    "view-fields:statistics:tab,indicator,metric,q,kind,year,mode,lens",
    "view-fields:compare:tab,indicator,metric,compareTo,year,mode",
    "view-fields:rankings:indicator,metric,year,level,mode",
    "view-fields:finance:tab,entity,id,q,kind,status,year,mode",
    "view-fields:procurement:tab,entity,id,q,kind,status,institution,year,mode",
    "view-fields:infrastructure:tab,entity,id,q,classCode,status,mode",
    "view-fields:promises:tab,entity,id,q,status,institution,year,suggestions,mode",
    "view-fields:calendar:entity,id,q,kind,year,month",
    "view-fields:content:entity,id,q,kind,tag",
    "view-fields:sources:entity,id,q,kind,status",
    "view-fields:evidence:entity,id,q,kind,status",
    "view-fields:coverage:kind,level,mode",
    "view-fields:report:entity,id,kind",
    "view-fields:search:q,kind",
    "view-entities:leaders:position,leader",
    "view-entities:institutions:institution,position",
    "view-entities:laws:instrument",
    "view-entities:parliament:session,motion,bill",
    "view-entities:politics:party",
    "view-entities:elections:election,contest",
    "view-entities:finance:project,fund,budget",
    "view-entities:procurement:tender,contract,supplier",
    "view-entities:infrastructure:infrastructure",
    "view-entities:promises:promise",
    "view-entities:calendar:event",
    "view-entities:content:content",
    "view-entities:sources:source",
    "view-entities:evidence:evidence",
    "view-entities:report:report",
  );
