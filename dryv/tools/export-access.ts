/**
 * Exports what the API needs from the contracts at runtime, because the NestJS pack does not wire
 * contract policies into guards:
 *
 *  - access rules: which HTTP operations require which policy (from `.authenticated().requires()`);
 *  - target kinds: the schema-qualified tables of every domain fact (plus files and source documents), so comments, evidence and review
 *    decisions can only point at records that exist in a known table.
 *
 *   bun tools/export-access.ts           write source/backend/api/src/auth/access-rules.generated.ts
 *   bun tools/export-access.ts --check   fail when the file is stale
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { compileIr, dryvRoot, storageOf } from "./lib/ir.ts";

const items = compileIr();
const schemas = new Map(items.filter((i) => i.kind === "schema").map((i) => [i.name, i.value]));

function extendsHistorical(name: string): boolean {
  const seen = new Set<string>();
  let current: string | undefined = name;
  while (current && !seen.has(current)) {
    if (current === "shared.HistoricalEntity") return true;
    seen.add(current);
    current = schemas.get(current)?.extends?.$ref?.replace("#/schemas/", "");
  }
  return false;
}

const rules: Record<string, string> = {};
for (const item of items.filter((i) => i.kind === "operation")) {
  const http = item.value.facets?.http;
  const policies: Array<{ $ref: string }> = item.value.access?.policies ?? [];
  if (!http || policies.length === 0) continue;
  if (policies.length > 1) throw new Error(`${item.name}: more than one policy is not supported`);
  const path = String(http.path).replace(/\{(\w+)\}/g, ":$1");
  rules[`${http.method} ${path}`] = policies[0]!.$ref.replace("#/policies/shared.", "");
}

/** Besides domain facts, comments and attributions may point at files and source documents. */
const extraTargets = ["filesystem.files", "source.documents"];
const targetKinds = [
  ...new Set([
    ...[...schemas.entries()]
      .filter(([name, schema]) => schema.role === "entity" && !schema.abstract && extendsHistorical(name))
      .map(([, schema]) => storageOf(items, schema))
      .filter(({ schema }) => schema !== "identity")
      .map(({ schema, table }) => `${schema}.${table}`),
    ...extraTargets,
  ]),
].sort();

const sorted = Object.fromEntries(Object.entries(rules).sort(([a], [b]) => a.localeCompare(b)));
const output = `/* Generated by dryv/tools/export-access.ts from the contracts. Do not edit. */

/** HTTP operations that require a policy, keyed by "METHOD /nest/path". Operations not listed are public reads. */
export const accessRules = ${JSON.stringify(sorted, null, 2)} as const satisfies Record<string, "ContributorAccess" | "ReviewerAccess" | "AdminAccess" | "PipelineReadAccess" | "AssessmentDraftAccess" | "AssessmentApproveAccess" | "CandidatePromoteAccess" | "AccessManageAccess">;

/** Schema-qualified table of every domain fact: the only valid targetKind values for audit records. */
export const targetKinds = ${JSON.stringify(targetKinds, null, 2)} as const;
`;

const file = join(dryvRoot, "..", "source/backend/api/src/auth/access-rules.generated.ts");
if (process.argv.includes("--check")) {
  if (!existsSync(file) || readFileSync(file, "utf8") !== output) {
    console.error("access-rules.generated.ts is stale. Run: bun run access:export");
    process.exit(1);
  }
  console.log("Access rules are current");
} else {
  writeFileSync(file, output);
  console.log(`Wrote ${Object.keys(sorted).length} access rules and ${targetKinds.length} target kinds`);
}
