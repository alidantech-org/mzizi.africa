/**
 * Verifies that `SubjectTable` matches the generated schema and writes the hand-authored subject-integrity release.
 *
 *   bun tools/subject-integrity.ts --check   fail when the enum and the generated tables disagree, or the release is stale
 *   bun tools/subject-integrity.ts           write source/backend/database/migrations/0002_subject_integrity.sql
 *
 * Dryv emits subject columns as plain `text` and `uuid`, so existence, enum membership and deletion behaviour are enforced by
 * this release: a CHECK on each carrier, a before-write existence trigger and a before-delete RESTRICT trigger on every subject
 * table. Only enum members reach `regclass`; no table name is ever taken from untrusted input.
 */
import { resolve } from "node:path";

const repo = resolve(import.meta.dir, "../..");
const snapshot = await Bun.file(resolve(repo, "source/backend/database/sql/schema.sql")).text();
const subjects = await Bun.file(resolve(repo, "dryv/contracts/schemas/_subjects.ts")).text();

const enumTables = [...subjects.matchAll(/^\s+[A-Za-z]+: "([a-z_]+\.[a-z_]+)",$/gm)].map((m) => m[1] as string);
const sqlTables = [...snapshot.matchAll(/CREATE TABLE "([a-z_]+)"\."([a-z_]+)"/g)].map((m) => `${m[1]}.${m[2]}`);
const eligible = sqlTables.filter((t) => !t.startsWith("audit.") && !t.startsWith("auth."));
const missing = eligible.filter((t) => !enumTables.includes(t));
const unknown = enumTables.filter((t) => !sqlTables.includes(t));
const duplicate = enumTables.filter((t, i) => enumTables.indexOf(t) !== i);
const errors = [
  ...missing.map((t) => `table ${t} is missing from SubjectTable`),
  ...unknown.map((t) => `SubjectTable lists ${t}, which is not a generated table`),
  ...duplicate.map((t) => `SubjectTable lists ${t} twice`),
];
// Carriers are the tables that hold subject_table/subject_id columns.
const carriers = [...snapshot.matchAll(/CREATE TABLE "([a-z_]+)"\."([a-z_]+)" \(([\s\S]*?)\n\);/g)]
  .filter((m) => /"subject_table" text/.test(m[3] ?? "") && /"subject_id" uuid/.test(m[3] ?? ""))
  .map((m) => `${m[1]}.${m[2]}`)
  .sort();
const list = (items: readonly string[]): string => items.map((t) => `'${t}'`).join(", ");
const nameOf = (qualified: string): string => qualified.replace(".", "_");

const sql = `-- Release 0002: subject integrity.
--
-- Generated by dryv/tools/subject-integrity.ts from the SubjectTable enum and the carrier tables of the snapshot; do not edit by hand.
-- Carriers (hold subject_table + subject_id): ${carriers.join(", ")}.
-- Policy: a subject row that is still referenced cannot be hard-deleted (RESTRICT). Soft deletion is unaffected.
create or replace function public.subject_exists(p_table text, p_id uuid) returns boolean
language plpgsql stable as $$
declare found boolean;
begin
  if p_table is null or p_id is null or p_table not in (${list(enumTables)}) then
    return false;
  end if;
  execute format('select exists (select 1 from %s where id = $1)', p_table::regclass) into found using p_id;
  return found;
end $$;

create or replace function public.assert_subject() returns trigger
language plpgsql as $$
begin
  if new.subject_table is not null and not public.subject_exists(new.subject_table, new.subject_id) then
    raise exception 'subject % % does not exist', new.subject_table, new.subject_id using errcode = 'foreign_key_violation';
  end if;
  return new;
end $$;

create or replace function public.guard_subject_delete() returns trigger
language plpgsql as $$
declare qualified text := tg_table_schema || '.' || tg_table_name;
begin
${carriers
  .map(
    (c) => `  if exists (select 1 from ${c} where subject_table = qualified and subject_id = old.id) then
    raise exception '% % is still referenced as a subject by ${c}', qualified, old.id using errcode = 'foreign_key_violation';
  end if;`,
  )
  .join("\n")}
  return old;
end $$;

${carriers
  .map(
    (c) => `alter table ${c} add constraint ck_${nameOf(c)}__subject_table check (subject_table is null or subject_table in (${list(enumTables)}));
create trigger tr_${nameOf(c)}__subject_exists before insert or update of subject_table, subject_id on ${c}
  for each row execute function public.assert_subject();`,
  )
  .join("\n\n")}

${enumTables
  .map((t) => `create trigger tr_${nameOf(t)}__subject_delete before delete on ${t} for each row execute function public.guard_subject_delete();`)
  .join("\n")}
`;

const target = resolve(repo, "source/backend/database/migrations/0002_subject_integrity.sql");
if (process.argv.includes("--check")) {
  const current = (await Bun.file(target).exists()) ? await Bun.file(target).text() : "";
  if (current !== sql) errors.push("0002_subject_integrity.sql is missing or stale; run `bun dryv/tools/subject-integrity.ts`");
  if (errors.length) {
    console.error(errors.join("\n"));
    process.exit(1);
  }
  console.log(`SubjectTable covers ${enumTables.length} tables; carriers: ${carriers.join(", ")}`);
} else {
  if (errors.length) {
    console.error(errors.join("\n"));
    process.exit(1);
  }
  await Bun.write(target, sql);
  console.log(`wrote ${target} (${enumTables.length} subject tables, carriers: ${carriers.join(", ")})`);
}
