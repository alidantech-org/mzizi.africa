/** Generates the web and Flutter icon code from source/ui/brand/icons.json. Run: bun scripts/brand/build.ts */
import { writeFileSync } from "node:fs";

const icons = (await Bun.file("source/ui/brand/icons.json").json()) as Record<string, string>;
const names = Object.keys(icons).filter((name) => !name.startsWith("_"));

const ts = `// Generated by scripts/brand/build.ts from source/ui/brand/icons.json. Do not edit.
export const ICONS = {
${names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(icons[n])},`).join("\n")}
} as const;
export type IconName = keyof typeof ICONS;
`;
writeFileSync("source/apps/web/lib/brand/icons.generated.ts", ts);
writeFileSync("source/apps/dev/lib/brand/icons.generated.ts", ts);

const dart = `// Generated by scripts/brand/build.ts from source/ui/brand/icons.json. Do not edit.
const Map<String, String> mzIconPaths = {
${names.map((n) => `  '${n}': r"""${icons[n]!.replaceAll("'", "'")}""",`).join("\n")}
};
`;
writeFileSync("source/apps/app/lib/presentation/brand/icons_generated.dart", dart);
console.log(`${names.length} icons`);
