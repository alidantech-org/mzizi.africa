/** The port a service will use: `<NAME>_PORT` from the environment, else its default. */
export function portOf(service: Service, env: Record<string, string | undefined> = process.env): number {
  const override = Number(env[`${service.name.toUpperCase()}_PORT`]);
  return Number.isInteger(override) && override > 0 ? override : service.port;
}

/**
 * Select projects. With no filter: the default set. A filter is a comma-separated list of project names
 * or kinds (`python`, `bun`, `flutter`), or `all`. Unknown names throw, so typos never pass silently.
 */
export function select(filter?: string): Project[] {
  if (!filter) return projects.filter((project) => project.byDefault);
  if (filter === "all") return [...projects];
  const wanted = filter
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean);
  const unknown = wanted.filter((name) => !projects.some((project) => project.name === name || project.kind === name));
  if (unknown.length)
    throw new Error(`unknown project or kind: ${unknown.join(", ")} (known: ${projects.map((project) => project.name).join(", ")})`);
  return projects.filter(
    (project) => wanted.includes(project.name) || (wanted.includes(project.kind) && (project.byDefault || wanted.includes(project.name))),
  );
}

/** Names of the `scripts` in a Bun project's package.json (empty when there is none). */
export function packageScripts(project: Project): Set<string> {
  const file = join(at(project.dir), "package.json");
  if (!existsSync(file)) return new Set();
  const parsed = JSON.parse(readFileSync(file, "utf8")) as { scripts?: Record<string, string> };
  return new Set(Object.keys(parsed.scripts ?? {}));
}
