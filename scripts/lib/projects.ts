/**
 * The single registry of projects in this repository. Every command derives its work from this list,
 * so adding a project here is the only change needed to include it in setup, checks, builds and dev.
 *
 * Tooling rule (user direction, 11 November 2026): Python projects use uv, JavaScript and TypeScript
 * projects use Bun. The Flutter app is opt-in (`--only mobile`) because it needs the Flutter SDK.
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { at } from "./paths.ts";

export type Kind = "python" | "bun" | "flutter";

export type Project = {
  /** Short name used with `--only`. */
  readonly name: string;
  readonly kind: Kind;
  /** Repository-relative directory. */
  readonly dir: string;
  readonly summary: string;
  /** False for projects that only run when named explicitly. */
  readonly byDefault: boolean;
};

/** A long-running process for `dev` and `start`. */
export type Service = {
  /** Short name used with `dev <name>` and `start <name>`. */
  readonly name: string;
  /** Repository-relative directory the command runs in. */
  readonly dir: string;
  /** Command for development (watch mode where the project supports it). */
  readonly dev: readonly string[];
  /** Command for start mode (no watcher; Next.js apps must be built first). */
  readonly start: readonly string[];
  /** Default port, shown in the banner. */
  readonly port: number;
  /** Environment variable that carries the port to the process. */
  readonly portEnv: string;
};

